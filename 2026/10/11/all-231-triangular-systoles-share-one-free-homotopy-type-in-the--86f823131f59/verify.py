V=tuple(range(1,17))
def faces(k):
    return {tuple(sorted(c)) for f in FACETS for c in combinations(f,k)}
E=sorted(faces(2))
T=sorted(faces(3))
assert (len(V),len(E),len(T),len(FACETS))==(16,106,180,90)

# Lexicographic BFS spanning tree rooted at 1.
adj={v:[] for v in V}
for a,b in E:
    adj[a].append(b); adj[b].append(a)
seen={1}; q=deque([1]); tree=set()
while q:
    u=q.popleft()
    for v in sorted(adj[u]):
        if v not in seen:
            seen.add(v); q.append(v); tree.add(tuple(sorted((u,v))))
assert len(tree)==15 and seen==set(V)
non=[e for e in E if e not in tree]
assert len(non)==91
idx={e:i+1 for i,e in enumerate(non)}

cert=json.loads(Path(__file__).with_name("group_certificate.json").read_text(encoding="utf-8"))
assert cert["degree"]==120
a=tuple(cert["generator_a_images_0_based"])
b=tuple(cert["generator_b_images_0_based"])
assert sorted(a)==list(range(120)) and sorted(b)==list(range(120))
words={int(k):list(v) for k,v in cert["edge_generator_words"].items()}
assert set(words)==set(range(1,92))
assert words[58]==[1] and words[91]==[2]

ID=tuple(range(120))
# SymPy-compatible abstract group multiplication used when the certificate was made:
# (p*q)(i) = q(p(i)).
def mul(p,q):
    return tuple(q[p[i]] for i in range(120))
def invp(p):
    r=[0]*120
    for i,j in enumerate(p): r[j]=i
    return tuple(r)
ainv=invp(a); binv=invp(b)

def peval(word):
    z=ID
    for x in word:
        g = a if x==1 else ainv if x==-1 else b if x==2 else binv
        z=mul(z,g)
    return z

def order(p):
    z=ID
    for n in range(1,121):
        z=mul(z,p)
        if z==ID: return n
    raise AssertionError("element order exceeds 120")

# Enumerate the subgroup generated by a,b.
gens=(a,b,ainv,binv)
G={ID}; dq=deque([ID])
while dq:
    x=dq.popleft()
    for g in gens:
        y=mul(x,g)
        if y not in G:
            G.add(y); dq.append(y)
assert len(G)==120

def edge_word(u,v):
    e=tuple(sorted((u,v)))
    if e in tree: return []
    k=idx[e]
    w=words[k]
    return w if u<v else [-x for x in reversed(w)]

def loop_perm(cyc):
    z=ID
    for i in range(len(cyc)):
        u,v=cyc[i],cyc[(i+1)%len(cyc)]
        z=mul(z, peval(edge_word(u,v)))
    return z

# Every triangular 2-simplex relation must vanish.
assert all(loop_perm(t)==ID for t in T)

# Every 3-vertex clique gives a simple triangular loop.
Es=set(E); Ts=set(T)
cliques=[q for q in combinations(V,3) if all(tuple(sorted(e)) in Es for e in combinations(q,2))]
missing=sorted(set(cliques)-Ts)
assert len(cliques)==411 and len(missing)==231

vals=[loop_perm(q) for q in missing]
assert Counter(order(g) for g in vals)==Counter({10:231})

# All minimizers lie in one inverse-stable conjugacy class.
g0=vals[0]
conj={mul(mul(invp(h),g0),h) for h in G}
assert len(conj)==12
assert invp(g0) in conj
assert all(g in conj for g in vals)

# This certificate gives a surjective map from the edge presentation of pi_1
# onto a group of order 120 because a and b themselves are images of edge
# generators 58 and 91. The published identification of this triangulation with
# the Poincare homology sphere gives |pi_1|=120, so the map is faithful.

print("VERIFY_OK f=16,106,180,90 tree=15 edge_generators=91 "
      "perm_group=120 triangle_relators=180 cliques3=411 "
      "missing3=231 missing3_orders=10:231 conjugacy_class=12 inverse_stable=yes")
