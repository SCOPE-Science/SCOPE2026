#!/usr/bin/env python3
import cmath
import numpy as np

# Group elements are represented by permutations as tuples, composed left-to-right:
# mul(a,b) is a after b, matching ordinary function composition.
def mul(a,b):
    return tuple(a[b[i]] for i in range(len(a)))
def inv(a):
    out=[0]*len(a)
    for i,j in enumerate(a): out[j]=i
    return tuple(out)
def closure(gens):
    n=len(gens[0]); e=tuple(range(n)); G={e}; frontier=[e]
    while frontier:
        x=frontier.pop()
        for h in gens:
            for y in (mul(x,h),mul(h,x)):
                if y not in G: G.add(y); frontier.append(y)
    return sorted(G)
def order(g):
    e=tuple(range(len(g))); x=e
    for m in range(1,1000):
        x=mul(x,g)
        if x==e:return m
    raise RuntimeError('order bound')
def right_perm_matrix(G,g):
    idx={x:i for i,x in enumerate(G)}; N=len(G)
    P=np.zeros((N,N),dtype=complex)
    for j,x in enumerate(G):
        P[idx[mul(x,g)],j]=1
    return P

def check_group(name,G):
    N=len(G); I=np.eye(N,dtype=complex); cases=0
    e=tuple(range(len(G[0])))
    for g in G:
        if g==e: continue
        m=order(g); P=right_perm_matrix(G,g)
        for k in range(m):
            lam=cmath.exp(2j*cmath.pi*k/m)
            # Kernel of I-lam^{-1} P has the resonant eigenvalue lam.
            A=I-(1/lam)*P
            rank=np.linalg.matrix_rank(A,tol=1e-8)
            exp=N-N//m
            assert rank==exp,(name,N,m,k,rank,exp)
            cases+=1
        B=I+2*P
        assert np.linalg.matrix_rank(B,tol=1e-8)==N
        cases+=1
    return cases

# S3 on three letters.
s3=closure([(1,0,2),(1,2,0)])
# D8, symmetries of a square on four vertices.
d8=closure([(1,2,3,0),(0,3,2,1)])
# A4 generated by 3-cycles.
a4=closure([(1,2,0,3),(1,3,2,0)])

total=0
for name,G in [('S3',s3),('D8',d8),('A4',a4)]:
    total+=check_group(name,G)
print(f'VERIFY_OK groups=3 cases={total} orders_tested=2,3,4')
