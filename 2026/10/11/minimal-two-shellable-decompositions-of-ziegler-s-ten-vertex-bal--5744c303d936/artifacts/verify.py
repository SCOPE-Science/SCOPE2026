# For each facet i and each possible subset T of its triangle-sharing neighbours,
# precompute the set of other facets whose nonempty intersection with F_i lies
# inside at least one triangle selected by T. This makes the recursive shelling
# test exact and fast.
tri_nei=[]; tri_lists=[]; allowed=[]
for i in range(n):
    tl=[j for j in range(n) if j!=i and len(F[i]&F[j])==3]
    tri_lists.append(tl)
    tri_nei.append(sum(1<<j for j in tl))
    a=[]
    for pat in range(1<<len(tl)):
        tris=[F[i]&F[tl[k]] for k in range(len(tl)) if (pat>>k)&1]
        am=0
        for j in range(n):
            if j==i: continue
            x=F[i]&F[j]
            if not x or any(x<=t for t in tris): am |= 1<<j
        a.append(am)
    allowed.append(a)

def removable_last(i,R):
    # Intersection of F_i with union(R) must be nonempty and pure 2-dimensional.
    tl=tri_lists[i]
    pat=0
    for k,j in enumerate(tl):
        if (R>>j)&1: pat |= 1<<k
    if pat==0: return False
    return (R & ~allowed[i][pat])==0

# shell[S] is exact shellability of the pure subcomplex generated by tetrahedra S.
# Numeric order is a topological order because S\{i}<S.
N=1<<n
shell=bytearray(N)
for i in range(n): shell[1<<i]=1
for S in range(1,N):
    if shell[S] or (S & (S-1))==0: continue
    x=S
    while x:
        b=x & -x; i=b.bit_length()-1; R=S^b
        if shell[R] and removable_last(i,R):
            shell[S]=1; break
        x ^= b
assert not shell[FULL]

def maximal_intersection(S,T):
    ints=set()
    ia=[i for i in range(n) if (S>>i)&1]
    ib=[j for j in range(n) if (T>>j)&1]
    for i in ia:
        for j in ib:
            x=F[i]&F[j]
            if x: ints.add(frozenset(x))
    return tuple(x for x in ints if not any(x<y for y in ints))

def shellable_generic(mfs):
    mfs=tuple(frozenset(x) for x in mfs)
    if not mfs: return False
    sz={len(x) for x in mfs}
    if len(sz)!=1: return False
    d1=next(iter(sz))
    @lru_cache(None)
    def rec(ids):
        if len(ids)<=1: return True
        ids_set=set(ids)
        for i in ids:
            rest=ids_set-{i}
            rid=tuple(sorted(rest))
            if not rec(rid): continue
            ints={mfs[i]&mfs[j] for j in rest if mfs[i]&mfs[j]}
            mx=[x for x in ints if not any(x<y for y in ints)]
            if mx and all(len(x)==d1-1 for x in mx): return True
        return False
    return rec(tuple(range(len(mfs))))

pairs=[]
