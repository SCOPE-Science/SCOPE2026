#!/usr/bin/env python3
"""Independent finite enumeration for icosahedral neighborhood rational homology characters.
No third-party packages are required. Run with Python 3.9 or later.
"""
from itertools import combinations
from collections import Counter

N = 12
E = set()
def edge(a,b):
    assert a!=b
    E.add(tuple(sorted((a,b))))
for i in range(5):
    u, v = 2+i, 7+i
    edge(0,u); edge(1,v)
    edge(u,2+(i+1)%5)
    edge(v,7+(i+1)%5)
    edge(u,v);edge(u,7+(i-1)%5)
assert len(E)==30
ADJ = tuple(frozenset(w for w in range(N) if tuple(sorted((v,w))) in E and v!=w) for v in range(N))
assert all(len(a)==5 for a in ADJ)

F=[]
all_faces=set()
for nb in ADJ:
    for k in range(1,6):
        all_faces.update(combinations(sorted(nb),k))
for k in range(1,6):
    F.append(tuple(sorted(f for f in all_faces if len(f)==k)))
assert tuple(map(len,F))==(12,60,120,60,12)

def rank_binary(columns):
    piv={}
    for x in columns:
        while x:
            b=x.bit_length()-1
            if b in piv:x^=piv[b]
            else:
                piv[b]=x
                break
    return len(piv)

def rank_mod3(columns):
    piv={}
    for col in columns:
        x=dict((j,int(v)%3) for j,v in col.items() if v%3)
        while x:
            j=max(x)
            if j not in piv:
                v=x[j]
                piv[j]={k:((1 if v==1 else 2))*a%3 for k,a in x.items()}
                break
            q=x[j]
            for k,a in piv[j].items():
                z=(x.get(k,0)-q*a)%3
                if z:x[k]=z
                elif k in x:del x[k]
    return len(piv)

ranks={0:0,5:0}
for k in range(1,5):
    idx={f:i for i,f in enumerate(F[k-1])}
    cols2=[];cols3=[]
    for face in F[k]:
        bd=[idx[face[:i]+face[i+1:]] for i in range(k+1)]
        cols2.append(sum(1<<j for j in bd))
        cols3.append({j:(1 if t%2==0 else -1) for t,j in enumerate(bd)})
    r2=rank_binary(cols2)
    r3=rank_mod3(cols3)
    assert r2==r3,(k,r2,r3)
    ranks[k]=r2
assert ranks=={0:0,1:11,2:49,3:48,4:12,5:0},ranks
betti=[len(F[k])-ranks[k]-ranks[k+1] for k in range(5)]
assert betti==[1,0,23,0,0]

def autos():
    def rec(m, used):
        if len(m)==N:
            yield tuple(m[v] for v in range(N))
            return
        remaining=[v for v in range(N) if v not in m]
        def possible(v):
            return [w for w in range(N) if w not in used and
                    all((x in ADJ[v])==(m[x] in ADJ[w]) for x in m)]
        v=min(remaining,key=lambda x:(len(possible(x)),-sum(y in m for y in ADJ[x])))
        for w in possible(v):
            m[v]=w
            yield from rec(m,used|{w})
            del m[v]
    return tuple(sorted(set(rec({},set()))))

AUT=autos()
assert len(AUT)==120
IDENT=tuple(range(N))
def mul(p,q):return tuple(p[q[i]] for i in range(N))
def power_order(p):
    cur=IDENT
    for k in range(1,121):
        cur=mul(cur,p)
        if cur==IDENT:return k
    raise AssertionError('bad order')
orders={p:power_order(p) for p in AUT}
assert Counter(orders.values())==Counter({1:1,2:31,3:20,5:24,6:20,10:24})
# Unique antipodal graph automorphism: each vertex has one distance-three partner.
def far(v):
    layer={v}; seen={v}
    for depth in range(1,4):
        layer=set().union(*(ADJ[u] for u in layer))-seen
        seen|=layer
        if depth==3:
            assert len(layer)==1
            return next(iter(layer))
ANT=tuple(far(i) for i in range(N))
assert ANT in AUT and power_order(ANT)==2
assert all(mul(ANT,p)==mul(p,ANT) for p in AUT)
# The proper icosahedral group is generated by elements of order five.
R={IDENT}; gen=[p for p in AUT if orders[p]==5]; front=[IDENT]
while front:
    a=front.pop()
    for b in gen:
        c=mul(a,b)
        if c not in R:R.add(c);front.append(c)
assert len(R)==60 and ANT not in R
assert R|{mul(ANT,p) for p in R}==set(AUT)
assert Counter(orders[p] for p in R)==Counter({1:1,2:15,3:20,5:24})

# Signed trace of the induced map on simplicial chains (Lefschetz number).
def sign_of_image(face,p):
    x=[face.index(p[v]) for v in face]
    crossings=sum(x[i]>x[j] for i in range(len(x)) for j in range(i+1,len(x)))
    return -1 if crossings%2 else 1

def trace_h2(p):
    L=0
    for d,faces in enumerate(F):
        for face in faces:
            if all(p[v] in face for v in face):
                L+=(-1)**d*sign_of_image(face,p)
    # H_0 has trace 1, all other rational H except H_2 are zero.
    return L-1

rot=Counter((orders[p], trace_h2(p)) for p in R)
inverted=Counter((orders[p], trace_h2(mul(ANT,p))) for p in R)
assert rot==Counter({(1,23):1,(2,3):15,(3,-1):20,(5,3):24}),rot
assert inverted==Counter({(1,-1):1,(2,-5):15,(3,-1):20,(5,-1):24}),inverted

# For 5-cycles both conjugacy classes have trace 3; each class has 12 elements.
# A_5 character table (identity, order2, order3, two order5 classes):
# 1:[1,1,1,1,1], 3:[3,-1,0,phi,phi'], 3':[3,-1,0,phi',phi],
# 4:[4,0,1,-1,-1], 5:[5,1,-1,0,0].
# For constant values on both 5-classes, the sum phi+phi'=1 suffices.
chars={'1':(1,1,1,2), '3':(3,-1,0,1), '3p':(3,-1,0,1),
       '4':(4,0,1,-2),'5':(5,1,-1,0)}
# fourth value is sum of the two order5 character values, not one value.
# Orthogonality inner products: 12*trace_5*(chi_5a+chi_5b).
class_counts=(1,15,20,12)
ctplus={k: (r+i)//2 for k,r,i in zip((1,2,3,5), (23,3,-1,3), (-1,-5,-1,-1))}
ctminus={k: (r-i)//2 for k,r,i in zip((1,2,3,5), (23,3,-1,3), (-1,-5,-1,-1))}
assert ctplus=={1:11,2:-1,3:-1,5:1}
assert ctminus=={1:12,2:4,3:0,5:2}

def inner(ct,ch):
    dim,c2,c3,sum5=ch
    num=ct[1]*dim+15*ct[2]*c2+20*ct[3]*c3+12*ct[5]*sum5
    assert num%60==0,(ct,ch,num)
    return num//60
mplus={a:inner(ctplus,ch) for a,ch in chars.items()}
mminus={a:inner(ctminus,ch) for a,ch in chars.items()}
assert mplus=={'1':0,'3':1,'3p':1,'4':0,'5':1},mplus
assert mminus=={'1':2,'3':0,'3p':0,'4':0,'5':2},mminus
assert 3+3+5==11 and 2+2*5==12
print('VERIFY_OK')
print('f_vector',tuple(map(len,F)),'boundary_ranks',ranks,'mod2_betti',betti)
print('graph_automorphisms',len(AUT),'rotations',len(R),'antipodal_trace',trace_h2(ANT))
print('rotation_characters',sorted(rot.items()))
print('antipodal_rotation_characters',sorted(inverted.items()))
print('even_summand_irreducibilities',mplus)
print('odd_summand_irreducibilities',mminus)
