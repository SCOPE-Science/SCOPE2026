import sympy as sp
from itertools import product
from collections import Counter

lam=sp.symbols("lam")
x11,x12,x13,x21,x22,x23,x31,x32,x33=sp.symbols(
    "x11 x12 x13 x21 x22 x23 x31 x32 x33"
)
T=sp.Matrix([
    [x11,x12,x13],
    [x21,x22,x23],
    [x31,x32,x33],
])
Alpha=sp.diag(1,lam,lam)
basis=[sp.eye(3)[:,j] for j in range(3)]

def lie(x,y):
    return sp.Matrix([0,0,sp.expand(x[0]*y[1]-x[1]*y[0])])

# alpha_lambda is a Lie endomorphism of the ordinary Heisenberg algebra.
for x in basis:
    for y in basis:
        assert sp.simplify(Alpha*lie(x,y)-lie(Alpha*x,Alpha*y))==sp.zeros(3,1)

def hbr(x,y):
    return sp.simplify(Alpha*lie(x,y))

comm=sp.simplify(T*Alpha-Alpha*T)

def defect(x,y):
    Tx=T*x
    Ty=T*y
    return sp.simplify(hbr(Tx,Ty)-T*hbr(Tx,y))

# Symbolically collect the full defining system.
symbolic=[]
for z in comm:
    z=sp.factor(z)
    if z!=0:
        symbolic.append(z)
for x in basis:
    for y in basis:
        for z in defect(x,y):
            z=sp.factor(z)
            if z!=0:
                symbolic.append(z)

# Generic lambda != 0,1 reduction.
generic_sub={
    x12:0,x13:0,x21:0,x31:0,x23:0
}
generic_remaining={sp.factor(z.subs(generic_sub)/lam)
                   for z in symbolic
                   if sp.factor(z.subs(generic_sub))!=0
                   and sp.factor(z.subs(generic_sub)).has(lam)}
# The reduced ideal is generated by x11(x22-x33) and x22(x33-x11).
g1=sp.expand(x11*(x22-x33))
g2=sp.expand(x22*(x33-x11))
G=sp.groebner([g1,g2],x11,x22,x32,x33,order="grevlex")
for z in generic_remaining:
    assert G.reduce(sp.expand(z))[1]==0

# lambda=1 reduction.
one_eq=[]
for z in symbolic:
    zz=sp.factor(z.subs(lam,1))
    if zz!=0:
        one_eq.append(zz)
# x13^2 and x23^2 occur, hence field-valued solutions have x13=x23=0.
one_sub={x13:0,x23:0}
one_red={sp.factor(z.subs(one_sub)) for z in one_eq if sp.factor(z.subs(one_sub))!=0}
targets=[
    x12*x33,
    x21*x33,
    x33*(x11-x22),
    x12*x21-x11*(x22-x33),
]
G1=sp.groebner(targets,x11,x12,x21,x22,x31,x32,x33,order="grevlex")
for z in one_red:
    assert G1.reduce(sp.expand(z))[1]==0
G2=sp.groebner(list(one_red),x11,x12,x21,x22,x31,x32,x33,order="grevlex")
for z in targets:
    assert G2.reduce(sp.expand(z))[1]==0

def bmod(x,y,l,q):
    return (0,0,l*(x[0]*y[1]-x[1]*y[0])%q)

def mv(M,x,q):
    return tuple(sum(M[3*i+j]*x[j] for j in range(3))%q for i in range(3))

def alpha_vec(x,l,q):
    return (x[0]%q,l*x[1]%q,l*x[2]%q)

def is_embedding(M,l,q):
    bas=((1,0,0),(0,1,0),(0,0,1))
    for x in bas:
        Tx=mv(M,x,q)
        if mv(M,alpha_vec(x,l,q),q)!=alpha_vec(Tx,l,q):
            return False
    for x in bas:
        for y in bas:
            Tx=mv(M,x,q)
            Ty=mv(M,y,q)
            if bmod(Tx,Ty,l,q)!=mv(M,bmod(Tx,y,l,q),q):
                return False
    return True

def rank3(M,q):
    A=[list(M[3*i:3*i+3]) for i in range(3)]
    r=0
    for c in range(3):
        piv=next((i for i in range(r,3) if A[i][c]%q),None)
        if piv is None:
            continue
        A[r],A[piv]=A[piv],A[r]
        inv=pow(A[r][c],-1,q)
        A[r]=[(inv*z)%q for z in A[r]]
        for i in range(3):
            if i!=r and A[i][c]%q:
                k=A[i][c]%q
                A[i]=[(A[i][j]-k*A[r][j])%q for j in range(3)]
        r+=1
    return r

def profiles(q):
    zero=(
        1,
        (q-1)*(q*q+2*q+2),
        (q-1)**2*(q+1)*(2*q+1),
        q*(q-1)**3*(q+1),
    )
    one=(
        1,
        q**4+2*q**3-q**2-q-1,
        q*(q-1)**2*(q+1)**2,
        q**2*(q-1),
    )
    generic=(
        1,
        2*(q*q-1),
        (q-1)**2,
        q*(q-1),
    )
    assert sum(zero)==q**5
    assert sum(one)==q**5+q**4+q**3-2*q**2
    assert sum(generic)==4*q**2-3*q
    return zero,one,generic

for q in (2,3):
    zero,one,generic=profiles(q)
    for l in range(q):
        cnt=Counter()
        for M in product(range(q),repeat=9):
            if is_embedding(M,l,q):
                cnt[rank3(M,q)]+=1
        got=tuple(cnt[i] for i in range(4))
        expected=zero if l==0 else one if l==1 else generic
        assert got==expected,(q,l,got,expected)
        print({"q":q,"lambda":l,"rank_profile":got,"total":sum(got)})

for q in (2,3,5,7):
    zero,one,generic=profiles(q)
    total=q**5+(q**5+q**4+q**3-2*q**2)+(q-2)*(4*q**2-3*q)
    assert total==2*q**5+q**4+5*q**3-13*q**2+6*q

print("VERIFY_OK")
