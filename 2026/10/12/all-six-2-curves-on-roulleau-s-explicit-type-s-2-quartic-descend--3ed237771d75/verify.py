from itertools import permutations

# Sparse polynomials in (a,b,c,d): exponent tuple -> integer coefficient.
def clean(p):
    return {m:c for m,c in p.items() if c}

def add(p,q):
    r=dict(p)
    for m,c in q.items(): r[m]=r.get(m,0)+c
    return clean(r)

def scale(p,k):
    return clean({m:k*c for m,c in p.items()})

def mul(p,q):
    r={}
    for m,c in p.items():
        for n,d in q.items():
            e=tuple(m[i]+n[i] for i in range(4))
            r[e]=r.get(e,0)+c*d
    return clean(r)

def power(p,n):
    r={(0,0,0,0):1}
    b=p
    while n:
        if n&1: r=mul(r,b)
        b=mul(b,b); n//=2
    return r

def P(*terms):
    # terms are (coefficient, (ea,eb,ec,ed))
    return clean({m:c for c,m in terms})

ac=P((1,(1,0,1,0))); ad=P((1,(1,0,0,1)))
bc=P((1,(0,1,1,0))); bd=P((1,(0,1,0,1)))

# The two rational Segre parametrizations used in the certificate.
phi1=[add(add(ac,scale(ad,3)),bc), add(scale(ad,-3),scale(bc,-1)), scale(bc,-1), add(add(ad,bc),bd)]
phi2=[ac,bd,scale(ad,3),bc]

# Source quadrics Q1=xy+y^2+2xz+yz+z^2+3xt+3yt and Q2=3xy-zt.
def eval_quad(phi, which):
    x,y,z,t=phi
    if which==1:
        out=mul(x,y)
        out=add(out,power(y,2)); out=add(out,scale(mul(x,z),2))
        out=add(out,mul(y,z)); out=add(out,power(z,2))
        out=add(out,scale(mul(x,t),3)); out=add(out,scale(mul(y,t),3))
        return out
    return add(scale(mul(x,y),3),scale(mul(z,t),-1))

assert eval_quad(phi1,1)=={}
assert eval_quad(phi2,2)=={}

