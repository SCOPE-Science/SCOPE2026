# Each Segre map is obtained from the standard four monomials by an invertible matrix.
def det(M):
    n=len(M)
    if n==1: return M[0][0]
    return sum(((-1)**j)*M[0][j]*det([row[:j]+row[j+1:] for row in M[1:]]) for j in range(n))
