import sympy as sp

basis=[sp.eye(3)[:,i] for i in range(3)]

def mul(x,y):
    # Ordered basis (z,u,v), with uv=vu=z and all other products zero.
    return sp.Matrix([sp.expand(x[1]*y[2]+x[2]*y[1]),0,0])

def defect(N,x,y):
    Nx=N*x
    Ny=N*y
    return sp.simplify(
        mul(Nx,Ny)-N*(mul(Nx,y)+mul(x,Ny)-N*mul(x,y))
    )

x11,x12,x13,x21,x22,x23,x31,x32,x33=sp.symbols(
    "x11 x12 x13 x21 x22 x23 x31 x32 x33"
)
M=sp.Matrix([
    [x11,x12,x13],
    [x21,x22,x23],
    [x31,x32,x33],
])

eq={}
for i,x in enumerate(basis):
    for j,y in enumerate(basis):
        eq[(i+1,j+1)]=[sp.factor(v) for v in defect(M,x,y)]

# The first column reduction over C.
assert sp.factor(eq[(1,2)][2]) == -x31**2
assert sp.factor(eq[(1,3)][1]) == -x21**2

sub0={x21:0,x31:0}
remaining=set()
for vals in eq.values():
    for f in vals:
        g=sp.factor(f.subs(sub0))
        if g!=0:
            remaining.add(g)

expected_generators={
    sp.factor(-2*x32*(x11-x22)),
    sp.factor(-2*x23*(x11-x33)),
    sp.factor(x11**2-x11*x22-x11*x33+x22*x33+x23*x32),
}
assert remaining == expected_generators, (remaining, expected_generators)

a,alpha,beta,p0,c0,d0,q0=sp.symbols("a alpha beta p0 c0 d0 q0")
K=sp.Matrix([[p0,c0],[d0,q0]])
J=sp.Matrix([[0,1],[1,0]])
KTJK=sp.expand(K.T*J*K)
assert KTJK == sp.Matrix([
    [2*d0*p0,c0*d0+p0*q0],
    [c0*d0+p0*q0,2*c0*q0],
])

Nstruct=sp.Matrix([
    [a,alpha,beta],
    [0,a+p0,c0],
    [0,d0,a+q0],
])
struct_def=[]
for x in basis:
    for y in basis:
        struct_def.extend([sp.factor(v) for v in defect(Nstruct,x,y) if v!=0])
# Each structural defect lies in the ideal generated by the three KTJK entries.
G=sp.groebner(
    [d0*p0,c0*q0,c0*d0+p0*q0],
    p0,c0,d0,q0,alpha,beta,a,
    order="lex"
)
for f in struct_def:
    assert G.reduce(f)[1] == 0

# Automorphisms.
p,q,rho,sigma=sp.symbols("p q rho sigma", nonzero=True)
Phi=sp.Matrix([
    [p*q,rho,sigma],
    [0,p,0],
    [0,0,q],
])
Swap=sp.Matrix([
    [p*q,rho,sigma],
    [0,0,p],
    [0,q,0],
])
for A in (Phi,Swap):
    for x in basis:
        for y in basis:
            assert sp.simplify(A*mul(x,y)-mul(A*x,A*y)) == sp.zeros(3,1)

# Block conjugation formula for the connected component.
F=sp.diag(p,q)
ell=sp.Matrix([[alpha,beta]])
r=sp.Matrix([[rho,sigma]])
lam=p*q
Nblock=sp.Matrix.vstack(
    sp.Matrix.hstack(sp.Matrix([[a]]),ell),
    sp.Matrix.hstack(sp.zeros(2,1),a*sp.eye(2)+K)
)
Conj=sp.simplify(Phi*Nblock*Phi.inv())
Kprime=sp.simplify(F*K*F.inv())
ellprime=sp.simplify((lam*ell+r*K)*F.inv())
Expected=sp.Matrix.vstack(
    sp.Matrix.hstack(sp.Matrix([[a]]),ellprime),
    sp.Matrix.hstack(sp.zeros(2,1),a*sp.eye(2)+Kprime)
)
assert sp.simplify(Conj-Expected)==sp.zeros(3,3)

t,s=sp.symbols("t s")
Krank1=sp.Matrix([[t,s],[0,0]])
assert sp.simplify(F*Krank1*F.inv()-sp.Matrix([[t,p*s/q],[0,0]]))==sp.zeros(2,2)

# Every displayed normal form is Nijenhuis identically.
E12=sp.zeros(3); E12[0,1]=1
E13=sp.zeros(3); E13[0,2]=1
E22=sp.zeros(3); E22[1,1]=1
E23=sp.zeros(3); E23[1,2]=1
I=sp.eye(3)
families=[
    a*I,
    a*I+E12,
    a*I+E12+E13,
    a*I+t*E22,
    a*I+t*E22+E13,
    a*I+t*E22+E23,
    a*I+E12+t*E22+E23,
]
for N in families:
    for x in basis:
        for y in basis:
            assert sp.simplify(defect(N,x,y))==sp.zeros(3,1)

# Residual-covector calculations used in the orbit proof.
# P case K=t E11: first ell coordinate can be shifted; second scales by p.
KP=sp.Matrix([[t,0],[0,0]])
ellP=sp.simplify((lam*ell+r*KP)*F.inv())
assert ellP == sp.Matrix([[q*alpha+rho*t/p, p*beta]])

# R case K=[[t,1],[0,0]]. Its stabilizer in the diagonal part has p=q.
r0=sp.symbols("r0", nonzero=True)
FR=sp.diag(r0,r0)
lamR=r0**2
ellR=sp.simplify((lamR*ell+r*sp.Matrix([[t,1],[0,0]]))*FR.inv())
assert ellR == sp.Matrix([[
    r0*alpha+rho*t/r0,
    r0*beta+rho/r0
]])

print("VERIFY_OK")
