"""Exact dual-plane orbit and Galois-stabilizer census for the Mukai quartic.

Run: python3 verify_planes.py
Uses only the Python standard library and rational arithmetic in Q(i,sqrt(5)).
The input group matrices and plane seeds are those of Naskrecki,
Explicit equations of 800 conics on a Barth-Bauer quartic,
arXiv:2108.13402, Section 1.
"""
from fractions import Fraction
from collections import Counter, deque

Q = Fraction
ZERO = (Q(0),) * 4
ONE = (Q(1), Q(0), Q(0), Q(0))
I = (Q(0), Q(1), Q(0), Q(0))
IR = (Q(0), Q(0), Q(0), Q(1))


def plus(a, b):
    return tuple(x + y for x, y in zip(a, b))


def minus(a):
    return tuple(-x for x in a)


def times(a, b):
    """Basis (1, i, sqrt(5), i*sqrt(5)); i^2=-1, sqrt(5)^2=5."""
    out = [Q(0)] * 4
    for j, x in enumerate(a):
        if x == 0:
            continue
        for k, y in enumerate(b):
            if y == 0:
                continue
            c = x * y
            if (j & k) & 1:
                c = -c
            if (j & k) & 2:
                c *= 5
            out[j ^ k] += c
    return tuple(out)


def sigma(a, flip_i=0, flip_sqrt5=0):
    return tuple(x * (-1 if flip_i and j & 1 else 1)
                    * (-1 if flip_sqrt5 and j & 2 else 1)
                 for j, x in enumerate(a))


def inverse(a):
    assert a != ZERO
    adjoint = ONE
    for gi, gr in ((1, 0), (0, 1), (1, 1)):
        adjoint = times(adjoint, sigma(a, gi, gr))
    norm = times(a, adjoint)
    assert norm[0] != 0 and norm[1:] == (Q(0),) * 3
    return tuple(x / norm[0] for x in adjoint)


def normalize(v):
    pivot = next(x for x in v if x != ZERO)
    inv = inverse(pivot)
    return tuple(times(x, inv) for x in v)


def rational(x):
    return (Q(x), Q(0), Q(0), Q(0))


def sum_field(xs):
    out = ZERO
    for x in xs:
        out = plus(out, x)
    return out


M1 = [[rational(int(j == k) * (-1 if k == 3 else 1))
       for j in range(4)] for k in range(4)]
M2_raw = [[ONE, ONE, I, I], [ONE, ONE, minus(I), minus(I)],
          [minus(I), I, ONE, minus(ONE)],
          [minus(I), I, minus(ONE), ONE]]
M2 = [[tuple(x / 2 for x in a) for a in row] for row in M2_raw]
M3 = [[rational(int(j == (1, 0, 2, 3)[k]))
       for j in range(4)] for k in range(4)]
M4 = [[rational(int(j == (0, 2, 1, 3)[k]))
       for j in range(4)] for k in range(4)]
GENERATORS = (M1, M2, M3, M4)


def action(v, matrix):
    # The projective dual group is generated by row actions v -> v*M.
    # Taking inverse matrices gives the same complete orbit.
    return normalize(tuple(sum_field(times(v[k], matrix[k][j])
                                     for k in range(4))
                           for j in range(4)))


def orbit(seed):
    points = {seed}
    todo = deque([seed])
    while todo:
        v = todo.popleft()
        for matrix in GENERATORS:
            w = action(v, matrix)
            if w not in points:
                points.add(w)
                todo.append(w)
    return points


def galois(v, flip_i, flip_sqrt5):
    return normalize(tuple(sigma(x, flip_i, flip_sqrt5) for x in v))


def stabilizer(v):
    return tuple((fi, fr) for fi in (0, 1) for fr in (0, 1)
                 if galois(v, fi, fr) == v)


def run():
    # The two displayed cutting planes for C1 and C3 in Theorem 1.1.
    a = tuple((x + y) / 2 for x, y in zip(I, IR))
    seed1 = normalize((ONE, ONE, ONE, ZERO))
    seed3 = normalize((ZERO, ZERO, ONE, a))
    first = orbit(seed1)
    third = orbit(seed3)
    assert len(first) == 160 and len(third) == 240
    assert first.isdisjoint(third)
    all_planes = first | third
    assert len(all_planes) == 400

    # Closure checks test the entire Galois action, not just fixed counts.
    for v in all_planes:
        assert all(galois(v, fi, fr) in all_planes
                   for fi in (0, 1) for fr in (0, 1))

    labels = {
        ((0, 0), (0, 1), (1, 0), (1, 1)): 'Q',
        ((0, 0), (0, 1)): 'Qi',
        ((0, 0), (1, 0)): 'Qsqrt5',
        ((0, 0),): 'K'
    }
    counts = Counter(labels[stabilizer(v)] for v in all_planes)
    assert counts == {'Q': 16, 'Qi': 144, 'Qsqrt5': 48, 'K': 192}
    assert Counter(labels[stabilizer(v)] for v in first) == {'Q': 16, 'Qi': 144}
    assert Counter(labels[stabilizer(v)] for v in third) == {'Qsqrt5': 48, 'K': 192}
    fixed_counts = {
        (fi, fr): sum(galois(v, fi, fr) == v for v in all_planes)
        for fi, fr in ((1, 0), (0, 1), (1, 1))
    }
    assert fixed_counts == {(1, 0): 64, (0, 1): 160, (1, 1): 16}
    assert sum(counts.values()) == 400
    assert 16 + 96 * 2 + 48 * 4 == 400
    print('VERIFY_OK planes=400 first_orbit=160 third_orbit=240'
          ' Q=16 Qi=144 Qsqrt5=48 K=192'
          ' Galois_orbits=16+96+48 fixed_i=64 fixed_sqrt5=160 fixed_both=16')


if __name__ == '__main__':
    run()
