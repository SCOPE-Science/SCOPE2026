#!/usr/bin/env python3
from itertools import product, combinations
from collections import Counter
import hashlib, json

N=6
WORDS=[''.join(p) for p in product('01', repeat=N)]
INDEX={w:i for i,w in enumerate(WORDS)}

def shadow(w):
    return {w[:i]+w[i+1:] for i in range(N)}
SH=[shadow(w) for w in WORDS]

# Compatibility graph: two words may coexist iff one-deletion shadows are disjoint.
adj=[0]*len(WORDS)
for i,j in combinations(range(len(WORDS)),2):
    if SH[i].isdisjoint(SH[j]):
        adj[i] |= 1<<j
        adj[j] |= 1<<i

best=0
max_cliques=[]
maximal_count=0

def bits(mask):
    while mask:
        b=mask & -mask
        yield b.bit_length()-1
        mask ^= b

def bronk(R, P, X):
    global best,max_cliques,maximal_count
    if R.bit_count()+P.bit_count() < best:
        return
    if not P and not X:
        maximal_count += 1
        rtuple=tuple(bits(R))
        k=len(rtuple)
        if k>best:
            best=k; max_cliques=[rtuple]
        elif k==best:
            max_cliques.append(rtuple)
        return
    union=P|X
    if union:
        # exact pivot maximizing neighbors in P
        u=max(bits(union), key=lambda v:(adj[v]&P).bit_count())
        cand=P & ~adj[u]
    else:
        cand=P
    for v in list(bits(cand)):
        vb=1<<v
        bronk(R|vb, P&adj[v], X&adj[v])
        P &= ~vb
        X |= vb

ALL=(1<<len(WORDS))-1
bronk(0,ALL,0)
MAXIMA=sorted(tuple(WORDS[i] for i in c) for c in max_cliques)
assert best==10 and len(MAXIMA)==9

# Verify directly from the definition.
for C in MAXIMA:
    assert len(C)==10 and all(SH[INDEX[a]].isdisjoint(SH[INDEX[b]]) for a,b in combinations(C,2))

# Explicit natural order-four action generated by bit complement and reversal.
def comp(w): return ''.join('1' if c=='0' else '0' for c in w)
def rev(w): return w[::-1]
OPS=(lambda w:w, comp, rev, lambda w:comp(rev(w)))
MSET=set(MAXIMA)
seen=set(); ORBITS=[]
for C in MAXIMA:
    if C in seen: continue
    orb={tuple(sorted(op(w) for w in C)) for op in OPS}
    assert orb <= MSET
    seen |= orb
    ORBITS.append(sorted(orb))
assert seen==MSET
orbit_sizes=sorted(len(o) for o in ORBITS)
assert orbit_sizes==[1,1,1,2,2,2]

# VT syndrome, classes, and common core.
def syndrome(w):
    return sum((i+1)*int(x) for i,x in enumerate(w)) % (N+1)
vt_sizes=[sum(syndrome(w)==a for w in WORDS) for a in range(N+1)]
assert vt_sizes==[10,9,9,9,9,9,9]
vt0=tuple(w for w in WORDS if syndrome(w)==0)
assert vt0 in MSET
vt_maxima=[C for C in MAXIMA if len({syndrome(w) for w in C})==1]
assert vt_maxima==[vt0]
common=set(MAXIMA[0])
for C in MAXIMA[1:]: common &= set(C)
assert sorted(common)==['000000','001100','110011','111111']

# Shadow-size and weight profiles, useful as equality fingerprints.
def wt(w): return w.count('1')
def profile(C):
    return {
      'weight': tuple(Counter(map(wt,C))[i] for i in range(N+1)),
      'shadow_size': tuple(sorted(Counter(len(SH[INDEX[w]]) for w in C).items()))
    }
profiles=Counter(json.dumps(profile(C),sort_keys=True) for C in MAXIMA)

canon='\n'.join(','.join(C) for C in MAXIMA)+'\n'
sha=hashlib.sha256(canon.encode()).hexdigest()
print('VERIFY_OK')
print('vertices',len(WORDS),'maximum',best,'maximal_cliques',maximal_count,'maximum_codes',len(MAXIMA))
print('natural_group',len(OPS),'orbit_sizes',','.join(map(str,orbit_sizes)))
print('vt_sizes',','.join(map(str,vt_sizes)),'vt_maximum_codes',len(vt_maxima))
print('common_core',','.join(sorted(common)))
print('maximum_census_sha256',sha)
for i,C in enumerate(MAXIMA,1): print(f'MAX{i:02d}',','.join(C))
