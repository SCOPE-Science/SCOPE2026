#!/usr/bin/env python3
from itertools import combinations
from collections import Counter

N = 6
V = list(range(1 << N))
ERR = [0] + [1 << i for i in range(N)] + [(1 << i) | (1 << (i + 1)) for i in range(N - 1)]
ERR_SET = set(ERR)
DIFF_BAD = {a ^ b for a in ERR for b in ERR}

def bits(x):
    return format(x, f"0{N}b")

def ball(x):
    return {x ^ e for e in ERR}

BALLS = [ball(x) for x in V]

# Two independent compatibility definitions.
def compatible_ball(x, y):
    return BALLS[x].isdisjoint(BALLS[y])

def compatible_diff(x, y):
    return (x ^ y) not in DIFF_BAD

for x, y in combinations(V, 2):
    assert compatible_ball(x, y) == compatible_diff(x, y)

ADJ = [0] * (1 << N)
EDGE_COUNT = 0
for x, y in combinations(V, 2):
    if compatible_diff(x, y):
        ADJ[x] |= 1 << y
        ADJ[y] |= 1 << x
        EDGE_COUNT += 1

# Direct upper bound: if two codewords agree on coordinates 0 and 1,
# their difference is supported on the other four consecutive coordinates.
# Every vector supported there is the xor of two allowed length <= 2 bursts.
KERNEL = {x for x in V if (x & 0b11) == 0}
assert KERNEL <= DIFF_BAD

# Exhaustive four-clique enumeration.  Every five-clique contains a four-clique;
# checking that every four-clique has empty common-neighbor set proves no five-clique exists.
FOUR = []
for a, b, c, d in combinations(V, 4):
    if not ((ADJ[a] >> b) & 1):
        continue
    if not ((ADJ[a] >> c) & 1 and (ADJ[b] >> c) & 1):
        continue
    if not ((ADJ[a] >> d) & 1 and (ADJ[b] >> d) & 1 and (ADJ[c] >> d) & 1):
        continue
    common = ADJ[a] & ADJ[b] & ADJ[c] & ADJ[d]
    assert common == 0
    FOUR.append((a, b, c, d))

assert len(FOUR) == 192

# Every maximum code is affine: translate by one codeword and check xor closure.
def direction(code):
    a = code[0]
    T = frozenset(x ^ a for x in code)
    assert 0 in T and len(T) == 4
    assert all((x ^ y) in T for x in T for y in T)
    return T

DIRECTIONS = sorted({direction(c) for c in FOUR}, key=lambda S: tuple(sorted(S)))
assert len(DIRECTIONS) == 12

# Each admissible direction has exactly 16 distinct affine cosets, and together they are all maxima.
def cosets(S):
    reps = []
    seen = set()
    for t in V:
        C = tuple(sorted(t ^ s for s in S))
        if C not in seen:
            seen.add(C)
            reps.append(C)
    return set(reps)

all_cosets = set()
for S in DIRECTIONS:
    cc = cosets(S)
    assert len(cc) == 16
    all_cosets |= cc
assert all_cosets == set(FOUR)

# Natural isometry group generated by all translations and coordinate reversal.
def reverse_bits(x):
    y = 0
    for i in range(N):
        if (x >> i) & 1:
            y |= 1 << (N - 1 - i)
    return y

assert {reverse_bits(e) for e in ERR} == ERR_SET

def act(code, t, rev):
    return tuple(sorted(((reverse_bits(x) if rev else x) ^ t) for x in code))

MAXSET = set(FOUR)
seen = set()
orbit_sizes = []
for C in sorted(MAXSET):
    if C in seen:
        continue
    orb = {act(C, t, rev) for t in V for rev in (False, True)}
    assert orb <= MAXSET
    seen |= orb
    orbit_sizes.append(len(orb))
assert seen == MAXSET
assert sorted(orbit_sizes) == [16, 16, 32, 32, 32, 32, 32]

# Direction orbit sizes under reversal (translations act trivially on directions).
dirset = set(DIRECTIONS)
seen_d = set()
dir_orbit_sizes = []
for S in DIRECTIONS:
    if S in seen_d:
        continue
    R = frozenset(reverse_bits(x) for x in S)
    orb = {S, R}
    assert orb <= dirset
    seen_d |= orb
    dir_orbit_sizes.append(len(orb))
assert sorted(dir_orbit_sizes) == [1, 1, 2, 2, 2, 2, 2]

# Pair-difference profile for every maximum, used as an additional census check.
def span(x):
    if x == 0:
        return 0
    p = [i for i in range(N) if (x >> i) & 1]
    return max(p) - min(p) + 1

profiles = Counter()
for C in FOUR:
    profile = tuple(sorted(( (x ^ y).bit_count(), span(x ^ y)) for x, y in combinations(C, 2)))
    profiles[profile] += 1
assert sorted(profiles.values()) == [16, 32, 32, 48, 64]

print(
    "VERIFY_OK "
    f"vertices={len(V)} errors={len(ERR)} bad_differences={len(DIFF_BAD)} edges={EDGE_COUNT} "
    f"maximum=4 labeled_maxima={len(FOUR)} affine_maxima={len(FOUR)} directions={len(DIRECTIONS)} "
    "cosets_per_direction=16 natural_group_size=128 orbits=7 orbit_sizes=16x2,32x5 "
    "direction_orbits=7 direction_orbit_sizes=1x2,2x5 profile_class_sizes=16,32,32,48,64"
)
