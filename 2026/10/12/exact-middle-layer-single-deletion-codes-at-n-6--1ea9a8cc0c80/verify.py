from itertools import combinations
from collections import Counter
import hashlib

N=6
K=3
WORDS=[''.join(bits) for bits in __import__('itertools').product('01', repeat=N) if bits.count('1')==K]
assert len(WORDS)==20

def shadow(w):
    return {w[:i]+w[i+1:] for i in range(len(w))}

def lcs(a,b):
    dp=[0]*(len(b)+1)
    for x in a:
        nd=[0]
        for j,y in enumerate(b,1):
            nd.append(dp[j-1]+1 if x==y else max(dp[j],nd[-1]))
        dp=nd
    return dp[-1]

SH={w:shadow(w) for w in WORDS}
# Two independent compatibility tests agree on every unordered pair.
pair_checks=0
for a,b in combinations(WORDS,2):
    pair_checks+=1
    direct=bool(SH[a]&SH[b])
    via_lcs=(lcs(a,b)>=N-1)
    assert direct==via_lcs

H={'00011','00110','01100','10101','11000'}
pre={h:[] for h in H}
for w in WORDS:
    hits=SH[w]&H
    assert len(hits)==1, (w,hits)
    pre[next(iter(hits))].append(w)
assert sorted(map(len,pre.values()))==[4]*5
# Any code has pairwise-disjoint shadows, so it contains at most one word from each H-bin.
upper=5

def valid(C):
    seen=set()
    for w in C:
        if seen & SH[w]: return False
        seen |= SH[w]
    return True

maxima=[tuple(C) for C in combinations(WORDS,upper) if valid(C)]
assert len(maxima)==8
assert not any(valid(C) for C in combinations(WORDS,upper+1))

rev=lambda w:w[::-1]
comp=lambda w:''.join('1' if c=='0' else '0' for c in w)
rc=lambda w:comp(rev(w))

def transform(C,f): return frozenset(f(w) for w in C)
MAX={frozenset(C) for C in maxima}
assert all(transform(C,rc)==C for C in MAX)
# Natural order-4 group generated by reversal and complement.
group=[lambda w:w, rev, comp, rc]
seen=set(); orbits=[]
for C in sorted(MAX,key=lambda s:tuple(sorted(s))):
    if C in seen: continue
    O={transform(C,g) for g in group}
    assert O <= MAX
    seen |= O; orbits.append(O)
assert len(orbits)==4 and sorted(map(len,orbits))==[2,2,2,2]

relevant={''.join(bits) for bits in __import__('itertools').product('01',repeat=5) if bits.count('1') in (2,3)}
assert len(relevant)==20
cover=Counter()
for C in MAX:
    U=set().union(*(SH[w] for w in C))
    assert U<=relevant
    cover[len(U)]+=1
assert cover==Counter({18:4,20:4})
perfect=sum(1 for C in MAX if len(set().union(*(SH[w] for w in C)))==20)
assert perfect==4

lines=[]
for C in sorted(MAX,key=lambda s:tuple(sorted(s))):
    U=set().union(*(SH[w] for w in C))
    lines.append(f"coverage={len(U)} " + ','.join(sorted(C)))
blob=('\n'.join(lines)+'\n').encode()
digest=hashlib.sha256(blob).hexdigest()
print('VERIFY_OK vertices=20 pair_checks=%d upper_certificate_bins=5 maximum=5 labeled_maxima=8 natural_group=4 orbits=4 orbit_sizes=2x4 reverse_complement_fixed=8 coverage=18x4,20x4 layer_perfect=4 maxima_sha256=%s' % (pair_checks,digest))
print('BINS=' + ';'.join(h+':'+','.join(sorted(pre[h])) for h in sorted(H)))
print('MAXIMA_SHA256='+digest)
