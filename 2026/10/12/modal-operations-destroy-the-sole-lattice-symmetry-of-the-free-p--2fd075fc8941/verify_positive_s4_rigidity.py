#!/usr/bin/env python3
from itertools import combinations, permutations, product
from collections import defaultdict

# Canonical seven one-variable positive-S4 terms in Fact 5.2.
# 0=x, 1=Bx, 2=DBx, 3=BDBx, 4=Dx, 5=BDx, 6=DBDx
names=('x','Bx','DBx','BDBx','Dx','BDx','DBDx')
# Hasse covers p<q read from Fact 5.2.
covers={(1,0),(0,4),(1,3),(3,2),(3,5),(2,6),(5,6),(6,4)}

# transitive closure of P
le={(i,i) for i in range(7)}|set(covers)
changed=True
while changed:
    changed=False
    for a,b in list(le):
        for c,d in list(le):
            if b==c and (a,d) not in le:
                le.add((a,d)); changed=True

checks=0
# Check covers are exactly the covers of this closure.
derived=set()
for a,b in le:
    if a==b: continue
    if not any(c not in (a,b) and (a,c) in le and (c,b) in le for c in range(7)):
        derived.add((a,b))
assert derived==covers; checks+=1

# Q = isotone maps P -> 2, represented by their true sets, i.e. upsets of P.
def is_upset_P(U):
    return all(i not in U or all(j in U for j in range(7) if (i,j) in le) for i in range(7))
Q=[]
for mask in range(1<<7):
    U=frozenset(i for i in range(7) if mask>>i & 1)
    if is_upset_P(U): Q.append(U)
assert len(Q)==14; checks+=1
Q=tuple(Q)

# The free bounded distributive lattice on the ordered generators P is Up(Q).
def is_upset_Q(S):
    return all(i not in S or all(j in S for j in range(len(Q)) if Q[i] <= Q[j]) for i in range(len(Q)))
L=[]
for mask in range(1<<len(Q)):
    S=frozenset(i for i in range(len(Q)) if mask>>i & 1)
    if is_upset_Q(S): L.append(S)
assert len(L)==37; checks+=1
L=set(L)

# Generator p is the upset {q in Q : p in q}.
gen=tuple(frozenset(k for k,q in enumerate(Q) if p in q) for p in range(7))
assert all(g in L for g in gen); checks+=7

# Enumerate all order automorphisms of Q. Rank in this inclusion poset is |U|,
# so every automorphism preserves cardinality. This leaves only 144 candidates.
blocks=defaultdict(list)
for i,U in enumerate(Q): blocks[len(U)].append(i)
block_keys=sorted(blocks)
perm_options=[list(permutations(blocks[k])) for k in block_keys]

def preserves_order(pi):
    for i in range(len(Q)):
        for j in range(len(Q)):
            checks_local = (Q[i] <= Q[j]) == (Q[pi[i]] <= Q[pi[j]])
            if not checks_local: return False
    return True

autos=[]
for choices in product(*perm_options):
    pi=list(range(len(Q)))
    for k,arr in zip(block_keys, choices):
        for src,dst in zip(blocks[k],arr): pi[src]=dst
    if preserves_order(pi): autos.append(tuple(pi))
assert len(autos)==2; checks+=1
idpi=tuple(range(len(Q)))
nontriv=next(pi for pi in autos if pi!=idpi)
assert all(nontriv[nontriv[i]]==i for i in range(len(Q))); checks+=len(Q)

# Induced lattice automorphism S -> pi[S].
def act(pi,S): return frozenset(pi[i] for i in S)
for pi in autos:
    for S in L:
        assert act(pi,S) in L; checks+=1
    for A in L:
        for B in L:
            assert act(pi,A & B)==(act(pi,A)&act(pi,B)); checks+=1
            assert act(pi,A | B)==(act(pi,A)|act(pi,B)); checks+=1

# The sole nontrivial lattice symmetry fixes x and swaps DBx with BDx,
# fixing the other four modal iterates among the seven generators.
images=[gen.index(act(nontriv,g)) if act(nontriv,g) in gen else None for g in gen]
assert images==[0,1,5,3,4,2,6]; checks+=1
assert act(nontriv,gen[0])==gen[0]; checks+=1

fixed=sum(act(nontriv,S)==S for S in L)
assert fixed==23 and (37-fixed)//2==7; checks+=1

# Therefore any positive-S4 algebra automorphism is one of these two lattice
# automorphisms; both fix x. Since the algebra is generated by x, a full
# algebra automorphism fixing x is the identity. The free universal property
# then gives exactly 37 endomorphisms, one for each possible image of x, and
# a surjective endomorphism must send x to another generator. Rigidity makes
# x the only such image.
assert len(L)==37 and len(autos)==2 and images[0]==0; checks+=1

print('Q_upsets', len(Q))
print('free_lattice_elements', len(L))
print('lattice_automorphisms', len(autos))
print('nontrivial_generator_action', dict(zip(names,[names[i] for i in images])))
print('nontrivial_lattice_fixed_points', fixed)
print('full_positive_S4_automorphisms', 1)
print('full_positive_S4_endomorphisms', 37)
print('unique_full_algebra_generator', 'x')
print(f'VERIFY_OK {checks} exact assertions')
