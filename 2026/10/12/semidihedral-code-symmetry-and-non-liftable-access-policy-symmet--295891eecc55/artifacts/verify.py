from itertools import product, permutations
from collections import Counter
from math import gcd

P=3
G=(
 (1,2,1,1,1,0,0,0),
 (0,1,2,1,1,1,0,0),
 (0,0,1,2,1,1,1,0),
 (0,0,0,1,2,1,1,1),
)
SOURCE_ACCESS={
 (1,2,3,4),(1,2,3,7),(1,3,5,6),(4,5,6,7),(2,3,5,6),
 (2,4,5,7),(2,3,5,7),(1,3,4,6),(1,5,6,7),(1,2,6,7),
 (1,4,7),(3,4,5),(3,6,7),(2,4,6),(1,2,5)
}

def lincomb(a):
    return tuple(sum(a[i]*G[i][j] for i in range(4))%P for j in range(8))
CODE={lincomb(a) for a in product(range(P), repeat=4)}
assert len(CODE)==81
wd=Counter(sum(x!=0 for x in v) for v in CODE)
assert wd==Counter({0:1,4:20,5:32,6:8,7:16,8:4})

def supp(v): return frozenset(i for i,x in enumerate(v) if x)
# Minimal means every nonzero word with contained support is a scalar multiple.
minimal=[]
for c in CODE:
    if not any(c): continue
    sc=supp(c)
    mults={tuple((lam*x)%P for x in c) for lam in (1,2)}
    if all((not any(d)) or not supp(d).issubset(sc) or d in mults for d in CODE):
        minimal.append(c)
assert Counter(sum(x!=0 for x in c) for c in minimal)==Counter({5:32,4:20})
access={tuple(i for i,x in enumerate(c) if i and x) for c in minimal if c[0]==1}
assert access==SOURCE_ACCESS and len(access)==15

def act_word(v,p):
    # p maps output coordinate i to old coordinate p[i]
    return tuple(v[p[i]] for i in range(8))
coord_aut=[]
for p in permutations(range(8)):
    if all(act_word(v,p) in CODE for v in CODE): coord_aut.append(p)
assert len(coord_aut)==16

def compose(p,q): return tuple(p[q[i]] for i in range(len(p)))
def ident(n): return tuple(range(n))
def inv(p):
    z=[0]*len(p)
    for i,j in enumerate(p): z[j]=i
    return tuple(z)
def power(p,k):
    z=ident(len(p))
    for _ in range(k): z=compose(z,p)
    return z
def order(p):
    z=ident(len(p))
    for k in range(1,100):
        z=compose(p,z)
        if z==ident(len(p)): return k
    raise AssertionError
r=(1,2,3,4,5,6,7,0)
s=(0,3,6,1,4,7,2,5)
assert r in coord_aut and s in coord_aut
assert order(r)==8 and order(s)==2
assert compose(compose(s,r),s)==power(r,3)
# subgroup generated by r,s
H={ident(8)}
changed=True
while changed:
    changed=False
    for a in list(H):
        for b in (r,s):
            for c in (compose(a,b),compose(b,a)):
                if c not in H: H.add(c); changed=True
assert H==set(coord_aut)
assert Counter(order(p) for p in coord_aut)==Counter({1:1,2:5,4:6,8:4})
# Dealer stabilizer (coordinate 0 fixed) has order 2.
stab0={p for p in coord_aut if p[0]==0}
assert stab0=={ident(8),s}

# Full automorphism group of the published minimal-access hypergraph.
def image_set(A,p): return tuple(sorted(p[i-1] for i in A))
access_aut=[]
for vals in permutations(range(1,8)):
    p={i+1:vals[i] for i in range(7)}
    if {tuple(sorted(p[i] for i in A)) for A in SOURCE_ACCESS}==SOURCE_ACCESS:
        access_aut.append(p)
assert len(access_aut)==4
# Explicit V4 generators.
a={1:3,2:6,3:1,4:4,5:7,6:2,7:5}
b={1:5,2:2,3:7,4:4,5:1,6:6,7:3}
def compdict(x,y): return {i:x[y[i]] for i in range(1,8)}
id7={i:i for i in range(1,8)}
V={tuple(g[i] for i in range(1,8)) for g in (id7,a,b,compdict(a,b))}
assert V=={tuple(g[i] for i in range(1,8)) for g in access_aut}
assert compdict(a,a)==id7 and compdict(b,b)==id7 and compdict(a,b)==compdict(b,a)
# Participant orbits.
seen=set(); orbits=[]
for x in range(1,8):
    if x not in seen:
        o={g[x] for g in access_aut}; seen|=o; orbits.append(tuple(sorted(o)))
assert sorted(orbits,key=lambda t:(len(t),t))==[(4,), (2,6), (1,3,5,7)]
# Code automorphisms fixing dealer induce exactly <a> on participants.
induced={tuple(p[i] for i in range(1,8)) for p in stab0}
assert induced=={tuple(id7[i] for i in range(1,8)),tuple(a[i] for i in range(1,8))}

print('CODEWORDS',len(CODE))
print('WEIGHT_DISTRIBUTION',dict(sorted(wd.items())))
print('MINIMAL_ACCESS_SETS',len(access))
print('COORDINATE_AUTOMORPHISMS',len(coord_aut))
print('COORDINATE_AUT_ORDER_CENSUS',dict(sorted(Counter(order(p) for p in coord_aut).items())))
print('ACCESS_HYPERGRAPH_AUTOMORPHISMS',len(access_aut))
print('PARTICIPANT_ORBITS',sorted(orbits,key=lambda t:(len(t),t)))
print('DEALER_STABILIZER_INDUCED',len(induced))
print('VERIFY_OK')
