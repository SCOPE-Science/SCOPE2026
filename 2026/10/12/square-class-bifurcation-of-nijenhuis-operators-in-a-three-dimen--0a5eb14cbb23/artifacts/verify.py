import sympy as sp
from itertools import product
from collections import Counter

beta,gamma=sp.symbols("beta gamma")
x,p,q0,r,s=sp.symbols("x p q0 r s")
alpha=sp.diag(1,2,2)
basis=[sp.eye(3)[:,i] for i in range(3)]

def br(u,v):
    return sp.Matrix([
        0,
        sp.expand(gamma*(u[0]*v[2]-u[2]*v[0])),
        sp.expand(beta*(u[0]*v[1]-u[1]*v[0])),
    ])

# Multiplicative Hom-Lie structure.
for u,v in product(basis,repeat=2):
    assert sp.simplify(alpha*br(u,v)-br(alpha*u,alpha*v))==sp.zeros(3,1)
for u,v,w in product(basis,repeat=3):
    J=br(alpha*u,br(v,w))+br(alpha*v,br(w,u))+br(alpha*w,br(u,v))
    assert sp.simplify(J)==sp.zeros(3,1)

B=sp.Matrix([[p,q0],[r,s]])
A=sp.Matrix([[0,gamma],[beta,0]])
N=sp.diag(x,1,1)
N[1:3,1:3]=B

def ndef(u,v):
    Nu,Nv=N*u,N*v
    inside=br(Nu,v)+br(u,Nv)-N*br(u,v)
    return sp.simplify(br(Nu,Nv)-N*inside)

target=sp.simplify((x*sp.eye(2)-B)*(A*B-B*A))
# Defects with e1 against V equal target columns up to a global sign convention.
D12=ndef(basis[0],basis[1])[1:3,0]
D13=ndef(basis[0],basis[2])[1:3,0]
assert sp.simplify(sp.Matrix.hstack(D12,D13)-target)==sp.zeros(2,2)
for u,v in product(basis,repeat=2):
    D=ndef(u,v)
    # Every defect is generated by those two columns.
    if u!=basis[0] and v!=basis[0]:
        assert sp.simplify(D)==sp.zeros(3,1)

def mv3(M,v,Q):
    return tuple(sum(M[3*i+j]*v[j] for j in range(3))%Q for i in range(3))

def brq(u,v,delta,Q):
    # normalized beta=1, gamma=delta
    return (
        0,
        delta*(u[0]*v[2]-u[2]*v[0])%Q,
        (u[0]*v[1]-u[1]*v[0])%Q,
    )

def is_nij(vals,delta,Q):
    xx,pp,qq,rr,ss=vals
    M=(xx,0,0,0,pp,qq,0,rr,ss)
    bas=((1,0,0),(0,1,0),(0,0,1))
    for u,v in product(bas,repeat=2):
        Nu,Nv=mv3(M,u,Q),mv3(M,v,Q)
        lhs=brq(Nu,Nv,delta,Q)
        a1=brq(Nu,v,delta,Q)
        a2=brq(u,Nv,delta,Q)
        a3=mv3(M,brq(u,v,delta,Q),Q)
        inside=tuple((a1[i]+a2[i]-a3[i])%Q for i in range(3))
        if lhs!=mv3(M,inside,Q):
            return False
    return True

def rank3(M,Q):
    A0=[list(M[3*i:3*i+3]) for i in range(3)]
    rr=0
    for c in range(3):
        piv=next((i for i in range(rr,3) if A0[i][c]%Q),None)
        if piv is None:
            continue
        A0[rr],A0[piv]=A0[piv],A0[rr]
        inv=pow(A0[rr][c],-1,Q)
        A0[rr]=[(z*inv)%Q for z in A0[rr]]
        for i in range(3):
            if i!=rr and A0[i][c]%Q:
                f=A0[i][c]%Q
                A0[i]=[(A0[i][j]-f*A0[rr][j])%Q for j in range(3)]
        rr+=1
    return rr

def split_union(vals,Q):
    xx,pp,qq,rr,ss=vals
    C0=(rr-qq)%Q==0 and (ss-pp)%Q==0
    k=(rr-qq)%Q
    Cp=((ss-pp-k)%Q==0 and (xx-(pp-qq))%Q==0)
    Cm=((ss-pp+k)%Q==0 and (xx-(pp+qq))%Q==0)
    return C0 or Cp or Cm

def centralizer(vals,delta,Q):
    xx,pp,qq,rr,ss=vals
    return (pp-ss)%Q==0 and (qq-delta*rr)%Q==0

cases=[(3,1,2),(5,1,2),(7,1,3)]
for Q,split_delta,nonsplit_delta in cases:
    split=[]
    nonsplit=[]
    for vals in product(range(Q),repeat=5):
        ds=is_nij(vals,split_delta,Q)
        dn=is_nij(vals,nonsplit_delta,Q)
        assert ds==split_union(vals,Q)
        assert dn==centralizer(vals,nonsplit_delta,Q)
        if ds:
            split.append(vals)
        if dn:
            nonsplit.append(vals)

    cs=Counter()
    for xx,pp,qq,rr,ss in split:
        M=(xx,0,0,0,pp,qq,0,rr,ss)
        cs[rank3(M,Q)]+=1
    expected_split=(
        1,
        (Q-1)*(2*Q+3),
        5*(Q-1)**2,
        3*(Q-1)**3,
    )
    assert tuple(cs[i] for i in range(4))==expected_split
    assert len(split)==3*Q**3-2*Q**2

    cn=Counter()
    for xx,pp,qq,rr,ss in nonsplit:
        M=(xx,0,0,0,pp,qq,0,rr,ss)
        cn[rank3(M,Q)]+=1
    expected_nonsplit=(
        1,
        Q-1,
        Q**2-1,
        (Q-1)*(Q**2-1),
    )
    assert tuple(cn[i] for i in range(4))==expected_nonsplit
    assert len(nonsplit)==Q**3

    parameter_total=(Q-1)**2*(len(split)+len(nonsplit))//2
    assert parameter_total==Q**2*(Q-1)**2*(2*Q-1)

    print({
        "q":Q,
        "split_count":len(split),
        "split_rank_profile":tuple(cs[i] for i in range(4)),
        "nonsplit_count":len(nonsplit),
        "nonsplit_rank_profile":tuple(cn[i] for i in range(4)),
        "nondegenerate_parameter_operator_triples":parameter_total,
    })

print("VERIFY_OK")
