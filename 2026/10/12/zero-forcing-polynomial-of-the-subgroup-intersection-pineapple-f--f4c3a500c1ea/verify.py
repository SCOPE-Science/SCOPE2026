#!/usr/bin/env python3
from itertools import combinations, product
from collections import Counter

def pineapple(p):
    # c = center; Q = noncentral clique vertices; L = pendant leaves.
    c=("c",0)
    Q=[("q",i) for i in range(p+1)]
    L=[("l",i) for i in range(p)]
    V=[c]+Q+L
    N={v:set() for v in V}
    clique=[c]+Q
    for x,y in combinations(clique,2):
        N[x].add(y); N[y].add(x)
    for l in L:
        N[c].add(l); N[l].add(c)
    return V,N,c,Q,L

def zero_forces(S,V,N):
    blue=set(S)
    while True:
        if len(blue)==len(V): return True
        move=None
        for v in V:
            if v in blue:
                white=N[v]-blue
                if len(white)==1:
                    move=next(iter(white)); break
        if move is None: return False
        blue.add(move)

def predicted_coeffs(p):
    # u^(2p-1)(u+p)(u+p+1)(u+1)
    roots=[p,p+1,1]
    coeff=[1]
    for a in roots:
        nxt=[0]*(len(coeff)+1)
        for i,c in enumerate(coeff):
            nxt[i]+=a*c
            nxt[i+1]+=c
        coeff=nxt
    return {2*p-1+i:c for i,c in enumerate(coeff)}

def check_abstract(p):
    V,N,c,Q,L=pineapple(p)
    poly=Counter()
    mins=[]
    for k in range(len(V)+1):
        for S in combinations(V,k):
            ok=zero_forces(S,V,N)
            W=set(V)-set(S)
            structural=(len(W&set(L))<=1 and len(W&set(Q))<=1)
            assert ok==structural,(p,S,W,ok,structural)
            if ok:
                poly[k]+=1
                if k==2*p-1: mins.append(set(S))
    assert dict(poly)==predicted_coeffs(p),(p,poly,predicted_coeffs(p))
    assert len(mins)==p*(p+1)
    for S in mins:
        W=set(V)-S
        assert c in W and len(W&set(L))==1 and len(W&set(Q))==1
    return dict(poly)

def add(x,y,p):
    return ((x[0]+y[0])%(p*p),(x[1]+y[1])%p)

def smul(a,x,p):
    return ((a*x[0])%(p*p),(a*x[1])%p)

def closure(gens,p):
    # additive subgroup generated by at most two generators
    out={(0,0)}
    for coeffs in product(range(p*p), repeat=len(gens)):
        x=(0,0)
        for a,g in zip(coeffs,gens):
            x=add(x,smul(a,g,p),p)
        out.add(x)
    return frozenset(out)

def actual_subgroups(p):
    elems=list(product(range(p*p),range(p)))
    subs={frozenset({(0,0)}),frozenset(elems)}
    for g in elems:
        subs.add(closure([g],p))
    for g,h in combinations(elems,2):
        subs.add(closure([g,h],p))
    proper=[H for H in subs if 1<len(H)<p**3]
    return elems,proper

def check_actual(p):
    elems,subs=actual_subgroups(p)
    assert len(subs)==2*p+2,(p,len(subs))
    byord=Counter(map(len,subs))
    assert byord==Counter({p:p+1,p*p:p+1}),(p,byord)

    E=frozenset(x for x in elems if smul(p,x,p)==(0,0))
    P=closure([(p,0)],p)
    assert len(E)==p*p and len(P)==p
    cyclic_p2=[]
    orderp=[]
    for H in subs:
        if len(H)==p:
            orderp.append(H)
        elif len(H)==p*p and H!=E:
            cyclic_p2.append(H)
    assert len(orderp)==p+1 and len(cyclic_p2)==p
    assert all(P < C for C in cyclic_p2)
    leaves=[H for H in orderp if H!=P]
    clique=[E,P]+cyclic_p2
    assert len(clique)==p+2 and len(leaves)==p
    one=frozenset({(0,0)})
    for A,B in combinations(clique,2):
        assert A&B != one
    for L in leaves:
        assert L&E != one
        for X in [P]+cyclic_p2+leaves:
            if X is L: continue
            assert L&X == one
    # degree signature of the intersection graph
    deg={}
    for H in subs:
        deg[H]=sum(1 for K in subs if K!=H and H&K!=one)
    assert deg[E]==2*p+1
    assert all(deg[L]==1 for L in leaves)
    assert all(deg[X]==p+1 for X in [P]+cyclic_p2)
    return byord, sorted(deg.values())

for p in [2,3,5,7]:
    poly=check_abstract(p)
    print(f"p={p}: abstract polynomial {poly}; minimum sets={p*(p+1)}")

for p in [2,3]:
    byord,degs=check_actual(p)
    print(f"p={p}: actual subgroup census {dict(byord)}; degrees={degs}")

print("VERIFY_OK")
