import sympy as sp
from itertools import product

# Symbolic structure and s-Rota-Baxter defects.
a,b,c,d,k,m = sp.symbols('a b c d k m')
R = sp.Matrix([[a,b],[c,d]])
alpha = sp.diag(k,1)
As = sp.diag(m,1)*R
E = [sp.Matrix([1,0]), sp.Matrix([0,1])]

def br(x,y):
    return sp.Matrix([sp.expand(x[0]*y[1]-x[1]*y[0]),0])

def tri(x,y,z):
    return sp.Matrix([sp.expand((x[0]*y[1]-x[1]*y[0])*z[1]),0])

def eq0(v):
    return all(sp.simplify(t)==0 for t in v)

# Verify the Hom-Lie-Yamaguti identities on basis vectors.
def al(x): return alpha*x
def al2(x): return alpha*alpha*x
for x,y in product(E, repeat=2):
    assert eq0(al(br(x,y))-br(al(x),al(y)))
for x,y,z in product(E, repeat=3):
    assert eq0(al(tri(x,y,z))-tri(al(x),al(y),al(z)))
    cyc = (br(br(x,y),al(z))+tri(x,y,z)
           +br(br(z,x),al(y))+tri(z,x,y)
           +br(br(y,z),al(x))+tri(y,z,x))
    assert eq0(cyc)
for x,y,z,h in product(E, repeat=4):
    cyc6 = (tri(br(x,y),al(z),al(h))
            +tri(br(z,x),al(y),al(h))
            +tri(br(y,z),al(x),al(h)))
    assert eq0(cyc6)
    lhs7 = tri(al(x),al(y),br(z,h))
    rhs7 = br(tri(x,y,z),al2(h))+br(al2(z),tri(x,y,h))
    assert eq0(lhs7-rhs7)
for a0,b0,x,y,z in product(E, repeat=5):
    lhs8 = tri(al2(a0),al2(b0),tri(x,y,z))
    rhs8 = (tri(tri(a0,b0,x),al2(y),al2(z))
            +tri(al2(x),tri(a0,b0,y),al2(z))
            +tri(al2(x),al2(y),tri(a0,b0,z)))
    assert eq0(lhs8-rhs8)

# R alpha = alpha R.
comm = sp.simplify(R*alpha-alpha*R)
assert sp.factor(comm[0,1]) == -b*(k-1)
assert sp.factor(comm[1,0]) == c*(k-1)

# Full s-Rota-Baxter defect.
def d2(x,y):
    return sp.simplify(br(R*x,R*y)-R*(br(As*x,y)+br(x,As*y)))

def d3(x,y,z):
    return sp.simplify(tri(R*x,R*y,R*z)-R*(tri(As*x,As*y,z)+tri(x,As*y,As*z)-tri(y,As*x,As*z)))

defects=[]
for x,y in product(E,repeat=2):
    defects += [sp.factor(t) for t in d2(x,y) if t!=0]
for x,y,z in product(E,repeat=3):
    defects += [sp.factor(t) for t in d3(x,y,z) if t!=0]

# Under k != 1, commutation forces b=c=0; then all defects are generated by m*a^2.
reduced=[sp.factor(t.subs({b:0,c:0})) for t in defects]
G=sp.groebner([m*a*a],a,d,m)
for t in reduced:
    assert t==0 or G.reduce(sp.expand(t))[1]==0
assert any(sp.factor(t-m*a*a)==0 or sp.factor(t+m*a*a)==0 for t in reduced)

# Descendent operations for a diagonal solution.
x,y,z=sp.symbols('x y z')
# On basis e1,e2 the only coefficients are ma+d and d^2+2mad.
Bdesc = (br(As*E[0],E[1])+br(E[0],As*E[1])).subs({b:0,c:0})
Tdesc = (tri(As*E[0],As*E[1],E[1])+tri(E[0],As*E[1],As*E[1])-tri(E[1],As*E[0],As*E[1])).subs({b:0,c:0})
assert sp.simplify(Bdesc-sp.Matrix([m*a+d,0]))==sp.zeros(2,1)
assert sp.simplify(Tdesc-sp.Matrix([2*m*a*d+d*d,0]))==sp.zeros(2,1)

# Exhaustive finite-field replay for representative nontrivial twists.
def mv(M,v,q):
    return ((M[0]*v[0]+M[1]*v[1])%q,(M[2]*v[0]+M[3]*v[1])%q)
def brq(x,y,q): return ((x[0]*y[1]-x[1]*y[0])%q,0)
def triq(x,y,z,q): return (((x[0]*y[1]-x[1]*y[0])*z[1])%q,0)
def alphaq(v,K,q): return (K*v[0]%q,v[1]%q)
def alpha_pow(v,K,S,q):
    M=pow(K,S,q) if S>0 else 1
    return (M*v[0]%q,v[1]%q)
def is_srb(M,K,S,q):
    bas=((1,0),(0,1))
    # commute
    for x in bas:
        if mv(M,alphaq(x,K,q),q)!=alphaq(mv(M,x,q),K,q): return False
    for x,y in product(bas,repeat=2):
        Rx,Ry=mv(M,x,q),mv(M,y,q)
        ARx,ARy=alpha_pow(Rx,K,S,q),alpha_pow(Ry,K,S,q)
        lhs=brq(Rx,Ry,q); p1=brq(ARx,y,q); p2=brq(x,ARy,q)
        inside=((p1[0]+p2[0])%q,(p1[1]+p2[1])%q)
        if lhs!=mv(M,inside,q): return False
    for x,y,z in product(bas,repeat=3):
        Rx,Ry,Rz=mv(M,x,q),mv(M,y,q),mv(M,z,q)
        ARx,ARy,ARz=alpha_pow(Rx,K,S,q),alpha_pow(Ry,K,S,q),alpha_pow(Rz,K,S,q)
        lhs=triq(Rx,Ry,Rz,q)
        p1=triq(ARx,ARy,z,q); p2=triq(x,ARy,ARz,q); p3=triq(y,ARx,ARz,q)
        inside=((p1[0]+p2[0]-p3[0])%q,(p1[1]+p2[1]-p3[1])%q)
        if lhs!=mv(M,inside,q): return False
    return True

for q in (5,7,11):
    for K,S,expected_dim in [(0,0,1),(0,1,2),(0,2,2),(2,0,1),(2,1,1),(2,2,1)]:
        # avoid K=2 becoming 1; q >=5.
        sols=[M for M in product(range(q),repeat=4) if is_srb(M,K,S,q)]
        pred=[]
        for aa,dd in product(range(q),repeat=2):
            if (pow(K,S,q) if S>0 else 1)*aa*aa%q==0:
                pred.append((aa,0,0,dd))
        assert set(sols)==set(pred)
        assert len(sols)==q**expected_dim
        print({'q':q,'k':K,'s':S,'count':len(sols)})

print('VERIFY_OK')
