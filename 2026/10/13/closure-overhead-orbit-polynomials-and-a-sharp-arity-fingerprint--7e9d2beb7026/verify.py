#!/usr/bin/env python3
"""Independent exact checks of bounded-arity meet-tree subset-orbit polynomials.

No external libraries. Two separate implementations: Pólya cycle-index formal
series and direct canonical enumeration of two-coloured finite rooted trees.
"""
from collections import Counter, defaultdict
from fractions import Fraction
from functools import lru_cache
import math

N = 6
TMAX = 2*N-1

# Sparse bivariate formal series in (marked vertices, unmarked vertices).
def plus(a,b):
    out=dict(a)
    for key, val in b.items():
        out[key]=out.get(key,0)+val
        if not out[key]: del out[key]
    return out

def scale(a,q):
    return {key:q*value for key,value in a.items() if value*q}

def mult(a,b):
    out=defaultdict(int)
    for (n,w),x in a.items():
        for (p,v),y in b.items():
            if n+p<=N and w+v<N and n+p+w+v<=TMAX:
                out[n+p,w+v] += x*y
    return {key:value for key,value in out.items() if value}

def shift(a,n,w):
    return {(p+n,v+w):x for (p,v),x in a.items()
            if p+n<=N and v+w<N and p+n+v+w<=TMAX}

def power_sub(a,j):
    return {(p*j,v*j):x for (p,v),x in a.items()
            if p*j<=N and v*j<N and j*(p+v)<=TMAX}

def cycle_index(F,K):
    # Exactly the multiset cycle-index recurrence E_j=(1/j) sum_{i=1}^j F(z^i,u^i)*E_(j-i).
    pieces=[{(0,0):Fraction(1)}]
    fj=[None]+[power_sub(F,j) for j in range(1,K+1)]
    for j in range(1,K+1):
        acc={}
        for i in range(1,j+1):
            acc=plus(acc,mult(fj[i],pieces[j-i]))
        pieces.append(scale(acc,Fraction(1,j)))
    result={}
    for E in pieces:
        result=plus(result,E)
    return result

def species_polynomial(k):
    K=min(k,N)
    F={}
    for t in range(TMAX+1):
        M=cycle_index(F,K)
        # F = z M + u(M - 1 - F)
        white=plus(plus(M,{(0,0):Fraction(-1)}),scale(F,-1))
        next_F=plus(shift(M,1,0),shift(white,0,1))
        if next_F==F:
            break
        F=next_F
    assert next_F==F, 'fixed point not stabilized'
    assert all(v.denominator==1 and v>0 for v in F.values())
    return {k:int(v) for k,v in F.items()}

# Direct rooted tree enumeration, with a canonical unordered tuple of subtrees.
# These objects are literally finite meet-closed structures on their marked nodes.
@lru_cache(None)
def stats(tree):
    c,children=tree
    n=1 if c==0 else 0
    w=0 if c==0 else 1
    for child in children:
        x,y=stats(child);n+=x;w+=y
    return n,w

@lru_cache(None)
def marked_lca_coverage(tree):
    # Every unmarked internal point must be the meet of two distinguished points.
    c,kids=tree
    if c==1 and len(kids)<2:return False
    if not kids: return c==0
    return all(marked_lca_coverage(kid) for kid in kids)

def explicit_trees():
    by_t={1:{(0,())}}
    alltrees={(0,())}
    counters=Counter()
    for t in range(2,TMAX+1):
        pool=sorted([tree for tree in alltrees if stats(tree)[0]+stats(tree)[1]<t],
                    key=lambda x:(stats(x)[0]+stats(x)[1],str(x)))
        candidates=[]
        max_k=N
        def rec(start,left,n_used,w_used,sub):
            if left==0:
                size=len(sub)
                if n_used+1<=N and w_used<N:
                    candidates.append((0,tuple(sorted(sub))))
                if size>=2 and n_used<=N and w_used+1<N:
                    candidates.append((1,tuple(sorted(sub))))
                return
            if len(sub)==max_k:return
            for j in range(start,len(pool)):
                kid=pool[j]
                kn,kw=stats(kid)
                length=kn+kw
                if length>left:continue
                if n_used+kn>N or w_used+kw>=N:continue
                rec(j,left-length,n_used+kn,w_used+kw,sub+[kid])
        rec(0,t-1,0,0,[])
        by_t[t]=set(candidates)
        assert len(by_t[t])==len(candidates), ('duplicate canonical code',t)
        for tree in by_t[t]:
            assert marked_lca_coverage(tree),('bad meet closure',tree)
        alltrees.update(by_t[t]);counters[t]=len(by_t[t])
    return alltrees,counters

def closure_by_pairwise_meets(tree):
    """Independently compute the meet-subsemilattice generated by marked nodes."""
    nodes=set()
    marked=[]
    def walk(subtree,path):
        nodes.add(path)
        if subtree[0]==0:
            marked.append(path)
        for index,child in enumerate(subtree[1]):
            walk(child,path+(index,))
    walk(tree,())
    generated=set()
    for a in marked:
        for b in marked:
            prefix=()
            for x,y in zip(a,b):
                if x!=y: break
                prefix+=(x,)
            generated.add(prefix)
    return generated==nodes

def maxchild(tree):
    _,children=tree
    return max([len(children)]+[maxchild(child) for child in children])

def main():
    shapes, counts=explicit_trees()
    for tree in shapes:
        assert closure_by_pairwise_meets(tree),('pairwise meet span not full',tree)
    print('Direct canonical enumeration: %d shapes on <=%d vertices' % (len(shapes), TMAX))
    assertions=len(shapes)
    results={}
    for k in range(1,N+1):
        brute=Counter(stats(t) for t in shapes if maxchild(t)<=k)
        gf=species_polynomial(k)
        keys=set(brute)|set(gf)
        for pair in keys:
            assert brute[pair]==gf.get(pair,0),(k,pair,brute[pair],gf.get(pair,0))
            assertions+=1
        results[k]=brute
    inf=results[N]
    # Unrestricted sequence is the published rooted-Greg-tree OEIS A052300.
    expected=[1,2,6,21,78,313]
    totals=[sum(value for (p,w),value in inf.items() if p==n) for n in range(1,N+1)]
    assert totals==expected,(totals,expected);assertions+=N
    # Sharp first arity signature: k vs unrestricted first differs at n=k+1,
    # by exactly the single (k+1)-fan with unmarked root, overhead 1.
    for k in range(1,N):
        for n in range(1,k+1):
            assert all(results[k].get((n,w),0)==inf.get((n,w),0) for w in range(n))
            assertions+=n
        for w in range(k+1):
            diff=inf.get((k+1,w),0)-results[k].get((k+1,w),0)
            assert diff==(1 if w==1 else 0),(k,w,diff)
            assertions+=1
    # Each overhead 0<=w<=n-1 is realized for all binary-and-above models.
    for k in range(2,N+1):
        for n in range(1,N+1):
            for w in range(n):
                assert results[k].get((n,w),0)>0,(k,n,w)
                assertions+=1
            assert all(results[k].get((n,w),0)==0 for w in range(n,N));assertions+=1
    # Endpoint = rooted unordered marked trees (all black), and full binary
    # trees counted by Wedderburn-Etherington at maximum overhead.
    we=[1,1,1,2,3,6] # n=1 through n=6
    rooted=[1,1,2,4,9,20]
    for n in range(1,N+1):
        assert inf[(n,0)]==rooted[n-1];assertions+=1
        assert inf[(n,n-1)]==we[n-1];assertions+=1
    print('GF and direct n,w,k census: VERIFIED for k<=6, n<=6')
    for k in (1,2,3,6):
        print('k=%s totals=%s'%(('infinity' if k==6 else k), [sum(v for (p,w),v in results[k].items() if p==n) for n in range(1,N+1)]))
    for n in range(1,7):
        print('unrestricted n=%d: '%n+str([inf.get((n,w),0) for w in range(n)]))
    print('VERIFY_OK %d exact coefficient and combinatorial assertions; %d independent rooted shapes; %d arities'%(assertions,len(shapes),N))
if __name__=='__main__':main()
