#!/usr/bin/env python3
from itertools import product, combinations

# GF(9)=F_3[u]/(u^2+1), encoded a+3b for a+bu; u^2=2.
def add(x,y): return ((x%3+y%3)%3)+3*((x//3+y//3)%3)
def mul(x,y):
    a,b=x%3,x//3; c,d=y%3,y//3
    return ((a*c+2*b*d)%3)+3*((a*d+b*c)%3)
def neg(x): return ((-x%3)%3)+3*((-(x//3))%3)
def sub(x,y): return add(x,neg(y))
def inv(x):
    assert x
    for y in range(1,9):
        if mul(x,y)==1: return y
    raise AssertionError

def smul(a,v): return (mul(a,v[0]),mul(a,v[1]))
def vadd(v,w): return (add(v[0],w[0]),add(v[1],w[1]))

def det(v,w): return sub(mul(v[0],w[1]),mul(v[1],w[0]))

# Four F_3-projective directions, each repeated twice.
dirs=[(1,0),(0,1),(1,1),(1,2)]
H=[d for d in dirs for _ in range(2)]

# Base ternary dual generated by H is [8,2,6]_3.
weights=[]
for a,b in product(range(3), repeat=2):
    if a==b==0: continue
    word=[(a*h[0]+b*h[1])%3 for h in H]
    weights.append(sum(x!=0 for x in word))
assert weights==[6]*8, weights

# Every pair of distinct directions is a basis over every extension field.
for v,w in combinations(dirs,2):
    assert det(v,w) in (1,2)
assert len(list(combinations(range(4),2)))*2*2==24

# Exhaustive GF(9) anchor: all deep syndromes have no weight-1 leader
# and exactly 24 weight-2 leaders.
lines=set()
for d in dirs:
    for a in range(1,9): lines.add(smul(a,d))
assert len(lines)==4*(9-1)
all_nonzero=[v for v in product(range(9), repeat=2) if v!=(0,0)]
deep=[v for v in all_nonzero if v not in lines]
assert len(deep)==80-32==48

for s in deep:
    one=0
    for j,h in enumerate(H):
        for a in range(1,9):
            if smul(a,h)==s: one+=1
    assert one==0
    two=0
    supports=set()
    for i,j in combinations(range(8),2):
        for a in range(1,9):
            ah=smul(a,H[i])
            for b in range(1,9):
                if vadd(ah,smul(b,H[j]))==s:
                    two+=1; supports.add((i,j))
    assert two==24, (s,two)
    assert len(supports)==24

print('VERIFY_OK')
