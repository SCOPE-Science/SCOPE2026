#!/usr/bin/env python3
"""Full independent enumeration of seven-symbol binary one-deletion/one-adjacent-swap codes.

Each compatible pair has disjoint one-deletion and at-most-one-swap output sets.
The depth-first clique search uses a proper greedy coloring upper bound; it does
not assume either the optimum or the number of optima in its search logic.
"""
from collections import Counter
from itertools import combinations
from pathlib import Path

N = 7
WORDS = [''.join(map(str, ((i >> j) & 1 for j in range(N - 1, -1, -1))))
         for i in range(1 << N)]
INDEX = {w: i for i, w in enumerate(WORDS)}

def delete_once(word):
    return {word[:i] + word[i + 1:] for i in range(N)}

def swap_at_most_once(word):
    out = {word}
    for i in range(N - 1):
        out.add(word[:i] + word[i + 1] + word[i] + word[i + 2:])
    return out

DEL = list(map(delete_once, WORDS))
SWAP = list(map(swap_at_most_once, WORDS))
ADJ = [0] * len(WORDS)
for a, b in combinations(range(len(WORDS)), 2):
    if DEL[a].isdisjoint(DEL[b]) and SWAP[a].isdisjoint(SWAP[b]):
        ADJ[a] |= 1 << b
        ADJ[b] |= 1 << a

# A color class is an independent set.  Each clique can use at most one member
# per color class, hence the greedy color count bounds clique extension size.
def color_sort(mask):
    vertices, upper = [], []
    remainder, color = mask, 0
    while remainder:
        color += 1
        independent = remainder
        while independent:
            low = independent & -independent
            v = low.bit_length() - 1
            vertices.append(v)
            upper.append(color)
            remainder ^= low
            independent ^= low
            independent &= ~ADJ[v]
    return vertices, upper

optimum = 0
codes = []
visited = 0

def search(candidates, chosen):
    global optimum, codes, visited
    visited += 1
    if not candidates:
        k = len(chosen)
        code = tuple(sorted(chosen))
        if k > optimum:
            optimum, codes = k, [code]
        elif k == optimum:
            codes.append(code)
        return
    vertices, upper = color_sort(candidates)
    for pos in range(len(vertices) - 1, -1, -1):
        if len(chosen) + upper[pos] < optimum:
            break
        v = vertices[pos]
        search(candidates & ADJ[v], chosen + (v,))
        candidates &= ~(1 << v)

search((1 << len(WORDS)) - 1, ())
assert optimum == 16, optimum
assert len(codes) == 28 and len(set(codes)) == 28

# The four symbol symmetries are generated by word reversal and complementation.
def transform(word, reversal, complement):
    y = word[::-1] if reversal else word
    return ''.join('0' if c == '1' else '1' for c in y) if complement else y

def image(code, reversal, complement):
    return tuple(sorted(INDEX[transform(WORDS[i], reversal, complement)]
                        for i in code))

unseen = set(codes)
orbit_sizes = Counter()
rows = []
while unseen:
    seed = min(unseen)
    orbit = {image(seed, r, c) for r in range(2) for c in range(2)}
    assert orbit <= set(codes)
    assert len(orbit) in (1, 2, 4)
    unseen -= orbit
    orbit_sizes[len(orbit)] += 1
    rows.append((len(orbit), min(orbit)))
rows.sort(key=lambda t: t[1])
assert orbit_sizes == Counter({4: 6, 2: 2}), orbit_sizes
assert len(rows) == 8

# This table is itself verification evidence.  The input paths are derived from
# this file's actual runtime location, not from other packages or prior output.
table = Path(__file__).resolve().with_name('representatives.tsv')
actual = [(int(line.split('\t')[0]),
           tuple(sorted(INDEX[s] for s in line.rstrip('\n').split('\t')[1].split(' '))))
          for line in table.read_text(encoding='utf-8').splitlines()
          if line and not line.startswith('#')]
assert actual == rows, (actual, rows)

# Every VT residue class has exactly 16 words, but no such class corrects this
# mixed channel.  This is not used as an assumption in the enumeration.
vt = [tuple(i for i, word in enumerate(WORDS)
            if sum((j + 1) * int(bit) for j, bit in enumerate(word)) % 8 == a)
      for a in range(8)]
assert all(len(class_) == 16 for class_ in vt)
assert all(not all(ADJ[u] >> v & 1 for u, v in combinations(class_, 2))
           for class_ in vt)

# A witness pair within each VT syndrome class and its common transposition
# output are provided independently of the clique enumeration.
witness_table = Path(__file__).resolve().with_name('vt_obstructions.tsv')
witnesses = [line.split('\t') for line in witness_table.read_text(encoding='utf-8').splitlines()
             if line and not line.startswith('#')]
assert len(witnesses) == 8
for residue, (a, x, y, z) in enumerate(witnesses):
    assert int(a) == residue and x != y
    assert x in (WORDS[i] for i in vt[residue])
    assert y in (WORDS[i] for i in vt[residue])
    assert z in swap_at_most_once(x) and z in swap_at_most_once(y)

print(f'VERIFY_OK optimum={optimum} labeled={len(codes)} orbit_sizes={dict(sorted(orbit_sizes.items()))} '
      f'classes={len(rows)} VT_classes_failing={len(vt)} nodes={visited}')
