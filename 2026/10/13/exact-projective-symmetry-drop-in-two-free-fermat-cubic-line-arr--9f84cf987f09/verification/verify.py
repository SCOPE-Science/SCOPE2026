#!/usr/bin/env python3
# Exact finite replay for the projective monomial normal forms in the proof.
from itertools import product

F3=range(3)
# Canonical projective representatives: z-exponent normalized to 0.
G=[(s,a,b) for s in (0,1) for a in F3 for b in F3]
assert len(G)==18

# Pullback action on line L_k: x + omega^k y = 0.
def line_perm(g):
    s,a,b=g
    if s==0:
        return tuple((k+b-a)%3 for k in F3)
    return tuple((a-b-k)%3 for k in F3)

perms={line_perm(g) for g in G}
assert len(perms)==6
kernel=[g for g in G if line_perm(g)==(0,1,2)]
assert len(kernel)==3
assert set(kernel)=={(0,0,0),(0,1,1),(0,2,2)}

# Complement generated by r=diag(omega,omega^-1,1) and s=swap.
def compose(g,h):
    # Return canonical form for g after h.
    sg,a,b=g; sh,c,d=h
    if sg==0 and sh==0: return (0,(a+c)%3,(b+d)%3)
    if sg==0 and sh==1: return (1,(a+c)%3,(b+d)%3)
    if sg==1 and sh==0: return (1,(a+d)%3,(b+c)%3)
    return (0,(a+d)%3,(b+c)%3)

def invpow(g,n):
    e=(0,0,0)
    for _ in range(n): e=compose(e,g)
    return e
r=(0,1,2); s=(1,0,0); e=(0,0,0)
assert invpow(r,3)==e and invpow(s,2)==e
assert compose(compose(s,r),s)==(0,2,1)  # r^{-1}
comp={e,r,compose(r,r),s,compose(r,s),compose(compose(r,r),s)}
assert len(comp)==6 and comp.intersection(kernel)=={e}

# D7 requires preservation of y+z=0. In canonical forms this means
# diagonal with b=0; no anti-diagonal form can preserve that line.
D7=[g for g in G if g[0]==0 and g[2]==0]
assert D7==[(0,0,0),(0,1,0),(0,2,0)]

print('VERIFY_OK D6_order=18 D6_group=C3xS3 line_action_order=6 line_kernel_order=3 D7_order=3 D7_group=C3')
