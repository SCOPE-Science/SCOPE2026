#!/usr/bin/env python3
import sympy as sp
from itertools import combinations

a,b,c=sp.symbols('a b c')
u=[
 a**2*(5*c**3-a**3),
 b**2*(b**3-5*c**3),
 c**2*(c**3-5*a**3),
 c**2*(5*b**3-c**3),
 5*b**2*(a**3-c**3),
 5*a**2*(c**3-b**3),
]
J=sp.Matrix([[sp.diff(f,v) for f in u] for v in (a,b,c)])
mins3=[]
for I in combinations(range(6),3):
    d=sp.factor(J[:,I].det())
    if d!=0: mins3.append((I,d))
g=None
for _,d in mins3:
    g=d if g is None else sp.gcd(g,d)
g=sp.factor(g)
assert sp.factor(g/(a*b*c)).is_Rational and sp.factor(g/(a*b*c)) != 0
# Three selected minors rule out any further common zero on abc != 0.
d023=sp.factor(dict(mins3)[(0,2,3)]/(a*b*c))
d123=sp.factor(dict(mins3)[(1,2,3)]/(a*b*c))
d034=sp.factor(dict(mins3)[(0,3,4)]/(a*b*c))
assert sp.factor(d023 - (-750*b*c**2*(a**3+c**3)**2))==0
assert sp.factor(d123 - (750*a*c**2*(b**3+c**3)**2))==0
R=sp.factor(d034/250)
expected=2*a**6*b**3-a**6*c**3-15*a**3*b**3*c**3+3*a**3*c**6-5*b**3*c**6-2*c**9
assert sp.factor(R-expected)==0
assert sp.expand(expected.subs({a**3:-c**3,b**3:-c**3})) == -18*c**9
# Rank on coordinate triangle: gcd of all 2x2 minors after restriction.
def gcd2_on(subs, vars2, expected_g):
    M=J.subs(subs)
    ds=[]
    for rows in combinations(range(3),2):
        for cols in combinations(range(6),2):
            d=sp.factor(M.extract(rows,cols).det())
            if d!=0: ds.append(d)
    gg=None
    for d in ds: gg=d if gg is None else sp.gcd(gg,d)
    gg=sp.factor(gg)
    assert sp.factor(gg/expected_g) in (1,-1,2,-2,5,-5,10,-10,25,-25,50,-50)
    # Normalize to monic up to Q*; only support matters.
    assert sp.factor(gg/expected_g).is_Rational
    return gg

ga=gcd2_on({a:0},(b,c),b*c)
gb=gcd2_on({b:0},(a,c),a*c)
gc=gcd2_on({c:0},(a,b),a*b)
# Jacobian ranks at vertices: projective differential rank is one less by Euler.
verts=[{a:1,b:0,c:0},{a:0,b:1,c:0},{a:0,b:0,c:1}]
assert [J.subs(v).rank() for v in verts]==[1,1,1]
# Generic cusp charts. We verify that in each axis chart two coordinates recover
# tangent t and y=x^3 formally, while another is a unit times x^2.
x,t,y=sp.symbols('x t y')
def repl_y(expr):
    num,den=sp.together(expr).as_numer_denom()
    def r(p):
        p=sp.Poly(sp.expand(p),x)
        out=0
        for (k,),coef in p.terms():
            out += coef*x**(k%3)*y**(k//3)
        return sp.expand(out)
    return sp.cancel(r(num)/r(den))

def chart(subs,den_index,pair,x2_index,expected_det0):
    us=[sp.expand(f.subs(subs)) for f in u]
    vs=[repl_y(sp.cancel(f/us[den_index])) for f in us]
    # Every affine coordinate belongs to Q(t,y)[x^2], so formally the image
    # is contained in the subring generated by t, y=x^3 and x^2.
    for vv in vs:
        nn,dd=sp.together(vv).as_numer_denom()
        for pp in (nn,dd):
            exps={k[0] for k,_ in sp.Poly(sp.expand(pp),x).terms()}
            assert exps.issubset({0,2})
    i,j=pair
    assert not vs[i].has(x) and not vs[j].has(x)
    det=sp.factor(sp.det(sp.Matrix([[sp.diff(vs[i],t),sp.diff(vs[i],y)],
                                    [sp.diff(vs[j],t),sp.diff(vs[j],y)]])))
    det0=sp.factor(det.subs(y,0))
    assert sp.factor(det0/expected_det0)==1
    w=sp.factor(vs[x2_index]/x**2)
    w0=sp.factor(w.subs({x:0,y:0}))
    assert w0!=0
    return det0,w0
# a=0, c=1; use u3 chart; v4,v5 recover t,y; v1 gives x^2.
da,wa=chart({a:x,b:t,c:1},2,(3,4),0,-50*t*(t+1)*(t**2-t+1))
# b=0, a=1; use u6 chart; v1,v4 recover t,y; v2 gives x^2.
db,wb=chart({a:1,b:x,c:t},5,(0,3),1,2*(t+1)*(t**2-t+1)/(5*t**5))
# c=0, b=1; use u2 chart; v5,v6 recover t,y; v3 gives x^2.
dc,wc=chart({a:t,b:1,c:x},1,(4,5),2,-50*t*(t+1)*(t**2-t+1))
print('VERIFY_OK nonimmersive=abc=0 vertex_projective_rank=0 generic_cusp=C[[t,x^2,x^3]] exceptions=t^3+1=0 axis_gcds=%s,%s,%s' % (ga,gb,gc))
