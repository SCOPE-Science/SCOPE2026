#!/usr/bin/env python3
"""Exact finite symbolic checks of hollow symmetric rank-two projective charts.

Only finite checks; the universal theorem is proved algebraically in RESULT.md.
Requires Python >=3.9 and sympy.
"""
from itertools import combinations
from math import comb, factorial
import sympy as sp


def check_n(n):
    m = n - 2
    u = sp.symbols('u0:'+str(m))
    v = sp.symbols('v0:'+str(m))
    M = sp.zeros(n)
    M[0, 1] = M[1, 0] = sp.Integer(1)
    for i in range(m):
        M[0, i+2] = M[i+2, 0] = u[i]
        M[1, i+2] = M[i+2, 1] = v[i]
        for j in range(i):
            M[i+2,j+2] = M[j+2,i+2] = u[i]*v[j] + v[i]*u[j]
    # Check all 3x3 minors vanish modulo the squarefree edge products u_i*v_i.
    ringvars = tuple(u) + tuple(v)
    minors = 0
    for rows in combinations(range(n), 3):
        for cols in combinations(range(n), 3):
            expr = sp.Poly(M.extract(rows,cols).det(method='berkowitz'), *ringvars)
            for exponents, coefficient in expr.terms():
                if coefficient == 0:
                    continue
                if not any(exponents[i] and exponents[m+i] for i in range(m)):
                    raise AssertionError((n,rows,cols,exponents,coefficient))
            minors += 1
    # Each product relation is explicitly a pivot 3x3 principal minor divided by 2.
    for i in range(m):
        assert sp.expand(M.extract([0,1,2+i],[0,1,2+i]).det() - 2*u[i]*v[i]) == 0
    # The chart ideal generated by all minors therefore equals (u_i*v_i).
    return minors


for n in range(3,7):
    print('n=%d: %d 3x3 minors vanish modulo squarefree nodes; %d node generators recovered' %
          (n,check_n(n),n-2))
for n in range(3,12):
    deg = sum(comb(n,a)*comb(n-2,a-1) for a in range(1,n))//2
    expected = comb(2*n-2,n-1)//2
    assert deg == expected
    print('n=%d: components=%d, total_degree=%d, maximum_local_multiplicity=%d' %
          (n, 2**(n-1)-1, deg, 2**(n-2)))
print('CHECK_OK')
