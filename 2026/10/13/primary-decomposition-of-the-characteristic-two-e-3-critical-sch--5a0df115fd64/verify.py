#!/usr/bin/env python3
"""Exact GF(2) verification of the four-axis primary decomposition."""

from itertools import combinations

# A polynomial over GF(2) is a frozenset of exponent tuples with coefficient 1.
def p_add(a, b):
    return a ^ b

def m_mul(a, b):
    return tuple(x + y for x, y in zip(a, b))

def mon_poly(m):
    return frozenset((m,))

def p_mul(a, b):
    out = set()
    for ma in a:
        for mb in b:
            mm = m_mul(ma, mb)
            if mm in out:
                out.remove(mm)
            else:
                out.add(mm)
    return frozenset(out)

def m_divides(a, b):
    return all(x <= y for x, y in zip(a, b))

def m_quot(b, a):
    return tuple(y - x for x, y in zip(a, b))

def lead(p):
    return max(p)  # lexicographic order on exponent tuples

def reduce_poly(f, G):
    p = set(f)
    r = set()
    while p:
        lm = max(p)
        reducer = None
        for g in G:
            if g and m_divides(lead(g), lm):
                reducer = g
                break
        if reducer is None:
            p.remove(lm)
            if lm in r:
                r.remove(lm)
            else:
                r.add(lm)
        else:
            q = m_quot(lm, lead(reducer))
            p ^= set(p_mul(mon_poly(q), reducer))
    return frozenset(r)

def spol(f, g):
    lf, lg = lead(f), lead(g)
    lcm = tuple(max(a, b) for a, b in zip(lf, lg))
    return p_add(
        p_mul(mon_poly(m_quot(lcm, lf)), f),
        p_mul(mon_poly(m_quot(lcm, lg)), g),
    )

def groebner(gens):
    G = [frozenset(g) for g in gens if g]
    pairs = {(i, j) for i in range(len(G)) for j in range(i)}
    while pairs:
        i, j = pairs.pop()
        s = reduce_poly(spol(G[i], G[j]), G)
        if s:
            k = len(G)
            G.append(s)
            for h in range(k):
                pairs.add((k, h))
    changed = True
    while changed:
        changed = False
        new = []
        for i, g in enumerate(G):
            others = [h for j, h in enumerate(G) if j != i]
            rg = reduce_poly(g, others)
            if not rg:
                changed = True
            else:
                new.append(rg)
                if rg != g:
                    changed = True
        uniq = []
        for g in new:
            if g not in uniq:
                uniq.append(g)
        G = uniq
    return sorted(G, key=lead, reverse=True)

def var_poly(n, i):
    e = [0] * n
    e[i] = 1
    return mon_poly(tuple(e))

def const_poly(n):
    return mon_poly((0,) * n)

def poly_from_monomial_index_lists(n, monomials):
    p = frozenset()
    for inds in monomials:
        e = [0] * n
        for i in inds:
            e[i] += 1
        p = p_add(p, mon_poly(tuple(e)))
    return p

def lift4(p):
    return frozenset((0,) + m for m in p)

def drop_z(p):
    return frozenset(m[1:] for m in p)

def intersection(A, B):
    # Elimination formula in characteristic two:
    # A cap B = (z A + (1+z) B) cap GF(2)[x1,x2,x3,x4].
    z = var_poly(5, 0)
    one_plus_z = p_add(const_poly(5), z)
    gens = [p_mul(z, lift4(a)) for a in A]
    gens += [p_mul(one_plus_z, lift4(b)) for b in B]
    G = groebner(gens)
    elim = [drop_z(g) for g in G if all(m[0] == 0 for m in g)]
    return groebner(elim)

def membership(poly, G):
    return reduce_poly(poly, G) == frozenset()

def fmt_mon(m):
    names = ["x1", "x2", "x3", "x4"]
    pieces = []
    for name, e in zip(names, m):
        if e == 1:
            pieces.append(name)
        elif e > 1:
            pieces.append(f"{name}^{e}")
    return "1" if not pieces else "*".join(pieces)

def fmt_poly(p):
    return " + ".join(fmt_mon(m) for m in sorted(p, reverse=True)) if p else "0"

n = 4
x = [var_poly(n, i) for i in range(n)]

def lin(i, j):
    return p_add(x[i], x[j])

def sq(i):
    return p_mul(x[i], x[i])

# Partial derivatives of e3 in characteristic two.
f1 = poly_from_monomial_index_lists(n, [(1, 2), (1, 3), (2, 3)])
f2 = poly_from_monomial_index_lists(n, [(0, 2), (0, 3), (2, 3)])
f3 = poly_from_monomial_index_lists(n, [(0, 1), (0, 3), (1, 3)])
f4 = poly_from_monomial_index_lists(n, [(0, 1), (0, 2), (1, 2)])
e3 = poly_from_monomial_index_lists(n, [(0, 1, 2), (0, 1, 3), (0, 2, 3), (1, 2, 3)])

GI = groebner([f1, f2, f3])
assert membership(f4, GI), "fourth derivative is not generated by first three"
assert membership(e3, GI), "Euler relation failed: e3 should lie in gradient ideal"

Q1 = groebner([lin(1, 3), lin(2, 3), sq(3)])
Q2 = groebner([lin(0, 3), lin(2, 3), sq(3)])
Q3 = groebner([lin(0, 3), lin(1, 3), sq(3)])
Q4 = groebner([lin(0, 2), lin(1, 2), sq(2)])
Qs = [Q1, Q2, Q3, Q4]

for idx, Q in enumerate(Qs, 1):
    for f in (f1, f2, f3):
        assert membership(f, Q), f"I is not contained in Q{idx}"

J = Q1
for Q in (Q2, Q3, Q4):
    J = intersection(J, Q)

assert J == GI, "intersection of the four primary components differs from I"

print("gradient_generators=3")
print("fourth_derivative_reduces_to_zero=yes")
print("e3_reduces_to_zero=yes")
print("primary_components=4")
for i, Q in enumerate(Qs, 1):
    print(f"Q{i}_groebner=" + " ; ".join(fmt_poly(p) for p in Q))
print("intersection_groebner=" + " ; ".join(fmt_poly(p) for p in J))
print("ideal_equality=I_intersection_Q1_Q2_Q3_Q4")
print("VERIFY_OK")
