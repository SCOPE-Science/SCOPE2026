#!/usr/bin/env python3
"""Standalone checks for sparse generators of cyclic three-agent S5 frames.

Only Python standard library. No external data or files are needed.
"""
from itertools import combinations
from math import ceil, log2


def modal_partition(n, marked, three=True):
    """Direct depth-by-depth modal type signatures (ordinary SET semantics)."""
    N = n*n
    colors = [int((i,j) in marked) for i in range(n) for j in range(n)]
    trace = [len(set(colors))]
    for _ in range(4*n+8):
        x_sets = [frozenset(colors[i*n+j] for j in range(n)) for i in range(n)]
        y_sets = [frozenset(colors[i*n+j] for i in range(n)) for j in range(n)]
        d_sets = [frozenset(colors[i*n+j] for i in range(n) for j in range(n)
                            if (i+j)%n == d) for d in range(n)] if three else None
        sig = [(colors[i*n+j], x_sets[i], y_sets[j],
                d_sets[(i+j)%n] if three else ())
               for i in range(n) for j in range(n)]
        ident = {x: k for k,x in enumerate(sorted(set(sig), key=repr))}
        new = [ident[x] for x in sig]
        trace.append(len(ident))
        if new == colors or trace[-1] == trace[-2]:
            return trace
        colors = new
    raise AssertionError('Partition refinement did not stabilize')


def direct_closure(n, marked, three=True):
    """Independent Boolean-set saturation using integer masks; only small n."""
    N=n*n
    full=(1<<N)-1
    m=sum(1<<(i*n+j) for i,j in marked)
    # Build an entire Boolean algebra by repeatedly refining atoms by
    # actually computed modal image sets, rather than using modal types.
    family={0,full,m,full^m}
    while True:
        # Atom partition generated by current Boolean sets.
        fs=tuple(sorted(family))
        signatures={}
        for k in range(N):
            sig=tuple((z>>k)&1 for z in fs)
            signatures.setdefault(sig,0)
            signatures[sig]|=1<<k
        atoms=list(signatures.values())
        generated={0}
        for a in atoms:
            generated |= {z|a for z in list(generated)}
        assert len(generated)<=1<<N
        fam_new=set(generated)
        for s in generated:
            for mode in range(3 if three else 2):
                image=0
                for i in range(n):
                    for j in range(n):
                        seen=False
                        if mode==0:
                            seen=any(s&(1<<(i*n+k)) for k in range(n))
                        elif mode==1:
                            seen=any(s&(1<<(k*n+j)) for k in range(n))
                        else:
                            seen=any(s&(1<<(k*n+((i+j-k)%n))) for k in range(n))
                        if seen: image|=1<<(i*n+j)
                fam_new.add(image)
        if fam_new == family: return len(generated),atoms
        family=fam_new


def constructive_lines(n):
    """Verify the explicit line-by-line definability induction using actual sets."""
    assert n>=3
    W={(x,y) for x in range(n) for y in range(n)}
    P={(0,0),(1,0),(0,1)}
    def diamond(s,mode):
        if mode=='x':
            xs={u for u,v in s}
            return {(u,v) for u,v in W if u in xs}
        if mode=='y':
            ys={v for u,v in s}
            return {(u,v) for u,v in W if v in ys}
        if mode=='d':
            ds={(u+v)%n for u,v in s}
            return {(u,v) for u,v in W if (u+v)%n in ds}
        raise ValueError(mode)
    xp=diamond(P,'x'); yp=diamond(P,'y')
    pivot=(xp & yp)-P
    assert pivot=={(1,1)}
    X={1:diamond(pivot,'x')}
    Y={1:diamond(pivot,'y')}
    X[0]=xp-X[1]
    Y[0]=yp-Y[1]
    for k in (0,1):
        assert X[k]=={(k,j) for j in range(n)}
        assert Y[k]=={(i,k) for i in range(n)}
    depth=2
    top=1
    while top<n-1:
        nxt=min(n-1,2*top)
        new_x,new_y={},{}
        for s in range(top+1,nxt+1):
            a=min(s,top)
            b=s-a
            assert a in X and b in Y
            dline=diamond(X[a]&Y[b],'d')
            assert dline=={(i,j) for i,j in W if (i+j)%n==s}
            new_x[s]=diamond(dline&Y[0],'x')
            new_y[s]=diamond(dline&X[0],'y')
            assert new_x[s]=={(s,j) for j in range(n)}
            assert new_y[s]=={(i,s) for i in range(n)}
        X.update(new_x);Y.update(new_y)
        top=nxt;depth+=2
    for i in range(n):
        for j in range(n): assert X[i]&Y[j]=={(i,j)}
    bound=2+2*ceil(log2(n-1))
    assert depth<=bound
    return depth


def run():
    direct_cases=0
    # Full closure for all valuations on n=2; distinguish no markers, one marker.
    for mask in range(1<<4):
        P={(i,j) for i in range(2) for j in range(2) if mask & (1<<(i*2+j))}
        size,atoms=direct_closure(2,P)
        assert size == 2**modal_partition(2,P,three=True)[-1]
        if len(P)==1: assert size==16
        direct_cases+=1
    # Exhaustively check the lower-bound support sizes at n=3 with direct
    # Boolean-algebra saturation, plus the L-shaped three-marker witness.
    for k in range(3):
        for indices in combinations(range(9),k):
            P={(z//3,z%3) for z in indices}
            size,atoms=direct_closure(3,P)
            assert size<2**9
            assert size == 2**modal_partition(3,P,three=True)[-1]
            direct_cases+=1
    n3={(0,0),(1,0),(0,1)}
    assert direct_closure(3,n3)[0] == 2**9
    direct_cases+=1
    # Prove the reflection is an actual nontrivial valuation automorphism on
    # small cyclic frames for every zero-, one-, and two-mark subset.
    reflection_checks=0
    for n in range(3,10):
        W=[(i,j) for i in range(n) for j in range(n)]
        for k in range(3):
            for points in combinations(W,k):
                if not points: continue
                if k==1:
                    a=tuple((2*v)%n for v in points[0])
                else:
                    a=tuple((points[0][z]+points[1][z])%n for z in (0,1))
                f=lambda x: ((a[0]-x[0])%n,(a[1]-x[1])%n)
                assert set(map(f,points))==set(points)
                assert any(f(x)!=x for x in W)
                reflection_checks+=1
    constructive_cases=0
    partition_cases=0
    for n in range(3,65):
        d=constructive_lines(n)
        constructive_cases+=1
        if n<=60:
            tr=modal_partition(n,{(0,0),(1,0),(0,1)},three=True)
            assert tr[-1]==n*n
            # The constructive formulas give a valid, though not necessarily
            # sharp, logarithmic stabilization upper bound.
            assert len(tr)-2 <= d
            partition_cases+=1
    # For two modalities, fewer than n-1 marks leave two completely
    # unmarked x-columns (or rows) and cannot generate the full algebra.
    two_modal_cases=0
    for n in range(3,6):
        W=[(i,j) for i in range(n) for j in range(n)]
        for k in range(n-1):
            for P in combinations(W,k):
                assert modal_partition(n,P,three=False)[-1] <n*n
                two_modal_cases+=1
    print('VERIFY_OK', 'direct_boolean_closures',direct_cases,
          'reflection_checks',reflection_checks,
          'three_modal_constructive_sizes',constructive_cases,
          'three_modal_partition_sizes',partition_cases,
          'two_modal_sparse_cases',two_modal_cases)
if __name__=='__main__':run()
