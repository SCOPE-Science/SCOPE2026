static inline bool has_period_suffix(const string& s, int L, int p){
    int st=(int)s.size()-L;
    for(int i=0;i<L-p;i++) if(s[st+i]!=s[st+i+p]) return false;
    return true;
}
static bool append_ok_7_4(const string& s, char c){
    string t=s; t.push_back(c);
    int n=t.size();
    for(int L=2;L<=n;L++){
        int maxp=(4*L)/7;
        for(int p=1;p<=maxp;p++) if(has_period_suffix(t,L,p)) return false;
    }
    return true;
}
static int d3(const string& s, vector<string>* D=nullptr){
    bool p2[4][4]{}; bool p3[4][4][4]{};
    for(int i=0;i+1<(int)s.size();i++) p2[s[i]-'0'][s[i+1]-'0']=1;
    for(int i=0;i+2<(int)s.size();i++) p3[s[i]-'0'][s[i+1]-'0'][s[i+2]-'0']=1;
    int d=0;
    if(D) D->clear();
    for(int a=0;a<4;a++) for(int b=0;b<4;b++) for(int c=0;c<4;c++)
        if(p2[a][b] && p2[b][c] && !p3[a][b][c]){
            d++; if(D){ string q; q+=char('0'+a);q+=char('0'+b);q+=char('0'+c);D->push_back(q); }
        }
    return d;
}
static int paircount(const string& s){
    bool p2[4][4]{}; int z=0;
    for(int i=0;i+1<(int)s.size();i++) p2[s[i]-'0'][s[i+1]-'0']=1;
    for(int a=0;a<4;a++)for(int b=0;b<4;b++)z+=p2[a][b];
    return z;
}
static bool full_check_7_4(const string& s){
    int n=s.size();
    for(int st=0;st<n;st++) for(int L=2;st+L<=n;L++){
        int maxp=(4*L)/7;
        for(int p=1;p<=maxp;p++){
            bool per=true; for(int i=0;i<L-p;i++) if(s[st+i]!=s[st+i+p]) {per=false;break;}
            if(per) return false;
        }
    }
    return true;
}
struct Stats{ long long total=0; array<long long,16> hist{}; long long paircomplete=0; vector<string> ge3; };
static Stats target67,target68;
static void dfs(string& s, int target){
    int n=s.size();
    if(n==target){
        Stats &st=(target==67?target67:target68);
        st.total++;
        int d=d3(s); if(d<16) st.hist[d]++;
        if(paircount(s)==8) st.paircomplete++;
        if(d>=3) st.ge3.push_back(s);
        return;
    }
    int parity=(s.back()-'0')&1;
    // Reduced square-free extension must switch parity; try both letters of opposite parity.
    if(parity==0){
        for(char c: {'1','3'}) if(append_ok_7_4(s,c)){ s.push_back(c); dfs(s,target); s.pop_back(); }
    } else {
        for(char c: {'0','2'}) if(append_ok_7_4(s,c)){ s.push_back(c); dfs(s,target); s.pop_back(); }
    }
}
