#!/usr/bin/env python3
"""Exact verification of path-five randomized-time mixing moments.

Requires SymPy (tested with 1.13.1). All asserted algebraic equalities
are exact in the field generated by sqrt(3).
"""
import sympy as s

n=5
A=s.zeros(n)
for i in range(n-1):
    A[i,i+1]=A[i+1,i]=1
v=[s.sqrt(3),s.Integer(1),s.Integer(0),-s.Integer(1),-s.sqrt(3)]
P={}
for a in v:
    R=s.eye(n)
    for b in v:
        if b!=a:
            R=R*(A-b*s.eye(n))/(a-b)
    P[a]=R.applyfunc(s.simplify)
    assert (A*P[a]-a*P[a]).applyfunc(s.simplify)==s.zeros(n)
assert (sum(P.values(),s.zeros(n))-s.eye(n)).applyfunc(s.simplify)==s.zeros(n)
B=s.diag(1,-1,1,-1,1)
for a in [s.sqrt(3),s.Integer(1)]:
    assert P[-a]==B*P[a]*B

x,y,X,Y,Z,W=s.symbols('x y X Y Z W',real=True)
moments=[x,y,X,Y,Z,W]
Q=P[s.Integer(0)]
E=P[s.sqrt(3)]
F=P[s.Integer(1)]
q=[]
for i in range(n):
    for j in range(i,n):
        if (i-j)%2==0:
            a,b,c=Q[i,j],2*E[i,j],2*F[i,j]
            val=a*a + b*b*X+c*c*Y+2*a*b*x+2*a*c*y+2*b*c*Z
        else:
            b,c=2*E[i,j],2*F[i,j]
            val=b*b*(1-X)+c*c*(1-Y)+2*b*c*W
        q.append(s.expand(val-s.Rational(1,n)))
idx=[(i,j) for i in range(n) for j in range(i,n)]
M=s.Matrix([[s.diff(z,h) for h in moments] for z in q])
row_indices=[idx.index(p) for p in [(0,0),(0,1),(0,2),(0,3),(1,1),(1,2)]]
assert s.simplify(M[row_indices,:].det()-s.sqrt(3)/972)==0
unique=s.solve(q,moments,dict=True)
target={x:s.Rational(-1,5),y:0,X:s.Rational(2,5),Y:s.Rational(2,5),Z:0,W:0}
assert len(unique)==1 and unique[0]==target
assert all(s.simplify(z.subs(target))==0 for z in q)

# The explicitly positive product density has cosine Fourier coefficients
# (-2/5,-2/5) in theta and (0,-2/5) in phi, respectively.
assert (s.Rational(1,2)*s.Rational(-2,5)==target[x])
assert ((1+s.Rational(-1,5))/2==target[X])
assert ((1+s.Rational(-1,5))/2==target[Y])

# Independent 8x8 trapezoidal quadrature exactly integrates every Fourier
# monomial occurring in this finite trigonometric polynomial (frequencies
# strictly below 8 in both coordinates); numeric replay is auxiliary.
import cmath,math
num=[[0.0]*n for _ in range(n)]
for k in range(8):
    th=2*math.pi*k/8
    fth=1-0.4*math.cos(th)-0.4*math.cos(2*th)
    for h in range(8):
        ph=2*math.pi*h/8
        fph=1-0.4*math.cos(2*ph)
        phases=[cmath.exp(1j*th),cmath.exp(1j*ph),1,cmath.exp(-1j*ph),cmath.exp(-1j*th)]
        # Evaluate all individual matrix entries, not the total scalar.
        for i in range(n):
            for j in range(n):
                u=sum(complex(P[a][i,j].evalf())*phases[r]
                      for r,a in enumerate(v))
                num[i][j]+=fth*fph*abs(u)**2/64
assert max(abs(num[i][j]-1/5) for i in range(n) for j in range(n))<1e-12
print('VERIFY_OK exact_projectors=5 independent_moment_rank=6 determinant=sqrt(3)/972 equations=15 weighted_grid=64 max_error<1e-12')
