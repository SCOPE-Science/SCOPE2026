#!/usr/bin/env python3
"""Independent finite maximal-clique enumeration; standard library only.

All four-part partitions are independently generated by combinations with
replacement, and every maximal compatible family is enumerated using the
Bron--Kerbosch pivot recursion. This script does not establish any
unbounded statement.
"""
from collections import Counter
from itertools import combinations_with_replacement


def generate(n):
    return [p for p in combinations_with_replacement(range(1, n-2), 4)
            if sum(p) == n]


def shared(a, b):
    ca, cb = Counter(a), Counter(b)
    return sum(min(ca.get(x, 0), cb.get(x, 0)) for x in ca.keys() | cb.keys())


def max_clique_bk(parts):
    adj = [set() for _ in parts]
    for i in range(len(parts)):
        for j in range(i):
            if shared(parts[i], parts[j]) >= 2:
                adj[i].add(j)
                adj[j].add(i)
    best, maximal_count = 0, 0

    def rec(R, P, X):
        nonlocal best, maximal_count
        if not P and not X:
            best = max(best, len(R))
            maximal_count += 1
            return
        pivot = max(P | X, key=lambda u: len(P & adj[u])) if P or X else None
        for v in sorted(P - (adj[pivot] if pivot is not None else set())):
            rec(R | {v}, P & adj[v], X & adj[v])
            P.remove(v)
            X.add(v)

    rec(set(), set(range(len(parts))), set())
    return best, maximal_count


for n in range(4, 30):
    parts = generate(n)
    best, number_maximal = max_clique_bk(parts)
    expected = (n - 2) // 2 + int(n == 9)
    assert best == expected, (n, best, expected)
    print(n, len(parts), best, number_maximal)
print('INDEPENDENT_ALL_MAXIMAL_CLIQUES_PASS n=4..29')
