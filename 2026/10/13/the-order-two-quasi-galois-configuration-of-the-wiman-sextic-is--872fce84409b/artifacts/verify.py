#!/usr/bin/env python3
from itertools import permutations, combinations
from collections import defaultdict, deque

N = 6
ID = tuple(range(N))

def compose(p,q):
    return tuple(p[q[i]] for i in range(N))

def inverse(p):
    r=[0]*N
    for i,j in enumerate(p): r[j]=i
    return tuple(r)

def parity(p):
    inv=0
    for i in range(N):
        for j in range(i+1,N):
            inv += p[i] > p[j]
    return inv & 1

def cycle_lengths(p):
    seen=[False]*N; out=[]
    for i in range(N):
        if not seen[i]:
            j=i; k=0
            while not seen[j]:
                seen[j]=True; k+=1; j=p[j]
            out.append(k)
    return tuple(sorted(out, reverse=True))

def fixed_duad(p):
    f=tuple(i for i in range(N) if p[i]==i)
    assert len(f)==2
    return frozenset(f)

def transposed_pairs(p):
    pairs=[]; seen=set()
    for i in range(N):
        if p[i]!=i and i not in seen:
            j=p[i]
            assert p[j]==i
            pairs.append(frozenset((i,j)))
            seen.add(i); seen.add(j)
    assert len(pairs)==2
    return pairs

def syntheme_of(p):
    return frozenset(transposed_pairs(p)+[fixed_duad(p)])

def conjugate(g,p):
    return compose(compose(g,p), inverse(g))

S6=list(permutations(range(N)))
A6=[p for p in S6 if parity(p)==0]
assert len(A6)==360
I=[p for p in A6 if cycle_lengths(p)==(2,2,1,1)]
assert len(I)==45
Iset=set(I)

# Commuting graph on the 45 double transpositions.
adj={p:set() for p in I}
for a,b in combinations(I,2):
    if compose(a,b)==compose(b,a):
        adj[a].add(b); adj[b].add(a)
assert {len(v) for v in adj.values()}=={4}

# The 30 Klein-four triples generated by commuting involutions.
v4=set()
for a,b in combinations(I,2):
    if b in adj[a]:
        c=compose(a,b)
        assert c in Iset and c!=a and c!=b
        v4.add(frozenset((a,b,c)))
assert len(v4)==30
membership=defaultdict(list)
for T in v4:
    for a in T: membership[a].append(T)
assert {len(membership[a]) for a in I}=={2}

# Two intrinsic types: one common fixed duad (support type), or three fixed duads
# forming one perfect matching (syntheme type).
def v4_type(T):
    ds={fixed_duad(a) for a in T}
    if len(ds)==1: return 'duad'
    if len(ds)==3 and frozenset(ds)==syntheme_of(next(iter(T))): return 'syntheme'
    raise AssertionError((T,ds))
counts=defaultdict(int)
for T in v4: counts[v4_type(T)]+=1
assert counts=={'duad':15,'syntheme':15}
for a in I:
    assert sorted(v4_type(T) for T in membership[a])==['duad','syntheme']

# Conjugation by A6 has exactly the two 15-element V4 orbits.
def orbit(T):
    return {frozenset(conjugate(g,a) for a in T) for g in A6}
seed_duad=next(T for T in v4 if v4_type(T)=='duad')
seed_syn=next(T for T in v4 if v4_type(T)=='syntheme')
Od=orbit(seed_duad); Os=orbit(seed_syn)
assert len(Od)==15 and len(Os)==15 and Od.isdisjoint(Os) and Od|Os==v4

# Duad-syntheme incidence graph: 15+15 vertices, 45 edges, cubic, connected, girth 8.
duads={frozenset(c) for c in combinations(range(N),2)}
assert len(duads)==15
synthemes={syntheme_of(a) for a in I}
assert len(synthemes)==15
edges={(fixed_duad(a), syntheme_of(a)):a for a in I}
assert len(edges)==45
assert all(d in s for (d,s) in edges)
assert {sum(1 for d,s in edges if d==D) for D in duads}=={3}
assert {sum(1 for d,s in edges if s==S) for S in synthemes}=={3}
assert set(edges.values())==Iset

# Two double transpositions commute iff their incidence edges share one endpoint.
for a,b in combinations(I,2):
    ea=(fixed_duad(a), syntheme_of(a)); eb=(fixed_duad(b), syntheme_of(b))
    edge_share=(ea[0]==eb[0] or ea[1]==eb[1])
    assert (b in adj[a]) == edge_share

# Verify the 30-vertex incidence graph has the Tutte-Coxeter parameters, including girth 8.
verts=[('d',d) for d in duads]+[('s',s) for s in synthemes]
G={v:set() for v in verts}
for d,s in edges:
    u=('d',d); v=('s',s); G[u].add(v); G[v].add(u)
assert {len(G[v]) for v in G}=={3}
seen={verts[0]}; Q=deque([verts[0]])
while Q:
    u=Q.popleft()
    for v in G[u]:
        if v not in seen: seen.add(v); Q.append(v)
assert len(seen)==30

def girth(graph):
    best=10**9
    for start in graph:
        dist={start:0}; parent={start:None}; q=deque([start])
        while q:
            u=q.popleft()
            for v in graph[u]:
                if v not in dist:
                    dist[v]=dist[u]+1; parent[v]=u; q.append(v)
                elif parent[u]!=v:
                    best=min(best,dist[u]+dist[v]+1)
    return best
assert girth(G)==8

# The V4 triangles are exactly the 30 stars of the bipartite graph.
star_triples=set()
for v in G:
    labels=frozenset(edges[(d,s)] if v[0]=='d' else edges[(d,s)]
                     for d,s in edges
                     if (v[0]=='d' and d==v[1]) or (v[0]=='s' and s==v[1]))
    assert len(labels)==3
    star_triples.add(labels)
assert star_triples==v4

print('VERIFY_OK involutions=45 degree=4 V4=30 orbits=15+15 each_involution=2 duad_syntheme=TutteCoxeter commuting=line_graph girth=8')
