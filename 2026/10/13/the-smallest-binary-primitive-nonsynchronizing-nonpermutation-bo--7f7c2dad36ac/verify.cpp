template<int N> struct EnumResult { long long count=0; map<unsigned long long,long long> cls; map<pair<int,int>,long long> ranks; };

template<int N> vector<array<unsigned char,N>> partitions(){
 vector<array<unsigned char,N>> out; array<unsigned char,N> p{}; p[0]=0;
 function<void(int,int)> rec=[&](int i,int mx){ if(i==N){out.push_back(p); return;} for(int x=0;x<=mx+1;x++){p[i]=x; rec(i+1,max(mx,x));}};
 rec(1,0); return out;
}

template<int N> bool preserves(const array<unsigned char,N>& f,const array<unsigned char,N>& p){
 for(int i=0;i<N;i++) for(int j=i+1;j<N;j++) if(p[i]==p[j] && p[f[i]]!=p[f[j]]) return false; return true;
}

template<int N> int rankof(const array<unsigned char,N>& f){int m=0; for(int x:f)m|=1<<x; return __builtin_popcount((unsigned)m);}

template<int N> bool synchronizing(const array<unsigned char,N>& a,const array<unsigned char,N>& b){
 const int M=1<<N; bool seen[M]; memset(seen,0,sizeof(seen)); int q[M],h=0,t=0; q[t++]=M-1;seen[M-1]=1;
 while(h<t){int s=q[h++]; if((s&(s-1))==0)return true; for(auto *fp:{&a,&b}){int o=0;for(int i=0;i<N;i++)if(s>>i&1)o|=1<<(*fp)[i]; if(!seen[o]){seen[o]=1;q[t++]=o;}}} return false;
}


template<int N> bool synchronizing_pairs(const array<unsigned char,N>& a,const array<unsigned char,N>& b){
 for(int x=0;x<N;x++)for(int y=x+1;y<N;y++){
  bool seen[N][N]{}; pair<int,int> q[N*N]; int h=0,t=0; q[t++]={x,y}; seen[x][y]=true; bool hit=false;
  while(h<t&&!hit){auto [u,v]=q[h++]; for(auto *fp:{&a,&b}){int r=(*fp)[u],s=(*fp)[v]; if(r==s){hit=true;break;} if(r>s)swap(r,s); if(!seen[r][s]){seen[r][s]=true;q[t++]={r,s};}}}
  if(!hit)return false;
 }
 return true;
}

template<int N> bool primitive_direct(const array<unsigned char,N>& a,const array<unsigned char,N>& b){
 // Independent accepted-case check: the congruence generated by each unordered pair must be universal.
 for(int seed1=0;seed1<N;seed1++) for(int seed2=seed1+1;seed2<N;seed2++){
   int par[N]; iota(par,par+N,0);
   function<int(int)> F=[&](int x){while(par[x]!=x){par[x]=par[par[x]];x=par[x];}return x;};
   auto U=[&](int x,int y){x=F(x);y=F(y);if(x==y)return false;par[y]=x;return true;};
   U(seed1,seed2); bool ch=true;
   while(ch){ch=false; for(int i=0;i<N;i++)for(int j=i+1;j<N;j++)if(F(i)==F(j)){ch|=U(a[i],a[j]);ch|=U(b[i],b[j]);}}
   int r=F(0); bool all=true;for(int i=1;i<N;i++)if(F(i)!=r){all=false;break;} if(!all)return false;
 } return true;
}

template<int N> unsigned long long paircode(const array<unsigned char,N>&a,const array<unsigned char,N>&b){unsigned long long z=0,m=1;for(int x:a){z+=m*x;m*=N;}for(int x:b){z+=m*x;m*=N;}return z;}

template<int N> array<unsigned char,N> relabel(const array<unsigned char,N>&f,const array<int,N>&p){array<unsigned char,N>g{};for(int old=0;old<N;old++)g[p[old]]=p[f[old]];return g;}

template<int N> unsigned long long canon(const array<unsigned char,N>&a,const array<unsigned char,N>&b){array<int,N>p{};iota(p.begin(),p.end(),0);unsigned long long best=ULLONG_MAX;do{auto x=relabel<N>(a,p),y=relabel<N>(b,p);best=min(best,paircode<N>(x,y));best=min(best,paircode<N>(y,x));}while(next_permutation(p.begin(),p.end()));return best;}

template<int N> pair<array<unsigned char,N>,array<unsigned char,N>> decode(unsigned long long z){array<unsigned char,N>a{},b{};for(int i=0;i<N;i++){a[i]=z%N;z/=N;}for(int i=0;i<N;i++){b[i]=z%N;z/=N;}return {a,b};}

template<int N> EnumResult<N> run(){
 auto ps=partitions<N>(); vector<array<unsigned char,N>> nontriv; for(auto&p:ps){int k=*max_element(p.begin(),p.end())+1;if(k!=1&&k!=N)nontriv.push_back(p);} 
 long long C=1;for(int i=0;i<N;i++)C*=N; vector<array<unsigned char,N>> maps(C); vector<int> ranks(C); vector<vector<unsigned char>> ok(C, vector<unsigned char>(nontriv.size()));
 for(long long c=0;c<C;c++){long long z=c;for(int i=0;i<N;i++){maps[c][i]=z%N;z/=N;}ranks[c]=rankof<N>(maps[c]);for(size_t k=0;k<nontriv.size();k++)ok[c][k]=preserves<N>(maps[c],nontriv[k]);}
 EnumResult<N> R;
 for(long long i=0;i<C;i++)for(long long j=0;j<C;j++){
  if(ranks[i]==N&&ranks[j]==N)continue; bool prim=true;for(size_t k=0;k<nontriv.size();k++)if(ok[i][k]&&ok[j][k]){prim=false;break;} if(!prim)continue; if(synchronizing<N>(maps[i],maps[j]))continue;
  R.count++;R.ranks[{ranks[i],ranks[j]}]++; if constexpr(N==5){ if(!primitive_direct<N>(maps[i],maps[j])){cerr<<"direct primitivity mismatch\n";exit(8);} if(synchronizing_pairs<N>(maps[i],maps[j])){cerr<<"direct synchronization mismatch\n";exit(10);} R.cls[canon<N>(maps[i],maps[j])]++; }
 }
 return R;
}

