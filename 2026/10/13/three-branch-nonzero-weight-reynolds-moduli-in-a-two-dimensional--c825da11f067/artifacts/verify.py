import sympy as sp
from itertools import product
from collections import Counter

a,b,c,d,mu=sp.symbols("a b c d mu")
R=sp.Matrix([[a,b],[c,d]])
e1=sp.Matrix([1,0]); e2=sp.Matrix([0,1])
basis=(e1,e2)

def br(x,y):
    return sp.Matrix([sp.expand(x[0]*y[1]-x[1]*y[0]),0])

def tri(x,y,z):
    return br(br(x,y),z)

def bdef(x,y):
    Rx,Ry=R*x,R*y
    return sp.simplify(br(Rx,Ry)-R*(br(Rx,y)+br(x,Ry)+mu*br(Rx,Ry)))

def tdef(x,y,z):
    Rx,Ry,Rz=R*x,R*y,R*z
    inside=tri(x,Ry,Rz)+tri(Rx,y,Rz)+tri(Rx,Ry,z)+2*mu*tri(Rx,Ry,Rz)
    return sp.simplify(tri(Rx,Ry,Rz)-R*inside)

B1=sp.expand(a*a+b*c+mu*a*(a*d-b*c))
B2=sp.expand(c*(a+d+mu*(a*d-b*c)))

binary=[]
for x in basis:
    for y in basis:
        binary.extend(sp.factor(v) for v in bdef(x,y) if v!=0)

G=sp.groebner([B1,B2],a,b,c,d,order="grevlex")
for v in binary:
    assert G.reduce(sp.expand(v))[1]==0
G2=sp.groebner(binary,a,b,c,d,order="grevlex")
assert G2.reduce(B1)[1]==0
assert G2.reduce(B2)[1]==0

# Ternary defect belongs to the ideal generated by the binary equations.
for x in basis:
    for y in basis:
        for z in basis:
            for v in tdef(x,y,z):
                if v!=0:
                    assert G.reduce(sp.expand(v))[1]==0

def bq(x,y,q):
    return ((x[0]*y[1]-x[1]*y[0])%q,0)

def tq(x,y,z,q):
    return bq(bq(x,y,q),z,q)

def mv(M,x,q):
    return ((M[0]*x[0]+M[1]*x[1])%q,
            (M[2]*x[0]+M[3]*x[1])%q)

def is_reynolds(M,w,q):
    bas=((1,0),(0,1))
    for x in bas:
        for y in bas:
            Rx,Ry=mv(M,x,q),mv(M,y,q)
            lhs=bq(Rx,Ry,q)
            p1,p2,p3=bq(Rx,y,q),bq(x,Ry,q),bq(Rx,Ry,q)
            inside=((p1[0]+p2[0]+w*p3[0])%q,
                    (p1[1]+p2[1]+w*p3[1])%q)
            if lhs!=mv(M,inside,q):
                return False
            for z in bas:
                Rz=mv(M,z,q)
                lhs3=tq(Rx,Ry,Rz,q)
                u1=tq(x,Ry,Rz,q)
                u2=tq(Rx,y,Rz,q)
                u3=tq(Rx,Ry,z,q)
                u4=tq(Rx,Ry,Rz,q)
                inside3=((u1[0]+u2[0]+u3[0]+2*w*u4[0])%q,
                         (u1[1]+u2[1]+u3[1]+2*w*u4[1])%q)
                if lhs3!=mv(M,inside3,q):
                    return False
    return True

def sqzero(M,q):
    return mm(M,M,q)==(0,0,0,0)

def mm(A,B,q):
    return tuple(sum(A[2*i+k]*B[2*k+j] for k in range(2))%q
                 for i in range(2) for j in range(2))

def inv2(M,q):
    aa,bb,cc,dd=M
    det=(aa*dd-bb*cc)%q
    if det==0:
        return None
    z=pow(det,-1,q)
    return (dd*z%q,-bb*z%q,-cc*z%q,aa*z%q)

def rank2(M,q):
    if all(x%q==0 for x in M):
        return 0
    return 2 if (M[0]*M[3]-M[1]*M[2])%q else 1

def auts(q):
    return [(s,t,0,1) for s in range(1,q) for t in range(q)]

def conj(M,P,q):
    return mm(mm(P,M,q),inv2(P,q),q)

for q in (2,3,5,7):
    for w in range(1,q):
        sols={M for M in product(range(q),repeat=4) if is_reynolds(M,w,q)}
        delta=(-pow(w,-1,q))%q
        A={(0,bb,0,dd) for bb in range(q) for dd in range(q)}
        B={(aa,bb,0,delta) for aa in range(q) for bb in range(q)}
        N={M for M in product(range(q),repeat=4) if sqzero(M,q)}
        assert sols==A|B|N
        assert len(A&B)==q
        assert len(A&N)==q
        assert not (B&N)
        assert len(sols)==3*q*q-2*q

        ranks=Counter(rank2(M,q) for M in sols)
        assert tuple(ranks[i] for i in range(3))==(1,2*q*q-q-1,q*(q-1))

        Gq=auts(q)
        pool=set(sols); orbits=[]
        while pool:
            M=next(iter(pool))
            O={conj(M,P,q) for P in Gq}
            assert O<=sols
            orbits.append(O)
            pool-=O
        assert len(orbits)==2*q+2
        sizes=Counter(len(O) for O in orbits)

        # Structural orbit-size multiset, with collisions automatically merged.
        expected=Counter()
        expected[1]+=2
        expected[q-1]+=2
        expected[q]+=2*q-3
        expected[q*(q-1)]+=1
        assert sizes==expected,(q,w,sizes,expected)

    # Report one representative nonzero weight per field.
    w=1
    sols={M for M in product(range(q),repeat=4) if is_reynolds(M,w,q)}
    ranks=Counter(rank2(M,q) for M in sols)
    Gq=auts(q); pool=set(sols); orbits=[]
    while pool:
        M=next(iter(pool))
        O={conj(M,P,q) for P in Gq}
        orbits.append(O); pool-=O
    print({
        "q":q,
        "fixed_nonzero_weight_count":len(sols),
        "rank_profile":tuple(ranks[i] for i in range(3)),
        "automorphism_classes":len(orbits),
        "orbit_sizes":dict(sorted(Counter(map(len,orbits)).items())),
    })

print("VERIFY_OK")
