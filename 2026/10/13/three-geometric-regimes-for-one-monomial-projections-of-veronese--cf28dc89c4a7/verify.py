#!/usr/bin/env python3
"""Exact integer-semigroup checks for one-coordinate projections of Veronese surfaces.

Uses the Python standard library only. The general statements require the algebraic
proof in RESULT.md; these checks test finitely many degrees and ideal powers.
"""
from math import comb


def degree_d_triples(d):
    return [(a, b, d - a - b) for a in range(d + 1) for b in range(d - a + 1)]


def regime(d, omitted):
    entries = sorted(omitted, reverse=True)
    if entries == [d, 0, 0]:
        return 'pure'
    if entries == [d - 1, 1, 0]:
        return 'tangent'
    return 'other'


def chart_generators(d, omitted, vertex):
    """Exponent pairs for ratios of the allowed degree-d monomials to x_vertex^d."""
    axes = [q for q in range(3) if q != vertex]
    return {(a[axes[0]], a[axes[1]]) for a in degree_d_triples(d) if a != omitted}


def monomial_span(generators, bound):
    """Semigroup span of nonnegative pairs whose sum is <= bound."""
    out = {(0, 0)}
    work = [(0, 0)]
    generators = {g for g in generators if g != (0, 0)}
    for point in work:
        for g in generators:
            z = point[0] + g[0], point[1] + g[1]
            if sum(z) <= bound and z not in out:
                out.add(z)
                work.append(z)
    return out


def expected_tangent(bound, missing):
    return {(i, j) for i in range(bound + 1) for j in range(bound + 1 - i)
            if (i, j) != missing}


def monomial_ideal_power_membership(i, j, n):
    # (v,u^2)^n in C[u,v]: exists a+b=n with u^(2b) v^a dividing u^i v^j.
    return any(i >= 2 * b and j >= n - b for b in range(n + 1))


def verify_all():
    cases = 0
    charts = 0
    for d in range(3, 17):
        tally = {'pure': 0, 'tangent': 0, 'other': 0}
        for omitted in degree_d_triples(d):
            r = regime(d, omitted)
            tally[r] += 1
            cases += 1
            if r == 'pure':
                # The omitted vertex is a base point; check both exceptional charts
                # of its blowup. At a chosen exceptional direction y, put
                # u=y/x and w=z/y; ratios are u^(i+j-1) w^j.
                base = omitted.index(d)
                others = [j for j in range(3) if j != base]
                for exceptional_direction in others:
                    other = next(j for j in others if j != exceptional_direction)
                    exponents = {(a[exceptional_direction] + a[other] - 1,
                                  a[other]) for a in degree_d_triples(d)
                                 if a != omitted}
                    sem = monomial_span(exponents, 12)
                    full = {(i,j) for i in range(13) for j in range(13 - i)}
                    assert sem == full, (d, omitted, exceptional_direction)
                    charts += 1
                # The charts at the two remaining coordinate vertices are smooth.
                for axis in others:
                    sem = monomial_span(chart_generators(d, omitted, axis), 12)
                    full = {(i,j) for i in range(13) for j in range(13 - i)}
                    assert sem == full, (d, omitted, axis)
                    charts += 1
                continue
            for axis in range(3):
                g = chart_generators(d, omitted, axis)
                s = monomial_span(g, max(2 * d, 8))
                if omitted[axis] == d - 1 and r == 'tangent':
                    missing = next(x for x in ((1, 0), (0, 1)) if x not in g)
                    ex = expected_tangent(max(2 * d, 8), missing)
                else:
                    ex = {(i, j) for i in range(max(2 * d, 8) + 1)
                          for j in range(max(2 * d, 8) + 1 - i)}
                assert s == ex, (d, omitted, axis, len(s), len(ex), sorted(ex - s)[:5])
                charts += 1
        assert tally['pure'] == 3 and tally['tangent'] == 6
        assert tally['other'] == comb(d + 2, 2) - 9
    # m=(v,u^2) as a subset of the normalization ring B; m^n=(v,u^2)^n B.
    # Check that every monomial in this ideal is factorable into n elements of
    # R\{1}, for n=1,...,10 and total degree <=32.
    # Finite product test: m^n is generated by n-fold products of
    # v,u^2,uv,u^3, multiplied by semigroup monomials from R.
    bound = 32
    R = expected_tangent(bound, (1, 0))
    generators = [(0, 1), (2, 0), (1, 1), (3, 0)]
    products = {(0, 0)}
    for n in range(1, 11):
        products = {(a + i, b + j) for a, b in products for i, j in generators
                    if a + b + i + j <= bound}
        span = {(a + i, b + j) for a, b in products for i, j in R
                if a + b + i + j <= bound}
        for i in range(bound + 1):
            for j in range(bound + 1 - i):
                assert ((i, j) in span) == monomial_ideal_power_membership(i, j, n), (n,i,j)
        # B/I^n has monomials outside the ideal; its length is n(n+1).
        outside = sum(not monomial_ideal_power_membership(i,j,n)
                      for i in range(2 * n + 3) for j in range(2 * n + 3))
        assert outside == n * (n + 1), (n, outside)
        assert outside - 1 == 2 * comb(n + 1, 2) - 1
    # Test the three distinct projective Hilbert polynomial formulas against
    # exact graded-semigroup cardinalities; these finite values supplement RR.
    hilbert_checks = 0
    for d in range(3, 8):
        for omitted in [(d, 0, 0), (d - 1, 1, 0),
                        (1, 1, d - 2)]:
            r = regime(d, omitted)
            generating = set(degree_d_triples(d)) - {omitted}
            sums = {(0, 0, 0)}
            for n in range(1, 7):
                sums = {tuple(v[i] + w[i] for i in range(3))
                        for v in sums for w in generating}
                if n < 3:
                    continue
                if r == 'pure':
                    expected = ((d*d - 1)*n*n + (3*d - 1)*n)//2 + 1
                else:
                    expected = comb(d*n + 2, 2) - (r == 'tangent')
                assert len(sums) == expected, (d, omitted, n, len(sums), expected)
                hilbert_checks += 1
    print(f'PASS: {hilbert_checks} exact graded Hilbert polynomial tests for 3 regimes, d=3..7.')
    print(f'PASS: {cases} monomial omissions, {charts} affine charts (including exceptional blowup charts), d=3..16.')
    print('PASS: exact tangent semigroup generators and ordinary smooth chart generators.')
    print('PASS: conductor and m-adic power equalities tested at n=1..10 (degree <=32).')
    print('PASS: Hilbert-Samuel colength 2*binom(n+1,2)-1 for n=1..10.')


if __name__ == '__main__':
    verify_all()
