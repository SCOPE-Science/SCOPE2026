"""Finite-field checks for zero-insertive loci of small acyclic path algebras.

Uses only Python standard library. Algebra multiplication follows path concatenation.
An exhaustive test here is only for the displayed finite examples.
"""
from itertools import product


def make_algebra(vertices, arrows, p):
    # Directed paths represented by vertex tuples; repeated arrows are represented
    # by distinct labels in a more general path algebra, not used in these checks.
    paths = [(i,) for i in vertices]
    starts = {u: [(u, v) for x, v in arrows if x == u] for u in vertices}
    frontier = [e for e in arrows]
    while frontier:
        paths.extend(frontier)
        frontier = [path + (nxt,) for path in frontier for nxt in vertices
                    if (path[-1], nxt) in arrows]
    paths = sorted(set(paths), key=lambda x: (len(x), x))
    pos = {path: i for i, path in enumerate(paths)}
    multiplication = [[-1] * len(paths) for _ in paths]
    for i, path in enumerate(paths):
        for j, other in enumerate(paths):
            if path[-1] == other[0]:
                multiplication[i][j] = pos[path + other[1:]]
    return paths, multiplication


def exhaustive_locus(vertices, arrows, p):
    paths, table = make_algebra(vertices, arrows, p)
    dimension = len(paths)
    vectors = list(product(range(p), repeat=dimension))
    zero = (0,) * dimension
    def multiply(x, y):
        out = [0] * dimension
        for i, xi in enumerate(x):
            if xi:
                for j, yj in enumerate(y):
                    k = table[i][j]
                    if k >= 0 and yj:
                        out[k] = (out[k] + xi * yj) % p
        return tuple(out)
    locus = set()
    for a in vectors:
        for b in vectors:
            if multiply(a, b) == zero:
                for r in vectors:
                    locus.add(multiply(multiply(a, r), b))
    return paths, locus


def verify():
    # The path algebra of the line 1 -> 2 -> 3 is the full upper triangular
    # 3-by-3 matrix algebra. A radical element is an ordered triple (a,b,c)
    # at paths (1,2), (1,2,3), (2,3).
    paths, locus = exhaustive_locus((1, 2, 3), {(1, 2), (2, 3)}, 2)
    pos = {path: i for i, path in enumerate(paths)}
    assert len(paths) == 6
    assert len(locus) == 6
    for vals in product(range(2), repeat=6):
        a = vals[pos[(1, 2)]]
        c = vals[pos[(2, 3)]]
        radical = all(vals[pos[(i,)]] == 0 for i in (1, 2, 3))
        assert (vals in locus) == (radical and a * c == 0)
    print('LINE_A3_F2_COMPLETE_6_OF_8_OK')
    # The fork 1 -> 3 <- 2 has radical square zero. Every radical element
    # is generated by a single zero-product sandwich.
    paths, locus = exhaustive_locus((1, 2, 3), {(1, 3), (2, 3)}, 2)
    pos = {path: i for i, path in enumerate(paths)}
    assert len(paths) == 5
    assert len(locus) == 4
    for vals in product(range(2), repeat=5):
        radical = all(vals[pos[(i,)]] == 0 for i in (1, 2, 3))
        assert (vals in locus) == radical
    print('SOURCE_SINK_FORK_F2_COMPLETE_4_OF_4_OK')
    # Quantitative A3 formula for three small finite fields follows from
    # direct independent enumeration of radical coefficients.
    for q in (2, 3, 5):
        n = sum(1 for a, b, c in product(range(q), repeat=3) if a * c == 0)
        assert n == q * (2 * q - 1)
        missing = q ** 3 - n
        assert missing == (q - 1) ** 2 * q
    print('A3_FINITE_FIELD_COUNTS_OK')
    print('VERIFY_OK')


if __name__ == '__main__':
    verify()
