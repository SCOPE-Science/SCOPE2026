# Independent exhaustive RREF and polynomial-gcd verifier, Python >=3.10, SymPy
from itertools import product, combinations
from collections import Counter
from math import comb
from sympy import Poly,symbols
X=symbols('X')
q=3

def represent(w):
 w=tuple(int(i)%q for i in w)
 z=next((v for v in w[::-1] if v),None)
 if z is None:raise ValueError('zero')
 return tuple(v*(1 if z==1 else 2)%q for v in w)

D=7
is_squarefree={}
for raw in product(range(q),repeat=D):
 if not any(raw):continue
 f=represent(raw)
 if f in is_squarefree:continue
 polynomial=Poly(sum(f[i]*X**i for i in range(D)),X,modulus=3)
 ok=polynomial.degree()>=5 and polynomial.gcd(polynomial.diff()).degree()==0
 is_squarefree[f]=ok
assert len(is_squarefree)==(3**D-1)//2
assert sum(is_squarefree.values())==648


def combine(a,b,c=1):return represent(tuple((a[i]+c*b[i])%q for i in range(D)))

def root_count(f):
 # f(X,Y)=sum f[i]X^iY^{6-i}
 return int(f[6]==0)+sum(sum(f[i]*pow(x,i,3) for i in range(D))%3==0 for x in range(3))

def gcd_homogeneous(a,b):
 pa=Poly(sum(a[i]*X**i for i in range(D)),X,modulus=3)
 pb=Poly(sum(b[i]*X**i for i in range(D)),X,modulus=3)
 return 6-max(pa.degree(),pb.degree())+pa.gcd(pb).degree()

planes=set();prof=Counter();base=Counter()
for i in range(D):
 for j in range(i+1,D):
  ufree=[k for k in range(i+1,D) if k!=j]
  vfree=list(range(j+1,D))
  for param in product(range(q),repeat=len(ufree)+len(vfree)):
   u=[0]*D;v=[0]*D;u[i]=1;v[j]=1
   for k,c in zip(ufree,param[:len(ufree)]):u[k]=c
   for k,c in zip(vfree,param[len(ufree):]):v[k]=c
   a=represent(u);b=represent(v)
   members=frozenset([a,b,combine(u,v),combine(u,v,-1)])
   assert len(members)==4
   if all(is_squarefree[z] for z in members):
    assert members not in planes
    planes.add(members)
    prof[tuple(sorted(map(root_count,members)))]+=1
    base[gcd_homogeneous(a,b)]+=1
assert len(planes)==10005,(len(planes),)
assert dict(base)=={0:9612,2:195,3:72,4:54,5:72}
assert sum(prof.values())==10005

# Independent PGL2 generators, using direct binomial expansion of two linear forms

def mul(a,b):
 out=[0]*(len(a)+len(b)-1)
 for i,s in enumerate(a):
  for j,t in enumerate(b):out[i+j]=(out[i+j]+s*t)%3
 return out

def exponent(a,n):
 r=[1]
 for _ in range(n):r=mul(r,a)
 return r

def transform(f,m):
 a,b,c,d=m
 ans=[0]*D
 for i in range(D):
  t=mul(exponent([b,a],i),exponent([d,c],6-i))
  for k in range(D):ans[k]=(ans[k]+f[i]*t[k])%3
 return represent(ans)

# PGL2 generated by translations, inversion, nonsquare scale.
gens=[(1,1,0,1),(0,1,1,0),(2,0,0,1)]
actions=[{f:transform(f,m) for f in is_squarefree} for m in gens]
remaining=set(planes);orbit_sizes=Counter()
while remaining:
 seed=min(remaining,key=lambda e:tuple(sorted(e)))
 todo=[seed];found={seed}
 while todo:
  line=todo.pop()
  for perm in actions:
   t=frozenset(perm[f] for f in line)
   if t not in found:
    assert t in remaining
    found.add(t);todo.append(t)
 remaining-=found;orbit_sizes[len(found)]+=1
assert dict(orbit_sizes)=={3:1,6:1,12:43,24:395},orbit_sizes
print('ALL PASS')
print('forms_total',len(is_squarefree),'smooth_forms',sum(is_squarefree.values()))
print('rref_pencils_total',99463,'all_smooth_pencils',len(planes))
print('rational_branch_profiles',sorted(prof.items()))
print('common_branch_divisor_degrees',sorted(base.items()))
print('pgl2_orbits',sum(orbit_sizes.values()),'sizes',sorted(orbit_sizes.items()))
