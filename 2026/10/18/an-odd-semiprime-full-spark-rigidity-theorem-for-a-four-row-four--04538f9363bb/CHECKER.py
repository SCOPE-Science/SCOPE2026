"""Exact finite checks for four-row Fourier minors on cyclic ternary semiprimes.

Each h2 coefficient belongs to the cyclotomic field generated by a primitive
third and a primitive p-th root, p != 3.  No floating-point arithmetic is used.
"""
from itertools import combinations, combinations_with_replacement
from math import comb


def vanishes(c, p):
    """Exact criterion for h2 of four primitive (3p)-th roots."""
    counts = [[0] * p for _ in range(3)]
    for i in range(4):
        for j in range(i, 4):
            s = c[i] + c[j]
            counts[s % 3][s % p] += 1
    # In Q(omega), omega^2=-1-omega. In Q(omega,zeta_p),
    # 1+X+...+X^(p-1) is the minimal polynomial of zeta_p.
    a = [counts[0][j] - counts[2][j] for j in range(p)]
    b = [counts[1][j] - counts[2][j] for j in range(p)]
    return len(set(a)) == 1 and len(set(b)) == 1


def expected(c, p):
    return p == 5 and len({x % 3 for x in c}) == 1


def histogram(c):
    out = [0, 0, 0]
    for i in range(4):
        for j in range(i, 4):
            out[(c[i] + c[j]) % 3] += 1
    return tuple(sorted(out))


allowed = {tuple(sorted(histogram(c))) for c in combinations_with_replacement(range(3), 4)}
assert allowed == {(0, 0, 10), (1, 3, 6), (3, 3, 4)}, allowed
print('mod-3 pair-sum histograms:', sorted(allowed))
for p in (5, 7, 11, 13):
    N = 3 * p
    zero = 0
    for c in combinations(range(N), 4):
        actual = vanishes(c, p)
        predicted = expected(c, p)
        assert actual == predicted, (p, c, actual, predicted)
        zero += actual
    assert zero == (15 if p == 5 else 0)
    print(f'p={p}, N={N}, total={comb(N, 4)}, exact_zero_minors={zero}, PASS')
print('All exact cyclotomic tests passed.')
