#!/usr/bin/env python3
"""Independent finite tests of coordinate-avoidance Galois closures and Horn arity witnesses."""
from itertools import product
from collections import Counter

def bits(x):
    while x:
        k=(x & -x).bit_length()-1
        yield k
        x &= x-1

def run(q,d,complete=True):
    vs=list(product(range(q),repeat=d)); n=len(vs); allbits=(1<<n)-1
    incidence=[]
    for x in vs:
        mask=0
        for j,y in enumerate(vs):
            if all(a!=b for a,b in zip(x,y)): mask|=1<<j
        incidence.append(mask)
    def direct_closure(mask):
        deriv=allbits
        for k in bits(mask): deriv &= incidence[k]
        result=allbits
        for j in bits(deriv): result &= incidence[j]
        return result
    def predicted(mask):
        if not mask:return 0
        ps=[set() for _ in range(d)]
        for k in bits(mask):
            for i,a in enumerate(vs[k]):ps[i].add(a)
        if any(len(s)==q for s in ps):return allbits
        result=0
        for j,y in enumerate(vs):
            if all(y[i] in ps[i] for i in range(d)):result |= 1<<j
        return result
    def closure_via_binary_mixing_and_full_coordinate(mask):
        if not mask:return 0
        cur=mask
        while True:
            indices=list(bits(cur)); nxt=cur
            for a_i in range(len(indices)):
                x=vs[indices[a_i]]
                for b_i in range(a_i+1,len(indices)):
                    y=vs[indices[b_i]]
                    for z in product(*[{x[i],y[i]} for i in range(d)]):
                        nxt |= 1<<where[z]
            if nxt==cur:break
            cur=nxt
        if any(set(vs[j][i] for j in bits(cur))==set(range(q)) for i in range(d)):
            return allbits
        return cur
    where={v:i for i,v in enumerate(vs)}
    # Infinite proof predicts # 2+(2^q-2)^d.
    if complete:
        seen=set(); critical=[]; actual_closure={}
        for mask in range(1<<n):
            got=direct_closure(mask); exp=predicted(mask)
            assert got==exp,(q,d,mask,got,exp)
            seen.add(got);actual_closure[mask]=got
        assert len(seen)==2+(2**q-2)**d,(q,d,len(seen))
        # Every minimal implicational witness's premise size is bounded by max(q,d).
        max_stem=0
        for mask,v in actual_closure.items():
            if not mask:continue
            avail=v &~mask
            if not avail:continue
            if any(avail & actual_closure[mask & ~(1<<j)] for j in bits(mask)):
                # Min stem for a particular conclusion may still exist;
                # enumerate all conclusions only for small instances.
                pass
            for concl in bits(avail):
                if all(not (actual_closure[mask & ~(1<<j)] & (1<<concl)) for j in bits(mask)):
                    max_stem=max(max_stem,mask.bit_count())
        expected=0 if d==1 else (2 if q==2 else max(q,d))
        assert max_stem==expected,(q,d,max_stem,expected)
        print('FULL',q,d,'vertices',n,'subsets',1<<n,'concepts',len(seen),'max_direct_stem',max_stem,'PASS')
    else:
        # Fixed-seed deterministic samples of arbitrary subsets, plus both lower-bound examples.
        import random
        rng=random.Random(q*1000+d)
        for _ in range(2000):
            mask=0
            for j in range(n):
                if rng.randrange(4)==0:mask|=1<<j
            assert direct_closure(mask)==predicted(mask)
        print('SAMPLED',q,d,'vertices',n,'samples',2000,'PASS')
    # Explicit forcing of all q letters in one coordinate, with other coordinates fixed.
    if d>=2:
        line=[where[(a,)+(0,)*(d-1)] for a in range(q)]
        S=sum(1<<j for j in line)
        assert direct_closure(S)==allbits
        assert all(direct_closure(S & ~(1<<j))==(S & ~(1<<j)) for j in line)
        # An outside conclusion requires all q line premises and cannot be generated by <q-premise rules.
        outsider=where[(0,1)+(0,)*(d-2)]
        assert not (S & (1<<outsider))
        # Sharp d-stem (nonbinary): one private 0-coordinate per witness.
        if q>=3:
            witnesses=[where[tuple(0 if i==j else 1 for i in range(d))] for j in range(d)]
            R=sum(1<<k for k in witnesses); y=where[(0,)*d]
            assert direct_closure(R)&(1<<y)
            assert not (R&(1<<y))
            assert all(not (direct_closure(R&~(1<<j))&(1<<y)) for j in witnesses)
    # Check binary-mixing closure by rule search on random small subsets.
    if n<=16:
        import random
        rng=random.Random(q*1000+d)
        checks=range(1<<n) if n<=9 else [0,allbits]+[rng.randrange(1<<n) for _ in range(60)]
        for mask in checks:
            assert closure_via_binary_mixing_and_full_coordinate(mask)==direct_closure(mask),(q,d,mask)
        print('HORN',q,d,'subsets',len(checks),'iterative_basis','PASS')

if __name__=='__main__':
    for p in [(2,1),(2,2),(2,3),(2,4),(3,1),(3,2),(4,1),(4,2)]:run(*p,complete=(p[0]**p[1]<=16))
    run(3,3,complete=False)
    print('VERIFY_OK direct_galois_vs_boxes=PASS finite_stems=PASS binary_mixing_plus_q_saturation=PASS')
