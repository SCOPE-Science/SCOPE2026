"""Independent finite checks of explicit toric presentations of three-term affine repunit semigroups."""
from math import gcd

def data(a,b,d):
    A=a; B=b*a+d; C=b*b*a+(b+1)*d
    q,r=divmod(a,b+1)
    if q==0 or (q==1 and r==0):
        h,t=divmod(b+1,a)
        K=b*b-b*t+h*d
        rel=[((0,0,1),(K,t,0)),((0,a,0),(B,0,0))]
        return (A,B,C),rel,'embedding-two'
    if r==0:
        rel=[((0,b+1,0),(b,0,1)),((0,0,q),(b*b*q+d,0,0))]
        return (A,B,C),rel,'complete-intersection'
    M=b*b*q+b*r+d
    Mp=b*b*q-b+b*r+d
    rel=[((0,b+1,0),(b,0,1)),((0,r,q),(M,0,0)),((0,0,q+1),(Mp,b+1-r,0))]
    return (A,B,C),rel,'three-relation'

def normal(t,rel):
    x,y,z=t
    for _ in range(10000):
        for L,R in rel:
            if x>=L[0] and y>=L[1] and z>=L[2]:
                x+=R[0]-L[0];y+=R[1]-L[1];z+=R[2]-L[2]
                break
        else:
            return (x,y,z)
    raise AssertionError(('nontermination',t,rel))

def check_case(a,b,d,cap):
    weights,rel,_=data(a,b,d)
    A,B,C=weights
    assert gcd(a,d)==1
    for lhs,rhs in rel:
        assert sum(i*j for i,j in zip(lhs,weights))==sum(i*j for i,j in zip(rhs,weights)),(a,b,d,lhs,rhs)
        for i in range(3):assert min(lhs[i],rhs[i])==0
    # Exhaust all factorization vectors up to weight cap, test each fiber has one normal form.
    seen={};vectors=0
    for z in range(cap//C+1):
        for y in range((cap-C*z)//B+1):
            for x in range((cap-C*z-B*y)//A+1):
                degree=A*x+B*y+C*z
                n=normal((x,y,z),rel)
                assert degree==sum(i*j for i,j in zip(n,weights))
                if degree in seen:
                    assert n==seen[degree],(a,b,d,degree,n,seen[degree])
                else:seen[degree]=n
                vectors+=1
    # Verify no named relation is generated by others using finite fiber connectivity:
    # degree of its left factorization, build graph via other reversible moves.
    for omitted,(left,right) in enumerate(rel):
        others=rel[:omitted]+rel[omitted+1:]
        todo=[left];found={left}
        while todo:
            p=todo.pop()
            for L,R in others:
                for source,target in ((L,R),(R,L)):
                    if all(p[i]>=source[i] for i in range(3)):
                        nxt=tuple(p[i]-source[i]+target[i] for i in range(3))
                        if nxt not in found:found.add(nxt);todo.append(nxt)
        assert right not in found,(a,b,d,omitted,left,right)
    return vectors

if __name__=='__main__':
    cases=vectors=0
    for a in range(2,24):
        for b in range(2,10):
            for d in range(1,13):
                if gcd(a,d)!=1:continue
                vectors+=check_case(a,b,d,cap=500)
                cases+=1
    print(f'PASS: {cases} distinct (a,b,d) settings; {vectors} independent monomial normal-form checks; each relation indispensable by complete finite fiber connectivity.')
    for a,b,d in ((2,2,1),(4,2,1),(6,2,1),(7,2,1),(10,3,1)):
        w,R,typ=data(a,b,d)
        print(f'example: a={a} b={b} d={d}; generators={w}; regime={typ}; relations={R}')
