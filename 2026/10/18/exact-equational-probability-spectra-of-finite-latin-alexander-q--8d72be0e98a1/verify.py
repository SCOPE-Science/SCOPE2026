#!/usr/bin/env python3
"""Exact small-field checks for equation spectra of Latin Alexander quandles."""
import itertools, random

def mul(A,B,p):
 n=len(A);return tuple(tuple(sum(A[i][k]*B[k][j] for k in range(n))%p for j in range(n)) for i in range(n))
def add(A,B,p):return tuple(tuple((x+y)%p for x,y in zip(a,b)) for a,b in zip(A,B))
def neg(A,p):return tuple(tuple((-v)%p for v in row) for row in A)
def sub(A,B,p):return add(A,neg(B,p),p)
def zero(n):return tuple((0,)*n for _ in range(n))
def eye(n):return tuple(tuple(int(i==j) for j in range(n)) for i in range(n))
def rank(A,p):
 B=[list(row) for row in A];n=len(B);r=0
 for c in range(n):
  j=next((j for j in range(r,n) if B[j][c]%p),None)
  if j is None:continue
  B[r],B[j]=B[j],B[r];inv=pow(B[r][c],-1,p)
  B[r]=[(x*inv)%p for x in B[r]]
  for i in range(n):
   if i!=r and B[i][c]:
    z=B[i][c];B[i]=[(a-z*b)%p for a,b in zip(B[i],B[r])]
  r+=1
 return r

def vecmul(A,x,p):return tuple(sum(v*y for v,y in zip(row,x))%p for row in A)

def analyze(name,p,T,expect):
 n=len(T);I=eye(n);B=sub(I,T,p)
 assert rank(T,p)==n and rank(B,p)==n
 # independent enumeration of the coefficient ring F_p[T]
 R=set();powers=[I]
 for k in range(n):
  powers.append(mul(powers[-1],T,p))
 for cs in itertools.product(range(p),repeat=n):
  a=zero(n)
  for c,tk in zip(cs,powers):
   for _ in range(c):a=add(a,tk,p)
  R.add(a)
 # finite subquasigroup generated by the variable binary projections
 S={zero(n),I};changed=True
 while changed:
  changed=False
  for a,b in itertools.product(tuple(S),repeat=2):
   z=add(mul(T,a,p),mul(B,b,p),p)
   if z not in S:S.add(z);changed=True
 assert S==R,(name,len(S),len(R))
 spec=sorted({rank(a,p) for a in R});assert spec==expect,(name,spec,expect)
 # exhaustive polynomial probabilities on pairs for each possible coefficient difference
 V=list(itertools.product(range(p),repeat=n));N=len(V)
 for A in R:
  nsol=sum(vecmul(A,x,p)==(0,)*n for x in V)
  assert nsol==p**(n-rank(A,p)),(name,'kernel',A,nsol)
 # test pair-equation generated terms on all input pairs using independent evaluation
 for A in S:
  F=[tuple((u+v)%p for u,v in zip(vecmul(A,x,p),vecmul(sub(I,A,p),y,p))) for x in V for y in V]
  assert len(F)==N*N
 # independently brute-force nonlinear term syntax (ternary, depths up to 4)
 rng=random.Random(1234);terms=[(lambda vs,i=i: vs[i]) for i in range(3)]
 coefs=[]
 for i in range(3):coefs.append(tuple(I if i==j else zero(n) for j in range(3)))
 for _ in range(40):
  i,j=rng.randrange(len(terms)),rng.randrange(len(terms))
  ta,tb=terms[i],terms[j]
  terms.append(lambda vs,ta=ta,tb=tb:tuple((u+v)%p for u,v in zip(vecmul(T,ta(vs),p),vecmul(B,tb(vs),p))))
  ca,cb=coefs[i],coefs[j]
  coefs.append(tuple(add(mul(T,a,p),mul(B,b,p),p) for a,b in zip(ca,cb)))
 for i,j in [(3,9),(5,23),(8,40),(33,37)]:
  C=tuple(sub(a,b,p) for a,b in zip(coefs[i],coefs[j]))
  # Directly enumerate ternary term equations and compare the probability with the rank of the combined coefficient matrix.
  count=0
  for vs in itertools.product(V,repeat=3):
   if terms[i](vs)==terms[j](vs):count+=1
  assert count==p**(3*n-rank_from_images(C,p,n)),(name,i,j,count)
 print(name, 'p=',p,'dimension=',n,'ring_elements=',len(R),'ranks=',spec, 'probabilities=',[f'1/{p**r}' for r in reversed(spec)])

def rank_from_images(Cs,p,n):
 # rank of n by 3n joined matrix
 rows=[[A[i][j] for A in Cs for j in range(n)] for i in range(n)]
 # rectangular Gaussian elimination
 z=0; w=len(rows[0]);
 for c in range(w):
  r=next((r for r in range(z,n) if rows[r][c]%p),None)
  if r is None:continue
  rows[z],rows[r]=rows[r],rows[z];inv=pow(rows[z][c],-1,p)
  rows[z]=[(a*inv)%p for a in rows[z]]
  for t in range(n):
   if t!=z and rows[t][c]:
    v=rows[t][c];rows[t]=[(a-v*b)%p for a,b in zip(rows[t],rows[z])]
  z+=1
  if z==n:break
 return z

def companion(poly,p):
 # ascending coeffs monic poly of degree n
 n=len(poly)-1;return tuple(tuple((1 if i==j+1 else 0) if j<n-1 else (-poly[i])%p for j in range(n)) for i in range(n))

if __name__=='__main__':
 analyze('scalar F3^2',3,((2,0),(0,2)),[0,2])
 analyze('Jordan F3^2',3,((2,1),(0,2)),[0,1,2])
 analyze('irreducible F2^2',2,companion((1,1,1),2),[0,2])
 analyze('mixed F5^2',5,((2,0),(0,3)),[0,1,2])
 analyze('Jordan+scalar F3^3',3,((2,1,0),(0,2,0),(0,0,2)),[0,1,3])
 analyze('irreducible squared F2^4',2,companion((1,0,1,0,1),2),[0,2,4])
 print('ALL CHECKS PASSED')
