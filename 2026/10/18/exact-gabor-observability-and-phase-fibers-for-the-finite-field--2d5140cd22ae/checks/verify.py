#!/usr/bin/env python3
"""Exact finite-field checks for a hyperbola-window Gabor ambiguity theorem.

Uses arithmetic in prime fields and quadratic extensions, never floating-point
approximations to roots of unity.  Zero of a sum of p-th roots is detected by
coefficient equality modulo the p-th cyclotomic polynomial.
"""
from collections import deque

class Field:
    def __init__(self, p, degree=1, nonsquare=None):
        self.p = p
        self.degree = degree
        self.q = p**degree
        if degree == 2:
            self.d = nonsquare if nonsquare is not None else next(d for d in range(2,p) if pow(d, (p-1)//2,p)==p-1)
            assert pow(self.d, (p-1)//2,p) == p-1
        else:
            self.d = 0
        self.neg = [self.sub(0,a) for a in range(self.q)]
        self.inv = [None]*self.q
        for a in range(1,self.q):
            self.inv[a] = next(b for b in range(1,self.q) if self.mul(a,b)==1)
        self.points = [(a,b) for a in range(self.q) for b in range(self.q)]

    def add(self, x,y):
        if self.degree == 1:return (x+y)%self.p
        p=self.p;return ((x%p+y%p)%p)+p*((x//p+y//p)%p)
    def sub(self, x,y):
        if self.degree == 1:return (x-y)%self.p
        p=self.p;return ((x%p-y%p)%p)+p*((x//p-y//p)%p)
    def mul(self,x,y):
        if self.degree == 1:return (x*y)%self.p
        p=self.p;a,b=x%p,x//p;c,d=y%p,y//p
        return (a*c+self.d*b*d)%p+p*((a*d+b*c)%p)
    def trace(self,x):
        if self.degree == 1:return x%self.p
        return (2*(x%self.p))%self.p
    def plus(self, x,y):return self.add(x,y)
    def diffpair(self,x,y):return (self.sub(x[0],y[0]),self.sub(x[1],y[1]))
    def addpair(self,x,y):return (self.add(x[0],y[0]),self.add(x[1],y[1]))
    def dot(self,x,y):return self.add(self.mul(x[0],y[0]),self.mul(x[1],y[1]))


def verify(p,degree=1):
    F=Field(p,degree); q=F.q; n=q*q
    H={(t,F.inv[t]) for t in range(1,q)}
    assert len(H)==q-1
    D={F.diffpair(x,y) for x in H for y in H}
    expected_D=1+(q-1)**2//2
    assert len(D)==expected_D,(q,len(D),expected_D)
    # Independently test the discriminant characterization of each displacement.
    four=F.add(F.add(1,1),F.add(1,1))
    for a,b in F.points:
        if (a,b)==(0,0):pred=True
        elif a==0 or b==0:pred=False
        else:
            ab=F.mul(a,b)
            value=F.sub(1,F.mul(four,F.inv[ab]))
            pred=(value in {F.mul(z,z) for z in range(q)})
        assert pred==((a,b) in D),(q,(a,b),pred)
    # Cyclotomic zero test of EVERY ambiguity coefficient (displacement, modulation).
    # A(h,xi)=sum_{z in H and z-h in H} exp(2pi i Tr(xi dot z)/p).
    zero_count=0
    for a,b in F.points:
        I=[z for z in H if F.diffpair(z,(a,b)) in H]
        assert (len(I)>0)==((a,b) in D)
        if (a,b)!=(0,0):assert len(I)<=2
        for c,d in F.points:
            coeff=[0]*p
            for z in I:
                exponent=F.trace(F.dot((c,d),z))
                coeff[exponent]+=1
            vanishes=(len(set(coeff))==1)
            assert vanishes==((a,b) not in D),(q,(a,b),(c,d),coeff)
            zero_count+=vanishes
    expected_rank=n*expected_D
    assert n*n-zero_count==expected_rank
    # Graph of observed pair products on the complete coordinate set.
    # Components are cosets of the additive subgroup generated by D.
    unseen=set(F.points)
    cc=0
    while unseen:
        cc+=1
        root=unseen.pop()
        todo=[root]
        while todo:
            z=todo.pop()
            for h in D:
                w=F.addpair(z,h)
                if w in unseen:
                    unseen.remove(w)
                    todo.append(w)
    assert cc==(3 if q==3 else 1),(q,cc)
    # Exact counterexample to global phase retrieval: horizontal pairs are not joined.
    assert (1,0) not in D
    # Full-support contrast and rank defect are strictly nontrivial in all tested fields.
    assert 0<expected_rank<n*n
    print(f'GF({q}): |H|={q-1}, |H-H|={expected_D}, rank={expected_rank}, nullity={n*n-expected_rank}, '
          f'ambiguity_tests={n*n}, full_support_components={cc}, ALL_PASS')

if __name__=='__main__':
    for prime,degree in [(3,1),(5,1),(7,1),(3,2),(11,1),(13,1),(5,2)]:
        verify(prime,degree)
    print('VERIFY_OK')
