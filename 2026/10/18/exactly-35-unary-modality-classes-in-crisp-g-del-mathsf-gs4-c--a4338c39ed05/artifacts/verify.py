"""Finite certificate for the 35 unary word operators of crisp Goedel S4.

No external packages. The upper check uses only contextual consequences of the
listed universally valid modality equations; the lower check uses five explicit
finite birelational models with no fallible worlds.
"""
from itertools import product

REPS=['','N','B','D','NN','BN','DN','NB','DB','BD','BNN','DNN','DBN','BDN','NNB','BNB','BDB','NBD','DBD','DBNN','BDNN','BDBN','DBDN','DNNB','DBNB','NBDB','NNBD','BNBD','BDBNN','DBDNN','BDNNB','NNBDB','DNNBD','DBNBD','BDNNBD']
RULES=[('BB','B'),('DD','D'),('NNN','N'),('BDBD','BD'),('DBDB','DB'),('BN','ND'),('DNN','NBN'),('DNB','NB')]
WITNESSES=[(4,(3,2,4,8),(1,3,15,8),10),(4,(3,2,4,8),(1,2,12,12),6),(4,(1,2,4,8),(13,6,4,8),4),(3,(3,2,4),(1,2,7),2),(2,(1,2),(3,2),1)]

def valid_model(n,p,r,a):
  bits=range(n)
  for rel in (p,r):
    assert all(rel[i]>>i&1 for i in bits)
    assert all((not (rel[i]>>j&1)) or (rel[j]&~rel[i]==0) for i in bits for j in bits)
  assert all(not((p[w]>>u&1) and (p[w]>>v&1)) or (p[u]>>v&1) or (p[v]>>u&1) for w,u,v in product(bits,repeat=3))
  assert all(not(a>>w&1) or p[w]&~a==0 for w in bits)
  for w,v in product(bits,repeat=2):
    if r[w]>>v&1:
      for vp in bits:
        if p[v]>>vp&1: assert any((p[w]>>wp&1) and (r[wp]>>vp&1) for wp in bits) # backward
      for wp in bits:
        if p[w]>>wp&1: assert any((r[wp]>>vp&1) and (p[v]>>vp&1) for vp in bits) # forward
    if p[w]>>v&1:
      for vp in bits:
        if r[v]>>vp&1: assert any((r[w]>>wp&1) and (p[wp]>>vp&1) for wp in bits) # downward

def values(n,p,r,a):
  def N(s):return sum(1<<w for w in range(n) if not p[w]&s)
  def B(s):return sum(1<<w for w in range(n) if not r[w]&~s)
  def D(s):return sum(1<<w for w in range(n) if r[w]&s)
  d={'N':N,'B':B,'D':D}
  return [nextval(word,a,d) for word in REPS]

def nextval(word,a,ops):
  for c in reversed(word):a=ops[c](a)
  return a

def upper_certificate():
  # For every representative and each outer generator, prove its product is
  # congruent to an existing representative by explicitly computing the
  # contextual congruence generated by the eight identities.
  words=[''];frontier=['']
  for k in range(9):
    frontier=[w+c for w in frontier for c in 'NBD']; words.extend(frontier)
  ids={w:i for i,w in enumerate(words)}
  parents=list(range(len(words)))
  def find(x):
    while parents[x]!=x:
      parents[x]=parents[parents[x]];x=parents[x]
    return x
  def union(x,y):
    rx,ry=find(x),find(y)
    if rx!=ry:parents[rx]=ry
  for w in words:
    for lhs,rhs in RULES:
      start=0
      while True:
        where=w.find(lhs,start)
        if where<0:break
        changed=w[:where]+rhs+w[where+len(lhs):]
        if changed in ids:union(ids[w],ids[changed])
        start=where+1
  root2rep={find(ids[w]):i for i,w in enumerate(REPS)}
  assert len(root2rep)==35
  table={}
  for g in 'NBD':
    row=[]
    for word in REPS:
      root=find(ids[g+word]);assert root in root2rep,(g,word)
      row.append(root2rep[root])
    table[g]=row
  return table

def main():
  table=upper_certificate()
  for n,p,r,a in WITNESSES:valid_model(n,p,r,a)
  vectors=[values(*model) for model in WITNESSES]
  signatures=[tuple(v[i] for v in vectors) for i in range(35)]
  assert len(set(signatures))==35
  print('representatives',len(REPS),'witness_models',len(WITNESSES),'distinct_signatures',len(set(signatures)))
  print('closure rows of 35 representatives by generator, zero-based indices:')
  for g,row in table.items():print(g,*row)
  print('GS4C_35_VERIFY_OK')
  return table
if __name__=='__main__': main()
