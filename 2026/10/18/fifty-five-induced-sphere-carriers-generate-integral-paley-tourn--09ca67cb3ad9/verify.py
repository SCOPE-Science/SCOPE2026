"""Exact integral chain checks for induced spherical generators of Paley-11 directed flag homology.
Run: python verify.py  (requires SymPy >=1.10).
"""
from collections import Counter, defaultdict
from itertools import combinations
from math import prod
from sympy import ZZ, SparseMatrix
from sympy.matrices.normalforms import smith_normal_form

P = 11
QR = {1, 3, 4, 5, 9}
V = tuple(range(P))

def arrow(a,b):
    return (b-a) % P in QR

def ordered(face):
    return tuple(sorted(face, key=lambda v: -sum(arrow(v,w) for w in face)))

def transitive(face):
    f = ordered(face)
    return all(arrow(a,b) for i,a in enumerate(f) for b in f[i+1:])

F = {k:[ordered(t) for t in combinations(V,k+1) if transitive(t)]
     for k in range(4)}
assert [len(F[k]) for k in range(4)] == [11,55,110,55]
index = {k:{frozenset(s):i for i,s in enumerate(F[k])} for k in F}

def boundary(k):
    ans = []
    for f in F[k]:
        col = defaultdict(int)
        for j in range(k+1):
            col[index[k-1][frozenset(f[:j]+f[j+1:])]] += (-1)**j
        ans.append({i:v for i,v in col.items() if v})
    return ans
B1, B2, B3 = boundary(1), boundary(2), boundary(3)

# Check both consecutive simplicial boundary identities exactly over integers.
for triangle_boundary in B2:
    accumulated = defaultdict(int)
    for edge_id, coeff in triangle_boundary.items():
        for vertex_id, val in B1[edge_id].items():
            accumulated[vertex_id] += coeff * val
    assert not any(accumulated.values())
for tetra_boundary in B3:
    accumulated = defaultdict(int)
    for triangle_id, coeff in tetra_boundary.items():
        for edge_id, val in B2[triangle_id].items():
            accumulated[edge_id] += coeff * val
    assert not any(accumulated.values())

def columns_to_matrix(cols,rows):
    M = SparseMatrix(rows,len(cols),{})
    for j,c in enumerate(cols):
        for i,v in c.items(): M[i,j] = v
    return M

def rank_mod(cols,p):
    basis = {}
    for col in cols:
        w={i:v%p for i,v in col.items() if v%p}
        while w:
            top=max(w)
            if top not in basis:
                inv=pow(w[top],-1,p)
                basis[top]={i:(v*inv)%p for i,v in w.items() if (v*inv)%p}
                break
            fac=w[top]
            for i,v in basis[top].items():
                new=(w.get(i,0)-fac*v)%p
                if new: w[i]=new
                else: w.pop(i,None)
    return len(basis)

def smith_invariants(cols, rows):
    diag=smith_normal_form(columns_to_matrix(cols,rows),domain=ZZ)
    return [abs(int(diag[i,i])) for i in range(min(diag.shape)) if diag[i,i]!=0]

# Cycle classification: a full five-vertex induced complex has all ten edges.
# By exact mod-2 boundary ranks, only these subsets have nonzero H_2.
carriers=[]
for S in combinations(V,5):
    s=set(S)
    twos=[i for i,f in enumerate(F[2]) if set(f)<=s]
    threes=[i for i,f in enumerate(F[3]) if set(f)<=s]
    edges=[i for i,f in enumerate(F[1]) if set(f)<=s]
    ei={v:i for i,v in enumerate(edges)}
    ti={v:i for i,v in enumerate(twos)}
    cols2=[{ei[e]:v for e,v in B2[j].items()} for j in twos]
    cols3=[{ti[t]:v for t,v in B3[j].items()} for j in threes]
    beta2=len(twos)-rank_mod(cols2,2)-rank_mod(cols3,2)
    assert beta2 in (0,1)
    if beta2: carriers.append(S)
assert len(carriers)==55

base={0,1,2,3,7}
orbit={tuple(sorted((a*x+b)%P for x in base)) for a in QR for b in V}
assert len(orbit)==55 and orbit==set(carriers)

# Each six-facet sphere on five vertices has a spare edge. Solve its
# integral orientation by propagation across the nine sphere edges.
Z=[]
for S in carriers:
    s=set(S)
    tris=[j for j,f in enumerate(F[2]) if set(f)<=s]
    tetra=[j for j,f in enumerate(F[3]) if set(f)<=s]
    assert len(tris)==6 and not tetra
    incidence=defaultdict(list)
    for j in tris:
        for e,v in B2[j].items():incidence[e].append((j,v))
    used={e:x for e,x in incidence.items() if x}
    assert len(used)==9 and all(len(x)==2 for x in used.values())
    sign={tris[0]:1}
    changed=True
    while changed:
        changed=False
        for pair in used.values():
            (i,a),(j,b)=pair
            if i in sign and j not in sign:
                sign[j]=-sign[i]*a//b;changed=True
            if j in sign and i not in sign:
                sign[i]=-sign[j]*b//a;changed=True
    assert len(sign)==6 and set(sign.values())<={-1,1}
    z={i:sign[i] for i in tris}
    assert all(sum(v*z.get(j,0) for j,v in incident)==0
               for incident in ([ (j,c) for j,c in pair ] for pair in used.values()))
    Z.append(z)

# Integral ranks and Smith forms: the full cycle lattice is generated by
# the 55 local sphere cycles plus degree-three boundaries.
# Exact rational rank of d2 is 45: modular rank gives the lower bound,
# and im(d2) <= ker(d1), dimension 55 - (11-1) = 45, gives the upper.
assert rank_mod(B1,101)==10
assert rank_mod(B2,101)==45
assert rank_mod(B3,101)==55
assert rank_mod(B3,2)==54
assert Counter(smith_invariants(B3,110)) == Counter({1:54,2:1})
assert Counter(smith_invariants(B3+Z,110)) == Counter({1:65})
assert rank_mod(B3+Z,101)==65

# Canonical order-two cycle: half the boundary of the sum of all 55
# coherently oriented transitive tetrahedra.
tetra_sum=defaultdict(int)
for col in B3:
    for i,v in col.items(): tetra_sum[i]+=v
assert len(tetra_sum)==110 and Counter(tetra_sum.values())==Counter({2:55,-2:55})
torsion={i:v//2 for i,v in tetra_sum.items()}
assert len(torsion)==110
for edge in range(55):
    assert sum(v*torsion.get(i,0) for i,v in
               [(i,c.get(edge,0)) for i,c in enumerate(B2)])==0
# 2*torsion lies in im(d3). If torsion were a boundary, full column rank
# over Q would force its unique preimage to be (1/2,...,1/2), not integral.

# Translations and quadratic-residue multipliers preserve the unique
# transitive orders and the all-tetrahedra torsion chain.
for a in QR:
    for b in V:
        perm=lambda x:(a*x+b)%P
        assert all(transitive(tuple(perm(x) for x in f)) for f in F[3])
        assert {frozenset(perm(x) for x in S) for S in carriers}=={frozenset(S) for S in carriers}

print('VERIFY_OK 11_VERTICES 55_SPHERE_CARRIERS 55_AFFINE_ORBIT')
print('CHAIN_FVECTOR 11_55_110_55 RANK_D2_45 RANK_D3_55')
print('SMITH_D3 54_ONES_AND_2; SMITH_D3_PLUS_SPHERES 65_ONES')
print('CANONICAL_TORSION 110_TRIANGLES 55_PLUS_55_MINUS')
