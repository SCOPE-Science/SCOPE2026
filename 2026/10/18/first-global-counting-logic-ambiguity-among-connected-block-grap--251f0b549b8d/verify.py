#!/usr/bin/env python3
"""Exact, dependency-free census of small block graphs under 1-WL.

All graphs have vertex set {0,...,n-1} and a bit for each unordered pair.
Isomorphism orbits are generated by adjacent transpositions of vertices;
the transpositions generate the full symmetric group. Colour signatures are
interned over all isomorphism classes of each fixed order, not per graph.
"""
from collections import Counter, defaultdict, deque


def pairs(n):
    return [(i, j) for i in range(n) for j in range(i+1, n)]


def encode(n, edges):
    lookup = {e: j for j, e in enumerate(pairs(n))}
    mask = 0
    for u, v in edges:
        mask |= 1 << lookup[tuple(sorted((u, v)))]
    return mask


def graph_edges(n, mask):
    return tuple(e for i, e in enumerate(pairs(n)) if (mask >> i) & 1)


def adjacency(n, mask):
    A = [set() for _ in range(n)]
    for a, b in graph_edges(n, mask):
        A[a].add(b); A[b].add(a)
    return tuple(tuple(sorted(neigh)) for neigh in A)


def swap_tables(n):
    E = pairs(n); e_id = {e: k for k, e in enumerate(E)}
    tables = []
    for s in range(n-1):
        dest = []
        for u, v in E:
            w = s+1 if u == s else s if u == s+1 else u
            z = s+1 if v == s else s if v == s+1 else v
            dest.append(1 << e_id[tuple(sorted((w, z)))])
        tables.append(tuple(dest))
    return tables


def swap_mask(mask, table):
    ans = 0
    while mask:
        b = mask & -mask
        ans |= table[b.bit_length()-1]
        mask ^= b
    return ans


def representatives(n):
    tables = swap_tables(n)
    unseen = bytearray(b'\x01') * (1 << len(pairs(n)))
    reps = []
    canonical = {} # each labeled graph mask -> its orbit's minimum (BFS starts minimum)
    for seed in range(len(unseen)):
        if not unseen[seed]:
            continue
        reps.append(seed)
        unseen[seed] = 0
        todo = [seed]
        for mask in todo:
            canonical[mask] = seed
            for tab in tables:
                alt = swap_mask(mask, tab)
                if unseen[alt]:
                    unseen[alt] = 0
                    todo.append(alt)
    assert len(canonical) == (1 << len(pairs(n)))
    assert not any(unseen)
    return reps, canonical


def is_block_graph(A):
    n = len(A)
    # Connectedness test, including singleton graph.
    seen = {0}; stack = [0]
    while stack:
        v = stack.pop()
        for w in A[v]:
            if w not in seen: seen.add(w); stack.append(w)
    if len(seen) != n: return False
    # Tarjan's DFS edge-stack decomposition into biconnected edge blocks.
    when = [-1]*n; low = [-1]*n; edge_stack=[];clock=[0]; blocks=[]
    def visit(v,parent):
        when[v]=low[v]=clock[0]; clock[0]+=1
        for w in A[v]:
            if when[w]<0:
                edge_stack.append((v,w))
                visit(w,v)
                low[v]=min(low[v],low[w])
                if low[w]>=when[v]:
                    edges=[]
                    while True:
                        e=edge_stack.pop();edges.append(e)
                        if e==(v,w):break
                    blocks.append(edges)
            elif w!=parent and when[w]<when[v]:
                low[v]=min(low[v],when[w]);edge_stack.append((v,w))
    visit(0,-1)
    assert not edge_stack
    for edges in blocks:
        vertices = {x for a,b in edges for x in (a,b)}
        if len(edges) != len(vertices)*(len(vertices)-1)//2:
            return False
    return True


def wl_classes(adjs):
    if not adjs: return {}
    n = len(adjs[0]); colors=[[0]*n for A in adjs]
    for round_no in range(2*n+3):
        desc = [[(colors[g][v], tuple(sorted(Counter(colors[g][u] for u in A[v]).items())))
                 for v in range(n)] for g,A in enumerate(adjs)]
        dictionary = {x:i for i,x in enumerate(sorted({x for row in desc for x in row}))}
        new = [[dictionary[x] for x in row] for row in desc]
        if new==colors:
            break
        colors=new
    else:
        raise AssertionError('Global refinement did not stabilize')
    groups=defaultdict(list)
    for index,col in enumerate(colors):
        groups[tuple(sorted(col))].append(index)
    return groups


def run():
    graph_totals=[1,2,4,11,34,156]
    block_totals=[1,1,2,4,9,22]
    for n in range(1,7):
        reps,canonical = representatives(n)
        assert len(reps)==graph_totals[n-1],(n,len(reps))
        As=[adjacency(n, mask) for mask in reps]
        blocks={i for i,A in enumerate(As) if is_block_graph(A)}
        assert len(blocks)==block_totals[n-1],(n,len(blocks))
        groups=wl_classes(As)
        bad={i:sorted(bucket) for bucket in groups.values() if len(bucket)>1 for i in bucket if i in blocks}
        expected=1 if n==6 else 0
        assert len(bad)==expected,(n,bad)
        if n==6:
            i, partners = next(iter(bad.items()))
            assert len(partners)==2 and sum(j in blocks for j in partners)==1
            assert len(groups)==152
            G=encode(n,((0,1),(0,2),(1,2),(0,3),(3,4),(3,5),(4,5)))
            H=encode(n,((0,3),(0,1),(1,2),(2,3),(0,4),(4,5),(5,3)))
            assert set(partners)=={reps.index(canonical[G]),reps.index(canonical[H])}
            assert is_block_graph(adjacency(n,G))
            assert not is_block_graph(adjacency(n,H))
            def triangle_count(A):
                return sum(1 for a in range(n) for b in A[a] if a<b
                           for c in A[b] if b<c and c in A[a])
            assert triangle_count(adjacency(n,G))==2
            assert triangle_count(adjacency(n,H))==0
            assert sum(len(bucket)>1 for bucket in groups.values() if i in bucket)==1
            print('order 6: unique connected block-graph exception, unique nonisomorphic partner;')
            print('  block witness has 2 triangles, partner 0 triangles; both have 7 edges')
        print(f'n={n}: unlabeled={len(reps)} connected_block={len(blocks)} '
              f'nonamenable_connected_block={len(bad)} global_WL_classes={len(groups)}')
    print('VERIFIED_FIRST_FAILURE_ORDER_6_AND_UNIQUE_PAIR')

if __name__ == '__main__':run()
