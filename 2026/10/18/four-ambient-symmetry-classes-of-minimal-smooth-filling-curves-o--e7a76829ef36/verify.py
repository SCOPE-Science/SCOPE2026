# Basis monomials X0^(4-i) X1^i Y0^(3-j) Y1^j, i=0..4,j=0..3
terms=[(i,j) for i in range(5) for j in range(4)]
pt=[(1,0),(0,1),(1,1)]
def evexp(i,j,X,Y): return (X[0]**(4-i)*X[1]**i*Y[0]**(3-j)*Y[1]**j)&1
