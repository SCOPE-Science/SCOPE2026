# GL2(F2) generated by swap and shear
maps=[((0,1),(1,0)),((1,1),(0,1))]
def mul_exp(a,b):
 prod={(0,0):1}
 for _ in range(a):
  nxt={}
  for (i,j) in prod:nxt[(i+1,j)]=nxt.get((i+1,j),0)^1;nxt[(i,j+1)]=nxt.get((i,j+1),0)^1
  prod={p:v for p,v in nxt.items() if v}
 return prod

def linear_pow(v,d):
 out={(0,0):1}
 for _ in range(d):
  nxt={}
  for (i,j) in out:
   if v[0]:nxt[(i+1,j)]=nxt.get((i+1,j),0)^1
   if v[1]:nxt[(i,j+1)]=nxt.get((i,j+1),0)^1
  out={p:v for p,v in nxt.items() if v}
 return out

def polysmul(f,g):
 h={}
 for (a,b) in f:
  for (c,d) in g:h[(a+c,b+d)]=h.get((a+c,b+d),0)^1
 return {i:v for i,v in h.items() if v}

def monomial_action(dim,m):
 # use exponents i of coord1 basis degree dim
 out=[]
 for i in range(dim+1):
  po=polysmul(linear_pow(m[0],dim-i),linear_pow(m[1],i))
  out.append({k:v for k,v in po.items() if v})
 return out

def generate_action(dim,m,onx=True):
 ps=monomial_action(dim,m);output=[]
 for i,j in terms:
  nbits=0
  for (a,b) in ps[i if onx else j]:
   if onx:idx=terms.index((b,j))
   else:idx=terms.index((i,b))
   nbits ^=1<<idx
  output.append(nbits)
 return output
