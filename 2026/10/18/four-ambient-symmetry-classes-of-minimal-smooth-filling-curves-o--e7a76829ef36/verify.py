def parity(x):return x.bit_count()&1

def gf2null(rows,n):
 rows=list(rows);piv=[];row=0
 for col in range(n):
  k=next((i for i in range(row,len(rows)) if rows[i]&(1<<col)),None)
  if k is None:continue
  rows[row],rows[k]=rows[k],rows[row]
  for i in range(len(rows)):
   if i!=row and (rows[i]&(1<<col)):rows[i]^=rows[row]
  piv.append(col); row+=1
  if row==len(rows):break
 free=[j for j in range(n) if j not in piv]; basis=[]
 for j in free:
  v=1<<j
  for r,p in zip(rows,piv):
   if r&(1<<j):v|=1<<p
  basis.append(v)
 return basis,row
basis,rank=gf2null(evalrows,20)
