"""Finite-field independent test for prime-field ring generation in incidence algebras.

Run with Python 3.10+. The program computes subrings generated by matrices,
without using the proposed Frobenius-orbit criterion in the generation test.
"""
from itertools import product
from math import comb


def ff_mul(a,b,q):
    if q in (2,3): return (a*b)%q
    if q==4:
        ans=0
        for i in range(2):
            for j in range(2):
                if (a>>i)&1 and (b>>j)&1: ans ^= 1<<(i+j)
        if ans&4: ans ^=7  # x^2 = x+1
        return ans
    raise ValueError(q)

def ff_add(a,b,q):
    return a^b if q==4 else (a+b)%q


def flatten_basis_mats(q,n):
    return [(i,j) for i in range(n) for j in range(i,n)]

def mul(x,y,q,n,coords):
    D={(i,j):t for t,(i,j) in enumerate(coords)}
    return tuple(sum((ff_mul(x[D[i,k]],y[D[k,j]],q) for k in range(n) if (i,k) in D and (k,j) in D))%q if q in (2,3) else _xorprods(x,y,i,j,D) for i,j in coords)

def _xorprods(x,y,i,j,D):
    v=0
    for k in range(max(j+1,i+1)):
        if (i,k) in D and (k,j) in D:
            v^=ff_mul(x[D[i,k]],y[D[k,j]],4)
    return v


def is_ring_generated(mats,q,n,coords):
    """Additive closure of 1, generators and all their ring products."""
    zero=(0,)*len(coords)
    unit=tuple(int(i==j) for i,j in coords)
    p=2 if q==4 else q
    # Maintain F_p-span of ring elements, from raw vectors of polynomial coordinate encoding.
    # For q=4 split coefficient into two bits; for prime q each coefficient is one digit.
    def arr(x):
        return sum(((x[i]>>b)&1)<< (2*i+b) for i in range(len(x)) for b in range(2)) if q==4 else tuple(x)
    vecspace={zero}
    seed=[unit,*mats]
    products=[]
    while seed:
        elt=seed.pop()
        if elt in vecspace: continue
        if q==4:
            vecspace |= {tuple(a^b for a,b in zip(v,elt)) for v in tuple(vecspace)}
        else:
            vecspace |= {tuple((a+t*b)%q for a,b in zip(v,elt)) for v in tuple(vecspace) for t in range(p)}
        products.append(elt)
        # New element times previously generated monomial basis in both orders
        for other in products:
            seed.append(mul(elt,other,q,n,coords))
            seed.append(mul(other,elt,q,n,coords))
    return len(vecspace)==q**len(coords)


def expected(q,n,k,c,rho,e,p):
    from math import prod
    def mu(n):
        if n==1:return 1
        factors=0; d=2
        while d*d<=n:
            if n%d==0:
                n//=d;factors+=1
                if n%d==0:return 0
                while n%d==0:n//=d
            d+=1
        return (-1)**(factors+(n>1))
    N=sum(mu(d)*p**(e*k//d) for d in range(1,e+1) if e%d==0)//e
    diag=prod((e*(N-i) for i in range(n))) if N>=n else 0
    return diag*(q**k-q)**c*q**(k*(rho-n-c))


def run_case(q,n,k,e,p,coord=None):
    if coord is None: coord=flatten_basis_mats(q,n)
    m=q**len(coord)
    total=m**k
    gen=0
    for flat in product(range(m), repeat=k):
        mats=[tuple((number//(q**j))%q for j in range(len(coord))) for number in flat]
        gen+=is_ring_generated(mats,q,n,coord)
    covers=sum(1 for i,j in coord if i!=j and not any(i!=h!=j and (i,h) in coord and (h,j) in coord for h in range(n)))
    formula=expected(q,n,k,covers,len(coord),e,p)
    print(f'field={q} n={n} k={k}: direct={gen}, formula={formula}, total={total}',flush=True)
    assert gen==formula

if __name__=='__main__':
    for args in [(2,2,2,1,2),(3,2,2,1,3),(4,2,1,2,2),(4,2,2,2,2),(2,3,2,1,2)]:
        run_case(*args)
    run_case(2,3,2,1,2,[(0,0),(0,1),(0,2),(1,1),(2,2)])  # fork
    run_case(4,2,2,2,2,[(0,0),(1,1)])  # discrete poset
    print('VERIFY_OK: independent exhaustive generated-subring closure over seven finite incidence-ring families')
