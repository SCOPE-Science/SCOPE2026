#!/usr/bin/env python3
"""Finite exhaustive certificate for the symmetry census of convex team properties.

Only Python's standard library is required.  Four valuations are coded 0..3;
a team is the subset-mask 0..15, and a property is a 16-bit family mask.
"""
from collections import Counter
from itertools import permutations, product

V = range(4)
T = range(16)


def subset(a, b):
    return (a & b) == a


def convex_families(items, leq):
    n = len(items)
    intervals = [
        (i, j, sum(1 << h for h in range(n)
                   if leq(i, h) and leq(h, j)))
        for i in range(n) for j in range(n) if leq(i, j)
    ]
    ans = []
    for fam in range(1 << n):
        if all(not ((fam >> i) & 1 and (fam >> j) & 1)
               or (fam & middle) == middle
               for i, j, middle in intervals):
            ans.append(fam)
    return ans


def d8():
    out = set()
    for transpose in (False, True):
        for flip_p, flip_q in product((0, 1), repeat=2):
            perm = []
            for v in V:
                p, q = v >> 1, v & 1
                if transpose:
                    p, q = q, p
                perm.append(((p ^ flip_p) << 1) | (q ^ flip_q))
            out.add(tuple(perm))
    return sorted(out)


def team_map(team, perm):
    return sum(1 << perm[v] for v in V if (team >> v) & 1)


def family_map(fam, perm):
    return sum(1 << team_map(team, perm)
               for team in T if (fam >> team) & 1)


def quotient_poset(perm):
    # A cyclic group generated by perm acts on all 16 teams.
    seen = set()
    orbits = []
    for x in T:
        if x in seen:
            continue
        orbit = []
        y = x
        while y not in orbit:
            orbit.append(y)
            y = team_map(y, perm)
        assert y == x
        seen.update(orbit)
        orbits.append(tuple(orbit))

    order = [[any(subset(a, b) for a in orbits[i] for b in orbits[j])
              for j in range(len(orbits))]
             for i in range(len(orbits))]
    assert all(order[i][i] for i in range(len(orbits)))
    assert all(not (order[i][j] and order[j][i])
               for i in range(len(orbits)) for j in range(len(orbits))
               if i != j)
    assert all(not (order[i][j] and order[j][k]) or order[i][k]
               for i in range(len(orbits)) for j in range(len(orbits))
               for k in range(len(orbits)))
    return orbits, order


def cycletype(perm):
    seen = set()
    lengths = []
    for v in V:
        if v in seen:
            continue
        w, size = v, 0
        while w not in seen:
            seen.add(w)
            size += 1
            w = perm[w]
        lengths.append(size)
    return tuple(sorted(lengths))


def main():
    good = convex_families(list(T), lambda i, j: subset(i, j))
    assert len(good) == 3938
    G = d8()
    assert len(G) == 8
    by_type = {}
    for perm in G:
        orbits, order = quotient_poset(perm)
        fixed_from_quotient = len(convex_families(orbits,
                          lambda i, j: order[i][j]))
        fixed_direct = sum(family_map(fam, perm) == fam for fam in good)
        assert fixed_direct == fixed_from_quotient
        t = cycletype(perm)
        if t in by_type:
            assert by_type[t][1:] == (len(orbits), fixed_direct)
            by_type[t] = (by_type[t][0] + 1, len(orbits), fixed_direct)
        else:
            by_type[t] = (1, len(orbits), fixed_direct)

    assert by_type == {
        (1, 1, 1, 1): (1, 16, 3938),
        (1, 1, 2): (2, 12, 526),
        (2, 2): (3, 10, 186),
        (4,): (2, 6, 26),
    }
    assert sum(m * fix for m, n, fix in by_type.values()) == 5600
    assert 5600 // len(G) == 700

    unseen = set(good)
    histogram = Counter()
    while unseen:
        fam = min(unseen)
        orbit = {family_map(fam, perm) for perm in G}
        assert orbit <= unseen
        unseen.difference_update(orbit)
        histogram[len(orbit)] += 1
    assert dict(histogram) == {1: 26, 2: 54, 4: 289, 8: 331}
    assert sum(size * count for size, count in histogram.items()) == len(good)
    assert sum(histogram.values()) == 700

    # Distinguish literal automorphisms D8 from arbitrary relabelings S4.
    fixed_s4 = Counter()
    for perm in permutations(V):
        fixed_s4[cycletype(perm)] += sum(
            family_map(fam, perm) == fam for fam in good)
    assert dict(fixed_s4) == {
        (1, 1, 1, 1): 3938, (1, 1, 2): 3156,
        (2, 2): 558, (1, 3): 568, (4,): 156,
    }
    assert sum(fixed_s4.values()) // 24 == 349
    print('ORBIT_CERT_OK convex=3938 D8_orbits=700 '
          'orbit_sizes={1:26,2:54,4:289,8:331} '
          'fixed_types={1^4:3938,1^2_2:526,2^2:186,4:26} '
          'S4_orbits=349')


if __name__ == '__main__':
    main()
