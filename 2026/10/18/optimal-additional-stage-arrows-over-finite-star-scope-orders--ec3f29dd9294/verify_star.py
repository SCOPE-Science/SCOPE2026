"""Exhaustive checks for stage-preorder extension normal forms on finite rooted stars."""
from itertools import combinations
from math import comb

def close(k, mask):
    n=k+1
    rows=[(1<<i)|(((1<<n)-2) if i==0 else 0) for i in range(n)]
    e=0
    for i in range(1,n):
        for j in range(n):
            if j==i:continue
            if (mask>>e)&1:rows[i]|=1<<j
            e+=1
    for h in range(n):
        for i in range(n):
            if (rows[i]>>h)&1:rows[i]|=rows[h]
    return tuple(rows)

def popcnt(x):return x.bit_count()

def profile(k,rows):
    L=range(1,k+1)
    unseen=set(L); groups=[]
    while unseen:
        i=min(unseen)
        cls={j for j in unseen if (rows[i]>>j&1) and (rows[j]>>i&1)}
        groups.append(cls);unseen-=cls
    order={(a,b) for a,A in enumerate(groups) for b,B in enumerate(groups) if a!=b and (rows[min(A)]>>min(B))&1}
    covers={(a,b) for a,b in order if not any((a,c) in order and (c,b) in order for c in range(len(groups)))}
    U={i for i in L if all((rows[i]>>j)&1 for j in L)}
    merged={i for i in L if rows[i]&1}
    assert not merged or merged==U
    if merged:
        ui=next(a for a,G in enumerate(groups) if G==U)
        cc={a for a in range(len(groups)) if a!=ui}
        # quotient covers involving U are already generated by rooted scope links
        extras=len(U)+sum(len(G) for a,G in enumerate(groups) if a!=ui and len(G)>1)+sum(1 for a,b in covers if a in cc and b in cc)
    else:
        extras=sum(len(G) for G in groups if len(G)>1)+len(covers)
    return extras,len(groups),bool(merged)

def probe_signature(k,rows):
    # At each leaf, enumerate the truth of Box_! p under upward-closed
    # valuations p = leaves and p = leaves minus one leaf.
    Lmask=((1<<(k+1))-2)
    V=[Lmask]+[Lmask & ~(1<<j) for j in range(1,k+1)]
    return tuple(tuple(rows[i] & ~P ==0 for P in V) for i in range(1,k+1))

def stirling(n,k):
    a=[[0]*(n+1) for _ in range(n+1)];a[0][0]=1
    for i in range(1,n+1):
        for j in range(1,i+1):a[i][j]=a[i-1][j-1]+j*a[i-1][j]
    return a[n][k]

# Exact labelled poset counts through four classes by independent brute enumeration.
def poset_count(n):
    if n==0:return 1
    bits=[(i,j) for i in range(n) for j in range(n) if i!=j]
    ct=0
    for x in range(1<<len(bits)):
        rows=[1<<i for i in range(n)]
        for a,(i,j) in enumerate(bits):
            if (x>>a)&1:rows[i]|=1<<j
        if any((rows[i]>>j&1) and (rows[j]>>i&1) for i in range(n) for j in range(i+1,n)):continue
        if any((rows[i]>>j&1) and (rows[j]&~rows[i]) for i in range(n) for j in range(n)):continue
        ct+=1
    return ct

def main():
    p=[poset_count(j) for j in range(5)]
    assert p==[1,1,3,19,219]
    count0=1
    for k in range(1,5):
        minima={}
        for mask in range(1<<(k*k)):
            R=close(k,mask)
            c=popcnt(mask)
            minima[R]=min(c,minima.get(R,k*k+1))
        expected=sum(stirling(k,j)*(p[j]+j*p[j-1]) for j in range(1,k+1))
        assert len(minima)==expected,(k,len(minima),expected)
        assert len({probe_signature(k,r) for r in minima})==len(minima)
        for r,c in minima.items():
            val,_,_=profile(k,r)
            assert val==c,(k,r,val,c)
        maxmin=max(minima.values())
        predicted=[None,1,2,3,5][k]
        assert maxmin==predicted,(k,maxmin,predicted)
        print(f'k={k} relations={len(minima)} maximum_minimal_extra_edges={maxmin} all_minima_and_semantics_ok')
    for k in range(5,40):
        vals=[q*q//4+k-q+min(q,k-q) for q in range(1,k+1)]
        assert max(vals)==k*k//4
    print('EXTREMAL_FORMULA_OK k=1..39')
    print('ALL_CHECKS_OK')

if __name__=='__main__':main()
