"""Reproduce the classification of smooth ternary cubic pencils with a blocking fiber.

Python 3, SymPy; exact arithmetic only. Run: python verify_ternary_pencil.py
All projective entities are enumerated once modulo nonzero scalar.
"""
from itertools import product
from collections import Counter
import sympy as S

q = 3
X, Y, Z = S.symbols('X Y Z')
variables = (X, Y, Z)
monomials = [(i,j,3-i-j) for i in range(3,-1,-1) for j in range(3-i,-1,-1)]
assert len(monomials) == 10


def normalize(v):
    first = next((x for x in v if x), None)
    if first is None:
        raise ValueError('zero vector')
    inv = 1 if first == 1 else 2
    return tuple((inv*x) % q for x in v)

points = sorted({normalize(v) for v in product(range(q), repeat=3) if any(v)})
assert len(points) == 13
lines = [tuple(i for i,p in enumerate(points) if sum(a*b for a,b in zip(l,p)) % q == 0) for l in points]
assert len(lines)==13 and all(len(line)==4 for line in lines)
monvalues = [tuple((p[0]**i*p[1]**j*p[2]**k)%q for i,j,k in monomials) for p in points]

def evaluation(c):
    return tuple(sum(a*b for a,b in zip(c,v))%q for v in monvalues)

def zero_mask(values):
    return sum((1<<i) for i,v in enumerate(values) if v==0)

def blocks(mask):
    return all(any(mask & (1<<i) for i in line) for line in lines)

def line_component(mask):
    # Degree 3 restriction to a rational line vanishes identically if and only if
    # it vanishes at all 4 rational points of that projective line.
    return any(all(mask & (1<<i) for i in line) for line in lines)

# Directly certify the ternary nontrivial blocking-set lower bound.
# Search all 2^13 point sets, excluding sets containing a full rational line.
assert min(m.bit_count() for m in range(1<<len(points))
           if blocks(m) and not line_component(m)) == 6

def smooth(c):
    # Scheme-theoretic geometric smoothness: in each standard affine chart,
    # the ideal generated by the cubic and its three partial derivatives is (1).
    f=sum(int(a)*X**i*Y**j*Z**k for a,(i,j,k) in zip(c,monomials))
    derivs=[S.diff(f,v) for v in variables]
    for v in variables:
        basis=S.groebner([f,*derivs,v-1], *variables, modulus=q)
        if not (len(basis.polys)==1 and basis.polys[0].as_expr()==1):
            return False
    return True

F_expr=X**3+Y**3+Z**3-(X+Y+Z)*(X*Y+X*Z+Y*Z)+X*Y*Z
F_pol=S.Poly(F_expr,*variables,modulus=q)
F=tuple(int(F_pol.coeff_monomial(X**i*Y**j*Z**k))%q for i,j,k in monomials)
assert normalize(F)==F
F_eval=evaluation(F)
F_mask=zero_mask(F_eval)
assert F_mask.bit_count()==6 and blocks(F_mask) and smooth(F)

all_forms=[]
blocking_without_line=[]
for v in product(range(q), repeat=10):
    if not any(v) or normalize(v)!=v:
        continue
    all_forms.append(v)
    zmask=zero_mask(evaluation(v))
    if blocks(zmask) and not line_component(zmask):
        blocking_without_line.append(v)
assert len(all_forms)==29524
assert len(blocking_without_line)==936

# Check transitivity of the rational projective group without assuming the
# classification of blocking cubics.  Because cubics have degree < q+1,
# their point-evaluation map is injective over F_3.
forms_values={normalize(evaluation(c)) for c in blocking_without_line}
assert len(forms_values)==936
orbit=set()
for a in product(range(q),repeat=9):
    # Distinct PGL matrices: retain the scalar-normalized invertible matrices.
    if not any(a) or normalize(a)!=a:
        continue
    matrix=S.Matrix(3,3,a)
    if int(matrix.det())%q==0:
        continue
    transformed=[]
    for p in points:
        u=[sum(a[3*i+j]*p[j] for j in range(3))%q for i in range(3)]
        transformed.append(sum(c*u[0]**i*u[1]**j*u[2]**k for c,(i,j,k) in zip(F,monomials))%q)
    orbit.add(normalize(transformed))
assert len(orbit)==936 and orbit==forms_values

# Only pencils with a blocking member need to be counted. Every pencil
# through F has exactly three other projective members [G], [G+F], [G-F].
# Basepoint-freeness over F3 is the condition G(P) != 0 for all P on F.
# A rational singular-point sieve is used solely for efficiency; the final
# geometric smoothness check is the exact Groebner chart test above.
derivatives=[]
for i,j,k in monomials:
    derivatives.append(tuple((i*(p[0]**max(0,i-1))*(p[1]**j)*(p[2]**k))%q if i else 0 for p in points))
# Build all three derivative evaluation matrices (p, monomial, variable).
deriv_values=[]
for p in points:
    row=[]
    for i,j,k in monomials:
        ee=(i,j,k)
        vals=[]
        for axis in range(3):
            if ee[axis]==0: vals.append(0);continue
            vv=1
            for axis2 in range(3):
                vv=vv*pow(p[axis2],ee[axis2]-(axis==axis2),q)%q
            vals.append((ee[axis]*vv)%q)
        row.append(vals)
    deriv_values.append(row)

def smooth_at_rational_points(c):
    ev=evaluation(c)
    for k,e in enumerate(ev):
        if e: continue
        grad=[sum(c[m]*deriv_values[k][m][j] for m in range(10))%q for j in range(3)]
        if grad==[0,0,0]: return False
    return True

valid=[]
rational_survivors=0
for G in all_forms:
    e=evaluation(G)
    if any(v==0 for v,fval in zip(e,F_eval) if fval==0):
        continue
    plus=tuple((a+b)%q for a,b in zip(G,F))
    minus=tuple((a-b)%q for a,b in zip(G,F))
    members=(G,plus,minus)
    if not all(smooth_at_rational_points(m) for m in members):
        continue
    rational_survivors += 1
    if not all(smooth(m) for m in members):
        continue
    profile=tuple(sorted(sum(v==0 for v in evaluation(m)) for m in members))
    valid.append(profile)
assert rational_survivors==1152
assert len(valid)==936
profile_count=Counter(valid)
assert profile_count==Counter({(1,1,5):72,(1,2,4):396,(1,3,3):126,(2,2,3):342})
assert all(n%3==0 for n in profile_count.values())
per_F={k:v//3 for k,v in sorted(profile_count.items())}
assert sum(per_F.values())==312
assert 936*312==292032

G=(0,0,1,0,0,0,1,0,1,0) # X^2 Z + Y^3 + Y Z^2
assert evaluation(G)!=evaluation(F)
assert all(smooth(m) for m in (G,tuple((a+b)%q for a,b in zip(G,F)),tuple((a-b)%q for a,b in zip(G,F))))
assert tuple(sorted([sum(v==0 for v in evaluation(m)) for m in (G,tuple((a+b)%q for a,b in zip(G,F)),tuple((a-b)%q for a,b in zip(G,F)))]))==(1,2,4)
assert not (F_mask & zero_mask(evaluation(G)))

print('projective ternary cubic forms:',len(all_forms))
print('blocking cubics without rational linear factors:',len(blocking_without_line))
print('PGL3(F3) orbit of the smooth model:',len(orbit))
print('candidate other members surviving rational singular-point checks:',rational_survivors)
print('smooth nonbasepoint pairs (F,G):',len(valid))
print('pencils through F, by sorted other rational-point counts:',per_F)
print('total projective pencils with all F3-members smooth, no rational basepoint, and a blocking member:',936*312)
print('explicit pencil F,G: PASS')
print('ALL TESTS PASSED')
