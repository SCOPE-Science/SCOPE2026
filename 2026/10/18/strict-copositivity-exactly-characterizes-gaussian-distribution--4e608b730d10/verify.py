#!/usr/bin/env python3
"""Exact ancillary checks for the Gaussian copositivity theorem.

The infinite-dimensional analytic result is proved in RESULT.md; this program
checks its exact example and finite algebraic forms of two proof mechanisms.
Python 3 standard library only. Run: python verify.py
"""
from fractions import Fraction as F
from itertools import combinations, product
from math import factorial

B = ((1, 3), (1, 2), (1, -2), (1, -3))
S = tuple(tuple(sum(x[k] * y[k] for k in range(2)) for y in B) for x in B)
assert S == ((10, 7, -5, -8), (7, 5, -3, -5),
             (-5, -3, 5, 7), (-8, -5, 7, 10))
assert [S[i][i] for i in range(4)] == [10, 5, 5, 10]
# Gram rank two: one nonzero 2 by 2 principal minor, every column
# lies in the span of the two columns generated by the displayed B.
assert S[0][0] * S[1][1] - S[0][1]**2 == 1
assert sum(1 for i, j in combinations(range(4), 2) if S[i][j] < 0) == 4
# All vectors in conv(B) have first coordinate one, so its distance to
# the origin is at least one.  Opposite rows average to (1, 0).
assert tuple(F(B[0][k] + B[3][k], 2) for k in range(2)) == (1, 0)
assert tuple(row[0] for row in B) == (1, 1, 1, 1)
# Positive common factor is Z=G_1: a_i=1 and σ_i² = 10, 5, 5, 10.
assert min(F(1, S[i][i]) for i in range(4)) == F(1, 10)
# The linear transformations give a ratio that obeys the theorem.
num = sum(sum(row[k] for row in B)**2 for k in range(2))
den = sum(S[i][i] for i in range(4))
assert F(num, den) == F(8, 15) >= F(1, 10)
# Boundary: covariance diagonal-positive but a nonnegative null vector.
C = ((1, 0), (-1, 0), (0, 1))
w = (F(1,2), F(1,2), F(0))
assert all(sum(w[i] * C[i][k] for i in range(3)) == 0 for k in range(2))
assert sum(w[i]**2 * sum(v*v for v in C[i]) for i in range(3)) == F(1,2)

# Conditional Gaussian Hermite contraction: for centered Hermite
# polynomials, the variance after a ρ-correlated normal observation is
# Σ k! c_k² ρ^(2k) <= ρ² Σ k! c_k².  Exact rational cases only.
hermite_count = 0
for rho in (F(0), F(1,9), F(1,3), F(2,3), F(1)):
    for n in range(1, 11):
        cs = [F((-1)**k * (2*k + 1), (k + 1)**2) for k in range(1, n+1)]
        var = sum(F(factorial(k)) * cs[k-1]**2 for k in range(1, n+1))
        projected = sum(F(factorial(k)) * cs[k-1]**2 * rho**(2*k)
                        for k in range(1, n+1))
        assert projected <= rho**2 * var
        hermite_count += 1
# Monotone Chebyshev covariance: exact finite-support prototypes.
def covariance(xs, ys):
    n = len(xs)
    return sum(xs[i]*ys[i] for i in range(n))*n - sum(xs)*sum(ys)

mono_count = 0
zs = (F(-3), F(-1), F(0), F(2), F(4))
for a, b, c, d in product((F(1), F(2), F(3)),
                           (F(-2), F(0), F(1)),
                           (F(1), F(3)),
                           (F(-4), F(0), F(4))):
    xs = [max(F(0), a*z+b) for z in zs]
    ys = [max(F(0), c*z+d) for z in zs]
    assert covariance(xs, ys) >= 0
    mono_count += 1
print('PASS: exact 4x4 rank-two covariance, nonnegative-orthant certificate,')
print('      singular boundary witness, {} Hermite and {} monotonicity checks.'.format(
    hermite_count, mono_count))
