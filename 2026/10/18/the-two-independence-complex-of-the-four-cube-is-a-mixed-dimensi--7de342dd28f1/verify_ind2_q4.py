#!/usr/bin/env python3
"""Finite exact certificate for the three-path-free complex of the 4-cube.
Requires Python 3.9+; no optional libraries or external data.
"""
from collections import Counter, defaultdict, deque
from functools import lru_cache

N = 16
FULL = (1 << N) - 1
PIVOTS = [0, 11, 5, 4, 2, 3, 15, 10, 8, 13, 7, 14, 9, 12, 6, 1]

# Vertices are 4-bit strings, encoded as 0,...,15.
adjacency = [sum(1 << j for j in range(N) if (i ^ j).bit_count() == 1)
             for i in range(N)]
assert all(m.bit_count() == 4 for m in adjacency)
assert all((adjacency[i] >> j) & 1 == (adjacency[j] >> i) & 1
           for i in range(N) for j in range(N))


def is_face(s):
    # The selected subgraph has connected components of size <=2
    # iff no selected vertex has two selected neighbours.
    return all((adjacency[i] & s).bit_count() <= 1
               for i in range(N) if (s >> i) & 1)


faces = {s for s in range(1, FULL + 1) if is_face(s)}
f_vector = [sum(s.bit_count() == d + 1 for s in faces) for d in range(8)]
assert f_vector == [16, 120, 464, 964, 960, 440, 80, 10]
assert len(faces) == 3054
assert all((s ^ (1 << i)) in faces for s in faces for i in range(N)
           if s & (1 << i) and s.bit_count() > 1)

# A matching is generated by successively toggling the listed vertices,
# pairing only faces still unmatched from preceding toggle stages.
unmatched = set(faces)
up_of = {}
down_of = {}
for i in PIVOTS:
    toggle = 1 << i
    for s in sorted(unmatched):
        if not (s & toggle) and s | toggle in unmatched:
            u = s | toggle
            assert u.bit_count() == s.bit_count() + 1
            up_of[s] = u
            down_of[u] = s
            unmatched.remove(s)
            unmatched.remove(u)

critical = unmatched
critical_vector = Counter(s.bit_count() - 1 for s in critical)
assert len(up_of) == len(down_of) == 1518
assert dict(critical_vector) == {0: 1, 3: 16, 4: 1}
assert not(set(up_of) & set(down_of))
assert not(set(up_of) & critical) and not(set(down_of) & critical)

# Explicitly test Forman acyclicity by topologically sorting the *entire*
# directed face-poset Hasse graph.  Normally a face relation points down;
# the matching incidences are reversed, pointing up.
indeg = {s: 0 for s in faces}
outgoing = {s: [] for s in faces}
covers = 0
for upper in faces:
    if upper.bit_count() == 1:
        continue
    for i in range(N):
        if not (upper >> i) & 1:
            continue
        lower = upper ^ (1 << i)
        covers += 1
        if up_of.get(lower) == upper:
            src, target = lower, upper
        else:
            src, target = upper, lower
        outgoing[src].append(target)
        indeg[target] += 1
assert covers == 13568
queue = deque(s for s in faces if indeg[s] == 0)
visited = 0
while queue:
    s = queue.popleft()
    visited += 1
    for target in outgoing[s]:
        indeg[target] -= 1
        if indeg[target] == 0:
            queue.append(target)
assert visited == len(faces), 'matching has a closed gradient path'


def oriented_boundary(s):
    """Standard simplicial sign from increasing binary vertex labels."""
    return [(s ^ (1 << i), -1 if j & 1 else 1)
            for j, i in enumerate(i for i in range(N) if (s >> i) & 1)]

# The only potentially nonzero Morse differential maps degree 4 to 3.
# Algebraic elementary collapses give an exact Z-linear projection of the
# boundaries of 4-cells onto critical 3-cells.  A 3-cell paired downward
# with a 2-cell projects to 0.  A 3-cell paired upward with a 4-cell
# is eliminated using the oriented boundary of its matched 4-cell.
recursion_stack = set()
@lru_cache(None)
def project_three(s):
    assert s.bit_count() == 4
    if s in critical:
        return {s: 1}
    if s in down_of:
        return {}
    assert s in up_of
    if s in recursion_stack:
        raise AssertionError('circular elimination')
    recursion_stack.add(s)
    upper = up_of[s]
    assert upper.bit_count() == 5
    inc = dict(oriented_boundary(upper))
    assert inc[s] in (-1, 1)
    accumulator = defaultdict(int)
    for other, coefficient in inc.items():
        if other == s:
            continue
        for crit, val in project_three(other).items():
            accumulator[crit] -= inc[s] * coefficient * val
    recursion_stack.remove(s)
    return {crit: val for crit, val in accumulator.items() if val}

critical_top = next(s for s in critical if s.bit_count() == 5)
morse_boundary = defaultdict(int)
for s, coefficient in oriented_boundary(critical_top):
    for crit, val in project_three(s).items():
        morse_boundary[crit] += coefficient * val
morse_boundary = {s: c for s, c in morse_boundary.items() if c != 0}
assert not morse_boundary, morse_boundary

# Separate cross-check: mod-two ranks of all original (not Morse)
# simplicial boundary maps.  This does not substitute for the exact
# signed integral Morse differential above.
by_dimension = {d: sorted(s for s in faces if s.bit_count() - 1 == d)
                for d in range(8)}

def gf2_rank(d):
    row = {s: j for j, s in enumerate(by_dimension[d - 1])}
    pivots = {}
    for upper in by_dimension[d]:
        vector = 0
        for i in range(N):
            if (upper >> i) & 1:
                vector ^= 1 << row[upper ^ (1 << i)]
        while vector:
            lead = vector.bit_length() - 1
            if lead in pivots:
                vector ^= pivots[lead]
            else:
                pivots[lead] = vector
                break
    return len(pivots)

ranks = [0] + [gf2_rank(d) for d in range(1, 8)] + [0]
betti = [f_vector[d] - ranks[d] - ranks[d + 1] for d in range(8)]
assert ranks == [0, 15, 105, 359, 589, 370, 70, 10, 0]
assert betti == [1, 0, 0, 16, 1, 0, 0, 0]

print('faces_nonempty:', len(faces))
print('f_vector:', f_vector)
print('forbidden_three_vertex_paths:',
      sum(not is_face(s) for s in range(1, FULL + 1) if s.bit_count() == 3))
print('matched_pairs:', len(up_of))
print('hasse_covers:', covers)
print('topological_sort_visited:', visited)
print('critical_vector:', sorted(critical_vector.items()))
print('critical_four_cell:', critical_top)
print('critical_three_cells:', sorted(s for s in critical if s.bit_count() == 4))
print('signed_morse_boundary:', morse_boundary)
print('f2_boundary_ranks:', ranks[1:8])
print('f2_betti:', betti)
print('RESULT: exact integral Morse model: 1 vertex, 16 three-cells, 1 four-cell, zero attaching degree')
