#!/usr/bin/env python3
"""Randomized reproducible test of stable cells and their automorphism group."""
import random, itertools, collections
R=random.Random(17311)

def closure(n,edges):
    reach=[set() for _ in range(n)]
    for a,b in edges: reach[a].add(b)
    for k in range(n):
        for i in range(n):
            if k in reach[i]:reach[i] |= reach[k]
    if any(i in reach[i] for i in range(n)):return None
    return tuple(sum(1<<j for j in reach[i]) for i in range(n))

def colors(rows):
    n=len(rows); color=[0]*n
    for _ in range(n):
        shapes=[]
        for x in range(n):
            ct=collections.Counter((color[y],0 if rows[x]>>y&1 else 1 if rows[y]>>x&1 else 2)
                                   for y in range(n) if y!=x)
            shapes.append((color[x],tuple(sorted((c,r,k) for (c,r),k in ct.items()))))
        inds={v:i for i,v in enumerate(sorted(set(shapes)))}
        updated=[inds[v] for v in shapes]
        if updated==color:break
        color=updated
    return color

def aut_count(rows,cols):
    groups=collections.defaultdict(list)
    for i,c in enumerate(cols):groups[c].append(i)
    pairs=[g for g in groups.values() if len(g)==2]
    assert all(len(g)<=2 for g in groups.values())
    comp=[]
    for mask in range(1<<len(pairs)):
        p=list(range(len(rows)))
        for a,(i,j) in enumerate(pairs):
            if mask>>a&1:p[i],p[j]=p[j],p[i]
        if all(((rows[i]>>j)&1)==((rows[p[i]]>>p[j])&1)
               for i in range(len(rows)) for j in range(len(rows))):comp.append(mask)
    # Matching graph components determine the free global flips.
    parent=list(range(len(pairs)))
    def root(i):
        while parent[i]!=i:i=parent[i]
        return i
    for a,A in enumerate(pairs):
        for b,B in enumerate(pairs):
            if a>=b:continue
            count=sum((rows[i]>>j)&1 for i in A for j in B)
            count+=sum((rows[i]>>j)&1 for i in B for j in A)
            if count==2:
                pa,pb=root(a),root(b)
                parent[pa]=pb
    expected=1<<len({root(i) for i in range(len(pairs))})
    return len(comp),expected

def main():
    tested=0
    for n in range(3,13):
        for _ in range(150):
            p=R.randrange(1,n)
            edges=[(i,i+1) for i in range(p-1)]
            edges += [(i,i+1) for i in range(p,n-1)]
            for i in range(p):
                for j in range(p,n):
                    if R.random()<.15: edges.append((i,j))
                    if R.random()<.15: edges.append((j,i))
            rows=closure(n,edges)
            if rows is None:continue
            col=colors(rows)
            # Colors generated by the order relation, no individualization.
            actual,predicted=aut_count(rows,col)
            assert actual==predicted,(n,actual,predicted,rows)
            tested+=1
    print(f'finite_width_two_order_samples={tested} n_range=3..12 orbit_and_group_checks=PASS')
if __name__=='__main__':main()
