"""Reproduce the affine-orbit and cyclic-span theorem for the binary BCH code of length 73.

Requires Python 3 standard library only. All computations use exact integer arithmetic.
"""
from collections import Counter, defaultdict
from itertools import combinations
from math import comb

N = 73
P = (1 << 9) | (1 << 4) | 1
MOD = (1 << N) | 1


def field_mul(a, b):
    ans = 0
    while b:
        if b & 1:
            ans ^= a
        b >>= 1
        a <<= 1
        if a & (1 << 9):
            a ^= P
    return ans


def field_pow(a, k):
    ans = 1
    while k:
        if k & 1:
            ans = field_mul(ans, a)
        a = field_mul(a, a)
        k >>= 1
    return ans


def minimal_polynomial(a):
    coeffs, visited = [1], set()
    while a not in visited:
        visited.add(a)
        nxt = [0] * (len(coeffs) + 1)
        for j, c in enumerate(coeffs):
            nxt[j] ^= field_mul(c, a)
            nxt[j + 1] ^= c
        coeffs = nxt
        a = field_mul(a, a)
    assert all(c in (0, 1) for c in coeffs)
    return sum(c << j for j, c in enumerate(coeffs))


def poly_mul(a, b):
    ans = 0
    while b:
        if b & 1:
            ans ^= a
        a <<= 1
        b >>= 1
    return ans


def poly_divmod(a, b):
    q = 0
    while a and a.bit_length() >= b.bit_length():
        d = a.bit_length() - b.bit_length()
        q ^= 1 << d
        a ^= b << d
    return q, a


def poly_gcd(a, b):
    while b:
        _, a = poly_divmod(a, b)
        a, b = b, a
    return a


def rank_gf2(rows):
    pivots = {}
    for row in rows:
        while row:
            k = row.bit_length() - 1
            if k not in pivots:
                pivots[k] = row
                break
            row ^= pivots[k]
    return len(pivots)


def polynomial_of_support(s):
    return sum(1 << i for i in s)


def krawtchouk(t, w):
    return sum((-1) ** j * comb(w, j) * comb(N-w, t-j)
               for j in range(t + 1) if j <= w and t-j <= N-w)


assert field_pow(2, 511) == 1
assert field_pow(2, 73) != 1 and field_pow(2, 7) != 1
beta = field_pow(2, 7)
assert beta != 1 and field_pow(beta, 73) == 1
m1 = minimal_polynomial(beta)
m3 = minimal_polynomial(field_pow(beta, 3))
assert (m1, m3) == (0x299, 0x217)
g = poly_mul(m1, m3)
assert g == 0x5165F and g.bit_length() - 1 == 18
h, residue = poly_divmod(MOD, g)
assert residue == 0 and h.bit_length() - 1 == 55
# Reciprocal of h generates the Euclidean dual of the cyclic code generated by g.
h_star = sum(((h >> j) & 1) << (55-j) for j in range(56))
dual_basis = [h_star << j for j in range(18)]
assert all(row.bit_length() <= N for row in dual_basis)
assert rank_gf2(dual_basis) == 18

# Exhaust the complete 2^18-word dual using Gray code; apply MacWilliams.
counts = Counter()
word = previous_gray = 0
for k in range(1 << 18):
    gray = k ^ (k >> 1)
    if k:
        word ^= dual_basis[(gray ^ previous_gray).bit_length() - 1]
    counts[word.bit_count()] += 1
    previous_gray = gray
assert sum(counts.values()) == 1 << 18
assert sorted(counts.items()) == [
    (0, 1), (24, 1533), (28, 12629), (32, 59130), (36, 92929),
    (40, 72927), (44, 20367), (48, 2409), (52, 219)]
primal_initial = []
for t in range(7):
    num = sum(c * krawtchouk(t, wt) for wt, c in counts.items())
    assert num % (1 << 18) == 0
    primal_initial.append(num >> 18)
assert primal_initial == [1, 0, 0, 0, 0, 0, 876]

# Reconstruct all 876 supports independently from equal pair of 3-subset syndromes.
cols = [sum(((dual_basis[j] >> i) & 1) << j for j in range(18))
        for i in range(N)]
buckets = defaultdict(list)
for triple in combinations(range(N), 3):
    buckets[cols[triple[0]] ^ cols[triple[1]] ^ cols[triple[2]]].append(triple)
supports = set()
for triples in buckets.values():
    for i, a in enumerate(triples):
        a_set = set(a)
        for b in triples[:i]:
            if a_set.isdisjoint(b):
                supports.add(tuple(sorted(a + b)))
assert len(supports) == 876
assert all(poly_divmod(polynomial_of_support(s), g)[1] == 0 for s in supports)

# Affine action: i -> a + 2^e i mod 73, a in Z_73, 0 <= e < 9.
def affine_orbit(seed):
    return {tuple(sorted((a + pow(2, e, N) * i) % N for i in seed))
            for a in range(N) for e in range(9)}

seed219 = (0, 1, 11, 20, 59, 67)
seed657 = (0, 1, 2, 35, 62, 64)
O219 = affine_orbit(seed219)
O657 = affine_orbit(seed657)
assert len(O219) == 219 and len(O657) == 657
assert O219.isdisjoint(O657)
assert O219 | O657 == supports
assert len(O219 | O657) == 876

# For any seed f, the shifted span is the ideal (gcd(f, X^73+1)).
even_generator = poly_mul(g, 3)
assert even_generator == 0xF3AE1
for seed, orbit in [(seed219, O219), (seed657, O657)]:
    assert poly_gcd(polynomial_of_support(seed), MOD) == even_generator
    assert rank_gf2(polynomial_of_support(s) for s in
                    (tuple((i + a) % N for i in seed) for a in range(N))) == 54
# Stronger diagnostic: verify gcd equality for all 876 words.
assert all(poly_gcd(polynomial_of_support(s), MOD) == even_generator
           for s in supports)

# The subgroup generated by -1 and 2 has order 18; four pair-difference classes.
H = {(sign * pow(2, e, N)) % N for sign in (-1, 1) for e in range(9)}
assert len(H) == 18
cosets, unseen = {}, set(range(1, N))
while unseen:
    rep = min(unseen)
    coset = {rep * h % N for h in H}
    assert len(coset) == 18
    cosets[rep] = coset
    unseen -= coset
assert list(cosets) == [1, 3, 5, 11]

def pair_types(seed):
    frequencies = Counter()
    for a, b in combinations(seed, 2):
        difference = (b - a) % N
        frequencies[next(rep for rep, C in cosets.items() if difference in C)] += 1
    assert sum(frequencies.values()) == 15
    return [frequencies[rep] for rep in cosets]

assert pair_types(seed219) == [3, 3, 6, 3]
assert pair_types(seed657) == [5, 3, 3, 4]

# There are 73*18/2=657 coordinate pairs of each difference type.
# Within a transitive orbit B, pair multiplicity is B*(seed pair count)/657.
expected = []
for j, rep in enumerate(cosets):
    c1 = len(O219) * pair_types(seed219)[j] // 657
    c2 = len(O657) * pair_types(seed657)[j] // 657
    expected.append(c1 + c2)
assert expected == [6, 4, 5, 5]
pair_counts = Counter(pair for s in supports for pair in combinations(s, 2))
for i in range(N):
    for j in range(i + 1, N):
        difference = (j-i) % N
        rep = next(t for t, C in cosets.items() if difference in C)
        assert pair_counts[(i, j)] == expected[list(cosets).index(rep)]
assert Counter(pair_counts.values()) == {4: 657, 5: 1314, 6: 657}
assert sum(pair_counts.values()) == 876 * 15
point_degrees = Counter(i for s in supports for i in s)
assert len(point_degrees) == N and set(point_degrees.values()) == {72}

print('BCH_PARAMETERS [73,55,6]')
print('DUAL_WEIGHT_ENUMERATOR', sorted(counts.items()))
print('MINIMUM_SUPPORTS', len(supports))
print('AFFINE_ORBITS', [(219, seed219), (657, seed657)])
print('CYCLIC_SPAN_DIMENSION', 54, 'CYCLIC_GCD', hex(even_generator))
print('DIFFERENCE_CLASS_REPRESENTATIVES', list(cosets))
print('PAIR_CLASS_MULTIPLICITIES', expected)
print('PAIR_COUNT_HISTOGRAM', sorted(Counter(pair_counts.values()).items()))
print('POINT_REPLICATION', 72)
print('VERIFY_OK')
