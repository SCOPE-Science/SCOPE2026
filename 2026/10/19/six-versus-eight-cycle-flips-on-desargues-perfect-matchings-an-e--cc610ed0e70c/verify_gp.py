#!/usr/bin/env python3
"""Exact shortest-cycle matching dynamics of GP(10,3); standard-library-only.

All ten-vertex matchings are generated by a recursive least-unmatched-vertex
search. Legal moves are checked by toggling independently enumerated simple
six- and eight-cycles of the underlying 20-vertex graph.
"""
from collections import Counter, deque
from itertools import combinations

V = set(range(20))
E = set()
for i in range(10):
    E.update({tuple(sorted((i, (i+1) % 10))),
              tuple(sorted((i, 10+i))),
              tuple(sorted((10+i, 10+(i+3) % 10)))})
assert len(E) == 30
A = [set() for _ in range(20)]
for u, v in E:
    A[u].add(v); A[v].add(u)
assert all(len(x)==3 for x in A)

M = []
def match(unused, edges):
    if not unused:
        M.append(frozenset(edges))
        return
    u=min(unused)
    for v in sorted(A[u] & unused):
        match(unused-{u,v}, edges + [tuple(sorted((u,v)))])
match(V, [])
assert len(M)==60 and len(set(M))==60
Mindex={m:i for i,m in enumerate(M)}

# Exhaustive simple cycle enumeration independently of matchings.
def simple_cycles(length):
    result=set()
    for start in range(20):
        def walk(p):
            if len(p)==length:
                if p[-1] in A[start]:
                    result.add(frozenset(tuple(sorted((p[j],p[(j+1)%length])))
                                         for j in range(length)))
                return
            for nxt in A[p[-1]]:
                if nxt not in p:
                    walk(p+[nxt])
        walk([start])
    return result
assert len(simple_cycles(4))==0
C6=simple_cycles(6)
C8=simple_cycles(8)
assert len(C6)==20 and len(C8)==30

def switches(cycles):
    edge_pairs=set()
    for i,m in enumerate(M):
        for cyc in cycles:
            if len(m & cyc) != len(cyc)//2:
                continue
            n=m ^ cyc
            assert len(n)==10
            assert {u for e in n for u in e}==V
            j=Mindex[n]
            if i != j:edge_pairs.add(tuple(sorted((i,j))))
    return edge_pairs
E6=switches(C6)
E8=switches(C8)
assert len(E6)==120 and len(E8)==60 and not (E6 & E8)

def neighbours(edges):
    result=[set() for _ in M]
    for i,j in edges:
        result[i].add(j);result[j].add(i)
    return result
N6=neighbours(E6);N8=neighbours(E8);N68=neighbours(E6 | E8)
assert Counter(map(len,N6)) == {0:6, 4:30, 5:24}
assert Counter(map(len,N8)) == {0:24, 2:30, 10:6}
assert Counter(map(len,N68)) == {5:24,6:30,10:6}
assert all({len(N6[i]),len(N6[j])}=={4,5} for i,j in E6)

hubs={i for i in range(60) if not N6[i]}
assert len(hubs)==6
assert hubs == {i for i in range(60) if len(N8[i])==10}
assert all(not N8[i] for i in range(60) if len(N6[i])==5)
assert all(len(N8[i]&hubs)==2 for i in range(60) if len(N6[i])==4)
assert all(len(N8[i]&N8[j])==2 for i,j in combinations(sorted(hubs),2))
assert all(len(M[i]&M[j])==2 for i,j in combinations(sorted(hubs),2))

# Exact shortest-path reachability, eccentricities, and layer counts.
def profile(N, start):
    distance={start:0}
    queue=deque([start])
    while queue:
        x=queue.popleft()
        for y in N[x]:
            if y not in distance:
                distance[y]=distance[x]+1
                queue.append(y)
    return len(distance),tuple(Counter(distance.values())[k]
                               for k in range(max(distance.values())+1))
P6=Counter((len(N6[i]),profile(N6,i)) for i in range(60))
assert P6 == {
    (0,(1,(1,))):6,
    (4,(54,(1,4,12,16,16,4,1))):30,
    (5,(54,(1,5,10,20,12,5,1))):24,
}
P68=Counter((len(N68[i]),profile(N68,i)) for i in range(60))
assert P68 == {
    (10,(60,(1,10,25,20,4))):6,
    (6,(60,(1,6,21,24,8))):30,
    (5,(60,(1,5,15,25,14))):24,
}

# Both models of the underlying Desargues graph are explicitly identified.
# Subset vertices 0..9 are lexicographically ordered 2-subsets of five points;
# vertices 10..19 are the lexicographic 3-subsets.
from itertools import combinations as choose
T=list(choose(range(5),2));U=list(choose(range(5),3))
phi=[0,10,4,16,7,19,9,15,3,12,11,1,17,5,13,8,18,2,14,6]
assert set(phi)==V
expected={(i,10+j) for i,t in enumerate(T) for j,u in enumerate(U)
          if set(t)<=set(u)}
assert {tuple(sorted((phi[i],phi[j]))) for i,j in E}==expected
# The GP(10,3) state labels map bijectively to the independent subset model.
from json import loads
certificate_path=__import__('pathlib').Path(__file__).resolve().with_name('state_transition_certificate.json')
if certificate_path.is_file():
    data=loads(certificate_path.read_text(encoding='utf-8'))
    assert data['gp_to_incidence_vertex_map']==phi
    def state_as_subset_permutation(m):
        q=[None]*10
        for a,b in m:
            x,y=sorted((phi[a],phi[b]))
            assert x<10<=y
            q[x]=y-10
        assert set(q)==set(range(10))
        return tuple(q)
    gp_states=[state_as_subset_permutation(m) for m in M]
    keys={tuple(x):i for i,x in enumerate(data['states'])}
    assert set(gp_states)==set(keys)
    def translate(edge_set):
        return {tuple(sorted((keys[gp_states[a]],keys[gp_states[b]]))) for a,b in edge_set}
    assert translate(E6)=={tuple(z) for z in data['six_cycle_edges']}
    assert translate(E8)=={tuple(z) for z in data['eight_cycle_edges']}

print('graph=GP(10,3)=middle_levels_H(5,2)')
print('perfect_matchings=60;girth=6;six_cycles=20;eight_cycles=30')
print('six_only: edges=120;components=one_54_plus_six_singletons')
print('six_only: degrees=0^6,4^30,5^24;active_diameter=6;active_radius=6')
print('eight_only: edges=60;subdivision_of_2K6_plus_24_singletons=TRUE')
print('six_or_eight: edges=180;connected=TRUE;radius=4;diameter=4')
print('all_vertex_eccentricities_for_combined_graph=4')
print('VERIFY_OK')
