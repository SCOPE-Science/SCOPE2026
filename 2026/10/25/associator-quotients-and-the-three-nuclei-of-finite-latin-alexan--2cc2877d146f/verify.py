"""Finite exhaustive checks of associators and all three nuclei of Alexander quandle algebras.

This checker works with integral coefficient equations: each nucleus constraint
has the form coefficient_i = coefficient_j because the Latin operation acts by
permutations. Thus connectivity conclusions hold for every coefficient ring.
"""
from itertools import product
from math import gcd


class DSU:
    def __init__(self, size):
        self.parent = list(range(size))
    def find(self, i):
        while self.parent[i] != i:
            self.parent[i] = self.parent[self.parent[i]]
            i = self.parent[i]
        return i
    def join(self, i, j):
        self.parent[self.find(i)] = self.find(j)
    def groups(self):
        return len({self.find(i) for i in range(len(self.parent))})


def check(elements, op, expected_associator_classes, latin):
    size = len(elements)
    lookup = {x: i for i, x in enumerate(elements)}
    op_idx = [[lookup[op(a, b)] for b in elements] for a in elements]
    ass = DSU(size)
    for a, b, c in product(range(size), repeat=3):
        ass.join(op_idx[op_idx[a][b]][c], op_idx[a][op_idx[b][c]])
    assert ass.groups() == expected_associator_classes, (size, ass.groups())
    if not latin:
        return
    nuclei = []
    for position in range(3):
        dsu = DSU(size)
        for other1, other2 in product(range(size), repeat=2):
            left, right = {}, {}
            for varied in range(size):
                if position == 0:
                    a, b, c = varied, other1, other2
                elif position == 1:
                    a, b, c = other1, varied, other2
                else:
                    a, b, c = other1, other2, varied
                l = op_idx[op_idx[a][b]][c]
                r = op_idx[a][op_idx[b][c]]
                assert l not in left and r not in right
                left[l], right[r] = varied, varied
            assert len(left) == size and len(right) == size
            for target in range(size):
                dsu.join(left[target], right[target])
        nuclei.append(dsu.groups())
    assert nuclei == [1, 1, 1], (size, nuclei)


def cyclic():
    checked = 0
    latin_checked = 0
    for n in range(1, 14):
        for t in range(n):
            if gcd(t, n) != 1:
                continue
            A = list(range(n))
            op = lambda a, b: (t * a + (1 - t) * b) % n
            # Additive subgroup generated by 1-t has order n/gcd(n,1-t).
            expected = gcd(n, 1 - t)
            is_latin = expected == 1
            check(A, op, expected, is_latin)
            checked += 1
            latin_checked += is_latin
    return checked, latin_checked


def matrix_cases():
    checked = 0
    # The unique fixed-point-free order-three matrix over F_2.
    B = ((0, 1), (1, 1))
    for dim in (2, 4):
        A = list(product((0, 1), repeat=dim))
        def linear(x):
            return tuple((B[i % 2][0] * x[2 * (i // 2)]
                         + B[i % 2][1] * x[2 * (i // 2) + 1]) % 2
                         for i in range(dim))
        def op(x, y):
            tx, ty = linear(x), linear(y)
            return tuple((tx[i] + y[i] - ty[i]) % 2 for i in range(dim))
        check(A, op, 1, True)
        checked += 1
    return checked


if __name__ == '__main__':
    c, l = cyclic()
    m = matrix_cases()
    print(f'VERIFY_OK cyclic_parameters={c} latin_cyclic={l} modular_vector_cases={m}')
