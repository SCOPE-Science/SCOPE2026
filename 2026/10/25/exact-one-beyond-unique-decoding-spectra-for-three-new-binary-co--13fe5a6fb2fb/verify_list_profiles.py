def spectrum(words, n, radius, expected):
    assert len(words) == len(set(words)) and all(0 <= u < (1 << n) for u in words)
    m = len(words)
    d_min = min((u ^ v).bit_count() for i,u in enumerate(words) for v in words[i+1:])
    assert d_min == 2 * radius - 1
    # Only pairs at distance 2r-1 or 2r can lie in the same r-ball.
    adj = [set() for _ in words]
    edges = 0
    for i in range(m):
        for j in range(i+1,m):
            dist = (words[i]^words[j]).bit_count()
            if dist <= 2*radius:
                adj[i].add(j)
                edges += 1
    triangles = 0
    quartets = 0
    centers4 = set()
    # Every near triangle has exactly one common center: its bitwise majority.
    # Any four-fold center must coincide with that triple's majority.
    for a in range(m):
        for b in sorted(adj[a]):
            ab = adj[a] & adj[b]
            for c in sorted(j for j in ab if j > b):
                triangles += 1
                maj = (words[a] & words[b]) | (words[a] & words[c]) | (words[b] & words[c])
                assert all((maj ^ words[i]).bit_count() <= radius for i in (a,b,c))
                for d in (j for j in (ab & adj[c]) if j > c):
                    if (maj ^ words[d]).bit_count() <= radius:
                        quartets += 1
                        centers4.add(maj)
    # A 5-list would give at least five different quadruples at its center.
    # Distinct quartet centers exclude 5-lists whenever len(centers4)=quartets.
    assert len(centers4) == quartets
    # In fact, all three codes have no list of size >= 5.
    moments = [None,
               m * sum(comb(n, j) for j in range(radius + 1)),
               edges * comb(2*radius, radius), triangles, quartets]
    N = [0]*5
    N[4] = moments[4]
    for i in (3,2,1):
        N[i] = moments[i] - sum(comb(j,i)*N[j] for j in range(i+1,5))
    N[0] = (1 << n) - sum(N[1:])
    assert all(v>=0 for v in N)
    assert N == expected, (N,expected)
    assert sum(N)==(1<<n)
    assert sum(j*N[j] for j in range(5))==moments[1]
    print(f'{n=}, size={m}, r={radius}, min_dist={d_min}, E={edges}, T={triangles}, Q={quartets}')
    print('centers histogram', N)
    return N

