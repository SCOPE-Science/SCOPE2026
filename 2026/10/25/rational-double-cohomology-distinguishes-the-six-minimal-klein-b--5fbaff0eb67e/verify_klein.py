"""Exact rational double-cohomology computation for eight-vertex Klein-bottle triangulations.

Requires Python 3, sympy and networkx.  Induced-subcomplex homology, restriction
maps and ranks are computed with exact rational linear algebra.  All six
isomorphism types are generated by bistellar edge flips from the facet list.
"""
import itertools as it, sympy as sp, collections, time
facets=['abe','bef','bcf','dfc','adc','gde','gfe','fgh','dfh','deh','abd','bdg','bgh','bhc','ceh','ace']
facets=sorted(tuple(sorted('abcdefgh'.index(x) for x in f)) for f in facets)
face_set=set(facets)
eds={tuple(sorted(e)) for t in facets for e in it.combinations(t,2)}
assert len(eds)==24 and len(facets)==16
assert all(sum(set(e).issubset(t) for t in facets)==2 for e in eds)
def homology(S):
 S=tuple(S); E=sorted(e for e in eds if set(e)<=set(S)); T=sorted(t for t in face_set if set(t)<=set(S));
 B1=sp.zeros(len(S),len(E)); B2=sp.zeros(len(E),len(T));
 for j,(a,b) in enumerate(E):B1[S.index(a),j]=-1;B1[S.index(b),j]=1
 for j,t in enumerate(T):
  for i in range(3):
   e=tuple(x for z,x in enumerate(t) if z!=i);B2[E.index(e),j]=(-1)**i
 # Rational complementary cycle classes modulo triangle boundaries
 Z=B1.nullspace(); rank=B2.rank(); assert rank==len(T), 'unexpected rational two-dimensional induced homology'; H=[]; mat=B2
 for z in Z:
  nxt=mat.row_join(z)
  if nxt.rank()>rank: H.append(z);mat=nxt;rank+=1
 # comp H0 using connectivity components and one vertex per component (difference reduced)
 import networkx as nx
 G=nx.Graph();G.add_nodes_from(S);G.add_edges_from(E)
 comps=[sorted(c) for c in nx.connected_components(G)]
 return dict(S=S,E=E,T=T,B1=B1,B2=B2,H=H,h0=len(comps)-1,components=comps)

data={S:homology(S) for r in range(1,9) for S in it.combinations(range(8),r)}

# Homology inclusion for p=1, exact rational arithmetic
for S,o in data.items():
 H=o['H'];B2=o['B2'];
 independent=[]; mat=sp.zeros(B2.rows,0)
 for j in range(B2.cols):
  N=mat.row_join(B2[:,j])
  if N.rank()>mat.cols: mat=N;independent.append(j)
 o['class_basis']=mat.row_join(sp.Matrix.hstack(*H) if H else sp.zeros(mat.rows,0))
 o['piv_rows']=list(o['class_basis'].T.rref()[1]);
 if H:
  F=o['class_basis'].extract(o['piv_rows'],range(o['class_basis'].cols));o['proj']=F.inv()[-len(H):,:]

def mapH1(J,I):
 # J proper subset of I
 a=data[J];b=data[I]; h1=len(a['H']);h2=len(b['H'])
 if h1*h2==0:return sp.zeros(h2,h1)
 srcE=a['E']; tgtE=b['E'];mat=sp.zeros(len(tgtE),h1)
 for j,z in enumerate(a['H']):
  for k,e in enumerate(srcE):mat[tgtE.index(e),j]=z[k]
 return b['proj']*mat.extract(b['piv_rows'],range(h1))

def mapH0(J,I):
 a,b=data[J],data[I];c0=a['h0'];c1=b['h0'];M=sp.zeros(c0,c1)
 if not c0 or not c1:return M
 which={v:i for i,c in enumerate(b['components']) for v in c}
 baseJ=a['components'][0][0]
 for k,c in enumerate(a['components'][1:]):
  x=c[0]
  for i in range(c1):M[k,i]=int(which[x]==i+1)-int(which[baseJ]==i+1)
 return M

def comp_mats(p):
 lev={r:sorted(S for S,o in data.items() if (len(o['H']) if p==1 else o['h0']) and len(S)==r) for r in range(2,9)}
 dim={r:sum(len(data[s]['H']) if p==1 else data[s]['h0'] for s in lev[r]) for r in lev}
 offsets={}
 for r in lev:
  offsets[r]={};total=0
  for S in lev[r]:offsets[r][S]=total; total+=len(data[S]['H']) if p==1 else data[S]['h0']
 mats={}
 for r in range(3,9):
  M=sp.zeros(dim[r-1],dim[r]);
  for S in lev[r]:
   for j,x in enumerate(S):
    J=tuple(v for v in S if v!=x)
    if J not in offsets[r-1]:continue
    block=mapH1(J,S).T if p==1 else mapH0(J,S)
    s0,t0=offsets[r][S],offsets[r-1][J]
    for i in range(block.rows):
     for k in range(block.cols):M[t0+i,s0+k]+=(-1)**j*block[i,k]
  mats[r]=M
 for r in range(4,9):
  assert mats[r-1]*mats[r]==sp.zeros(dim[r-2],dim[r]), ('d²',p,r)

 ranks={}
 for r in range(3,9):
  from sympy.polys.matrices import DomainMatrix
  from sympy.polys.domains import QQ
  import time
  ranks[r]=DomainMatrix.from_Matrix(mats[r]).convert_to(QQ).rank()

 return mats,dim,ranks

def incidence(faces):
 g=nx.Graph()
 for v in range(8):g.add_node(('v',v),type='v')
 for j,t in enumerate(sorted(faces)):
  g.add_node(('t',j),type='t')
  for v in t:g.add_edge(('v',v),('t',j))
 return g

def flips(faces):
 edges=sorted({tuple(sorted(pair)) for f in faces for pair in it.combinations(f,2)})
 for a,b in edges:
  neigh=[t for t in faces if a in t and b in t]
  assert len(neigh)==2
  x=next(v for v in neigh[0] if v!=a and v!=b);y=next(v for v in neigh[1] if v!=a and v!=b)
  if x==y or tuple(sorted((x,y))) in edges:continue
  newfaces=(faces-set(neigh))|{tuple(sorted((a,x,y))),tuple(sorted((b,x,y)))}
  yield ((a,b,x,y),newfaces)

import networkx as nx
start=set(facets);groups=[start];grouph=[incidence(start)];edges=[]
for ix,faces in enumerate(groups):
 for flip,F in flips(faces):
  graph=incidence(F)
  eq=next((j for j,g in enumerate(grouph) if nx.is_isomorphic(graph,g,node_match=lambda x,y:x['type']==y['type'])),None)
  if eq is None:
   eq=len(groups);groups.append(F);grouph.append(graph)
  edges.append((ix,eq,flip))
assert len(groups)==6 and len(edges)==36, (len(groups),len(edges))
assert all(len(f)==16 for f in groups)

for i,faces in enumerate(groups):
 facets=sorted(faces)
 face_set=set(faces)
 eds={tuple(sorted(e)) for t in faces for e in it.combinations(t,2)}
 d={S:homology(S) for r in range(1,9) for S in it.combinations(range(8),r)}
 # Form rational induced-homology bases for this combinatorial type.
 data=d
 for S,o in d.items():
  H=o['H'];B2=o['B2'];mat=sp.zeros(B2.rows,0)
  for j in range(B2.cols):
   N=mat.row_join(B2[:,j])
   if N.rank()>mat.cols:mat=N
  o['class_basis']=mat.row_join(sp.Matrix.hstack(*H) if H else sp.zeros(mat.rows,0))
  o['piv_rows']=list(o['class_basis'].T.rref()[1])
  if H:
   F=o['class_basis'].extract(o['piv_rows'],range(o['class_basis'].cols));o['proj']=F.inv()[-len(H):,:]
 M1,D1,R1=comp_mats(1);M0,D0,R0=comp_mats(0)
 expected_h0=[1,3,2,1,1,1][i]
 expected_h1=[0,2,1,0,0,0][i]
 assert D0[2]-R0[3]==expected_h0, (i,D0,R0)
 assert D1[4]-R1[4]-R1[5]==expected_h1, (i,D1,R1)
 assert all(D0[r]-R0.get(r,0)-R0.get(r+1,0)==0 for r in range(3,9))
 assert all(D1[r]-R1.get(r,0)-R1.get(r+1,0)==0 for r in list(range(2,4))+list(range(5,9)))
 assert tuple(D1.get(r,0) for r in range(3,9)) == ((20,71,96,60,16,1) if i in (0,5) else (17,70,96,60,16,1) if i==1 else (18,70,96,60,16,1) if i==2 else (19,70,96,60,16,1))
 assert all(sum(set(e).issubset(t) for t in facets)==2 for e in eds)
 print('CLASS',i,'FACETS',' '.join(''.join(chr(97+j) for j in t) for t in sorted(faces)),'HH_RANKS',(expected_h0,expected_h1), 'D0', D0, 'R0', R0, 'D1', D1,'R1',R1,flush=True)

