#!/usr/bin/env python3
"""Exact integer checks for a diagonal Fermat-sextic quotient."""
from collections import Counter
from math import comb, gcd

# Euler characteristic of a smooth degree-six hypersurface in P^5.
coefficient = sum(comb(6, j) * (-6)**(4-j) for j in range(5))
euler_sextic = 6 * coefficient
assert coefficient == 435 and euler_sextic == 2610

# Fixed loci indexed by exponent of the order-six automorphism.
fixed_euler = {0: euler_sextic, 1: 0, 2: 18, 3: -36, 4: 18, 5: 0}
quotient_euler_numerator = sum(fixed_euler.values())
assert quotient_euler_numerator == 6 * 435

# For the commuting-pair formula, common fixed points are those of
# the subgroup generated by a and b. gcd(0,0,6) means the identity.
counts = Counter(gcd(a, b, 6) for a in range(6) for b in range(6))
assert counts == {1: 24, 2: 8, 3: 3, 6: 1}, counts
orbifold_numerator = sum(counts[d] * fixed_euler[0 if d==6 else d] for d in counts)
assert orbifold_numerator == 6 * 441

# The nontrivial automorphism of order three is free on each Fermat
# plane sextic. Its four degree-three invariant monomials yield the
# complete canonical system of its genus-four quotient.
invariants = [tuple(e) for i in range(4) for j in range(4-i)
              for e in [(i,j,3-i-j)] if (e[1] + 2*e[2]) % 3 == 0]
assert set(invariants) == {(3,0,0),(0,3,0),(0,0,3),(1,1,1)}
assert (6-1)*(6-2)//2 == 10  # plane sextic genus
assert 1+(10-1)//3 == 4        # unramified quotient genus
assert 1+(2*3*(2+3-4))//2 == 4  # adjunction genus of a (2,3) complete intersection

# Residue weights: order-three stabilizer of a sextic line pair.
for residue in range(3):
    weights = sorted((j-residue) % 3 for j in range(6)
                     if j%3 != residue)
    assert weights == [1,1,2,2]

# The order-two involution fixes a plane curve and acts by -1 on
# its three transverse tangent directions in the fourfold.
assert 6//3 == 2 and 6//2 == 3
assert 3*6//2 == 9
assert 2*(2-2*4) == -12
print('VERIFY_OK: Euler=435, orbifold_Euler=441, strata=2 genus-4 curves + 9 isolated points')
