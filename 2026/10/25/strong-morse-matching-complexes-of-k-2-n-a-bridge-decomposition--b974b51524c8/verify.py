#!/usr/bin/env python3
"""Reproduce exact finite checks for strong matching complexes of K_{2,n}.

For a one-dimensional graph K, an edge (v,{v,u}) is paired in the
filtration-generated strong matching precisely when u is the unique
neighbor of v preceding v in the vertex order. The simplicial complex
is generated by all these sets of pairs. This independent enumeration
is compared against the explicit facet model for complete bipartite
K_{2,n}; finite computation supports but does not replace the proof.
"""
from itertools import permutations
from collections import defaultdict
from math import comb


def setup(n):
    left = (0, 1)
    right = tuple(range(2, n + 2))
    pairs = [(v, w) for v in left for w in right]
    pairs += [(w, v) for v in left for w in right]
    pos = {pair: j for j, pair in enumerate(pairs)}
    nbr = {v: set(right) for v in left}
    nbr.update({w: set(left) for w in right})
    return left, right, pos, nbr


def order_generators(n):
    left, right, pos, nbr = setup(n)
    generators = set()
    for order in permutations((*left, *right)):
        earlier = set()
        face = 0
        for v in order:
            old_neighbors = earlier.intersection(nbr[v])
            if len(old_neighbors) == 1:
                u = next(iter(old_neighbors))
                face |= 1 << pos[(v, u)]
            earlier.add(v)
        generators.add(face)
    return generators


def model_generators(n):
    left, right, pos, _ = setup(n)
    faces = set()
    for a in left:
        b = 1 - a
        v = {j: 1 << pos[(j, a)] for j in right}
        w = {j: 1 << pos[(a, j)] for j in right}
        center = 0
        for x in v.values():
            center |= x
        faces.add(center)
        for j in right:
            faces.add((center ^ v[j]) | w[j])
    for j in right:
        w0 = 1 << pos[(0, j)]
        w1 = 1 << pos[(1, j)]
        v0 = 1 << pos[(j, 0)]
        v1 = 1 << pos[(j, 1)]
        faces.update((w0 | w1, v0 | w1, w0 | v1))
    return faces


def simplices_from_generators(generators):
    faces = {0}
    for f in generators:
        sub = f
        while sub:
            faces.add(sub)
            sub = (sub - 1) & f
    return faces


def reduced_mod_two_betti(faces):
    levels = defaultdict(list)
    for f in faces:
        if f:
            levels[f.bit_count() - 1].append(f)
    maxdim = max(levels)
    rank = {}
    for d in range(1, maxdim + 1):
        index = {f: i for i, f in enumerate(levels[d - 1])}
        pivots = {}
        for simplex in levels[d]:
            col = 0
            left = simplex
            while left:
                bit = left & -left
                col ^= 1 << index[simplex ^ bit]
                left -= bit
            while col:
                k = col.bit_length() - 1
                if k in pivots:
                    col ^= pivots[k]
                else:
                    pivots[k] = col
                    break
        rank[d] = len(pivots)
    return [len(levels[d]) - rank.get(d, 0) - rank.get(d + 1, 0)
            - (1 if d == 0 else 0) for d in range(maxdim + 1)]


def face_vector_formula(n):
    return [(2 * (comb(n, r) + n * comb(n - 1, r - 1))
             + (3 * n if r == 2 else 0)) for r in range(1, n + 1)]


def main():
    for n in range(2, 8):
        independent = simplices_from_generators(order_generators(n))
        model = simplices_from_generators(model_generators(n))
        assert independent == model, ('facet model mismatch', n)
        vec = [sum(f.bit_count() == r for f in model)
               for r in range(1, n + 1)]
        assert vec == face_vector_formula(n), ('face formula mismatch', n, vec)
        betti = reduced_mod_two_betti(independent)
        assert betti == [0, 3 * n - 1] + [0] * (n - 2), (n, betti)
        print(f'n={n}: complete order enumeration agrees; f={vec}; mod2 reduced Betti={betti}')
    print('All checks passed. Infinite-family homotopy and integral representation use the written proof.')

if __name__ == '__main__':
    main()
