"""Finite arithmetic sanity checks for fractional Cesaro boundary flux.

Only standard-library arithmetic is required. This verifies numerical
instances and finite algebraic identities; it is not an infinite proof.
"""
from math import gamma, lgamma, exp, pi, fsum

EULER_GAMMA = 0.5772156649015328606


def theory(s):
    if s == 0.5:
        return pi * pi / 24
    # For half/integer values used here, the digamma differences are
    # elementary finite sums; for quarter order use the known log-2 value.
    if s == 0.25:
        return (0.25 * 0.25) * (4.0 * 0.6931471805599453094)
    if s == 0.75:
        return (0.75 * 0.75) * (4.0 - 4.0 * 0.6931471805599453094)
    if s == 1.0:
        return 1.0
    if s == 2.0:
        return 22.0 / 9.0
    raise ValueError('unsupported arithmetic checkpoint')


def flux_partial(s, alpha, N, M):
    # Gamma-ratio coefficients generated by exact recurrences.
    g = gamma(s)
    g2 = [g * g]
    for k in range(1, M + 1):
        g *= (k - 1 + s) / k
        g2.append(g * g)
    prefix = []
    accum = 0.0
    for z in g2:
        accum += z
        prefix.append(accum)
    h = exp(lgamma(alpha + 1) - lgamma(alpha + s + 1))
    # advance h(n) by an exact gamma recurrence
    for n in range(N + 1):
        h *= (n + alpha + 1) / (n + alpha + s + 1)
    terms = []
    for n in range(N + 1, M + 1):
        terms.append((s * h) ** 2 * (prefix[n] - prefix[n - N - 1]))
        h *= (n + alpha + 1) / (n + alpha + s + 1)
    return fsum(terms)


def finite_identity(s, alpha, N, M):
    # Compare the actual diagonal compression of T*T-TT* with the
    # cross-boundary square-energy sum for a finite M-by-M truncation.
    T = [[0.0] * M for _ in range(M)]
    for n in range(M):
        h = exp(lgamma(n + alpha + 1) - lgamma(n + alpha + s + 1))
        for j in range(n + 1):
            k = n - j
            T[n][j] = s * h * exp(lgamma(k + s) - lgamma(k + 1))
    lhs = fsum(fsum(T[n][j] ** 2 for n in range(M)) -
               fsum(T[j][k] ** 2 for k in range(j + 1))
               for j in range(N + 1))
    rhs = fsum(T[n][j] ** 2 for n in range(N + 1, M)
               for j in range(N + 1))
    assert abs(lhs - rhs) < 1e-10, (lhs, rhs)
    return lhs


def main():
    for s, alpha in [(0.25, 0), (0.5, 0), (0.75, -0.5),
                     (1.0, 0), (2.0, 1.0)]:
        finite_identity(s, alpha, 3, 25)
        low = flux_partial(s, alpha, 64, 13000)
        high = flux_partial(s, alpha, 256, 52000)
        goal = theory(s)
        assert abs(high - goal) < 0.045, (s, alpha, high, goal)
        assert abs(high - goal) < abs(low - goal) + 0.01
        print('order', s, 'shift', alpha, 'N=64', round(low, 7),
              'N=256', round(high, 7), 'limit', round(goal, 7))
    print('FINITE_CHECKS_OK')


if __name__ == '__main__':
    main()
