"""Finite checks for generator counts of permutation tense complex algebras.
No external dependencies; run with python3 checker.py.
"""
from itertools import permutations, product
from collections import Counter
from math import factorial


def mobius(n):
    primes = []
    d = 2
    t = n
    while d * d <= t:
        if t % d == 0:
            t //= d
            if t % d == 0:
                return 0
            primes.append(d)
        d += 1
    if t > 1:
        primes.append(t)
    return -1 if len(primes) % 2 else 1


def necklace(length, q):
    return sum(mobius(d) * q**(length//d) for d in range(1, length+1) if length % d == 0) // length


def cycles_of(perm):
    n=len(perm); visited=set(); cycles=[]
    for a in range(n):
        if a not in visited:
            cycle=[]; u=a
            while u not in visited:
                visited.add(u);cycle.append(u);u=perm[u]
            assert u==a
            cycles.append(cycle)
    return cycles


def predicted(perm,q):
    multiplicities=Counter(map(len,cycles_of(perm)))
    res=1
    for length,m in multiplicities.items():
        N=necklace(length,q)
        if N<m:return 0
        for i in range(m):
            res *= length*(N-i)
    return res


def brute(perm,q):
    n=len(perm); total=0
    for labelling in product(range(q),repeat=n):
        profiles={tuple(labelling[x] for x in cycle) for cycle in []} # no-op
        # The subalgebra generated by the k predicates consists exactly of
        # unions of fibres of all iterated colour observations.
        seen=set()
        for v in range(n):
            u=v;seq=[]
            # n! is a common multiple of all cycle lengths for n<=6; n! shifts
            # separate all periodic sequences that differ.
            for _ in range(factorial(n)):
                seq.append(labelling[u]);u=perm[u]
            seen.add(tuple(seq))
        if len(seen)==n:total+=1
    return total


def unit_tests():
    tests=0
    for n in range(1,7):
        for perm in permutations(range(n)):
            a=predicted(perm,2)
            b=brute(perm,2)
            assert a==b,(n,perm,a,b)
            tests+=1
    for n in range(1,5):
        for perm in permutations(range(n)):
            a=predicted(perm,4)
            b=brute(perm,4)
            assert a==b,(n,perm,a,b)
            tests+=1
    for ell in range(1,8):
        for q in range(1,7):
            brute_n=sum(1 for word in product(range(q),repeat=ell)
                        if all(any(word[i]!=word[(i+t)%ell] for i in range(ell))
                               for t in range(1,ell)))
            assert brute_n==ell*necklace(ell,q)
            tests+=1
    print('PERMUTATION_TENSE_GENERATORS_EXACT_OK',tests,'checks')

if __name__=='__main__':
    unit_tests()

def coefficient_test():
    checks=0
    for q in [2,4,8,16]:
        C=[1]+[0]*18
        for L in range(1,19):
            # [x^(L*j)] coefficient binom(N_L(q),j)
            nn=necklace(L,q)
            D=[0]*19
            comb=1
            for j in range(min(nn,18//L)+1):
                if j:comb=comb*(nn-j+1)//j
                for n in range(0,19-L*j):
                    D[n+L*j]+=C[n]*comb
            C=D
        for n in range(19):
            expect=(1 if n==0 else q if n==1 else q**n-q**(n-1))
            assert C[n]==expect,(q,n,C[n],expect)
            checks+=1
    total_checks=0
    for q,N in [(2,6),(4,4)]:
        for n in range(1,N+1):
            total=sum(predicted(p,q) for p in permutations(range(n)))
            expected=factorial(n)*(q if n==1 else q**n-q**(n-1))
            assert total==expected,(q,n,total,expected)
            total_checks+=1
    print('GENERATION_SQUAREFREE_IDENTITY_OK',checks,total_checks)

if __name__=='__main__':
    coefficient_test()
