#!/usr/bin/env python3
"""Self-contained exhaustive square-flip distance checker on the four-cube.

Standard-library Python 3.9+. No stored enumeration, internet, or auxiliary files.
"""
from collections import Counter, deque
from itertools import permutations

D = 4
N = 1 << D
EDGES = [(v, v ^ (1 << i)) for v in range(N) for i in range(D)
         if v < (v ^ (1 << i))]
assert len(EDGES) == 32
EID = {e: j for j, e in enumerate(EDGES)}


def enumerate_lowest(mask, chosen=0):
    if mask == 0:
        yield chosen
        return
    v = (mask & -mask).bit_length() - 1
    for k in range(D):
        w = v ^ (1 << k)
        if mask & (1 << w):
            e = EID[tuple(sorted((v, w)))]
            yield from enumerate_lowest(mask ^ (1 << v) ^ (1 << w),
                                        chosen | (1 << e))


def enumerate_bipartite():
    evens = [v for v in range(N) if v.bit_count() % 2 == 0]
    def step(t, used_odds, chosen):
        if t == len(evens):
            yield chosen
            return
        v = evens[t]
        for k in range(D):
            w = v ^ (1 << k)
            if not (used_odds & (1 << w)):
                e = EID[tuple(sorted((v, w)))]
                yield from step(t + 1, used_odds | (1 << w),
                                chosen | (1 << e))
    yield from step(0, 0, 0)


MATCHINGS = list(enumerate_lowest((1 << N) - 1))
assert len(MATCHINGS) == 272 == len(set(MATCHINGS))
assert set(MATCHINGS) == set(enumerate_bipartite())
INDEX = {mask: j for j, mask in enumerate(MATCHINGS)}


SQUARES = []
for i in range(D):
    for j in range(i + 1, D):
        for v in range(N):
            if (v & (1 << i)) or (v & (1 << j)):
                continue
            a, b, c, d = v, v ^ (1 << i), v ^ (1 << j), v ^ (1 << i) ^ (1 << j)
            p = (1 << EID[tuple(sorted((a, b)))]) | (1 << EID[tuple(sorted((c, d)))])
            q = (1 << EID[tuple(sorted((a, c)))]) | (1 << EID[tuple(sorted((b, d)))])
            SQUARES.append((p, q))
assert len(SQUARES) == 24
ADJ = [set() for _ in MATCHINGS]
for j, m in enumerate(MATCHINGS):
    for p, q in SQUARES:
        if m & p == p:
            ADJ[j].add(INDEX[m ^ p ^ q])
        if m & q == q:
            ADJ[j].add(INDEX[m ^ p ^ q])

# A second, face-list-independent construction: two distinct perfect matchings
# differing in four edges necessarily have an alternating four-cycle.
SECOND = [set() for _ in MATCHINGS]
for j, m in enumerate(MATCHINGS):
    for k in range(j + 1, len(MATCHINGS)):
        if (m ^ MATCHINGS[k]).bit_count() == 4:
            SECOND[j].add(k)
            SECOND[k].add(j)
assert ADJ == SECOND
assert all(i in ADJ[j] for i, neighbors in enumerate(ADJ) for j in neighbors)

COMPONENTS = []
seen = set()
for root in range(len(MATCHINGS)):
    if root in seen:
        continue
    stack, comp = [root], {root}
    while stack:
        for w in ADJ[stack.pop()]:
            if w not in comp:
                comp.add(w)
                stack.append(w)
    seen.update(comp)
    COMPONENTS.append(comp)
assert sorted(map(len, COMPONENTS)) == [1] * 8 + [264]
GIANT = next(c for c in COMPONENTS if len(c) == 264)
assert all(not ADJ[j] for comp in COMPONENTS if len(comp) == 1 for j in comp)


def bfs(root):
    d = {root: 0}
    todo = deque([root])
    while todo:
        v = todo.popleft()
        for w in ADJ[v]:
            if w not in d:
                d[w] = d[v] + 1
                todo.append(w)
    return d


DIST_PAIRS, ECC, DEG = Counter(), Counter(), Counter()
ANTIPODES = {v: set() for v in GIANT}
ECC_BY_VERTEX = {}
for v in sorted(GIANT):
    distance = bfs(v)
    assert len(distance) == 264
    ecc = max(distance.values())
    ECC[ecc] += 1
    ECC_BY_VERTEX[v] = ecc
    DEG[len(ADJ[v])] += 1
    for w, d in distance.items():
        if v < w:
            DIST_PAIRS[d] += 1
        if d == 8:
            ANTIPODES[v].add(w)
assert DIST_PAIRS == {1: 768, 2: 2640, 3: 6032, 4: 9360,
                      5: 9504, 6: 5296, 7: 1104, 8: 12}
assert sum(DIST_PAIRS.values()) == 264 * 263 // 2
assert ECC == {7: 252, 8: 12}
assert DEG == {3: 32, 4: 12, 5: 96, 6: 48, 8: 72, 12: 4}
assert set(v for v in GIANT if ANTIPODES[v]) == set(v for v in GIANT if ECC_BY_VERTEX[v] == 8)
assert all(len(ANTIPODES[v]) == 2 for v in GIANT if ANTIPODES[v])
visited, anti_sizes = set(), []
for v in ANTIPODES:
    if v in visited or not ANTIPODES[v]:
        continue
    stack, comp = [v], {v}
    while stack:
        for w in ANTIPODES[stack.pop()]:
            if w not in comp:
                comp.add(w)
                stack.append(w)
    visited.update(comp)
    anti_sizes.append(len(comp))
assert sorted(anti_sizes) == [4, 4, 4]

# 384 geometric automorphisms of the cube, generated by translations and
# coordinate permutations. Their induced action must preserve flip adjacency.
AUTS = []
for p in permutations(range(D)):
    for offset in range(N):
        def f(v):
            return offset ^ sum(((v >> k) & 1) << p[k] for k in range(D))
        emap = [EID[tuple(sorted((f(a), f(b))))] for a, b in EDGES]
        permutation_on_matchings = []
        for m in MATCHINGS:
            u = 0
            for k, e in enumerate(emap):
                if m & (1 << k):
                    u |= 1 << e
            permutation_on_matchings.append(INDEX[u])
        assert len(set(permutation_on_matchings)) == 272
        AUTS.append(permutation_on_matchings)
assert len(AUTS) == 384
assert all(ADJ[a] == {perm[j] for j in ADJ[perm.index(a)]}
           for perm in AUTS[:1] for a in [])  # audited below for every generator
for perm in AUTS:
    for v in range(len(MATCHINGS)):
        assert {perm[w] for w in ADJ[v]} == ADJ[perm[v]]
ORBIT_DATA = []
seen = set()
for v in range(len(MATCHINGS)):
    if v in seen:
        continue
    orbit = {perm[v] for perm in AUTS}
    assert all(len(ADJ[t]) == len(ADJ[v]) for t in orbit)
    seen |= orbit
    ORBIT_DATA.append((len(orbit), len(ADJ[v]), ECC_BY_VERTEX.get(v, 0)))
assert seen == set(range(272))
assert sorted(ORBIT_DATA) == sorted([
    (4, 12, 7), (48, 8, 7), (24, 8, 7), (48, 6, 7),
    (96, 5, 7), (12, 4, 8), (32, 3, 7), (8, 0, 0)])

# Print one explicit diametral pair in ground-set edge notation.
a = next(v for v in sorted(GIANT) if ECC_BY_VERTEX[v] == 8)
b = min(ANTIPODES[a])
def as_edges(v):
    return [EDGES[k] for k in range(len(EDGES)) if MATCHINGS[v] & (1 << k)]
print('MATCHINGS', len(MATCHINGS), 'SQUARES', len(SQUARES))
print('COMPONENTS', sorted(map(len, COMPONENTS)))
print('DIAMETER', max(ECC), 'RADIUS', min(ECC))
print('ECCENTRICITIES', sorted(ECC.items()))
print('UNORDERED_DISTANCE_PAIRS', sorted(DIST_PAIRS.items()))
print('GIANT_DEGREES', sorted(DEG.items()))
print('ANTIPODAL_COMPONENTS', sorted(anti_sizes))
print('AUTOMORPHISM_ORBITS', sorted(ORBIT_DATA))
print('DISTANCE_8_WITNESS', as_edges(a), as_edges(b))
print('VERIFY_OK')
