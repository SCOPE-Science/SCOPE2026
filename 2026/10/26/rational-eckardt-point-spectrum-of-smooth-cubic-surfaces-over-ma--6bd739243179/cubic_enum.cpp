static constexpr uint32_t MAXF=1u<<20;
uint8_t seen[MAXF];
int parity(uint32_t x){return __builtin_parity(x);}
int point_count(uint32_t f){int n=0;for(int i=0;i<15;i++)if(!parity(f&EVAL[i])) n++;return n;}
bool rat_smooth(uint32_t f){for(int i=0;i<15;i++)if(!parity(f&EVAL[i])){bool any=false;for(int k=0;k<4;k++)if(parity(f&GRAD[4*i+k]))any=true;if(!any)return false;}return true;}
int line_count(uint32_t f){int n=0;for(int i=0;i<35;i++){bool yes=true;for(int j=0;j<4;j++)if(parity(f&LINE[4*i+j]))yes=false;if(yes)n++;}return n;}
uint32_t transform(uint32_t f,int k){uint32_t g=0;while(f){int j=__builtin_ctz(f);f&=f-1;g^=TRANS[k][j];}return g;}
// Macaulay rank in homogeneous degree five: gradient quadratic ideal.
int grad5_rank(uint32_t f){uint64_t piv[56]={};int rank=0;
 for(int i=0;i<4;i++)for(int m=0;m<20;m++){
 uint64_t v=0;uint32_t x=f;
 while(x){int j=__builtin_ctz(x);x&=x-1;int pos=RANK_MAP[(i*20+m)][j];if(pos>=0)v^=1ULL<<pos;}
 while(v){int top=63-__builtin_clzll(v);if(!piv[top]){piv[top]=v;rank++;break;}v^=piv[top];}
 }
 return rank;
}
