#!/usr/bin/env python3
"""Exhaustive centrality and family checks for reduced power monoids of small generalized dihedral groups."""
from itertools import product

def group(moduli):
    A=list(product(*(range(m) for m in moduli))); N=len(A)
    amap={a:i for i,a in enumerate(A)}
    inv=lambda v:tuple(-x % m for x,m in zip(v,moduli))
    def add(a,b):return tuple((x+y)%m for x,y,m in zip(a,b,moduli))
    # index 0 is identity; followed by rotation vectors, then reflection vectors
    def mul_idx(x,y):
        i,e=divmod(x,N) if False else (x%N,x//N)
        j,f=y%N,y//N
        return amap[add(A[i],A[j] if e==0 else inv(A[j]))]+N*(e^f)
    tab=[[mul_idx(i,j) for j in range(2*N)] for i in range(2*N)]
    return A,amap,tab,add,inv

def family(C,A,amap,add,inv):
    N=len(A);R={a for i,a in enumerate(A) if C>>i&1}
    S={a for i,a in enumerate(A) if C>>(N+i)&1}
    if not S:return True
    a0=next(iter(S))
    K=set([A[0]])
    # generated by differences of members of S; just closure by iterated additions.
    generators={add(a,inv(a0)) for a in S}
    frontier=list(generators)
    while frontier:
        a=frontier.pop()
        if a in K:continue
        K.add(a)
        frontier.extend(add(a,b) for b in generators)
    # K has all negates as finite closure
    return S=={add(a0,k) for k in K} and R.issubset(K) and R=={inv(a) for a in R}

def subgroup_formula(A,add):
    N=len(A); zero=A[0]
    subgroups=set()
    for mask in range(1<<N):
        if not(mask&1):continue
        H=frozenset(A[i] for i in range(N) if mask>>i&1)
        if all(add(x,y) in H for x in H for y in H):subgroups.add(H)
    return (1<<(N-1))+sum((N//len(H))*(1<<((len(H)-1)//2)) for H in subgroups), {len(H) for H in subgroups}

def check(moduli):
    A,amap,tab,add,inv=group(moduli);N=len(A);size=2*N
    expected,sizes=subgroup_formula(A,add)
    # Every g's left/right translation on the group is a permutation.
    left=[[tab[g][i] for i in range(size)] for g in range(size)]
    right=[[tab[i][g] for i in range(size)] for g in range(size)]
    count=0
    for C in range(0,1<<size,2):
        # Need C intersection Cg == C intersection gC, for every g.
        matches=True
        for g in range(size):
            r=l=0
            bits=C
            while bits:
                bit=bits&-bits;i=bit.bit_length()-1;bits-=bit
                r|=1<<right[g][i];l|=1<<left[g][i]
            if (C&r)!=(C&l):matches=False;break
        predicted=family(C,A,amap,add,inv)
        if matches!=predicted:raise AssertionError((moduli,C,matches,predicted))
        count+=matches
    assert count==expected,(moduli,count,expected)
    print('H=',moduli,'|H|=',N,'subgroup sizes=',sizes,'center=',count,'formula=',expected)

if __name__=='__main__':
    for m in [(3,),(5,),(7,),(9,),(3,3)]:check(m)
    print('VERIFY_OK')
