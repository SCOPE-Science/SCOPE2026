"""Exact symbolic checks for the characteristic-three Hankel polar-map theorem.
Only standard Python and SymPy are required. These checks are supplements to the proof.
"""
import sympy as s
x0,x1,x2,x3,x4=s.symbols('a b c d e')
a,b,c,d,e=x0,x1,x2,x3,x4
A=a*c-b*b
B=a*d-b*c
C=a*e-b*d
D=b*d-c*c
E=b*e-c*d
G=c*e-d*d
F=s.det(s.Matrix([[a,b,c],[b,c,d],[c,d,e]]))
assert s.expand(F-(a*G+e*A-c*C+c*D)) == 0
assert all(s.expand(u)==0 for u in [
 F.diff(a)-G,
 F.diff(b)+2*E,
 F.diff(c)-(C+3*D),
 F.diff(d)+2*B,
 F.diff(e)-A,
 A*G-B*E+C*D,
 a*D-(b*B-c*A),
 b*D-(c*B-d*A),
 d*D-(c*E-b*G),
 e*D-(d*E-c*G),
])
# At p=[0:0:1:0:0], all five partial derivatives vanish in characteristic 3,
# while F=-1, so this is a polar base point outside the cubic.
vals={a:0,b:0,c:1,d:0,e:0}
assert [s.expand(F.diff(z)).subs(vals)%3 for z in (a,b,c,d,e)]==[0]*5
assert F.subs(vals)==-1
# Two independent rows in a generic 2-plane W impose four independent linear
# conditions on (a,b,c,d,e) that a shifted Hankel 2x4 matrix have row-space W.
# W^perp is generated by u=(-1,0,1,0), v=(0,-2,0,1).
M=s.Matrix([[-1,0,1,0,0],[0,-1,0,1,0],[0,-2,0,1,0],[0,0,-2,0,1]])
assert M.rank()==4
for p in (2,3,5,7):
    assert any(s.det(M[list(rows),list(cols)])%p for rows in __import__('itertools').combinations(range(4),4) for cols in __import__('itertools').combinations(range(5),4))
# Branch quadratic from the Pluecker quadric under projection (char not 2,3).
y0,y1,y2,y3,y4,t=s.symbols('y0 y1 y2 y3 y4 t')
AA=y4; BB=-y3/2; EE=-y1/2; GG=y0; CC=y2-3*t
pluecker=s.expand(AA*GG-BB*EE+CC*t)
assert s.expand(-pluecker-(3*t**2-y2*t+(y1*y3/4-y0*y4)))==0
assert s.expand(y2**2-12*(y1*y3/4-y0*y4))==y2**2-3*y1*y3+12*y0*y4
print('VERIFY_OK: Hankel determinant, five polar partials, Pluecker relation, omitted-minor annihilators, exceptional base point, rank-four birational reconstruction, branch discriminant')
