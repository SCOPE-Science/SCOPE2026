"""Independent finite tests for the unrestricted two-colour wild spectrum.

Uses only the Python standard library. Exhaustive over all connected
labelled simple graphs of orders 3, 4, 5 and all surjective two-colourings.
This is finite corroboration, not a proof of the infinite theorem.
"""
from itertools import combinations


def components(n, edges):
    parent = list(range(n))

    def root(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    for u, v in edges:
        a, b = root(u), root(v)
        if a != b:
            parent[a] = b
    return len({root(i) for i in range(n)})


def vertex_partitions(n):
    """Generate restricted growth strings exactly once per set partition."""
    def rec(labels, highest):
        if len(labels) == n:
            yield labels
        else:
            for j in range(highest + 2):
                yield from rec(labels + (j,), max(j, highest))
    yield from rec((0,), 0)


def partition_deficiency(n, edges):
    return max(2 * (max(p)) - sum(p[u] != p[v] for u, v in edges)
               for p in vertex_partitions(n))


def is_two_vertex_connected(n, edges):
    for deleted in range(n):
        reduced = [(u - (u > deleted), v - (v > deleted))
                   for u, v in edges if deleted not in (u, v)]
        if components(n - 1, reduced) != 1:
            return False
    return True


def cycle_equivalence_blocks(n, edges):
    """Edge blocks = equivalence classes generated by shared simple cycles."""
    m = len(edges)
    parent = list(range(m))

    def root(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    for cardinality in range(3, m + 1):
        for indices in combinations(range(m), cardinality):
            selected = [edges[i] for i in indices]
            degree = [0] * n
            for u, v in selected:
                degree[u] += 1
                degree[v] += 1
            nodes = [u for u in range(n) if degree[u] > 0]
            if all(degree[u] == 2 for u in nodes) and len(nodes) == cardinality:
                # There could be disjoint cycles; restrict to connected supports.
                mapping = {u: j for j, u in enumerate(nodes)}
                induced = [(mapping[u], mapping[v]) for u, v in selected]
                if components(len(nodes), induced) == 1:
                    first = root(indices[0])
                    for i in indices[1:]:
                        parent[root(i)] = first
    return len({root(i) for i in range(m)})


def all_surjective_wild_values(n, edges):
    m = len(edges)
    spectrum = set()
    max_w_count = 0
    for mask in range(1, (1 << m) - 1):
        red = [edges[i] for i in range(m) if (mask >> i) & 1]
        blue = [edges[i] for i in range(m) if not ((mask >> i) & 1)]
        w = components(n, red) + components(n, blue) - 2
        spectrum.add(w)
        max_w_count += (w == n - 1)
    return spectrum, max_w_count


def check(n, edges):
    assert components(n, edges) == 1 and len(edges) >= 2
    observed, max_count = all_surjective_wild_values(n, edges)
    lower = partition_deficiency(n, edges)
    upper = n - 2 if is_two_vertex_connected(n, edges) else n - 1
    assert observed == set(range(lower, upper + 1)), (n, edges, observed, lower, upper)
    blocks = cycle_equivalence_blocks(n, edges)
    expected_max_count = (2 ** blocks - 2) if blocks >= 2 else 0
    assert max_count == expected_max_count, (n, edges, max_count, blocks)


def main():
    for n in (3, 4, 5):
        universe = list(combinations(range(n), 2))
        checked = 0
        for mask in range(1 << len(universe)):
            edges = [e for i, e in enumerate(universe) if (mask >> i) & 1]
            if len(edges) >= 2 and components(n, edges) == 1:
                check(n, edges)
                checked += 1
        print(f"n={n}: connected graphs={checked}; every two-colouring, endpoint, and block-count test passed")
    # Deliberately asymmetric larger examples, including bridges, blocks, and dense graphs.
    n = 6
    cases = [
        [(i, i + 1) for i in range(5)],
        [(i, (i + 1) % 6) for i in range(6)],
        [(0, 1), (1, 2), (2, 0), (2, 3), (3, 4), (4, 5), (5, 3)],
        [(0, 1), (1, 2), (2, 0), (0, 3), (3, 4), (4, 5), (5, 3)],
        list(combinations(range(6), 2)),
    ]
    for edges in cases:
        check(n, edges)
    print(f"n=6: {len(cases)} additional examples passed")
    print("VERIFY_OK")


if __name__ == "__main__":
    main()
