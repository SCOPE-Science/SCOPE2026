"""Independent exact evaluation-based enumeration for the six-branch cubic cover over F_7."""
import numpy as np
from itertools import product
p=7
A=np.array(list(product(range(p), repeat=3)),dtype=np.int64)
B=np.array(list(product(range(p), repeat=4)),dtype=np.int64)
# a=A0*x^2+A1*x*y+A2*y^2; b=B0*x^3+...+B3*y^3.
valid=np.ones((len(A),len(B)),dtype=bool)
for t in range(1,7):
    aa=(A[:,0]*t*t+A[:,1]*t+A[:,2])%7
    bb=(B[:,0]*t**3+B[:,1]*t*t+B[:,2]*t+B[:,3])%7
    val=(3*aa[:,None]**3+bb[None,:]**2)%7
    valid &= (val==0)
# at [1:0] and [0:1] nonzero. Check sign relation automatically follows degree 6 with six distinct roots.
k=(3*A[:,0,None]**3+B[None,:,0]**2)%7
valid &= k!=0
idx=np.argwhere(valid)
sol=[]
for i,j in idx:
    a=A[i].tolist();b=B[j].tolist()
    kk=int(k[i,j])
    assert (3*a[2]**3+b[3]**2+kk)%7==0
    sol.append((tuple(a),tuple(b),kk))
print('INDEPENDENT_VERIFY_OK',len(sol))
from collections import Counter
print('scalars',dict(Counter(s[-1] for s in sol)))
assert len(sol)==12 and Counter(s[-1] for s in sol)=={3:6,4:6}
assert all((a[1],a[2],b[0],b[1],b[2])==(0,0,0,0,0) for a,b,k in sol if k==3)
assert all((a[0],a[1],b[1],b[2],b[3])==(0,0,0,0,0) for a,b,k in sol if k==4)
# Each fixed-branch scalar orbit is generated by z -> s*z (s ∈ F7*).
canon=((1,0,0),(0,0,0,2))
orb=set()
for s in range(1,7):
    sa=pow(s,-2,7); sb=pow(s,-3,7)
    orb.add((tuple(sa*x%7 for x in canon[0]),tuple(sb*y%7 for y in canon[1]),3))
assert orb==set(v for v in sol if v[2]==3)
# swap x,y sends scalar 3 to 4.
swap={(tuple(reversed(a)),tuple(reversed(b)),(-k)%7) for a,b,k in orb}
assert swap==set(v for v in sol if v[2]==4)
# Count points of Z^3+X^2 Z+2Y^3=0 over F7.
pts=sum((z**3+x*x*z+2)%7==0 for x in range(7) for z in range(7))
pts+=sum((z**3+z)%7==0 for z in range(7))
print('curve points',pts)
assert pts==13
