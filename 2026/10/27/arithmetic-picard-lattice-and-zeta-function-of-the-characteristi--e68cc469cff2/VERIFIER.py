"""Exact arithmetic of the point--line divisor configuration on a K3 double plane.

Requires SymPy. All matrices are computed over the integers or rationals.
"""
from sympy import Matrix, eye, zeros, ilcm, denom, gcdex
from sympy.matrices.normalforms import hermite_normal_form, smith_normal_form
from sympy.polys.domains import ZZ


def mul4(a, b):
    # F_4 = F_2[t]/(t^2+t+1); elements 0,1,t,1+t encoded 0,1,2,3.
    c = 0
    for i in range(2):
        for j in range(2):
            if (a >> i) & 1 and (b >> j) & 1:
                c ^= 1 << (i + j)
    if c & 4:
        c ^= 7
    return c


def normalized(p):
    leading = next(a for a in p if a)
    reciprocal = next(b for b in (1, 2, 3) if mul4(leading, b) == 1)
    return tuple(mul4(a, reciprocal) for a in p)


points = sorted({normalized((a, b, c)) for a in range(4)
                 for b in range(4) for c in range(4) if a or b or c})
assert len(points) == 21
frobenius = lambda p: tuple(mul4(x, x) for x in p)
permutation = [points.index(frobenius(p)) for p in points]
permutation += [21 + points.index(frobenius(p)) for p in points]
assert all(permutation[permutation[i]] == i for i in range(42))
assert sum(permutation[i] == i for i in range(21)) == 7
assert sum(permutation[i] == i for i in range(21, 42)) == 7

# The two disjoint 21-curve families have cross-intersection equal to
# projective incidence, as established for this double-plane model.
gram = zeros(42)
for i in range(42):
    gram[i, i] = -2
for i, p in enumerate(points):
    for j, ell in enumerate(points):
        dot = mul4(p[0], ell[0]) ^ mul4(p[1], ell[1]) ^ mul4(p[2], ell[2])
        if dot == 0:
            gram[i, 21+j] = gram[21+j, i] = 1
assert all(sum(gram[i, 21:]) == 5 for i in range(21))
assert all(sum(gram[21+j, :21]) == 5 for j in range(21))
assert gram.rank() == 22

# A rational basis of the nondegenerate 22-space and coordinates of all
# 42 integral generators in that basis.
indices, columns = [], []
for i in range(42):
    candidate = gram[:, i]
    if Matrix.hstack(*(columns + [candidate])).rank() > len(columns):
        indices.append(i)
        columns.append(candidate)
select = eye(42)[:, indices]
K = select.T * gram * select
C = K.inv() * select.T * gram
scale = ilcm(*[denom(v) for v in C])
H = hermite_normal_form((C * scale).applyfunc(int))
# The column HNF gives an integral basis of the lattice generated by
# all 42 curves, expressed in the chosen rational coordinates.
full_gram = H.T * K * H / (scale*scale)
assert all(v.q == 1 for v in full_gram)
assert full_gram.det() == -4

# Frobenius on the full integral lattice.
perm_rational = C[:, [permutation[i] for i in indices]]
F = H.inv() * perm_rational * H
assert all(v.q == 1 for v in F)
assert F * F == eye(22)
assert F.T * full_gram * F == full_gram
assert F.trace() == 8

# Primitive Z-kernel of F-I, using unimodular column operations alone.
A, U = F - eye(22), eye(22)
pivot = 0
for row in range(22):
    j0 = next((j for j in range(pivot, 22) if A[row, j]), None)
    if j0 is None:
        continue
    if j0 != pivot:
        A.col_swap(j0, pivot)
        U.col_swap(j0, pivot)
    for j in range(pivot + 1, 22):
        b = A[row, j]
        if b:
            a = A[row, pivot]
            s, t, g = map(int, gcdex(a, b))
            ap, aj = list(A.col(pivot)), list(A.col(j))
            up, uj = list(U.col(pivot)), list(U.col(j))
            for v in range(22):
                A[v, pivot] = s * ap[v] + t * aj[v]
                A[v, j] = -(b // g) * ap[v] + (a // g) * aj[v]
                U[v, pivot] = s * up[v] + t * uj[v]
                U[v, j] = -(b // g) * up[v] + (a // g) * uj[v]
    pivot += 1
assert pivot == 7
assert abs(U.det()) == 1
invariant_basis = U[:, pivot:]
assert (F-eye(22)) * invariant_basis == zeros(22, 15)
invariant_gram = invariant_basis.T * full_gram * invariant_basis
assert invariant_gram.det() == 256
smith = smith_normal_form(invariant_gram, domain=ZZ)
assert sorted(abs(int(smith[i, i])) for i in range(15)) == [1]*8 + [2]*6 + [4]

# Galois orbit sums are integral, and generate the full fixed lattice.
orbits, seen = [], set()
for i in range(42):
    if i not in seen:
        orbit = tuple(sorted({i, permutation[i]}))
        orbits.append(orbit)
        seen.update(orbit)
assert len(orbits) == 28
orbit_matrix = zeros(42, 28)
for j, orbit in enumerate(orbits):
    for i in orbit:
        orbit_matrix[i, j] = 1
traces = H.inv() * scale * C * orbit_matrix
assert all(v.q == 1 for v in traces)
coords = U.inv() * traces
assert coords[:7, :] == zeros(7, 28)
trace_hnf = hermite_normal_form(coords[7:, :].applyfunc(int))
assert abs(trace_hnf.det()) == 1

# Cross-check on the smooth Mukai complete-intersection model over F2 and F4.
for k in (1, 2):
    field_points = [p for p in points if k == 2 or all(x in (0, 1) for x in p)]
    number = 0
    for x in field_points:
        for y in field_points:
            a = 0
            b = 0
            for xi, yi in zip(x, y):
                a ^= mul4(xi, mul4(yi, yi))
                b ^= mul4(mul4(xi, xi), yi)
            if a == b == 0:
                number += 1
    assert number == (21 if k == 1 else 105)

# Radicial degree-two plane cover and 21 split A1 exceptional curves:
# over F_(2^n), 7 singular points are rational for n odd, all 21 for n even.
for n in range(1, 11):
    q = 2**n
    geometric_count = 1 + q*q + (8 if n % 2 else 22)*q
    exceptional_count = q*q + q + 1 + (7 if n % 2 else 21)*q
    assert geometric_count == exceptional_count
print('VERIFY_OK: PG(2,F4) 21 points/lines, Gram rank 22 discr -4, '
      'Frobenius (+15,-7), invariant rank 15 discr 256 SNF 1^8 2^6 4; '
      '28 orbit sums index 1; exact zeta count identities')
