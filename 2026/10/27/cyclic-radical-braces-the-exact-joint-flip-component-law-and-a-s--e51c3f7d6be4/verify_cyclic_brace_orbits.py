#!/usr/bin/env python3
"""Finite independent checks of cyclic radical-brace orbit and probability formulas.

Run with Python 3; no third-party packages are required.
The exhaustive tests are finite checks, not proofs of the general identities.
"""
from collections import Counter
from fractions import Fraction
from math import gcd


def predictions(p, n, s):
    k = n-s
    assert 1 <= s < n
    orbit_profile = Counter({1: p**s})
    for j in range(1, k+1):
        orbit_profile[p**j] = (p-1)*p**(s-1)
    flip = Fraction(p+k*(p-1), p**(k+1))
    ic = Fraction(sum(mult*length*length for length,mult in orbit_profile.items()), p**(2*n))
    overlap = Fraction(p**s + (p-1)*p**(s-1)*sum(p**(2*j) for j in range(1, k//2+1)), p**(2*n))
    return orbit_profile, flip, ic, overlap


def actual(p, n, s):
    N = p**n
    m = p**s
    lam = [[(1+m*a)*b % N for b in range(N)] for a in range(N)]
    # Directly compute the transitive-closure components of the action
    # generated by all left actions, without using the proposed formula.
    unseen = set(range(N))
    component = {}
    profiles = Counter()
    while unseen:
        seed = min(unseen)
        reached = {seed}
        frontier = [seed]
        while frontier:
            v = frontier.pop()
            for a in range(N):
                w = lam[a][v]
                if w not in reached:
                    reached.add(w)
                    frontier.append(w)
        for v in reached:
            assert v in unseen
            unseen.remove(v)
            component[v] = seed
        profiles[len(reached)] += 1
    flip_count = sum(m*a*b % N == 0 for a in range(N) for b in range(N))
    ic_count = sum(component[a] == component[b] for a in range(N) for b in range(N))
    joint_count = sum(component[a] == component[b] and m*a*b % N == 0
                      for a in range(N) for b in range(N))
    # Calculate each right action from the defining brace solution, and
    # ensure its images preserve the directly computed left-action orbits.
    for b in range(N):
        right_images = []
        for a in range(N):
            c = lam[a][b]
            u = (1 + m*c) % N
            assert gcd(u, N) == 1
            rho = (pow(u, -1, N)*a) % N
            assert component[rho] == component[a]
            assert lam[c][rho] == a
            right_images.append(rho)
        assert len(set(right_images)) == N
    return profiles, Fraction(flip_count,N*N), Fraction(ic_count,N*N), Fraction(joint_count,N*N)


def test_ybe(p, n, s):
    # Exhaustive braid and involutivity on the smallest nontrivial samples.
    N=p**n; m=p**s
    def r(a,b):
        c=(1+m*a)*b % N
        return c, (a*pow((1+m*c)%N,-1,N))%N
    for a in range(N):
      for b in range(N):
        assert r(*r(a,b))==(a,b)
        for c in range(N):
            u,v=r(a,b)
            v,w=r(v,c)
            u,v=r(u,v)
            x,y=r(b,c)
            z,x=r(a,x)
            x,y=r(x,y)
            assert (u,v,w)==(z,x,y)


def main():
    total=0
    for p,nmax in [(2,6),(3,4),(5,3),(7,2)]:
      for n in range(2,nmax+1):
        for s in range(1,n):
            expected=predictions(p,n,s)
            got=actual(p,n,s)
            assert got==expected, (p,n,s,got,expected)
            if p**n <= 16:
                test_ybe(p,n,s)
            total+=1
    print(f'VERIFY_OK: {total} exhaustive parameter cases; orbits, flip pairs, same-component pairs, joint events, right actions; small YBE cubes')

if __name__=='__main__': main()
