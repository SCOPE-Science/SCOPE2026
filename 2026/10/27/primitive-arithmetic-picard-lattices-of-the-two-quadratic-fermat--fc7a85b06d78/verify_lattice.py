Flip=Matrix(22,22,lambda i,j: (1 if (i,j) in [(0,1),(1,0)] else 0) if i<2 else (1 if j in (0,1) else (-1 if j==i else 0)))

def smith_kernel(A):
    D,U,V=smith_normal_decomp(A,domain=ZZ)
    assert U*A*V==D
    d=min(D.shape)
    rank=sum(D[i,i]!=0 for i in range(d))
    K=V[:,rank:]
    assert A*K==Matrix.zeros(A.rows,K.cols)
    assert K.cols==A.cols-rank
    assert abs(V.det())==1
    return K

def group_invariants(M):
    D,U,V=smith_normal_decomp(M,domain=ZZ)
    assert U*M*V==D
    return [abs(int(D[i,i])) for i in range(M.rows) if abs(D[i,i])!=1]

def main():
    assert G.shape==F.shape==(22,22)
    assert G==G.T,(G-G.T)
    assert G.det()==-25,G.det()
    assert F*F==Matrix.eye(22)
    assert F*G*F.T==G
    assert Flip*Flip==Matrix.eye(22)
    assert Flip*G*Flip.T==G
    assert F*Flip==Flip*F
    assert F.trace()==2
    assert Flip.trace()==-20
    for name,M in [('untwisted',F),('nonsquare-deck-twist',F*Flip)]:
        K=smith_kernel(M.T-Matrix.eye(22))
        B=K.T*G*K
        assert B.det()!=0
        print(name,'rank',K.cols,'disc',B.det(),'disc-group',group_invariants(B))
        print('K=',K.T.tolist())
    print('CHECK_OK: original integral Gram det -25, Frobenius/Flip commuting involutory isometries, primitive fixed kernels by Smith transformation')

