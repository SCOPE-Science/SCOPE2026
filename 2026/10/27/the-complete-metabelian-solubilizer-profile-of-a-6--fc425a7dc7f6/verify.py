#!/usr/bin/env python3
"""Exhaustive rational-integer certificate for bounded solubilizers of A6.

Uses only the Python standard library. Permutations act on the rightmost
argument first. The exhaustive loops are finite, with asserted coverage.
"""
import collections
import itertools

N = 6
permutations = [p for p in itertools.permutations(range(N)) if
                sum(p[i] > p[j] for i in range(N) for j in range(i + 1, N)) % 2 == 0]
assert len(permutations) == 360
identities = {p: i for i, p in enumerate(permutations)}
unit = identities[tuple(range(N))]
order = len(permutations)
multiply = [[identities[tuple(a[b[j]] for j in range(N))]
             for b in permutations] for a in permutations]
inverses = [next(j for j in range(order) if multiply[i][j] == unit)
            for i in range(order)]
assert all(multiply[inverses[i]][i] == unit for i in range(order))


def cycles(p):
    visited = set()
    lengths = []
    for i in range(N):
        if i not in visited:
            current = i
            length = 0
            while current not in visited:
                visited.add(current)
                current = p[current]
                length += 1
            if length > 1:
                lengths.append(length)
    return tuple(sorted(lengths, reverse=True))


def generated(*elements):
    """BFS produces exactly the generated subgroup: a finite submonoid
    containing the inverses is the subgroup, and every word is reached."""
    steps = tuple(dict.fromkeys(e for a in elements for e in (a, inverses[a])))
    seen = {unit}
    queue = [unit]
    for u in queue:
        for s in steps:
            v = multiply[u][s]
            if v not in seen:
                seen.add(v)
                queue.append(v)
    return frozenset(seen)


def derived(subgroup):
    """Return [H,H] generated by all commutators of elements of H."""
    commutators = set()
    for a in subgroup:
        for b in subgroup:
            ab = multiply[a][b]
            invab = multiply[inverses[a]][inverses[b]]
            commutators.add(multiply[invab][ab])
    return generated(*commutators)


derived_length_cache = {}

def length(subgroup):
    if subgroup in derived_length_cache:
        return derived_length_cache[subgroup]
    degree = 0
    current = subgroup
    while len(current) != 1:
        next_group = derived(current)
        if next_group == current:
            degree = -1  # not soluble
            break
        degree += 1
        current = next_group
    derived_length_cache[subgroup] = degree
    return degree


classes = []
unassigned = set(range(order))
while unassigned:
    x = min(unassigned)
    conjugates = frozenset(multiply[multiply[g][x]][inverses[g]]
                           for g in range(order))
    assert x in conjugates and conjugates.issubset(unassigned)
    classes.append((x, conjugates))
    unassigned.difference_update(conjugates)
assert len(classes) == 7 and sum(len(c) for _, c in classes) == 360

# Per-element expected (class size, centralizer size, cyclic normalizer size,
# exact [derived length 0,1,2,3,non-soluble]). There are two 5-cycle classes.
expected = {
    (): (1, 360, 360, (1, 359, 0, 0, 0)),
    (3,): (40, 9, 18, (0, 9, 54, 27, 270)),
    (3, 3): (40, 9, 18, (0, 9, 54, 27, 270)),
    (2, 2): (45, 8, 8, (0, 8, 128, 32, 192)),
    (5,): (72, 5, 10, (0, 5, 5, 0, 350)),
    (4, 2): (90, 4, 8, (0, 4, 68, 32, 256)),
}
all_counts = collections.Counter()
nonmetabelian_seeds = set()
example_S4 = None
for x, conjugates in classes:
    key = cycles(permutations[x])
    class_size, central_expected, normalizer_expected, count_expected = expected[key]
    assert len(conjugates) == class_size
    cyclic = generated(x)
    centralizer = sum(1 for g in range(order) if multiply[g][x] == multiply[x][g])
    normalizer = sum(1 for g in range(order)
                     if multiply[multiply[g][x]][inverses[g]] in cyclic)
    assert (centralizer, normalizer) == (central_expected, normalizer_expected)
    counts = collections.Counter()
    for y in range(order):
        subgroup = generated(x, y)
        d = length(subgroup)
        counts[d] += 1
        if d == 3:
            assert len(subgroup) == 24
            nonmetabelian_seeds.add(subgroup)
            example_S4 = subgroup
        elif d >= 4:
            raise AssertionError('Soluble length greater than three')
        elif d == -1:
            assert len(subgroup) in (60, 360)
    found = tuple(counts[d] for d in (0, 1, 2, 3, -1))
    assert found == count_expected, (key, found, count_expected)
    for d, v in counts.items():
        all_counts[d] += len(conjugates) * v
assert dict(all_counts) == {0: 1, 1: 2519, 2: 16920, 3: 6480, -1: 103680}
assert sum(all_counts.values()) == 360 ** 2
assert example_S4 is not None
# Conjugate the detected seed subgroups by all of A6, accounting for both
# A6 conjugacy classes of S4. Count generating pairs inside each subgroup.
all_S4 = set()
for subgroup in nonmetabelian_seeds:
    for g in range(order):
        all_S4.add(frozenset(multiply[multiply[g][h]][inverses[g]]
                             for h in subgroup))
assert len(all_S4) == 30
per_S4_pairs = sum(1 for x in example_S4 for y in example_S4
                   if generated(x, y) == example_S4)
assert per_S4_pairs == 216
assert len(all_S4) * per_S4_pairs == all_counts[3]
# Distinct S4 subgroups have pairwise distinct generator-pair sets. Every
# length-three subgroup is one of these 30 groups.
print('A6 order 360; seven conjugacy classes; exact classwise assertions pass.')
print('Ordered pairs at derived lengths 0,1,2,3,infinity:',
      tuple(all_counts[d] for d in (0, 1, 2, 3, -1)))
print('Distinct S4 subgroups:', len(all_S4),
      '; ordered generating pairs each:', per_S4_pairs)
print('VERIFY_OK')
