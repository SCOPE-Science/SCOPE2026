#!/usr/bin/env python3
"""Reproduce exact integral torus-relation calculations for UConf_2(|K_7|).

Requires Python 3 and SymPy. All inputs are generated internally from the
seven-vertex complete graph, with no external files or saved matrices.
"""
from itertools import combinations
from math import prod
from sympy import Matrix, ZZ
from sympy.matrices.normalforms import hermite_normal_form, smith_normal_form

V = range(7)
edges = list(combinations(V,2))
edge_id = {e:i for i,e in enumerate(edges)}
faces = [(e,f) for e,f in combinations(edges,2) if set(e).isdisjoint(f)]
face_id = {p:i for i,p in enumerate(faces)}
edge_vertex_cells = [(e,v) for e in edges for v in V if v not in e]
ev_id = {p:i for i,p in enumerate(edge_vertex_cells)}
assert (len(edges),len(faces),len(edge_vertex_cells))==(21,105,105)

def triangle(tri):
    a,b,c=tri
    return [((a,b),1),((b,c),1),((a,c),-1)]

pairs=[]
for used in combinations(V,6):
    for a in combinations(used,3):
        b=tuple(x for x in used if x not in a)
        if a<b:pairs.append((a,b))
assert len(pairs)==70
pair_id={p:i for i,p in enumerate(pairs)}
T=Matrix.zeros(105,70)
for k,(a,b) in enumerate(pairs):
    for e,ea in triangle(a):
        for f,fb in triangle(b):
            x,y=(e,f) if e<f else (f,e)
            T[face_id[(x,y)],k]+=ea*fb*(1 if e<f else -1)
assert set(T)=={-1,0,1}

# Cubical differential, with each square oriented in its ordered two edges.
D=Matrix.zeros(105,105)
for i,(e,f) in enumerate(faces):
    a,b=e;c,d=f
    for pair,cval in (((f,b),1),((f,a),-1),((e,d),-1),((e,c),1)):
        D[ev_id[pair],i]+=cval
assert D*T==Matrix.zeros(105,70)

# A modular full-rank minor lower-bounds the rank over Q.
def rank_mod_p(A,p=3):
    rows=[[int(A[i,j])%p for j in range(A.cols)] for i in range(A.rows)]
    rank=0
    for j in range(A.cols):
        pivot=next((i for i in range(rank,A.rows) if rows[i][j]),None)
        if pivot is None:continue
        rows[pivot],rows[rank]=rows[rank],rows[pivot]
        inv=pow(rows[rank][j],-1,p)
        rows[rank]=[(x*inv)%p for x in rows[rank]]
        for i in range(rank+1,A.rows):
            if rows[i][j]:
                coeff=rows[i][j]
                rows[i]=[(x-coeff*y)%p for x,y in zip(rows[i],rows[rank])]
        rank+=1
    return rank
rank_d_mod3=rank_mod_p(D,3)
assert rank_d_mod3==70,rank_d_mod3
T_basis=hermite_normal_form(T)
assert T_basis.shape==(105,35)
T_diag=smith_normal_form(T_basis,domain=ZZ)
T_smith=[abs(int(T_diag[i,i])) for i in range(35)]
assert T_smith==[1]*35
# Since D*T=0, its rank in characteristic zero is at most 105-35=70,
# and modulo 2 gives rank at least 70. Thus ker(D)_Q has dimension 35.
# The primitive 35-dimensional column lattice of T equals integral ker(D).

R=Matrix.zeros(70,35)
for j,a in enumerate(combinations(V,3)):
    complement=tuple(x for x in V if x not in a)
    for k in range(4):
        c=tuple(x for x in complement if x!=complement[k])
        p=tuple(sorted((a,c)))
        R[pair_id[p],j]+=(-1 if k%2 else 1)*(1 if a<c else -1)
assert T*R==Matrix.zeros(105,35)
R_smith=smith_normal_form(R,domain=ZZ)
R_inv=[abs(int(R_smith[i,i])) for i in range(35)]
assert R_inv.count(1)==34 and R_inv.count(2)==1, R_inv

# Explicit ten-term six-vertex alternating relation, e.g. omitting vertex zero.
old=Matrix.zeros(70,1)
used=tuple(range(1,7))
for a in combinations(used,3):
    b=tuple(x for x in used if x not in a)
    if a>=b:continue
    concat=a+b
    inversions=sum(concat[i]>concat[j] for i in range(6) for j in range(i+1,6))
    old[pair_id[(a,b)]]=(-1)**inversions
assert len([t for t in old if t])==10
assert T*old==Matrix.zeros(105,1)
aug=R.row_join(old)
aug_basis=hermite_normal_form(aug)
assert aug_basis.shape==(70,35)
aug_smith=smith_normal_form(aug_basis,domain=ZZ)
aug_inv=[abs(int(aug_smith[i,i])) for i in range(35)]
assert aug_inv==[1]*35
# The torus relation lattice is saturated in Z^70, since T's image is free.
# The full-rank primitive lattice generated by the local relations and one
# ten-term relation therefore coincides with ker(T) exactly.

print('C2=105 C1=105 primitive torus columns=70')
print('rank(d2 modulo 3)=',rank_d_mod3)
print('rank(torus map)=',T_basis.cols,'torus image Smith invariants: 1 x',len(T_smith))
print('rank(tetrahedral relations)=',len(R_inv),'Smith invariants: 1 x 34, 2 x 1')
print('ten-term relation support=',sum(bool(x) for x in old))
print('augmented local-plus-ten-term Smith invariants: 1 x 35')
print('H2(UConf_2(K7);Z)=Z^35, complete integral presentation, local index=2')
print('VERIFY_OK')
