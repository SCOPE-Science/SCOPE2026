#!/usr/bin/env python3
"""Independent finite checks for geometric symmetry-fixed independence complexes.

Reconstructs the ladder graph, involution orbits, their compatibility graph,
and mod-2 homology from scratch. Finite checks support, not replace, the
all-width graph-folding proof.
"""
from collections import defaultdict


def ladder(n):
    length = 2 * n + 1
    vertices = [(row, i) for row in (0, 1) for i in range(1, length + 1)]
    edges = set()
    def e(a, b): return frozenset((a, b))
    for row in (0, 1):
        for i in range(1, length):
            edges.add(e((row, i), (row, i + 1)))
    for i in range(1, length + 1, 2):
        edges.add(e((0, i), (1, i)))
    return vertices, edges


def flip(v, n, word):
    row, i = v
    if word in ("h", "w", "hv"):
        row = 1 - row
    if word in ("v", "w", "hv"):
        i = 2 * n + 2 - i
    return row, i


def orbit_graph(vertices, edges, n, word):
    # group H is generated by word or by both flips (V4)
    orbit_of, orbits = {}, []
    for v in vertices:
        if v in orbit_of:
            continue
        orbit = {v}
        pending = [v]
        while pending:
            u = pending.pop()
            for gen in (("h", "v") if word == "V4" else (word,)):
                z = flip(u, n, gen)
                if z not in orbit:
                    orbit.add(z)
                    pending.append(z)
        oid = len(orbits)
        for u in orbit: orbit_of[u] = oid
        orbits.append(frozenset(orbit))
    bad = {orbit_of[a] for x in edges for a in x
           if len({orbit_of[v] for v in x}) == 1}
    keep = [i for i in range(len(orbits)) if i not in bad]
    index = {o:i for i,o in enumerate(keep)}
    qedges = set()
    for edge in edges:
        a,b = (orbit_of[x] for x in edge)
        if a != b and a in index and b in index:
            qedges.add(frozenset((index[a], index[b])))
    return [orbits[o] for o in keep], qedges


def model_graph(length, triangle=False):
    vertices = [(r,i) for r in (0,1) for i in range(1,length+1)]
    if triangle: vertices += [(2,length+1)]
    edges = set()
    def add(a,b):edges.add(frozenset((a,b)))
    for r in (0,1):
        for i in range(1,length):add((r,i),(r,i+1))
    for i in range(1,length+1,2):add((0,i),(1,i))
    if triangle:
        add((2,length+1),(0,length))
        add((2,length+1),(1,length))
    return vertices,edges


def get_faces(qvertices, qedges):
    N=len(qvertices)
    neighbours=[0]*N
    for e in qedges:
        a,b=tuple(e)
        neighbours[a] |= 1<<b
        neighbours[b] |= 1<<a
    faces=defaultdict(list)
    def visit(i,mask,ban):
        if i==N:
            faces[mask.bit_count()-1].append(mask)
            return
        visit(i+1,mask,ban)
        if not (ban>>i&1):
            visit(i+1,mask|(1<<i),ban|neighbours[i])
    visit(0,0,0)
    return faces


def bettis_mod2(faces):
    ranks={}
    for k in range(1,max(faces,default=-1)+1):
        lower={m:i for i,m in enumerate(faces[k-1])}
        pivots={}
        for mask in faces[k]:
            boundary=0; bits=mask
            while bits:
                t=bits&-bits;bits-=t
                boundary ^= 1<<lower[mask^t]
            while boundary:
                p=boundary.bit_length()-1
                if p not in pivots:
                    pivots[p]=boundary
                    break
                boundary ^= pivots[p]
        ranks[k]=len(pivots)
    return {k:len(fs)-ranks.get(k,0)-ranks.get(k+1,0)
            for k,fs in faces.items() if k>=0
            and len(fs)-ranks.get(k,0)-ranks.get(k+1,0)}


def check():
    count=0
    for n in range(1,13):
        V,E=ladder(n)
        assert all(flip(flip(v,n,g),n,g)==v for v in V for g in ('h','v','w'))
        assert all(frozenset(flip(x,n,g) for x in e) in E for e in E for g in ('h','v','w'))
        for word in ('h','v','w','V4'):
            orbits,qedges=orbit_graph(V,E,n,word)
            L=len(orbits)
            if word=='h':
                assert L==n and len(qedges)==0
            elif word=='V4':
                assert L==(n+1)//2 and len(qedges)==0
            elif word=='v':
                assert L==2*(n+1)
                expected_vertices,expected_edges=model_graph(n+1)
                # Every orbit supported on a single row. Its min column
                # identifies the quotient's row and index.
                labels=[(next(iter(o))[0],min(v[1] for v in o)) for o in orbits]
                assert len(set(labels))==L
                assert {frozenset((labels[a],labels[b])) for a,b in map(tuple,qedges)}==expected_edges
            elif word=='w':
                if n%2:
                    assert L==2*n+1
                else:assert L==2*n
                expected_vertices,expected_edges=model_graph(n,triangle=(n%2==1))
                def label(o):
                    if min(v[1] for v in o)==n+1:return (2,n+1)
                    i=min(v[1] for v in o)
                    row=next(v[0] for v in o if v[1]==i)
                    return row,i
                labels=[label(o) for o in orbits]
                assert len(set(labels))==L
                assert {frozenset((labels[a],labels[b])) for a,b in map(tuple,qedges)}==expected_edges
            count+=1
            if n<=7:
                B=bettis_mod2(get_faces(orbits,qedges))
                if word in ('h','V4'):
                    assert B=={0:1}, (n,word,B)
                elif word=='v':
                    expected={0:1, n//2:2} if n%2==0 and n>=2 else {0:1}
                    assert B==expected, (n,word,B,expected)
                elif word=='w':
                    expected={0:3} if n==1 else ({0:1,(n-1)//2:2} if n%2 else {0:1})
                    assert B==expected, (n,word,B,expected)
    print('PASS: %d complete group-orbit compatibility graphs; mod-2 homology for n=1..7 (all four subgroups).' % count)
    print('PASS: graph automorphisms and canonical quotient models for n=1..12.')
    print('FINITE CHECKS DO NOT PROVE ALL-WIDTH HOMOTOPY TYPES.')

if __name__=='__main__':check()
