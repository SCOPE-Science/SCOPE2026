"""Exact integer and finite-field checks for Eulerian prime-block Hensel factors.

Stand-alone, Python 3 standard library.  These tests do not prove the
universally quantified local-field classification in the accompanying proof.
"""
from math import factorial, comb

def trim(a):
    a=list(a)
    while len(a)>1 and a[-1]==0:a.pop()
    return a

def mul(a,b):
    out=[0]*(len(a)+len(b)-1)
    for i,u in enumerate(a):
        for j,v in enumerate(b):out[i+j]+=u*v
    return trim(out)

def sub(a,b):
    return trim([(a[i] if i<len(a) else 0)-(b[i] if i<len(b) else 0) for i in range(max(len(a),len(b)))])

def add(a,b):
    return trim([(a[i] if i<len(a) else 0)+(b[i] if i<len(b) else 0) for i in range(max(len(a),len(b)))])

def modpoly(a,p):return trim([x%p for x in a])

def divrem(a,b,p):
    a=modpoly(a,p); b=modpoly(b,p)
    if b==[0]:raise ZeroDivisionError
    q=[0]*max(1,len(a)-len(b)+1)
    while a!=[0] and len(a)>=len(b):
        idx=len(a)-len(b)
        coeff=(a[-1]*pow(b[-1],-1,p))%p
        q[idx]=coeff
        for i in range(len(b)):a[idx+i]=(a[idx+i]-coeff*b[i])%p
        a=trim(a)
    return trim(q),a

def inv_mod_poly(a,b,p):
    oldr,r=modpoly(b,p),modpoly(a,p)
    olds,s=[0],[1]
    while r!=[0]:
        q,nr=divrem(oldr,r,p)
        oldr,r=r,nr
        olds,s=s,modpoly(sub(olds,mul(q,s)),p)
    assert len(oldr)==1 and oldr[0]%p
    inv=modpoly([x*pow(oldr[0],-1,p) for x in olds],p)
    return divrem(inv,b,p)[1]

def eulerian(n):
    a=[1]
    for m in range(1,n):
        b=[0]*(m+1)
        for k,c in enumerate(a):
            b[k]+=(k+1)*c
            b[k+1]+=(m-k)*c
        a=b
    assert len(a)==n and sum(a)==factorial(n)
    return a

def prime(p):return p>=2 and all(p%d for d in range(2,int(p**0.5)+1))

def run():
    trials=0
    for p in [3,5,7,11,13]:
        fbase=[1]*p
        for t in range(p-1):
            n=p+t
            A=eulerian(n)
            G0=modpoly(eulerian(t+1),p)
            F0=fbase[:]
            assert modpoly(mul(F0,G0),p)==modpoly(A,p)
            assert sum(G0)%p==factorial(t+1)%p!=0
            # One exact Hensel step: A=F*G modulo p^2.
            product=mul(F0,G0)
            delta=sub(A,product)
            assert all(c%p==0 for c in delta)
            R=modpoly([c//p for c in delta],p)
            inverse=inv_mod_poly(G0,F0,p)
            F1=divrem(mul(R,inverse),F0,p)[1]
            quotient,remainder=divrem(sub(R,mul(F1,G0)),F0,p)
            assert remainder==[0]
            G1=quotient
            assert len(F1)<=p-1 and (G1==[0] or len(G1)<=t)
            F=add(F0,[p*c for c in F1])
            G=add(G0,[p*c for c in G1])
            d=sub(A,mul(F,G))
            assert all(c%(p*p)==0 for c in d)
            assert F[-1]%p==1 and G[-1]%p==1
            assert sum(F)%p==0
            assert sum(F)%(p*p)==(p*(-pow(t+1,-1,p)))%(p*p)
            # Tame Kummer field is generated by root of Y^(p-1)=p/(t+1).
            assert sum(F)//p%p==(-pow(t+1,-1,p))%p
            trials+=1
        print('p=',p,'fields=',p-1,'all distinct unit classes: verified')
    print('VERIFY_OK full_prime_blocks=',trials,'including_first_Hensel_lifts_mod_p2')
if __name__=='__main__':run()
