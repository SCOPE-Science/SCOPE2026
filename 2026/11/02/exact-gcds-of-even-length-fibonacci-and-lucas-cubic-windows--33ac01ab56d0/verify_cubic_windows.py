#!/usr/bin/env python3
"""Exact-integer consistency checks for even-width Fibonacci/Lucas cubic-window GCDs.

The infinite proof is algebraic; this script checks its critical identities and
independent finite examples, and is not an exhaustive proof for all widths.
"""
from math import gcd

LIMIT = 160
N = 12
F, L = [0, 1], [2, 1]
for _ in range(6 * LIMIT + N + 10):
    F.append(F[-1] + F[-2])
    L.append(L[-1] + L[-2])

def xtab(A, t, lucas=False):
    if t >= 0:
        return A[t]
    q = -t
    # F(-q) = (-1)^(q+1) F(q); L(-q) = (-1)^q L(q).
    return ((-1) ** (q if lucas else q+1)) * A[q]

def T(a, t):
    return a * xtab(F, 3*t+2) + 6 * (-1)**t * xtab(F,t-1)

def U(a, t):
    return a * xtab(L, 3*t+2,True) - 6 * (-1)**t * xtab(L,t-1,True)

def expected(m, lucas):
    if m % 2:
        x = L[m]
    else:
        x = F[m] * (3 if m % 4 == 0 else 1)
        if lucas:
            x *= 5
    if m % 3 == 0:
        assert x % 2 == 0
        x //= 2
    return x

def direct_gcd(m, lucas):
    A = L if lucas else F
    k = 2 * m
    cur = sum(A[j] ** 3 for j in range(1, k + 1))
    result = 0
    for n in range(N):
        result = gcd(result, cur)
        cur += A[n + k + 1] ** 3 - A[n + 1] ** 3
    return result

checks = 0
for m in range(1, LIMIT + 1):
    s = L[m]
    if m % 2:
        assert L[3*m] == s * (s*s + 3)
    else:
        assert F[3*m] == F[m] * (s*s - 1)
    for lucas in (False, True):
        A = L if lucas else F
        assert direct_gcd(m, lucas) == expected(m, lucas), (m, lucas)
        for n in range(5):
            t = n + m
            left = sum(A[n + j] ** 3 for j in range(1, 2*m + 1))
            # Binet-derived exact finite sum identity, using F_-1=1, L_-1=-1.
            Am1 = -1 if lucas else 1
            high = A[3*(n + 2*m) + 2] - A[3*n + 2]
            low = A[n + 2*m - 1] - (Am1 if n == 0 else A[n - 1])
            if lucas:
                assert 2*left == high + 6*(-1)**n*low
            else:
                assert 10*left == (F[3*(n+2*m)+2] - F[3*n+2]) - 6*(-1)**n*low
            # Four-term normalized sequences at t: evaluated only for t>=1.
            if not lucas and m % 2:
                val = (s*s + 3)*F[3*t+2] + 6*(-1)**t*F[t-1]
                assert 10*left == s*val
            elif not lucas:
                val = (s*s - 1)*L[3*t+2] - 6*(-1)**t*L[t-1]
                assert 10*left == F[m]*val
            elif m % 2:
                val = (s*s + 3)*L[3*t+2] - 6*(-1)**t*L[t-1]
                assert 2*left == s*val
            else:
                val = (s*s - 1)*F[3*t+2] + 6*(-1)**t*F[t-1]
                assert 2*left == 5*F[m]*val
            checks += 1

for a in range(-500,501):
    for seq in (T,U):
        for t in range(-2,4):
            assert seq(a,t+4) == (3*seq(a,t+3)+6*seq(a,t+2)-3*seq(a,t+1)-seq(a,t))
    # First four values are generated by two integer initial values.
    T0,T1 = a+6,5*a
    T2,T3 = 21*a+6,89*a-6
    assert (T2,T3) == (T0+4*T1, -T0+18*T1)
    assert gcd(T0,T1) == gcd(a+6,30)
    U0,U1 = 3*a+6,11*a+12
    U2,U3 = 47*a-6,199*a+18
    assert (U2,U3) == (-21*U0+10*U1,-73*U0+38*U1)
    assert (11*U0-3*U1)==30

# Explicit nontrivial counterexamples to the 2022 proposed even-window formula.
assert direct_gcd(3,False)==2 and gcd(F[7]**3-1,F[8]**3-1)==4
assert direct_gcd(3,True)==2 and gcd(L[7]**3-1,L[8]**3-27)==28
print('VERIFY_OK windows=320 signed_sum_checks='+str(checks)+
      ' linear_parameter_cases=1001 k6_F_actual=2_proposed=4'+
      ' k6_L_actual=2_cube_difference_gcd=28')
