"""Exact finite sanity checks for the integral-module theorem on six clique blowups."""
from itertools import combinations, product
from math import prod

def rank_mod(columns, rows, prime=1000003):
    pivots={}
    for col in columns:
        v={r: (val%prime) for r,val in col.items() if val%prime}
        while v:
            p=min(v)
            if p not in pivots:
                inv=pow(v[p], -1, prime)
                pivots[p]={r:val*inv%prime for r,val in v.items()}
                break
            w=pivots[p]; coeff=v[p]
            for r,val in w.items():
                nv=(v.get(r,0)-coeff*val)%prime
                if nv: v[r]=nv
                else: v.pop(r,None)
    return len(pivots)

def sign_of_sorted(images):
    return (-1)**sum(images[i]>images[j] for i in range(len(images)) for j in range(i+1,len(images)))

def data(m):
    vertices=tuple(range(6*m))
    edges=[]
    for i,j in combinations(range(6),2):
        if (j-i)%6 not in (1,5):
            for a,b in product(range(m),repeat=2):
                edges.append((m*i+a,m*j+b))
    faces=[]
    for centers in ((0,2,4),(1,3,5)):
        for colors in product(range(m),repeat=3):
            faces.append(tuple(m*i+a for i,a in zip(centers,colors)))
    return tuple((v,) for v in vertices),tuple(edges),tuple(faces)

def chain_trace(faces, perm):
    face_set=set(faces); total=0
    for face in faces:
        img=tuple(perm[v] for v in face)
        if tuple(sorted(img))==face:
            total+=sign_of_sorted(img)
    return total

def theoretical_trace(m, map_vertex):
    # The geometric action must send each clique of size m onto another clique.
    sites=[map_vertex[m*i]//m for i in range(6)]
    assert all(map_vertex[m*i+a]//m==sites[i] for i in range(6) for a in range(m))
    parity_swap=(sites[0]%2==1)
    opposite_edges=[(m*i+a,m*(i+3)+b) for i in range(3) for a,b in product(range(m),repeat=2)]
    fixed_E=sum(tuple(sorted((map_vertex[u],map_vertex[v]))) == (u,v) for u,v in opposite_edges)
    chi1=(-1 if parity_swap else 1)*(fixed_E-1)
    if parity_swap: return chi1,0
    d=m-1
    # Trace of action on the reduced H0 tensor of the three odd/even clique sets.
    out=0
    for group in ((0,2,4),(1,3,5)):
        dest=[sites[i] for i in group]
        indices=[group.index(j) for j in dest]
        sgn=sign_of_sorted(indices)
        visited=set(); tr=1
        for start in range(3):
            if start in visited:continue
            cycle=[];t=start
            while t not in visited:
                visited.add(t);cycle.append(t);t=indices[t]
            # Coefficient label permutation around the factor cycle, composed in action order.
            def act_label(src,col):
                return map_vertex[m*group[src]+col]%m
            src=cycle[0]; current=list(range(m)); x=src
            for _ in range(len(cycle)):
                current=[act_label(x,col) for col in current];x=indices[x]
            tr*=sum(current[a]==a for a in range(m))-1
        out+=sgn*tr
    return chi1,out

def check(m):
    c0,c1,c2=data(m)
    assert (len(c0),len(c1),len(c2))==(6*m,9*m*m,2*m**3)
    edge_index={e:i for i,e in enumerate(c1)}
    bd1=[{v:-1,w:1} for v,w in c1]
    bd2=[]
    for a,b,c in c2:
        bd2.append({edge_index[(b,c)]:1,edge_index[(a,c)]:-1,edge_index[(a,b)]:1})
    r1=rank_mod(bd1,len(c0));r2=rank_mod(bd2,len(c1))
    assert r1==6*m-1 and r2==2*(m**3-(m-1)**3)
    assert (len(c1)-r1-r2,len(c2)-r2)==(3*m*m-1,2*(m-1)**3)
    identity=tuple(range(m))
    if m==2: sample=[identity,tuple(reversed(range(m)))]
    else: sample=[identity,(1,0,*range(2,m)),(*range(1,m),0)]
    tests=0
    for typ,k,colors in product(range(2),range(6),product(sample,repeat=2)):
        # D_6 generated by rotation i -> i+1 and reflection i -> -i.
        geo=lambda i: (k+(-i if typ else i))%6
        sigmas=[identity]*6
        sigmas[0]=colors[0];sigmas[3]=colors[1]
        perm=tuple(m*geo(i)+sigmas[geo(i)][a] for i in range(6) for a in range(m))
        got=theoretical_trace(m,perm)
        t0=chain_trace(c0,perm);t1=chain_trace(c1,perm);t2=chain_trace(c2,perm)
        # reduced Lefschetz = -H1+H2
        assert -1+t0-t1+t2==-got[0]+got[1],(m,typ,k,colors,got,(t0,t1,t2))
        tests+=1
    if m<=3:
        # Exhaustive geometric D6 and all independent color swaps at two opposite fibers.
        pass
    print('m=',m,'f=',tuple(map(len,(c0,c1,c2))),'ranks=',r1,r2,'betti=',(1,3*m*m-1,2*(m-1)**3),'trace_tests=',tests)

for m in (2,3,4):check(m)
