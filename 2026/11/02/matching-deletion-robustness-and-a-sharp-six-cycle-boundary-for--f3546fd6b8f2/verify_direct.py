"""Independent direct finite checks of proper three-colouring recolouring graphs.
All states are generated by brute force, without using the structural theorem.
Run: python verify_direct.py
"""
from collections import Counter, deque
from itertools import product


def _distances(root,nei,allowed):
    d={root:0};q=deque([root])
    while q:
        u=q.popleft()
        for v in nei[u]:
            if v in allowed and v not in d:d[v]=d[u]+1;q.append(v)
    return d

def check(m, n, t):
    assert 3 <= m <= n and 0 <= t <= m
    # A_i B_i is absent for each i < t; all other cross edges exist.
    forbidden = {(i, i) for i in range(t)}
    edges = [(i, j) for i in range(m) for j in range(n) if (i, j) not in forbidden]
    states = []
    for s in product(range(3), repeat=m+n):
        if all(s[i] != s[m+j] for i,j in edges):
            states.append(s)
    ind = {s:i for i,s in enumerate(states)}
    nei = [[] for _ in states]
    for i,s in enumerate(states):
        for v in range(m+n):
            for a in range(3):
                if a != s[v]:
                    z = s[:v]+(a,)+s[v+1:]
                    j = ind.get(z)
                    if j is not None:
                        nei[i].append(j)
        assert len(nei[i])==len(set(nei[i]))
    if (m,n,t)==(3,3,3):
        assert len(states)==66
        frozen=[i for i,x in enumerate(nei) if not x]
        assert len(frozen)==6
        rest=set(range(len(states)))-set(frozen)
        root=next(iter(rest));d={root:0};q=deque([root])
        while q:
            u=q.popleft()
            for v in nei[u]:
                if v not in d:d[v]=d[u]+1;q.append(v)
        assert set(d)==rest
        assert all(max(_distances(r,nei,rest).values())==9 for r in rest)
        print("DIRECT_BOUNDARY_PASS m=n=3 t=3 60-state component and six isolated states")
        return
    order = 3*(2**m+2**n)-6+6*t
    size = 3*(m*2**(m-1)+n*2**(n-1))+12*t
    assert len(states)==order, (m,n,t,'order',len(states),order)
    assert sum(map(len,nei))//2==size, (m,n,t,'edges')
    ecc=[]
    for s in range(len(states)):
        d=[-1]*len(states);d[s]=0;Q=deque([s])
        while Q:
            u=Q.popleft()
            for w in nei[u]:
                if d[w]<0:
                    d[w]=d[u]+1;Q.append(w)
        assert min(d)>=0, (m,n,t,'disconnected')
        ecc.append(max(d))
    D=3*(m+n)//2
    assert min(ecc)==max(ecc)==D, (m,n,t,'ecc',Counter(ecc))
    # Directly detect bipartiteness of the *recolouring* graph.
    sign=[-1]*len(states);sign[0]=0;Q=deque([0]);is_bip=True
    while Q:
        u=Q.popleft()
        for w in nei[u]:
            if sign[w]<0:sign[w]=sign[u]^1;Q.append(w)
            elif sign[w]==sign[u]:is_bip=False
    assert is_bip==((m+n)%2==0), (m,n,t,'bip')
    assert sum(1 for x in nei if len(x)==2)==6*t, (m,n,t,'ears')
    print(f'DIRECT_PASS m={m} n={n} t={t} V={order} E={size} ecc={D} bip={is_bip}')

if __name__ == '__main__':
    for m,n in [(3,3),(3,4),(3,5),(4,4),(4,5),(4,6),(5,5)]:
        for t in range(m+1):
            check(m,n,t)
    print('DIRECT_ALL_PASS')
