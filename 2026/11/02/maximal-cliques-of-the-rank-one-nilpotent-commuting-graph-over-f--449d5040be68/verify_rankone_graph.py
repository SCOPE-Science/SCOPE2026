#!/usr/bin/env python3
"""Independent finite checks for rank-one nilpotent commuting-graph theorem.
Finite tests only: not an infinite-dimensional correctness certificate.
"""
from itertools import product

class Field:
    def __init__(self,q):
        assert q in (2,3,4,5)
        self.q=q
    def add(self,a,b):return (a^b) if self.q==4 else ((a+b)%self.q)
    def sub(self,a,b):return (a^b) if self.q==4 else ((a-b)%self.q)
    def mul(self,a,b):
        if self.q!=4:return a*b%self.q
        p=0
        for k in range(2):
            if (b>>k)&1:p^=a<<k
        if p&8:p^=0b1100
        if p&4:p^=0b0111
        return p
    def dot(self,u,v):
        z=0
        for x,y in zip(u,v):z=self.add(z,self.mul(x,y))
        return z

def rank_vecs(vs,n,F):
    rows=[list(v) for v in vs if any(v)]
    h=0
    for j in range(n):
        pivot=next((k for k in range(h,len(rows)) if rows[k][j]),None)
        if pivot is None:continue
        rows[h],rows[pivot]=rows[pivot],rows[h]
        v=rows[h][j]
        inv=next(a for a in range(1,F.q) if F.mul(v,a)==1)
        rows[h]=[F.mul(inv,x) for x in rows[h]]
        for k in range(len(rows)):
            if k!=h and rows[k][j]:
                z=rows[k][j]
                rows[k]=[F.sub(a,F.mul(z,b)) for a,b in zip(rows[k],rows[h])]
        h+=1
        if h==len(rows):break
    return h

def gauss(n,k,q):
    z=1
    for i in range(k):
        z=z*(q**(n-i)-1)//(q**(k-i)-1) if False else z
    num=1; den=1
    for i in range(k):num*=q**(n-i)-1;den*=q**(k-i)-1
    return num//den

def test(n,q):
    F=Field(q)
    vectors=[u for u in product(range(q),repeat=n) if any(u)]
    facts={}
    for u in vectors:
        for v in vectors:
            if F.dot(u,v):continue
            M=tuple(F.mul(u[i],v[j]) for i in range(n) for j in range(n))
            facts[M]=(u,v)
    mats=list(facts)
    expected_vert=(q**n-1)*(q**(n-1)-1)//(q-1)
    assert len(mats)==expected_vert,(n,q,len(mats),expected_vert)
    # Independent ordinary matrix multiplication used to decide adjacency.
    def mm(A,B):
        return tuple(_mm(A,B,i,j) for i in range(n) for j in range(n))
    def _mm(A,B,i,j):
        z=0
        for k in range(n):z=F.add(z,F.mul(A[n*i+k],B[n*k+j]))
        return z
    adj=[set() for _ in mats]
    for i in range(len(mats)):
        A=mats[i]
        for j in range(i):
            B=mats[j]
            if mm(A,B)==mm(B,A):adj[i].add(j);adj[j].add(i)
    deg= q**(n-1)-2+(q**(n-1)-q)*(q**(n-2)-1)//(q-1)
    assert all(len(ns)==deg for ns in adj),(n,q,'degree')
    cliques=[]
    def maximal(R,P,X):
        if not P and not X:
            cliques.append(frozenset(R));return
        pivot=max(P|X,key=lambda j:len(P&adj[j])) if P or X else None
        for v in list(P-(adj[pivot] if pivot is not None else set())):
            maximal(R|{v},P&adj[v],X&adj[v]);P.remove(v);X.add(v)
    maximal(set(),set(range(len(mats))),set())
    want=sum(gauss(n,k,q) for k in range(1,n))
    assert len(cliques)==want,(n,q,len(cliques),want)
    seen=set(); by_k={}
    for C in cliques:
        # im(M) is generated by nonzero columns, independently of matrix factor choices.
        vectors_in=[tuple(mats[i][n*r+j] for r in range(n)) for i in C for j in range(n)]
        basis=[];rank=0
        for v in vectors_in:
            r=rank_vecs(basis+[v],n,F)
            if r>rank:basis.append(v);rank=r
        K=rank
        wanted=(q**K-1)*(q**(n-K)-1)//(q-1)
        assert len(C)==wanted,(n,q,K,len(C),wanted)
        for j,M in enumerate(mats):
            # membership iff every image column is in span K AND K lies in kernel M
            if all(rank_vecs(basis+[tuple(M[n*r+t] for r in range(n))],n,F)==K for t in range(n)) and all(all(F.dot(tuple(M[n*i+t] for t in range(n)),u)==0 for i in range(n)) for u in basis):
                assert j in C,(n,q,'missing expected clique element',j,K)
            else:
                assert j not in C,(n,q,'extra clique element',j,K)
        key=tuple(sorted(tuple(v) for v in basis))
        # basis choices not canonical; check K distinct by span membership
        for oldbasis in seen:
            if len(oldbasis)==K and all(rank_vecs(list(oldbasis)+[b],n,F)==K for b in basis):
                raise AssertionError((n,q,'same maximal space twice',K))
        seen.add(tuple(basis))
        by_k[K]=by_k.get(K,0)+1
    assert all(by_k.get(k,0)==gauss(n,k,q) for k in range(1,n)),(n,q,by_k)
    clique_size=max(len(C) for C in cliques)
    theo_size=(q**(n//2)-1)*(q**((n+1)//2)-1)//(q-1)
    assert clique_size==theo_size
    # For each two distinct maximal cliques verify the intersection cardinality by the
    # projective dimension formula using their reconstructed image spaces.
    spaces=[]
    for C in cliques:
        basis=[];rank=0
        for i in C:
            M=mats[i]
            for t in range(n):
                v=tuple(M[n*r+t] for r in range(n))
                j=rank_vecs(basis+[v],n,F)
                if j>rank:basis.append(v);rank=j
        spaces.append(basis)
    for i in range(len(spaces)):
        ki=len(spaces[i])
        for j in range(i):
            kj=len(spaces[j]);s=rank_vecs(spaces[i]+spaces[j],n,F)
            h=ki+kj-s
            want=((q**h-1)*(q**(n-s)-1)//(q-1))
            assert len(cliques[i]&cliques[j])==want,(n,q,'intersection',i,j)
    print(f'OK n={n} q={q} vertices={len(mats)} degree={deg} maximal_cliques={len(cliques)} clique_number={clique_size}')

if __name__=='__main__':
    for n,q in [(2,2),(2,3),(2,4),(2,5),(3,2),(3,3),(3,4),(4,2)]:test(n,q)
    print('RANK_ONE_NILPOTENT_CLIQUE_GEOMETRY_OK 8')
