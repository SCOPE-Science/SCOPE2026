#!/usr/bin/env python3
"""Independent three-round first-order type recursion for small subspace posets.

Subspaces are generated by repeatedly adjoining a vector and taking spans,
not by reduced-row-echelon enumeration.
"""
from itertools import product

def all_subspaces(n,q):
    universe=list(product(range(q),repeat=n))
    zero=(0,)*n
    pool={frozenset([zero])}
    frontier=list(pool)
    while frontier:
        S=frontier.pop()
        for v in universe:
            if v in S:continue
            span=frozenset(tuple((a[i]+t*v[i])%q for i in range(n))
                           for a in S for t in range(q))
            if span not in pool:
                pool.add(span);frontier.append(span)
    return list(pool)

def three_type(n,q):
    ss=all_subspaces(n,q)
    N=len(ss)
    R=[[0 if X==Y else 1 if X<Y else 2 if Y<X else 3
        for Y in ss] for X in ss]
    def triple(i,j,k):return (R[i][j],R[i][k],R[j][k])
    pair=[[frozenset(triple(i,j,k) for k in range(N)) for j in range(N)]
          for i in range(N)]
    roots=frozenset(frozenset(pair[i]) for i in range(N))
    return N,roots

if __name__=='__main__':
    roots={}
    for q,nmax in [(2,5),(3,4)]:
        for n in range(1,nmax+1):
            count,t=three_type(n,q)
            assert len(t)==n+1
            roots[n,q]=t
            print(f'FULL_RECURSION: dimension={n} field={q} subspaces={count} pointed_types={len(t)} PASS')
    for n in range(1,5):
        assert roots[n,2]==roots[n,3]
    for (n,q),t in roots.items():
        for (m,r),u in roots.items():
            assert (t==u)==(m==n)
    print('VERIFY_FULL_TYPES_PASS')
