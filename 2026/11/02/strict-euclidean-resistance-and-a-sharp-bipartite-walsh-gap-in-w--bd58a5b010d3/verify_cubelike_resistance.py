#!/usr/bin/env python3
"""Exact independent resistance and Walsh-spectrum checks for weighted cubelike networks.

Run with Python 3; standard library only. This is a finite diagnostic,
not a replacement for the all-dimension proof in RESULT.md.
"""
from fractions import Fraction


def parity(n):
    return n.bit_count() & 1


def invert(matrix):
    n = len(matrix)
    a = [[Fraction(x) for x in row] +
         [Fraction(i == j) for j in range(n)] for i, row in enumerate(matrix)]
    for col in range(n):
        pivot = next(i for i in range(col, n) if a[i][col])
        a[col], a[pivot] = a[pivot], a[col]
        x = a[col][col]
        a[col] = [v / x for v in a[col]]
        for i in range(n):
            if i != col and a[i][col]:
                factor = a[i][col]
                a[i] = [u - factor * v for u, v in zip(a[i], a[col])]
    return [row[n:] for row in a]


def verify_case(rank, generator_weights):
    size = 1 << rank
    assert generator_weights and all(0 < g < size and c > 0
                                     for g, c in generator_weights)
    # Connectivity: compute the group generated by edge displacements.
    reachable = {0}
    for g, _ in generator_weights:
        reachable |= {v ^ g for v in list(reachable)}
    assert len(reachable) == size
    conductances = [Fraction(0) for _ in range(size)]
    for g, c in generator_weights:
        conductances[g] += Fraction(c)
    generators = [g for g in range(1, size) if conductances[g] > 0]
    # Independently build and invert the grounded physical Laplacian.
    lap = [[Fraction(0) for _ in range(size)] for _ in range(size)]
    for x in range(size):
        for g in generators:
            y = x ^ g
            c = conductances[g]
            lap[x][x] += c
            lap[x][y] -= c
    green = invert([row[:-1] for row in lap[:-1]])

    def r_ground(x, y):
        if x == y:
            return Fraction(0)
        if x == size - 1:
            return green[y][y]
        if y == size - 1:
            return green[x][x]
        return green[x][x] + green[y][y] - 2 * green[x][y]

    symbol = [Fraction(0) for _ in range(size)]
    for chi in range(1, size):
        symbol[chi] = 2 * sum((conductances[g]
                                for g in generators if parity(chi & g)),
                               Fraction(0))
        assert symbol[chi] > 0
    weights = [Fraction(0)] + [1 / symbol[chi]
                                  for chi in range(1, size)]
    total = sum(weights)
    resist = []
    for z in range(size):
        value = Fraction(2, size) * sum(
            (weights[chi] * (1 - (-1 if parity(chi & z) else 1))
             for chi in range(1, size)), Fraction(0))
        resist.append(value)
    for x in range(size):
        for y in range(size):
            assert r_ground(x, y) == resist[x ^ y], (rank, x, y)
    assert resist[0] == 0 and all(v > 0 for v in resist[1:])
    # Independently Fourier-transform the squared physical resistance matrix.
    bipartition = [chi for chi in range(1, size)
                   if all(parity(chi & g) for g in generators)]
    assert len(bipartition) <= 1
    for tau in range(1, size):
        eigen = sum((resist[z]**2 * (-1 if parity(tau & z) else 1)
                     for z in range(size)), Fraction(0))
        convolution = sum((weights[chi] * weights[chi ^ tau]
                           for chi in range(size)), Fraction(0))
        formula = Fraction(4, size) * (
            convolution - 2 * total * weights[tau])
        lower_on_gram = Fraction(4, size) / symbol[tau]**2
        assert eigen == formula
        assert eigen < 0
        assert -eigen / 2 >= lower_on_gram
        assert (-eigen / 2 == lower_on_gram) == (tau in bipartition)
    print('EXACT_OK rank={} vertices={} generators={} bipartite={} '
          'pair_checks={}'.format(rank, size, len(generators),
                                 bool(bipartition), size * size))


def main():
    cases = [
        (1, [(1, 3)]),
        (2, [(1, 1), (2, 1)]),
        (3, [(1, 1), (2, 2), (4, 3)]),
        (3, [(1, 1), (2, 2), (4, 3), (3, 5)]),
        (3, [(1, 2), (2, 3), (4, 5), (7, 7)]),
        (4, [(1, 1), (2, 2), (4, 3), (8, 4), (7, 5)]),
        (4, [(1, 1), (2, 2), (4, 3), (8, 4), (3, 5), (15, 3)]),
        (4, [(1, 1), (2, 2), (4, 3), (8, 4), (3, 5), (7, 2)]),
    ]
    for case in cases:
        verify_case(*case)
    print('ALL_WEIGHTED_CUBELIKE_RESISTANCE_CHECKS_OK')


if __name__ == '__main__':
    main()
