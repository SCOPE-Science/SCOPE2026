"""Reproduce the exact central-section polygon-type law of the truncated octahedron.

Standard-library-only; finite checks support, rather than replace, the proof.
"""
import itertools
import math
import random
from fractions import Fraction

F = Fraction
V = sorted({tuple(a * s for a, s in zip(permutation, signs))
            for permutation in set(itertools.permutations((0, 1, 2)))
            for signs in itertools.product((-1, 1), repeat=3)})
E = [(v, w) for i, v in enumerate(V) for w in V[i + 1:]
     if sum((a - b) ** 2 for a, b in zip(v, w)) == 2]
assert len(V) == 24 and len(E) == 36
assert all(sum(x * x for x in v) == 5 for v in V)
assert all(sum(a * b for a, b in zip(v, w)) == 4 for v, w in E)
assert all(sum(v in pair for pair in E) == 3 for v in V)


def crossings(u):
    def dp(v):
        return sum(a * b for a, b in zip(u, v))
    return sum(dp(v) * dp(w) < 0 for v, w in E)


# Representatives in each open subregion of the fundamental Weyl chamber.
# (a,b,c) have a>b>c>0. The transitions are a=2b, a=2c, b=2c.
regions = [
    ((20, 6, 1), 8, (False, False, False)),
    ((20, 6, 4), 10, (False, False, True)),
    ((20, 14, 2), 6, (True, False, False)),
    ((20, 14, 9), 8, (True, False, True)),
    ((20, 16, 12), 6, (True, True, True)),
]
for u, sides, region_signs in regions:
    a, b, c = u
    assert (b > a / 2, c > a / 2, c > b / 2) == region_signs
    assert crossings(tuple(F(i) for i in u)) == sides

# Exhaust all vertex-orthogonality walls meeting the open chamber.
# The chamber is the cone generated by (1,0,0), (1,1,0), (1,1,1).
intersecting_walls = {
    v for v in V
    if min((v[0], v[0]+v[1], sum(v))) < 0
    < max((v[0], v[0]+v[1], sum(v)))
}
assert intersecting_walls == {
    (-1,0,2), (1,0,-2), (-1,2,0), (1,-2,0),
    (0,-1,2), (0,1,-2),
}

# Exact solid angle of the decagon triangular cone.
a = (1, 0, 0)
b = (4, 2, 1)
c = (2, 1, 1)
assert (b[1] * c[2] - b[2] * c[1]) == 1
D = 11 + 3 * math.sqrt(14) + 4 * math.sqrt(6) + 2 * math.sqrt(21)
omega = 2 * math.atan(1 / D)
omega_integrated = (math.atan(math.sqrt(3 / 2))
                    - math.atan(math.sqrt(21) / 2)
                    + math.atan(2) - math.pi / 4)
assert abs(omega - omega_integrated) < 2e-15

p10 = 12 * omega / math.pi
theta = math.acos(4 / 5)
mean = 36 * theta / math.pi
p8 = (mean - 6) / 2 - 2 * p10
p6 = 1 - p8 - p10
assert 0 < p6 < 1 and 0 < p8 < 1 and 0 < p10 < 1
assert abs(6*p6 + 8*p8 + 10*p10 - mean) < 1e-14
assert abs(p6 - 0.4984506899177036) < 1e-12
assert abs(p8 - 0.31610885558019086) < 1e-12
assert abs(p10 - 0.18544045450210578) < 1e-12

# Independent randomized test of rotational measure: directions are
# Gaussian-normalized and thus Haar-uniform on the sphere.
rng = random.Random(0x51CE)
num = 90000
hist = {6: 0, 8: 0, 10: 0}
for _ in range(num):
    u = tuple(rng.gauss(0, 1) for _ in range(3))
    n = crossings(u)
    assert n in hist
    hist[n] += 1
for n, p in [(6,p6), (8,p8), (10,p10)]:
    assert abs(hist[n]/num - p) < 0.010, (n, hist[n]/num, p)

print('VERTICES',len(V),'EDGES',len(E))
print('CHAMBER_TYPES', [(u,n) for u,n,_ in regions])
print('DECAGON_SOLID_ANGLE',format(omega,'.15f'))
print('EXACT_LAW_P6_P8_P10', *(format(p,'.15f') for p in [p6,p8,p10]))
print('CROFTON_EXPECTATION',format(mean,'.15f'))
print('SAMPLING_COUNTS', hist)
print('ALL_CHECKS_PASSED')
