#!/usr/bin/env python3
"""Direct chain-level verification of truncated-plane Poisson cohomology and cup products.

Independent finite-field GF(2), GF(4), GF(8) computations. Requires verify.py
for binary extension-field arithmetic only. All cochain matrices are formed directly.
"""
from itertools import product
from verify import gf_data


def verify(q):
    mult, inverse = gf_data(q)
    Z=(0,0,0,0)
    ONE=(1,0,0,0)
    X=(0,1,0,0)
    Y=(0,0,1,0)
    XY=(0,0,0,1)
    A=(ONE,X,Y,XY)

    def add(*args):return tuple(__import__('functools').reduce(lambda a,b:a^b,(v[i] for v in args),0) for i in range(4))
    def prod(u,v):
        a,b,c,d=u;e,f,g,h=v
        return (mult(a,e), mult(a,f)^mult(b,e), mult(a,g)^mult(c,e),
                mult(a,h)^mult(b,g)^mult(c,f)^mult(d,e))
    def dx(v):return (v[1],0,v[3],0)
    def dy(v):return (v[2],v[3],0,0)
    def bracket(g,u,v):return prod(g,add(prod(dx(u),dy(v)),prod(dy(u),dx(v))))
    def action(v,u):return add(prod(v[:4],dx(u)),prod(v[4:],dy(u)))
    def cup(v,w):return add(prod(v[:4],w[4:]),prod(v[4:],w[:4]))
    B8=tuple(u+Z for u in A)+tuple(Z+u for u in A)

    def rank(columns):
        if not columns:return 0
        m=len(columns[0]); mat=[[col[i] for col in columns] for i in range(m)]
        p=0
        for j in range(len(columns)):
            i=next((i for i in range(p,m) if mat[i][j]),None)
            if i is None:continue
            mat[i],mat[p]=mat[p],mat[i]
            s=inverse[mat[p][j]]
            mat[p]=[mult(u,s) for u in mat[p]]
            for k in range(m):
                if k!=p and mat[k][j]:
                    t=mat[k][j]
                    mat[k]=[u^mult(t,v) for u,v in zip(mat[k],mat[p])]
            p+=1
            if p==m:break
        return p

    def data(g):
        d0=[bracket(g,h,X)+bracket(g,h,Y) for h in A]
        d1=[add(bracket(g,X,v[4:]),bracket(g,v[:4],Y),action(v,g)) for v in B8]
        for u in d0:
            assert add(bracket(g,X,u[4:]),bracket(g,u[:4],Y),action(u,g))==Z
        return d0,d1

    num=0
    for g in product(range(q), repeat=4):
        b0,b1=data(g)
        r0,r1=rank(b0),rank(b1)
        exp=(0,0) if g==Z else (2,2) if g[:3]==(0,0,0) else (3,3)
        assert (r0,r1)==exp,(q,g,r0,r1,exp)
        num+=1

    for d in range(q):
        # Unit normal form: H^1 generated by y*d/dx, x*d/dy,
        # whose wedge is [xy] in H^2 (modulo coboundaries).
        g=add(ONE,(0,0,0,d))
        b0,b1=data(g)
        u=Y+Z;v=Z+X
        assert all(add(bracket(g,X,w[4:]),bracket(g,w[:4],Y),action(w,g))==Z for w in (u,v))
        assert rank(b0+[u,v])==rank(b0)+2
        assert rank(b1+[cup(u,v)])==rank(b1)+1
        assert cup(u,v)==XY

        # Linear normal form: H^1 generators xy*d/dx and (1+dy)*d/dy.
        g=add(X,(0,0,0,d))
        b0,b1=data(g)
        u=XY+Z;v=Z+(1,0,d,0)
        assert all(add(bracket(g,X,w[4:]),bracket(g,w[:4],Y),action(w,g))==Z for w in (u,v))
        assert rank(b0+[u,v])==rank(b0)+2
        assert rank(b1+[cup(u,v)])==rank(b1)+1
        assert cup(u,v)==XY

        if d:
            # Socle normal form: four linear 1-cocycles, symplectic wedge
            # pairing to [xy]; [1],[xy] span H^2, and xy kills H^1.
            g=(0,0,0,d)
            b0,b1=data(g)
            fields=[X+Z,Y+Z,Z+X,Z+Y]
            assert all(add(bracket(g,X,w[4:]),bracket(g,w[:4],Y),action(w,g))==Z for w in fields)
            assert rank(b0+fields)==rank(b0)+4
            assert rank(b1+[ONE,XY])==rank(b1)+2
            assert cup(fields[0],fields[3])==XY
            assert cup(fields[1],fields[2])==XY
            assert cup(fields[0],fields[1])==Z
            assert cup(fields[2],fields[3])==Z
            assert all(prod(XY,w[:4])==Z and prod(XY,w[4:])==Z for w in fields)
            assert prod(XY,ONE)==XY

    print('GF(%d): %d brackets checked; full H0,H1,H2 ranks, cup generators and socle products PASS' %(q,num))

if __name__=='__main__':
    for field in (2,4,8):verify(field)
    print('CHAR2_POISSON_COHOMOLOGY_RINGS_AND_CUPS_OK')
