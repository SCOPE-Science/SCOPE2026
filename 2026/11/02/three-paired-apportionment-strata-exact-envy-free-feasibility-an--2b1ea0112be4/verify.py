#!/usr/bin/env python3
"""Exact finite checks for a three-stratum apportionment theorem.

Runs with the Python 3 standard library only. Finite checks corroborate, but
are not a substitute for, the symbolic proof in RESULT.md.
"""
from itertools import combinations, product
from fractions import Fraction as F

# The six positions in each outcome: high and low entries of each of three strata.
PAIRS = ((0, 1), (2, 3), (4, 5))
OUTCOMES = tuple(combinations(range(6), 3))
ZERO_ENVY = tuple(w for w in OUTCOMES if all(not (low in w and high not in w)
                                                for high, low in PAIRS))
assert len(OUTCOMES) == 20 and len(ZERO_ENVY) == 7
assert set(ZERO_ENVY) == {
    (0, 2, 4), (0, 1, 2), (0, 1, 4), (0, 2, 3),
    (2, 3, 4), (0, 4, 5), (2, 4, 5)
}, ZERO_ENVY

# Independent integral max-flow check of the off-diagonal transportation system.
def transport_feasible(low, high, den):
    S = sum(low)
    if S > den:
        return False
    zeros = [den - h for h in high]
    assert sum(zeros) == S
    n = 8
    cap = [[0] * n for _ in range(n)]
    for i in range(3):
        cap[0][1+i] = low[i]
        cap[4+i][7] = zeros[i]
        for j in range(3):
            if i != j:
                cap[1+i][4+j] = den * 3
    flow = 0
    while True:
        prev = [-1] * n
        prev[0] = 0
        todo = [0]
        for u in todo:
            for v in range(n):
                if prev[v] < 0 and cap[u][v] > 0:
                    prev[v] = u
                    todo.append(v)
        if prev[7] < 0:
            break
        augment = 10**9
        v = 7
        while v:
            u = prev[v]
            augment = min(augment, cap[u][v])
            v = u
        v = 7
        while v:
            u = prev[v]
            cap[u][v] -= augment
            cap[v][u] += augment
            v = u
        flow += augment
    return flow == S

cases = feasible = infeasible = 0
for den in range(2, 11):
    groups = tuple((h, l) for h in range(den) for l in range(h+1))
    for blocks in product(groups, repeat=3):
        if sum(h+l for h,l in blocks) != 3*den:
            continue
        high = tuple(h for h,l in blocks)
        low = tuple(l for h,l in blocks)
        S = sum(low)
        criterion = S <= den and all(low[i]+den-high[i] <= S for i in range(3))
        alternate = transport_feasible(low, high, den)
        assert criterion == alternate, (den, blocks, criterion, alternate)
        feasible += criterion
        infeasible += not criterion
        cases += 1
assert cases > 2000 and feasible > 0 and infeasible > 0

# Direct, full 20-outcome check: exactly seven patterns avoid all inversions.
# Sharp-support example, in units of 1/40:
# x_{12},x_{13},x_{21},x_{23},x_{31},x_{32} = (1,2,3,4,5,7)/40.
w = (1, 2, 3, 4, 5, 7)
edge_order = ((0, 1), (0, 2), (1, 0), (1, 2), (2, 0), (2, 1))
low = (3, 7, 12)
zeros = (8, 8, 6)
high = tuple(40-z for z in zeros)
assert sum(low) == sum(zeros) == 22
assert sum(high) + sum(low) == 120
assert sum(w[i] for i,(a,b) in enumerate(edge_order) if a==0) == low[0]
for i in range(3):
    assert sum(w[j] for j,(a,b) in enumerate(edge_order) if a==i) == low[i]
    assert sum(w[j] for j,(a,b) in enumerate(edge_order) if b==i) == zeros[i]

# Algebraically all tables with these exact margins form one line.
# The nullspace is generated by (-1, 1, 1, -1, -1, 1).
null = (-1, 1, 1, -1, -1, 1)
assert all(sum(null[j] for j,(a,b) in enumerate(edge_order) if a==i)==0 for i in range(3))
assert all(sum(null[j] for j,(a,b) in enumerate(edge_order) if b==i)==0 for i in range(3))
lo = max(F(-w[j], null[j]) for j in range(6) if null[j]>0)
hi = min(F(w[j], -null[j]) for j in range(6) if null[j]<0)
assert lo == -2 and hi == 1, (lo,hi)
for t in (lo,hi,F(0)):
    table = [F(w[j])+t*null[j] for j in range(6)]
    assert all(x>=0 for x in table)
    assert sum(x>0 for x in table) == (6 if t==0 else 5)
assert all(sum(w[j]+t*null[j]>0 for j in range(6))>=5 for t in
           (lo,F(-1),F(0),hi))
assert 40-sum(w) == 18>0 # all-one outcome has mandatory mass 18/40

# Exact, positive-residue examples for both kinds of obstruction.
examples = [
    ((F(7,10),)*3, (F(3,10),)*3, True),
    ((F(11,20),)*3, (F(9,20),)*3, False),
    ((F(9,20), F(9,10), F(9,10)),
     (F(7,20), F(1,5), F(1,5)), False),
]
for h,l,expected in examples:
    s=sum(l)
    assert sum(h)+s==3
    actual=(s<=1 and all(l[i]+1-h[i]<=s for i in range(3)))
    assert actual==expected, (h,l)

print(f'VERIFY_OK grid_profiles={cases} feasible={feasible} infeasible={infeasible} '
      f'zero_envy_patterns={len(ZERO_ENVY)} sharp_support=6 '
      f'support_interval=[{lo},{hi}]')
