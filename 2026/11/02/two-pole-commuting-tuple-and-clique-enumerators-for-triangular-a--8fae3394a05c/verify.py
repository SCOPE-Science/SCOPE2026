"""Direct independent finite-ring verification of triangular commuting tuples.

Usage: python verify.py
Only uses the Python standard library. Exhaustive means all indicated finite
matrices are enumerated, not only randomly chosen representatives.
"""
from itertools import product, combinations
from math import comb

class Ring:
    def __init__(self, p, length, model='integer'):
        self.p, self.length, self.model = p, length, model
        self.order = p**length
        assert model in ('integer', 'truncated_polynomial')
        if model == 'integer':
            self.add = lambda a,b: (a+b) % self.order
            self.mul = lambda a,b: (a*b) % self.order
        else:
            def coeff(a):
                return [(a//(p**i))%p for i in range(length)]
            def add(a,b):
                aa,bb=coeff(a),coeff(b)
                return sum(((aa[i]+bb[i])%p)*(p**i) for i in range(length))
            def mul(a,b):
                aa,bb=coeff(a),coeff(b)
                return sum((sum(aa[j]*bb[i-j] for j in range(i+1))%p)*(p**i)
                           for i in range(length))
            self.add,self.mul=add,mul
        self.neg=lambda a: next(x for x in range(self.order) if self.add(a,x)==0)
        self.minus=lambda a,b:self.add(a,self.neg(b))
        self.vals = tuple(range(self.order))
        self.add_table = [[self.add(a,b) for b in self.vals] for a in self.vals]
        self.mul_table = [[self.mul(a,b) for b in self.vals] for a in self.vals]
        self.neg_table = [self.neg(a) for a in self.vals]

    def det(self,a,b,c,d):
        m=self.mul_table
        return self.add_table[m[a][d]][self.neg_table[m[b][c]]]


def predicted(p,length,k):
    s=sum(p**j for j in range(length+1))
    return s*p**(2*length*k)-(s-1)*p**((2*length-1)*k)


def exhaustive(ring,k):
    # k ordered vectors in R^2; scalar diagonal components are independent.
    vals=ring.vals
    m=ring.mul_table
    neg=ring.neg_table
    add=ring.add_table
    count=0
    for flat in product(vals,repeat=2*k):
        if all(add[m[flat[2*i]][flat[2*j+1]]][neg[m[flat[2*i+1]][flat[2*j]]]]==0
               for i in range(k) for j in range(i+1,k)):
            count+=1
    return count*ring.order**k


def submodule_census(ring):
    # Every submodule of R^2 is generated by at most two elements over a
    # finite chain ring; independently enumerate their additive spans.
    Q=ring.order
    vectors=tuple(product(range(Q),repeat=2))
    A,M=ring.add_table,ring.mul_table
    def plus(u,v):return (A[u[0]][v[0]],A[u[1]][v[1]])
    def scale(c,v):return (M[c][v[0]],M[c][v[1]])
    def span(u,v):
        a=[scale(c,u) for c in range(Q)]
        b=[scale(c,v) for c in range(Q)]
        return frozenset(plus(x,y) for x in a for y in b)
    max_isotropic=set()
    all_isotropic=set()
    for u in vectors:
        for v in vectors:
            W=span(u,v)
            if W in all_isotropic:continue
            # Bilinearity makes it enough to check the two generators.
            if ring.det(u[0],u[1],v[0],v[1])==0:
                all_isotropic.add(W)
                if len(W)==Q:max_isotropic.add(W)
    assert all(len(W)<=Q for W in all_isotropic)
    return len(max_isotropic),len(all_isotropic)


def check():
    # Independent exhaustive matrix-tuple enumeration: no formula is used
    # to construct counted objects.
    cases=[(2,1,'integer',3),(3,1,'integer',3),
           (2,2,'integer',3),(3,2,'integer',3),
           (2,3,'integer',3),(3,3,'integer',2),
           (2,4,'integer',2),
           (2,2,'truncated_polynomial',3),
           (3,2,'truncated_polynomial',3),
           (2,3,'truncated_polynomial',2)]
    outputs=[]
    for p,length,model,k in cases:
        ring=Ring(p,length,model)
        got=exhaustive(ring,k)
        expected=predicted(p,length,k)
        assert got==expected,(p,length,model,k,got,expected)
        outputs.append((p,length,model,k,got))
    print('TUPLE_CENSUS_OK',len(outputs),outputs)
    # Independent maximal-clique enumeration via actual submodule spans.
    c=[]
    for p,length,model in [(2,1,'integer'),(3,1,'integer'),
                           (2,2,'integer'),(3,2,'integer'),
                           (2,3,'integer'),(2,4,'integer'),
                           (2,2,'truncated_polynomial'),
                           (3,2,'truncated_polynomial'),
                           (2,3,'truncated_polynomial')]:
        ring=Ring(p,length,model)
        got,num_isotropic=submodule_census(ring)
        expected=sum(p**j for j in range(length+1))
        assert got==expected,(p,length,model,got,expected)
        c.append((p,length,model,got,num_isotropic))
    print('MAXIMAL_CLIQUES_OK',len(c),c)
    # Check generated function over a larger symbolic parameter range.
    for p in (2,3,4,5,7):
        for length in range(1,9):
            for k in range(0,9):
                rhs=predicted(p,length,k)
                if k==0:assert rhs==1
                else:
                    W=(p+1)*sum(p**(length-1-2*t)
                         for t in range((length+1)//2))
                    alt=(p**((length+2*(length//2))*k)
                         +W*(p**(2*length*k)-p**((2*length-1)*k)))
                    assert alt==rhs,(p,length,k,alt,rhs)
    print('FORMULA_IDENTITY_OK',5*8*9)
    # An independently enumerated small clique f-vector: tuples are not
    # computed here, only unordered distinct vertex sets of commuting graphs.
    clique_rows=[]
    for p,length,model in [(2,1,'integer'),(3,1,'integer'),
                           (2,2,'integer'),(2,2,'truncated_polynomial')]:
        ring=Ring(p,length,model)
        m=ring.order
        triples=tuple(product(range(m),repeat=3))
        for r in (2,3):
            found=0
            for inds in combinations(range(m**3),r):
                rows=[(ring.minus(triples[i][0],triples[i][2]),triples[i][1])
                      for i in inds]
                if all(ring.det(*(rows[a]+rows[b]))==0
                       for a in range(r) for b in range(a+1,r)):
                    found+=1
            S=sum(p**i for i in range(length+1))
            expected=S*comb(p**(2*length),r)-(S-1)*comb(p**(2*length-1),r)
            assert found==expected,(p,length,model,r,found,expected)
            clique_rows.append((p,length,model,r,found))
    print('CLIQUE_F_VECTOR_OK',len(clique_rows),clique_rows)


if __name__=='__main__':check()
