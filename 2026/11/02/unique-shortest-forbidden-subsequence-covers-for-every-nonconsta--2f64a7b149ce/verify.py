#!/usr/bin/env python3
"""Independent exact finite tests for shortest constrained subsequence covers."""
from collections import deque
from itertools import product


def words(n):
    return map(''.join, product('01', repeat=n))


def is_subsequence(pattern, source):
    i = 0
    for ch in source:
        if i < len(pattern) and pattern[i] == ch:
            i += 1
    return i == len(pattern)


def canonical(pattern, k):
    t = k - 2
    if pattern in ('000','111'):
        z = pattern[0]
        o = '1' if z == '0' else '0'
        return (o * t + z) * 2 + o * t
    if pattern in ('010','101'):
        z = pattern[0]
        o = '1' if z == '0' else '0'
        return o * (k - 1) + z * k + o * (k - 1)
    # Mixed patterns with a single transition are generated by reversal
    # and bit complementation from 001.
    w = '1' * (k - 2) + '0' + '1' * (k - 1) + '0' * (k - 1)
    if pattern == '001': return w
    if pattern == '100': return w[::-1]
    if pattern == '110': return ''.join('1' if c == '0' else '0' for c in w)
    if pattern == '011': return ''.join('1' if c == '0' else '0' for c in w[::-1])
    raise ValueError(pattern)


def bfs_minimal(pattern, k):
    targets = [w for w in words(k) if not is_subsequence(pattern, w)]
    s0 = (0,) * (len(targets) + 1)
    q = deque([s0]); dist = {s0: 0}; count = {s0: 1}
    goal = k
    nstates = 0
    while q:
        s = q.popleft(); nstates += 1
        d = dist[s]
        if all(x == goal for x in s[:-1]):
            return d, count[s], nstates
        for c in '01':
            p = s[-1]
            np = p + (pattern[p] == c)
            if np == len(pattern): continue
            t = tuple(x + (x < k and w[x] == c) for w, x in zip(targets, s)) + (np,)
            if t not in dist:
                dist[t] = d + 1
                count[t] = count[s]
                q.append(t)
            elif dist[t] == d + 1:
                count[t] += count[s]
    raise AssertionError('No cover exists')


def main():
    tests = 0
    for pattern in words(3):
        for k in range(3, 13):
            cover = canonical(pattern, k)
            assert not is_subsequence(pattern, cover)
            assert len(cover) == 3*k-4 + sum(pattern[i] != pattern[i+1] for i in (0,1))
            for target in words(k):
                if not is_subsequence(pattern, target):
                    assert is_subsequence(target, cover), (pattern, k, target)
                tests += 1
            if k <= 7:
                min_length, min_count, _ = bfs_minimal(pattern, k)
                assert (min_length, min_count) == (len(cover), 1), (pattern, k, min_length, min_count)
    print('VERIFY_OK', 'coverage_instances', tests, 'BFS_instances', 8*5)

if __name__ == '__main__': main()
