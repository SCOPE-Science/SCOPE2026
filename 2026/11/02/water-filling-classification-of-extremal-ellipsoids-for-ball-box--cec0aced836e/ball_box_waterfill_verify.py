#!/usr/bin/env python3
"""Standalone finite checks for the exact ellipsoids of ball–box intersections.

This script checks containment, contact moment identities, and the water-level
identity. Numerical samples only corroborate the analytical proof.
"""
import math
import random
from fractions import Fraction
from itertools import product


def radii(a):
    """Return active water level and optimal inscribed-box half-widths."""
    a = tuple(float(v) for v in a)
    if len(a) < 2 or any(not 0 < x <= 1 for x in a):
        raise ValueError('Requires dimension >= 2 and cap widths in (0,1].')
    square = tuple(x*x for x in a)
    if sum(square) <= 1:
        return None, a
    ordered = sorted(square)
    acc = 0.
    d = len(a)
    for count, t in enumerate(ordered):
        level2 = (1.-acc)/(d-count)
        if level2 <= t + 1e-14:
            level = math.sqrt(max(0., level2))
            return level, tuple(min(x, level) for x in a)
        acc += t
    raise AssertionError('Water level not found')


def test_case(a, rng):
    d = len(a)
    level, m = radii(a)
    assert abs(sum(x*x for x in m)-min(sum(x*x for x in a), 1)) < 2e-12
    # Exact extremal semiaxes: J has a_i; L has sqrt(d)*m_i.
    outer = tuple(math.sqrt(d)*v for v in m)
    assert all(0 < v <= 1 for v in m)
    # Every vertex of [-m,m] is a point of K and an L-contact point.
    assert all(v <= cap + 1e-12 for v, cap in zip(m, a))
    for bits in product((-1, 1), repeat=d):
        point = [sign*v for sign,v in zip(bits,m)]
        assert sum(x*x for x in point) <= 1 + 2e-12
        assert abs(sum((x/b)**2 for x,b in zip(point,outer))-1)<2e-12
    # Isotropic sign-averaged normalized contact distribution:
    # diag E[yy^T]=1/d; off-diagonal E[yy^T]=0.
    for i in range(d):
        assert abs((m[i]/outer[i])**2-1/d)<1e-12
    # In the cut-ball case the maximum over K of the enclosing quadratic
    # is the water identity, not an experimental approximation.
    if level is not None:
        active = [i for i in range(d) if a[i] < level]
        rhs=len(active)+(1-sum(a[i]*a[i] for i in active))/level**2
        assert abs(rhs-d)<2e-10
    # Admissible points are generated by clipping Gaussian directions to
    # coordinate caps and then radially contracting if needed.
    for _ in range(1000):
        x=[rng.uniform(-v,v) for v in a]
        norm=math.sqrt(sum(t*t for t in x))
        if norm > 1:
            x=[t/norm for t in x]
        assert sum(t*t for t in x)<1+1e-12
        assert all(abs(t)<v+1e-12 for t,v in zip(x,a))
        assert sum((t/b)**2 for t,b in zip(x,outer))<=1+2e-11
    # The outer shape includes the inner shape, as a basic consistency check.
    assert all(x>=y-1e-12 for x,y in zip(outer,a))
    return level,m,math.prod(outer)/math.prod(a)


def exact_checks():
    cases=[(Fraction(1,5),Fraction(3,5),Fraction(1),Fraction(1)),
           (Fraction(1,5),Fraction(3,10),Fraction(1),Fraction(1)),
           (Fraction(1,5),Fraction(1,4),Fraction(1,3))]
    for a in cases:
        square=[v*v for v in a]
        if sum(square) <= 1:
            m2=square
        else:
            s=Fraction(0)
            for k,v in enumerate(sorted(square)):
                w2=(1-s)/(len(a)-k)
                if w2<=v:
                    m2=[min(c,w2) for c in square]
                    break
                s+=v
            else:
                raise AssertionError('Exact water fill did not terminate.')
        assert sum(m2)==min(sum(square),Fraction(1))
        # The complete 2^d sign design has covariance I/d after scaling.
        for i in range(len(a)):
            assert m2[i]/(len(a)*m2[i]) == Fraction(1,len(a))
        print('exact squared contact radii:',[str(v) for v in m2])


def main():
    exact_checks()
    rng=random.Random(205211)
    tests=0
    for d in range(2,9):
        for _ in range(30):
            a=[10**rng.uniform(-1.5,0) for i in range(d)]
            level,m,ratio=test_case(a,rng)
            assert 1-1e-9<=ratio<=d**(d/2)+1e-8
            tests+=1
    for a in [(0.2,0.6,1,1),(0.2,0.3,1,1),(0.8,0.85,1),
              (1,1,1,1),(0.1,1),(0.2,0.25,0.33)]:
        level,m,ratio=test_case(a,rng)
        print('example:',a,'water=',level,'contacts=',m,'ratio=',ratio)
        tests+=1
    print('PASS:',tests,'configurations, exact rational identities, full contact sets, and 216000 random admissible points')

if __name__=='__main__':
    main()
