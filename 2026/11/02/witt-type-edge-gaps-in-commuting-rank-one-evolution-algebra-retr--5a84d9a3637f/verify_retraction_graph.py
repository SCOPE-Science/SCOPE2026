#!/usr/bin/env python3
"""Independent finite-field rank-one retraction-graph checks (prime fields)."""
from itertools import product
from math import comb


def inv(a,q):
    return pow(a,-1,q)

def dot(u,v,q):
    return sum(x*y for x,y in zip(u,v))%q

def norm(v,q):
    return dot(v,v,q)

def projective_vectors(n,q):
    for v in product(range(q),repeat=n):
        if not any(v):
            continue
        first=next(i for i,a in enumerate(v) if a)
        if v[first]!=1:
            continue
        yield v

def zero(a):return not any(a)

def span(u,v,q):
    return {tuple((a*x+b*y)%q for x,y in zip(u,v)) for a in range(q) for b in range(q)}

def check(n,q,u):
    assert q in (3,5,7)
    vlist=list(projective_vectors(n,q))
    isot=[v for v in vlist if norm(v,q)==0]
    is_iso=norm(u,q)==0
    # Exclude the singular line generated by u, when it exists.
    lines=[v for v in isot if v not in span(u,(0,)*n,q)]
    maps=[]
    for v in lines:
        for f in product(range(q),repeat=n):
            if dot(f,v,q)==1 and dot(f,u,q)==0:
                assert dot(v,v,q)==0
                maps.append((v,f))
    # Edge criterion and independent direct multiplication using pairs of rank-one maps.
    E=0
    for i in range(len(maps)):
        v,f=maps[i]
        for j in range(i):
            w,g=maps[j]
            # PVQ=v*(f.w)*g and QVP=w*(g.v)*f; literal matrix products
            lhs=tuple((dot(f,w,q)*v[a]*g[b])%q for a in range(n) for b in range(n))
            rhs=tuple((dot(g,v,q)*w[a]*f[b])%q for a in range(n) for b in range(n))
            if lhs==rhs:
                assert lhs==tuple(0 for _ in lhs), (n,q,u,i,j,'nonzero equal rank-one products')
                E+=1
    M=len(isot)
    if is_iso:
        # Count isotropic projective lines in u-perpendicular, minus Ku, divided by q
        L=[v for v in isot if dot(u,v,q)==0]
        J=(len(L)-1)//q
        assert 1+q*J==len(L)
        forbidden=q*(q-1)*J//2
        exp_pairs=comb(M-1,2)-forbidden
    else:
        S=len([v for v in isot if dot(u,v,q)==0])
        assert (M-S)%2==0
        forbidden=(M-S)//2
        exp_pairs=comb(M,2)-forbidden
    expected_vertices=q**(n-2)*(M-int(is_iso))
    expected_edges=q**(2*n-6)*exp_pairs
    assert len(maps)==expected_vertices,(n,q,u,'vertices',len(maps),expected_vertices)
    assert E==expected_edges,(n,q,u,'edges',E,expected_edges)
    print('PASS',f'q={q}',f'n={n}',f'u={u}',f'isotropic={is_iso}',f'M={M}',f'V={len(maps)}',f'E={E}',f'forbidden_pairs={forbidden}')

def complete_matrix_homomorphism_check(q,u):
    """Scan all linear maps on F_q^3 and compare genuinely algebraic retractions."""
    n=3
    assert q==3 and len(u)==3
    projected={tuple((v[i]*f[j])%q for i in range(n) for j in range(n))
        for v in projective_vectors(n,q) if norm(v,q)==0
        for f in product(range(q),repeat=n)
        if dot(v,f,q)==1 and dot(u,f,q)==0}
    checked=set()
    for a in product(range(q),repeat=9):
        if not any(a): continue
        # Matrix idempotence and rank exactly one (every 2-by-2 minor vanishes).
        if any(sum(a[3*i+k]*a[3*k+j] for k in range(3))%q != a[3*i+j]
               for i in range(3) for j in range(3)): continue
        if any((a[3*i+j]*a[3*k+l]-a[3*i+l]*a[3*k+j])%q
               for i in range(3) for k in range(i+1,3)
               for j in range(3) for l in range(j+1,3)): continue
        Pu=[sum(a[3*i+j]*u[j] for j in range(3))%q for i in range(3)]
        # For standard B, e_i*e_j = delta_ij u: check all basis products.
        if all(((sum(a[3*k+i]*a[3*k+j] for k in range(3))*u[t])%q == (Pu[t] if i==j else 0))
               for i in range(3) for j in range(3) for t in range(3)):
            checked.add(a)
    assert checked==projected, ('rank-one algebra maps',u,len(checked),len(projected))
    print('PASS_ALL_LINEAR_MAPS',f'q={q}',f'u={u}',f'count={len(checked)}')


def main():
    cases=[(3,3,(1,0,0)),(3,3,(1,1,0)),(3,3,(1,1,1)),
           (3,5,(1,0,0)),(3,5,(1,1,0)),(3,5,(1,2,0)),
           (4,3,(1,0,0)),(4,3,(1,1,0)),(4,3,(1,1,1,0)),
           (2,5,(1,0))]
    # n=2 is graph-structure boundary, not tested by general edge factor formula.
    for n,q,u in cases[:-1]:check(n,q,u)
    for u in ((1,0,0),(1,1,0),(1,1,1)):
        complete_matrix_homomorphism_check(3,u)
    print('VERIFY_OK',len(cases)-1,'graph configurations and 3 all-linear-map checks')
if __name__=='__main__':main()
