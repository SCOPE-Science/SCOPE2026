"""Exact characteristic-two checks for the Steiner quartic Jacobian scheme.

Only finite symbolic algebra is verified here. The accompanying proof supplies
local exhaustiveness, sheaf-theoretic support and the eventual Hilbert polynomial.
"""
import sympy as sp
from math import comb

W,X,Y,Z=sp.symbols('W X Y Z')
F=(X*Y+X*Z+Y*Z)**2+W*X*Y*Z
# Over F_2 the squared parenthesis has no mixed terms.
partials=[sp.diff(F,v) for v in (W,X,Y,Z)]
assert sp.Poly(partials[0],W,X,Y,Z,modulus=2)==sp.Poly(X*Y*Z,W,X,Y,Z,modulus=2)
for got,expected in zip(partials[1:],[W*Y*Z,W*X*Z,W*X*Y]):
    assert sp.Poly(got-expected,W,X,Y,Z,modulus=2).is_zero
# Verify the equation belongs to the ideal generated by partials plus (XY+XZ+YZ)^2.
G=sp.groebner(partials+[F],W,X,Y,Z,order='grevlex',modulus=2)
print('JACOBIAN_GROEBNER', [str(p.as_expr()) for p in G.polys])
# The local ideal on X=1.
a,b,c=sp.symbols('a b c')
Jloc=sp.groebner([a*b,a*c,b*c,b*b+c*c],a,b,c,order='grevlex',modulus=2)
print('LOCAL_GROEBNER', [str(p.as_expr()) for p in Jloc.polys])
for poly in [a*b,a*c,b*c,b*b+c*c,b**3,c**3,a*b*b]:
    assert Jloc.reduce(poly)[1]==0
assert all(Jloc.reduce(p)[1]!=0 for p in (b,c,b*b))
# Exhaust standard monomials of the projective lex-compatible Groebner basis.
gens=[W,X,Y,Z]
leading=[]
for poly in G.polys:
    mons=[(mon,coeff%2) for mon,coeff in poly.terms() if coeff%2]
    leading.append(mons[0][0])
def count_standard(d):
    s=0
    for w in range(d+1):
      for x in range(d-w+1):
       for y in range(d-w-x+1):
        z=d-w-x-y
        e=(w,x,y,z)
        if not any(all(e[i]>=lm[i] for i in range(4)) for lm in leading):s+=1
    return s
H=[count_standard(d) for d in range(13)]
assert H[:8]==[1,4,10,16,21,25,28,31],H
assert all(H[d]==3*d+10 for d in range(5,13)),H
print('HILBERT_VALUES_d0_TO_12',H)
print('HILBERT_POLYNOMIAL_for_d_ge_5','3d+10')
print('LOCAL_NILRADICAL_BASIS','b,c,b^2=c^2; all a-products zero; N^3=0; length=3')
print('THREE_CHARTS_SYMMETRIC; TOTAL_NIL_LENGTH 9')
print('ALL_CHECKS_PASSED')
