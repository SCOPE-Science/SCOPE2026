"""Independent finite-field checks for a derivation-Lie-algebra commutator census.

Run: python verify.py
Only the Python standard library is required.
"""
from collections import Counter
from itertools import product
from random import Random


class Field:
    def __init__(self, p, degree=1):
        assert degree == 1 or (p, degree) == (3, 2)
        self.p, self.degree, self.q = p, degree, p**degree

    def add(self, a, b):
        if self.degree == 1:
            return (a + b) % self.p
        return ((a % 3 + b % 3) % 3) + 3 * (((a // 3 + b // 3) % 3))

    def neg(self, a):
        return self.mul(self.p - 1, a)

    def sub(self, a, b):
        return self.add(a, self.neg(b))

    def mul(self, a, b):
        if self.degree == 1:
            return (a * b) % self.p
        a0, a1 = a % 3, a // 3
        b0, b1 = b % 3, b // 3
        # t^2 = -1 = 2 in F_3
        return ((a0*b0 + 2*a1*b1) % 3) + 3*((a0*b1 + a1*b0) % 3)

    def scale(self, a, n):
        return self.mul(a, n % self.p)

    def inv(self, a):
        assert a
        for b in range(1, self.q):
            if self.mul(a, b) == 1:
                return b
        raise AssertionError('non-field')


def independent_centralizer_dimension(f, F):
    # f represents sum_{i=1}^{n-1} f[i-1] x^i d/dx.
    m = len(f)
    A = [[0] * m for _ in range(m)]
    for i, a in enumerate(f, 1):
        for j in range(1, m + 1):
            t = i + j - 1
            if t <= m:
                A[t-1][j-1] = F.add(A[t-1][j-1], F.scale(a, j-i))
    rank = 0
    for col in range(m):
        pivot = next((r for r in range(rank, m) if A[r][col]), None)
        if pivot is None:
            continue
        A[rank], A[pivot] = A[pivot], A[rank]
        z = F.inv(A[rank][col]); A[rank] = [F.mul(z, a) for a in A[rank]]
        for r in range(m):
            if r != rank and A[r][col]:
                z = A[r][col]
                A[r] = [F.sub(a, F.mul(z, b)) for a, b in zip(A[r], A[rank])]
        rank += 1
    return m - rank


def first_index(f):
    return next((i for i, a in enumerate(f, 1) if a), len(f)+1)


def predicted_dimension(j, p):
    if j == p+2:
        return p+1
    if j in (1, p+1):
        return 2 if j == 1 else p+1
    return j if 2*j <= p+2 else j-1


def bracket_is_zero(f, g, F):
    m = len(f)
    assert len(g) == m
    for t in range(1, m+1):
        c = 0
        for i in range(1, m+1):
            j = t-i+1
            if 1 <= j <= m:
                c = F.add(c, F.scale(F.mul(f[i-1], g[j-1]), j-i))
        if c:
            return False
    return True


def run(p, extension=1, exhaustive=True):
    F = Field(p, extension); q=F.q; m=p+1
    predicted_total = q**(p+3) + ((p-1)//2)*(q*q-1)*q**p
    counts = Counter(); direct_sum=0; total=0
    iterable = product(range(q), repeat=m) if exhaustive else (
        [0]*m if t == 0 else [Random(14977+t).randrange(q) for _ in range(m)] for t in range(600))
    for f in iterable:
        f=tuple(f); j=first_index(f); d=independent_centralizer_dimension(f,F)
        assert d == predicted_dimension(j,p), (p,q,f,j,d)
        total += 1
        counts[(j,d)] += 1
        direct_sum += q**d
    if exhaustive:
        assert total == q**m
        assert direct_sum == predicted_total,(p,q,direct_sum,predicted_total)
        for j in range(1,p+2):
            assert counts[(j, predicted_dimension(j,p))] == (q-1)*q**(m-j)
        assert counts[(p+2,p+1)] == 1
    if p==3 and extension==1:
        z=0
        for f in product(range(q), repeat=m):
            for g in product(range(q), repeat=m):
                z+=bracket_is_zero(f,g,F)
        assert z==predicted_total
    # The center is exactly the line generated by x^(p+1) d/dx.
    for j in range(1,m+1):
        e=[0]*m; e[j-1]=1
        assert bracket_is_zero(tuple([0]*(m-1)+[1]),e,F)
    if p==3 or p==5:
        e2=[0]*m; ep=[0]*m; e2[1]=1; ep[p-1]=1
        assert not bracket_is_zero(e2,ep,F)  # non-splitting witness
    return dict(p=p,q=q,derivation_dimension=m,objects_tested=total,
                commuting_pairs=direct_sum if exhaustive else None,
                predicted_pairs=predicted_total,centralizers=dict(sorted((f'{j}:{d}',n) for (j,d),n in counts.items())))


if __name__=='__main__':
    for p,extension,exhaustive in [(3,1,True),(3,2,True),(5,1,True),(7,1,False)]:
        res=run(p,extension,exhaustive)
        print('PASS p={p} q={q} tested={objects_tested} pairs={commuting_pairs} expected={predicted_pairs}'.format(**res))
    print('WITT_TRUNCATION_CENTRALIZER_AND_COMMUTING_CENSUS_PASS')
