"""Independent finite-field image-space checks for inner derivations."""
from collections import Counter
from itertools import product
from verify_fields import operations, dihedral_table

def image_key(x,mult,field):
    add,mul,neg,inv=field
    n=len(x)
    # The columns of the commutator map span its image.
    mat=[[0]*n for _ in range(n)]
    for i,a in enumerate(x):
        if a:
            for j in range(n):
                u,v=mult[i][j],mult[j][i]
                mat[j][u]=add(mat[j][u],a)
                mat[j][v]=add(mat[j][v],neg[a])
    # Reduced row-echelon normal form of the subspace generated by columns.
    r=0
    for j in range(n):
        pivot=next((h for h in range(r,n) if mat[h][j]),None)
        if pivot is None:continue
        mat[r],mat[pivot]=mat[pivot],mat[r]
        di=inv[mat[r][j]]
        for k in range(n):mat[r][k]=mul(di,mat[r][k])
        for h in range(n):
            if h!=r and mat[h][j]:
                a=neg[mat[h][j]]
                for k in range(n):mat[h][k]=add(mat[h][k],mul(a,mat[r][k]))
        r+=1
    return tuple(tuple(row) for row in mat[:r])

def expected(n,q):
    d=1
    while pow(q,d,n) not in (1,n-1):d+=1
    copies=(n-1)//(2*d)
    p={0:1}
    Q=q**d
    for _ in range(copies):
        new=p.copy()
        for k,a in p.items():new[k+2*d]=new.get(k+2*d,0)+a*(Q*Q+Q+1)
        p=new
    return p

def main():
    for q,n in ((2,3),(2,5),(4,3),(5,3)):
        F=operations(q); mult=dihedral_table(n)
        seen=set()
        hist=Counter()
        for x in product(range(q),repeat=2*n):
            key=image_key(x,mult,F)
            if key not in seen:
                seen.add(key)
                hist[len(key)]+=1
        assert dict(hist)==expected(n,q),(q,n,hist,expected(n,q))
        print('unique images',q,n,dict(hist))
    print('VERIFY_IMAGES_OK')

if __name__=='__main__':main()
