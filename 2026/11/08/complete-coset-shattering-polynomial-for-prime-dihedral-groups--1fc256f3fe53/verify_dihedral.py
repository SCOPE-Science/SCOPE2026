"""Independent finite coset/trace enumeration for odd prime dihedral groups."""
from itertools import combinations, chain
from math import comb


def test(p):
    assert p >= 3 and all(p % d for d in range(2, int(p**.5)+1))
    elements = [(a, i) for i in (0, 1) for a in range(p)]
    identity = (0, 0)
    index = {x: j for j, x in enumerate(elements)}

    def multiply(x, y):
        a, i = x
        b, j = y
        return ((a + (-b if i else b)) % p, i ^ j)

    subgroups = set()
    for generators in chain(combinations(elements, 1), combinations(elements, 2)):
        subgroup = {identity, *generators}
        while True:
            closure = subgroup | {multiply(a, b) for a in subgroup for b in subgroup}
            if len(closure) == len(subgroup):
                break
            subgroup = closure
        subgroups.add(frozenset(subgroup))

    # Every subgroup of an order-2p group is generated by at most two elements.
    assert len(subgroups) == p + 3
    cosets = {frozenset(multiply(g, h) for h in subgroup)
              for subgroup in subgroups for g in elements}
    assert len(cosets) == p * p + 2 * p + 3
    masks = [sum(1 << index[x] for x in coset) for coset in cosets]
    counts = []
    for k in range(5 if p <= 7 else 4):
        count = 0
        for support in combinations(range(2 * p), k):
            traces = {sum(((mask >> j) & 1) << i
                          for i, j in enumerate(support))
                      for mask in masks}
            count += (len(traces) == 1 << k)
        counts.append(count)
    expected = [1, 2*p, comb(2*p, 2), p*p*(p-1)]
    assert counts == (expected + ([0] if p <= 7 else [])), (p, counts, expected)
    print('DIHEDRAL_COSET_PASS', p, len(cosets), counts)


if __name__ == '__main__':
    for prime in (3, 5, 7, 11):
        test(prime)
    print('ALL_DIHEDRAL_COSET_SHATTERING_CHECKS_PASS')
