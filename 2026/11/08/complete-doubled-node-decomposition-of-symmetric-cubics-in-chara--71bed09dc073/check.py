"""Exact finite-field checks for the singular schemes of elementary symmetric cubics.

Run with Python 3 standard library: python check.py
Computations validate finite instances, while the accompanying proof covers all n divisible by four.
"""
from itertools import combinations
from math import comb


def parity(x):
    return x.bit_count() & 1


def rank_gf2(rows, n):
    basis = [0] * n
    rank = 0
    for row in rows:
        z = row
        while z:
            i = z.bit_length() - 1
            if basis[i]:
                z ^= basis[i]
            else:
                basis[i] = z
                rank += 1
                break
    return rank


def cubic(mask, n):
    return comb(mask.bit_count(), 3) % 2


def gradient(mask, n):
    # The order-two elementary-symmetric polynomial on the complement of i.
    k = mask.bit_count()
    return sum((comb(k - ((mask >> i) & 1), 2) % 2) << i for i in range(n))


def hessian(mask, n):
    # Off-diagonal entry equals the first elementary-symmetric polynomial
    # on variables other than i,j, evaluated at mask.
    out = []
    k = mask.bit_count()
    for i in range(n):
        row = 0
        for j in range(n):
            if i != j and (k - ((mask >> i) & 1) - ((mask >> j) & 1)) % 2:
                row |= 1 << j
        out.append(row)
    return out


def verify(n):
    assert n >= 4 and n % 4 == 0
    support = []
    # A primary component is generated by equality within the two blocks
    # and by the square of the common coordinate on the complement.
    for m in range(1, n, 4):
        ell = n - m
        assert ell % 4 == 3
        # Coefficients of a^2, ab, b^2 in a derivative at an inside index.
        inside = (comb(m - 1, 2) % 2,
                  ((m - 1) * ell) % 2,
                  comb(ell, 2) % 2)
        # Same coefficients for a derivative at an outside index.
        outside = (comb(m, 2) % 2,
                   (m * (ell - 1)) % 2,
                   comb(ell - 1, 2) % 2)
        assert inside == outside == (0, 0, 1), (n, m, inside, outside)
    for mask in range(1, 1 << n):
        is_critical = gradient(mask, n) == 0
        predicted = mask.bit_count() % 4 == 1
        assert is_critical == predicted, (n, mask)
        if is_critical:
            assert cubic(mask, n) == 0
            H = hessian(mask, n)
            assert rank_gf2(H, n) == n - 2, (n, mask)
            radial = mask
            complement = ((1 << n) - 1) ^ mask
            assert all(parity(row & radial) == 0 for row in H)
            assert all(parity(row & complement) == 0 for row in H)
            assert (comb(complement.bit_count(), 2) % 2) == 1
            support.append(mask)
    assert len(support) == 2 ** (n - 2)
    assert 2 * len(support) == 2 ** (n - 1)
    print(f'n={n}: GF(2) points={len(support)}; support, two-block restriction, Hessian and tangent cone PASS')


if __name__ == '__main__':
    for n in (4, 8, 12):
        verify(n)
    print('ALL_EXACT_FINITE_CHECKS_PASS')
