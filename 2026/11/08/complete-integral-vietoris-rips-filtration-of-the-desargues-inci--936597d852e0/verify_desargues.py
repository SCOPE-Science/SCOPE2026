#!/usr/bin/env python3
"""Standalone exhaustive finite proof checker for the Desargues graph Rips filtration.

Requires only the Python standard library. The nonempty face sets are generated by
independent clique recursion and complete Boolean-subset enumeration.
"""
from collections import Counter, deque
from itertools import combinations
from math import comb

TWO = [sum(1 << i for i in c) for c in combinations(range(5), 2)]
THREE = [sum(1 << i for i in c) for c in combinations(range(5), 3)]
assert len(TWO) == len(THREE) == 10
ADJ = [set() for _ in range(20)]
for i, a in enumerate(TWO):
    for j, b in enumerate(THREE, 10):
        if a & b == a:
            ADJ[i].add(j)
            ADJ[j].add(i)
assert sum(map(len, ADJ)) == 60 and all(len(s) == 3 for s in ADJ)

DIST = []
for v in range(20):
    d = [-1] * 20
    d[v] = 0
    q = deque([v])
    while q:
        x = q.popleft()
        for y in ADJ[x]:
            if d[y] == -1:
                d[y] = d[x] + 1
                q.append(y)
    assert all(0 <= z <= 5 for z in d)
    DIST.append(d)

# Independently derive each distance using intersections of the indexed subsets.
# This verifies the graph metric without relying on BFS as its only witness.
distance_counts = Counter()
missing_pairs = []
for i in range(20):
    for j in range(i + 1, 20):
        if i < 10 and j < 10:
            expected = 2 if (TWO[i] & TWO[j]).bit_count() == 1 else 4
        elif i >= 10 and j >= 10:
            expected = 2 if (THREE[i-10] & THREE[j-10]).bit_count() == 2 else 4
        else:
            k = (TWO[i] & THREE[j-10]).bit_count()
            expected = {2: 1, 1: 3, 0: 5}[k]
        assert DIST[i][j] == DIST[j][i] == expected, (i, j, expected)
        distance_counts[expected] += 1
        if expected == 5:
            missing_pairs.append((i, j))
assert distance_counts == {1: 30, 2: 60, 3: 60, 4: 30, 5: 10}
assert len(missing_pairs) == 10 and len({x for p in missing_pairs for x in p}) == 20
print('GRAPH_DISTANCE_COUNTS', dict(sorted(distance_counts.items())))


def neighbors(radius):
    return [sum(1 << j for j in range(20) if j != i and DIST[i][j] <= radius)
            for i in range(20)]


def faces_incremental(radius):
    nb = neighbors(radius)
    faces = {0}
    for i in range(20):
        new = {s | (1 << i) for s in faces if not (s & ~nb[i])}
        faces.update(new)
    faces.remove(0)
    return faces


def faces_exhaustive(radius):
    nb = neighbors(radius)
    valid = bytearray(1 << 20)
    valid[0] = 1
    for mask in range(1, 1 << 20):
        lowbit = mask & -mask
        v = lowbit.bit_length() - 1
        lower = mask ^ lowbit
        valid[mask] = valid[lower] and not bool(lower & ~nb[v])
    return {mask for mask in range(1, 1 << 20) if valid[mask]}


def morse_matching(faces):
    available = set(faces)
    pairs = []
    # Lexicographic sequence of twenty toggling matchings.
    for v in range(20):
        for lower in sorted(available):
            upper = lower | (1 << v)
            if upper != lower and lower in available and upper in available:
                available.remove(lower)
                available.remove(upper)
                pairs.append((lower, upper))
    return available, pairs


def acyclic_hasse(faces, pairs):
    pair_set = set(pairs)
    assert len(pair_set) == len(pairs)
    used = [x for a, b in pairs for x in (a, b)]
    assert len(set(used)) == len(used)
    indeg = {f: 0 for f in faces}
    arcs = {f: [] for f in faces}
    covering = 0
    reversed_count = 0
    for upper in faces:
        mask = upper
        while mask:
            bit = mask & -mask
            mask ^= bit
            lower = upper ^ bit
            if lower == 0:
                continue
            assert lower in faces
            covering += 1
            if (lower, upper) in pair_set:
                src, dst = lower, upper
                reversed_count += 1
            else:
                src, dst = upper, lower
            arcs[src].append(dst)
            indeg[dst] += 1
    assert reversed_count == len(pairs)
    q = deque(f for f in faces if indeg[f] == 0)
    visited = 0
    while q:
        u = q.popleft()
        visited += 1
        for v in arcs[u]:
            indeg[v] -= 1
            if indeg[v] == 0:
                q.append(v)
    assert visited == len(faces), (visited, len(faces))
    return covering, visited


def gf2_betti(faces):
    by_size = {}
    for m in faces:
        by_size.setdefault(m.bit_count(), []).append(m)
    for cells in by_size.values():
        cells.sort()
    ranks = {}
    for size in range(2, max(by_size) + 1):
        ix = {x: i for i, x in enumerate(by_size[size - 1])}
        pivots = {}
        for upper in by_size[size]:
            v = upper
            col = 0
            while v:
                bit = v & -v
                v ^= bit
                col ^= 1 << ix[upper ^ bit]
            while col:
                lead = col.bit_length() - 1
                if lead not in pivots:
                    pivots[lead] = col
                    break
                col ^= pivots[lead]
        ranks[size - 1] = len(pivots)
    betti = {}
    for size, cells in by_size.items():
        val = len(cells) - ranks.get(size, 0) - ranks.get(size - 1, 0)
        if size == 1:
            val -= 1
        if val:
            betti[size - 1] = val
    return betti

for radius, expected_fvec, expected_crit, expected_betti in [
    (2, (20,90,120,30), {0: 1, 2: 19}, {2:19}),
    (3, (20,150,540,1000,960,450,80), {0:1, 3:1}, {3:1}),
]:
    faces = faces_incremental(radius)
    independent = faces_exhaustive(radius)
    assert faces == independent
    fvec = tuple(sum(1 for f in faces if f.bit_count() == k)
                 for k in range(1, max(map(int.bit_count, faces)) + 1))
    assert fvec == expected_fvec, (radius, fvec)
    critical, pairs = morse_matching(faces)
    critical_dims = dict(Counter(x.bit_count() - 1 for x in critical))
    assert critical_dims == expected_crit, (radius, critical_dims)
    assert 2 * len(pairs) + len(critical) == len(faces)
    covering, visited = acyclic_hasse(faces, pairs)
    betti = gf2_betti(faces)
    assert betti == expected_betti, (radius, betti)
    print('RADIUS', radius, 'F_VECTOR', fvec, 'FACES', len(faces),
          'MATCHED_PAIRS', len(pairs), 'CRITICAL', sorted(critical_dims.items()),
          'HASSE_INCIDENCES', covering, 'TOPOLOGICAL_SORT', visited,
          'MOD2_BETTI', sorted(betti.items()))

# Distance-four Rips: the ten missing edges constitute a perfect matching.
# Thus faces choose at most one vertex from each antipodal pair: an S^9
# cross-polytope boundary. Check all dimension counts via the binomial theorem.
four_fvec = tuple(comb(10, k) * 2 ** k for k in range(1, 11))
assert sum(four_fvec) == 3 ** 10 - 1 == 59048
assert len(missing_pairs) == 10
print('RADIUS 4 CROSS_POLYTOPE_S9', four_fvec, 'FACES', sum(four_fvec))
print('RADIUS 1 CYCLE_RANK', 30 - 20 + 1)
print('RADIUS 5 CONTRACTIBLE', max(max(d) for d in DIST))
print('ALL_CHECKS_PASS')
