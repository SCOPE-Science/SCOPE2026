"""Exact finite check of directed color refinement on connected endofunctions.

Builds all connected functional digraphs as directed cycles of rooted trees.
Every rooted tree is generated by recursively adding one leaf.  Rooted trees
are canonically encoded, and cycles are quotiented by rotation only.
No probabilistic hashes, third-party packages, or external datasets are used.
"""
from collections import Counter, defaultdict
from functools import lru_cache
from itertools import permutations, product

@lru_cache(None)
def tree_code(tree):
    return '(' + ''.join(tree_code(t) for t in tree) + ')'

@lru_cache(None)
def add_leaf(tree):
    answer = {tuple(sorted(tree + ((),), key=tree_code))}
    for j, child in enumerate(tree):
        for bigger in add_leaf(child):
            new_children = tree[:j] + (bigger,) + tree[j + 1:]
            answer.add(tuple(sorted(new_children, key=tree_code)))
    return frozenset(answer)

def rooted_tree_catalogue(n):
    levels = {1: {()}}
    for k in range(2, n + 1):
        levels[k] = set().union(*(add_leaf(t) for t in levels[k - 1]))
    tree_by_code = {tree_code(t): t for level in levels.values() for t in level}
    codes_by_size = {k: sorted(tree_code(t) for t in level)
                     for k, level in levels.items()}
    return tree_by_code, codes_by_size

def min_rotation(sequence):
    return min(sequence[i:] + sequence[:i] for i in range(len(sequence)))

def connected_necklaces(n, codes_by_size):
    def rec(prefix, remaining):
        if remaining == 0:
            seq = tuple(prefix)
            if seq == min_rotation(seq):
                yield seq
            return
        for s in range(1, remaining + 1):
            for item in codes_by_size[s]:
                yield from rec(prefix + [item], remaining - s)
    return list(rec([], n))

def function_from_necklace(seq, tree_by_code):
    parent = []
    cycle_roots = []
    def attach(tree):
        root = len(parent)
        parent.append(-1)
        for child in tree:
            child_root = attach(child)
            parent[child_root] = root
        return root
    for item in seq:
        cycle_roots.append(attach(tree_by_code[item]))
    for i, root in enumerate(cycle_roots):
        parent[root] = cycle_roots[(i + 1) % len(cycle_roots)]
    return parent

def stable_histograms(functions):
    n = len(functions[0])
    # Initially the atomic unary type detects an edge-loop.
    colors = [[int(p == i) for i, p in enumerate(f)] for f in functions]
    for _ in range(2 * n + 3):
        signatures = []
        for f, cc in zip(functions, colors):
            incoming = [[] for _ in f]
            for u, v in enumerate(f):
                incoming[v].append(cc[u])
            for u in range(n):
                signatures.append((cc[u], cc[f[u]], tuple(sorted(incoming[u]))))
        palette = {sig: j for j, sig in enumerate(sorted(set(signatures)))}
        updated = [[palette[sig] for sig in signatures[k*n:(k+1)*n]]
                   for k in range(len(functions))]
        if updated == colors:
            break
        colors = updated
    else:
        raise AssertionError('refinement did not stabilize')
    return [tuple(sorted(Counter(cc).items())) for cc in colors]


def individual_colors(f):
    n = len(f)
    colors = [int(i == f[i]) for i in range(n)]
    for _ in range(2*n+3):
        incoming = [[] for _ in f]
        for u,v in enumerate(f):
            incoming[v].append(colors[u])
        patterns = [(colors[u], colors[f[u]], tuple(sorted(incoming[u])))
                    for u in range(n)]
        palette = {z:i for i,z in enumerate(sorted(set(patterns)))}
        new = [palette[z] for z in patterns]
        if new == colors:
            return colors
        colors = new
    raise AssertionError('individual refinement did not stabilize')

def verify_orbit_partition(f):
    n = len(f)
    colors = individual_colors(f)
    groups = defaultdict(list)
    for i,c in enumerate(colors): groups[c].append(i)
    group_lists = [groups[k] for k in sorted(groups)]
    reachable = [set((i,)) for i in range(n)]
    for choices in product(*(permutations(g) for g in group_lists)):
        pi = list(range(n))
        for g,perm in zip(group_lists,choices):
            for a,b in zip(g,perm):pi[a]=b
        if all(pi[f[i]] == f[pi[i]] for i in range(n)):
            for i in range(n):reachable[i].add(pi[i])
    assert all(reachable[i] == set(groups[colors[i]]) for i in range(n)), f

def main():
    n_max = 12
    trees, code_levels = rooted_tree_catalogue(n_max)
    known_counts = (1,2,4,9,20,51,125,329,862,2311,6217,16949)
    for n, expected in enumerate(known_counts, start=1):
        necklaces = connected_necklaces(n, code_levels)
        assert len(necklaces) == expected, (n, len(necklaces), expected)
        funcs = [function_from_necklace(s, trees) for s in necklaces]
        assert all(len(f) == n and all(0 <= v < n for v in f)
                   for f in funcs)
        hist = stable_histograms(funcs)
        distinct = len(set(hist))
        assert distinct == len(necklaces), (n, distinct, len(necklaces))
        if n <= 7:
            for f in funcs: verify_orbit_partition(f)
        print(f'order={n} connected_types={len(necklaces)} refinement_classes={distinct}')
    # Without the connectedness restriction, distinct loopless permutations
    # C_6 and C_3 + C_3 are C^2-equivalent.
    six_cycle = [1,2,3,4,5,0]
    two_three = [1,2,0,4,5,3]
    assert stable_histograms([six_cycle, two_three])[0] == stable_histograms([six_cycle, two_three])[1]
    # No loops or reciprocal arcs, and each vertex has exactly one
    # outgoing and one incoming arc: identical full C^2 color type.
    for f in (six_cycle, two_three):
        assert all(f[i] != i and f[f[i]] != i for i in range(6))
        assert Counter(f) == Counter(range(6))
    print('ORBIT_PARTITION_OK through_order=7')
    print('DISCONNECTED_BOUNDARY_OK n=6')
    print('VERIFY_OK connected_classes_through_12=16949')

if __name__ == '__main__':
    main()
