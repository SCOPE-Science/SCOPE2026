#!/usr/bin/env python3
"""Self-contained exact checks for the scale-two/three truncated-octahedron Rips modules.

Only Python standard library is required. Each finite set is generated by explicit
combinatorial definitions. Matrix ranks and persistence are computed over F_2;
Lefschetz character identities use exact signed integer simplicial chains.
"""
import itertools
import math
from collections import Counter


def parity(seq):
    return -1 if sum(seq[i] > seq[j] for i in range(len(seq)) for j in range(i + 1, len(seq))) % 2 else 1


def rank_extend(v, basis):
    while v:
        j = v.bit_length() - 1
        if j not in basis:
            basis[j] = v
            return True
        v ^= basis[j]
    return False


def kernel_with_masks(columns):
    pivots = {}
    ker = []
    for i, col in enumerate(columns):
        chain, witness = col, 1 << i
        while chain and (j := chain.bit_length() - 1) in pivots:
            other_chain, other_witness = pivots[j]
            chain ^= other_chain
            witness ^= other_witness
        if chain:
            pivots[chain.bit_length() - 1] = (chain, witness)
        else:
            ker.append(witness)
    return len(pivots), ker


perms = sorted(set(itertools.permutations((0, 1, 2))))
signs = list(itertools.product((-1, 1), repeat=3))
V = sorted({tuple(s[i] * q[i] for i in range(3)) for q in perms for s in signs})
assert len(V) == 24
index = {x: i for i, x in enumerate(V)}
G = [[False] * 24 for _ in range(24)]
for i, x in enumerate(V):
    for j, y in enumerate(V):
        if i < j and sum((x[k] - y[k]) ** 2 for k in range(3)) == 2:
            G[i][j] = G[j][i] = True
assert sum(sum(row) for row in G) // 2 == 36
assert {sum(row) for row in G} == {3}
D = [[99] * 24 for _ in range(24)]
for i in range(24):
    D[i][i] = 0
    for j in range(24):
        if G[i][j]:
            D[i][j] = 1
for k in range(24):
    for i in range(24):
        for j in range(24):
            D[i][j] = min(D[i][j], D[i][k] + D[k][j])
assert max(max(row) for row in D) == 6


def all_faces(r):
    adjacent = [sum(1 << j for j in range(24) if i < j and D[i][j] <= r) for i in range(24)]
    result = []
    def go(prefix, candidates):
        if prefix:
            result.append(tuple(prefix))
        while candidates:
            bit = candidates & -candidates
            candidates -= bit
            i = bit.bit_length() - 1
            go(prefix + [i], candidates & adjacent[i])
    go([], (1 << 24) - 1)
    return sorted(result, key=lambda t: (len(t), t))


def boundary_bits(face, low_index):
    return sum(1 << low_index[face[:i] + face[i + 1:]] for i in range(len(face)))


F = {r: all_faces(r) for r in (2, 3)}
rows = {}
for r in (2, 3):
    fs = F[r]
    dims = {k: [s for s in fs if len(s) == k] for k in range(1, 8)}
    fvec = tuple(len(dims[k]) for k in range(1, 8) if dims[k])
    print('scale', r, 'f-vector', fvec)
    assert fvec == ((24, 96, 112, 30) if r == 2 else (24, 168, 472, 618, 384, 92))
    E = {edge: i for i, edge in enumerate(dims[2])}
    Tri = {tri: i for i, tri in enumerate(dims[3])}
    r2, ker2 = kernel_with_masks([boundary_bits(tri, E) for tri in dims[3]])
    b3 = {}
    for tet in dims[4]:
        rank_extend(boundary_bits(tet, Tri), b3)
    h2 = len(dims[3]) - r2 - len(b3)
    assert (r2, len(b3), h2) == ((73, 30, 9) if r == 2 else (145, 326, 1))
    assert len(dims[2]) - 23 - r2 == 0  # H_1 over F_2.
    rows[r] = {'dims': dims, 'triangle_index': Tri, 'kernel': ker2, 'b3': b3}
    print('scale', r, 'rank_d2', r2, 'rank_d3', len(b3), 'beta2_F2', h2)

normals = list(itertools.product((-1, 1), repeat=3))
hexagons = {n: tuple(sorted(index[tuple(n[k] * q[k] for k in range(3))] for q in perms)) for n in normals}
assert all(len(set(h)) == 6 for h in hexagons.values())


def cyclic_order(h):
    h = set(h)
    start = min(h)
    choices = sorted(j for j in h if G[start][j])
    assert len(choices) == 2
    order = [start, choices[0]]
    while len(order) < 6:
        nxt = [j for j in h if G[order[-1]][j] and j != order[-2]]
        assert len(nxt) == 1
        order.append(nxt[0])
    assert len(set(order)) == 6 and G[order[-1]][start]
    return order


def local_cycle(order):
    out = {}
    for bits in itertools.product((0, 1), repeat=3):
        selected = [order[j + 3 * bits[j]] for j in range(3)]
        face = tuple(sorted(selected))
        out[face] = (-1) ** sum(bits) * parity(selected)
    assert len(out) == 8
    return out


base = local_cycle(cyclic_order(hexagons[(1, 1, 1)]))

def act_chain(chain, perm):
    out = {}
    for face, coeff in chain.items():
        img = tuple(perm[i] for i in face)
        target = tuple(sorted(img))
        out[target] = coeff * parity(img)
    return out

cycles = {}
for n in normals:
    diag = tuple(index[tuple(n[j] * V[i][j] for j in range(3))] for i in range(24))
    cycles[n] = act_chain(base, diag)
    assert set(cycles[n]) == {s for s in itertools.combinations(hexagons[n], 3) if s in rows[2]['triangle_index']}
    boundary = Counter()
    for tri, val in cycles[n].items():
        for j in range(3):
            boundary[tri[:j] + tri[j+1:]] += (-1)**j * val
    assert not any(boundary.values())
    assert max(D[i][j] for i in hexagons[n] for j in hexagons[n]) == 3

# The two alternating triangles of each hexagon occur in no tetrahedron
# at scale two, and no alternating triangle belongs to another hexagon.
alternating = {}
all_alt = set()
tets2 = rows[2]['dims'][4]
for n in normals:
    cyc = cyclic_order(hexagons[n])
    alts = [tuple(sorted(cyc[0::2])), tuple(sorted(cyc[1::2]))]
    assert all(t in cycles[n] for t in alts)
    assert not any(set(t).issubset(tet) for t in alts for tet in tets2)
    assert all(t not in all_alt for t in alts)
    assert all(t not in cycles[m] for t in alts for m in normals if m != n)
    alternating[n] = alts
    all_alt.update(alts)
print('local hexagon octahedral cycles',len(cycles), 'private alternating triangles',len(all_alt))

# Signed coordinate-permutation group: all 48 automorphisms.
symmetries = []
for p in itertools.permutations(range(3)):
    for s in signs:
        image = tuple(index[tuple(s[j] * V[i][p[j]] for j in range(3))] for i in range(24))
        det = parity(p) * math.prod(s)
        assert all(G[i][j] == G[image[i]][image[j]] for i in range(24) for j in range(24))
        symmetries.append((p, s, image, det))
assert len({x[2] for x in symmetries}) == 48

for p, s, image, det in symmetries:
    for n in normals:
        target = tuple(s[j] * n[p[j]] for j in range(3))
        assert act_chain(cycles[n], image) == cycles[target]  # Unsigned face permutation.
    for r in (2, 3):
        chain_trace = 0
        for dim, faces in rows[r]['dims'].items():
            if not faces:
                continue
            for face in faces:
                img = [image[i] for i in face]
                if set(img) == set(face):
                    chain_trace += (-1) ** (dim - 1) * parity(img)
        # H_0 is the trivial module and all other rational homology vanishes
        # except H_2 for these two previously classified Rips complexes.
        observed = chain_trace - 1
        fixed_hexagons = sum(tuple(s[j] * n[p[j]] for j in range(3)) == n for n in normals)
        expected = det + fixed_hexagons if r == 2 else det
        assert observed == expected, (r, p, s, observed, expected)
print('all 48 signed group actions and both Lefschetz characters verified')

# Explicit image on H_2 over F_2. Construct all kernel cycles in scale two,
# include them in the larger scale-three triangle space, and reduce against
# the complete scale-three 3-simplex boundary span.
tri2 = rows[2]['dims'][3]
tri3_index = rows[3]['triangle_index']
b3 = rows[3]['b3'].copy()
image_rank = 0
witness_support = 0
for mask in rows[2]['kernel']:
    inc = 0
    for j, tri in enumerate(tri2):
        if (mask >> j) & 1:
            inc ^= 1 << tri3_index[tri]
    if rank_extend(inc, b3):
        image_rank += 1
        witness_support = mask.bit_count()
assert image_rank == 1
# The eight geometric hexagon classes vanish at scale three since the six
# vertices of every hexagon span a full 5-simplex there.
assert all(max(D[i][j] for i in h for j in h) <= 3 for h in hexagons.values())
print('H2 scale-2 -> scale-3 rank over F2',image_rank,'witness triangle support',witness_support)
print('VERIFIED_OK')
