#!/usr/bin/env python3
"""Independent finite certificate verifier for rooted-triplet online depth.

Run: python3 verify_rooted_triplet_online.py [rooted_triplet_strategy.json]
Uses Python's standard library only. Every possible rooted binary tree with
3 through 6 labeled leaves is generated by successive leaf insertions.
"""
import json,itertools,collections,sys

def ckey(tree):
    if isinstance(tree,int):return tree
    a,b=(ckey(x) for x in tree)
    def lowest(t):return t if isinstance(t,int) else lowest(t[0])
    return (a,b) if lowest(a)<lowest(b) else (b,a)

def insert_leaf(tree,leaf):
    result=[ckey((leaf,tree))]  # add a new root above the old root
    if isinstance(tree,tuple):
        a,b=tree
        for x in insert_leaf(a,leaf):result.append(ckey((x,b)))
        for x in insert_leaf(b,leaf):result.append(ckey((a,x)))
    return result

def trees(n):
    t=[(0,1)]
    for leaf in range(2,n):
        t=[z for x in t for z in insert_leaf(x,leaf)]
        assert len(t)==len(set(t)),"duplicate insertion construction"
    return t

def lca_depths(t):
    d={}
    def descend(node,level):
        if isinstance(node,int):return [node]
        left=descend(node[0],level+1)
        right=descend(node[1],level+1)
        for a in left:
            for b in right:d[tuple(sorted((a,b)))]=level
        return left+right
    descend(t,0)
    return d

def truth(depth,q):
    a,b,c=q
    return depth[tuple(sorted((a,b)))]>depth[tuple(sorted((a,c)))]

def verify():
    filename=sys.argv[1] if len(sys.argv)>1 else 'rooted_triplet_strategy.json'
    with open(filename,encoding='utf8') as f:bundle=json.load(f)
    assert bundle['schema_version']==1
    assert set(bundle['strategies'])=={'3','4','5','6'}
    results=[]
    for n in range(3,7):
        tt=trees(n)
        num=len(tt)
        assert num=={3:3,4:15,5:105,6:945}[n]
        queries=[(a,b,c) for a,b,c in itertools.permutations(range(n),3) if a<b]
        queries.sort()
        depths=[lca_depths(t) for t in tt]
        masks={q:sum(1<<i for i,d in enumerate(depths) if truth(d,q)) for q in queries}
        assert len(set(tuple(truth(d,q) for q in queries) for d in depths))==num
        allset=(1<<num)-1
        s=bundle['strategies'][str(n)]
        height=s['depth'];nodes=s['node_queries']
        assert len(nodes)==(1<<height)-1
        assert all(tuple(q) in masks for q in nodes)
        leafsets=[]
        def replay(i,cur,remaining):
            if remaining==0:
                assert cur!=0,'empty branch'
                leafsets.append(cur)
                return
            q=tuple(nodes[i]);y=cur&masks[q];no=cur^y
            assert no and y,'branch absent'
            replay(2*i+1,no,remaining-1)
            replay(2*i+2,y,remaining-1)
        replay(0,allset,height)
        assert len(leafsets)==(1<<height)
        seen=0
        for subset in leafsets:
            assert not (seen&subset),'branches overlap'
            seen |= subset
        assert seen==allset,'branch family does not cover all trees'
        if n!=5: assert num<(1<<(height+1)), 'entropy upper bound inconclusive'
        results.append((n,num,len(queries),height,len(nodes),min(x.bit_count() for x in leafsets),max(x.bit_count() for x in leafsets)))
        if n==5:
            # The entropy bound alone gives <=6. Every first query has
            # 35 positive trees. A depth-5 subtree on these 35 trees
            # must choose at its root a split with >=16 trees on each side;
            # the unique such split has a child with 17 trees, none of whose
            # available queries split that child into two groups >=8.
            for root in queries:
                P=masks[root]
                assert P.bit_count()==35
                viable=[u for u in queries if min((P&masks[u]).bit_count(),(P&~masks[u]).bit_count())>=16]
                assert len(viable)==1
                q=viable[0]
                sides=[P&masks[q],P&~masks[q]]
                smaller=min(sides,key=int.bit_count)
                assert smaller.bit_count()==17
                assert max(min((smaller&masks[u]).bit_count(),(smaller&~masks[u]).bit_count()) for u in queries)<=7
    assert [x[3] for x in results]==[1,3,5,9]
    print('ROOTED_TRIPLET_ONLINE_PASS n3..6 3,15,105,945 trees 1,3,5,9 depths 511-node six-leaf strategy')
    for row in results:print('n=%d trees=%d queries=%d Ldim=%d certificate_nodes=%d leaf_cardinality_range=%d..%d'%row)
if __name__=='__main__':verify()
