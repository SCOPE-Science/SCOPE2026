"""Standalone numeric and exact-arithmetic checks of two-dimensional log-Nystrom formulas.

This program checks finite algebra and evaluations; the limit laws require the proof.
Requires Python 3 standard library only.
"""
from fractions import Fraction
from math import atan, cos, exp, log, log1p, pi, sin, sqrt, tan

checks = 0

def close(x, y, tol=1e-9):
    global checks
    checks += 1
    if abs(x - y) > tol * (1 + abs(x) + abs(y)):
        raise AssertionError((x, y, tol))

def exact(x, y):
    global checks
    checks += 1
    if x != y:
        raise AssertionError((x, y))

def h_of_t(a, b, t):
    return log1p(b*(a-b)*t/(a*(1+a)+b*(1+b)*t))

def inverse_t(a, b, h):
    z = exp(h)
    return a*(1+a)*(z-1)/(b*((1+a)-(1+b)*z))

def mean_h(a, b):
    return 2*log1p((sqrt(b)-sqrt(b*(1+b)/(1+a)))/(sqrt(a)+sqrt(b*(1+b)/(1+a))))

def direct_loss(a, b, theta):
    A, B = log1p(a), log1p(b)
    return A*B/(A*cos(theta)**2+B*sin(theta)**2)

# Rational checks of the fundamental rank-one trace and residual identities.
for i in range(2, 19):
    for j in range(1, i):
        a,b = Fraction(i,3),Fraction(j,5)
        if not a>b: continue
        for k in range(0, 19):
            t=Fraction(k,7)
            x=(a*a+b*b*t)/(a+b*t)
            e=(1+a)*(a+b*t)/(a*(1+a)+b*(1+b)*t)
            exact((1+a)/(1+x),e)
            A,B=Fraction(i+1,4),Fraction(j+1,7)
            direct=(A+B)-(A*A+B*B*t)/(A+B*t)
            exact(direct,A*B*(1+t)/(A+B*t))

# The exact CDF is generated by a squared standard Cauchy variable.
for a,b in ((2.0,0.5),(4.0,1.0),(20.0,0.3),(100.0,2.0)):
    for q in (0.0001, .01, .1, .25, .5, .75, .9, .99, .9999):
        t=tan(pi*q/2)**2
        h=h_of_t(a,b,t)
        close(inverse_t(a,b,h),t,3e-8)
        close(2*atan(sqrt(inverse_t(a,b,h)))/pi,q,3e-9)
        close(log1p(a)+log1p(b)-log1p((a*a+b*b*t)/(a+b*t))-log1p(b), h)
        A,B=log1p(a),log1p(b)
        d=A*B*(1+t)/(A+B*t)
        inv=A*(d-B)/(B*(A-d))
        close(inv,t,3e-8)
        close(2*atan(sqrt(inv))/pi,q,3e-9)

# Angular integrals (periodic midpoint quadrature): exact means of both estimators.
for a,b in ((2.0,1.0),(3.0,.4),(10.,1.),(70.,2.)):
    n=60000
    sh=sd=0.0
    for k in range(n):
        theta=pi*(k+.5)/n
        t=tan(theta)**2
        sh+=h_of_t(a,b,t)
        sd+=direct_loss(a,b,theta)
    close(sh/n, mean_h(a,b),2e-8)
    close(sd/n,sqrt(log1p(a)*log1p(b)),2e-8)

# Sharp high-spike mean and fixed-quantile scales.
for b in (.2,1.,3.):
    a=1e10
    close(sqrt(a)*mean_h(a,b),2*sqrt(b),2e-5)
    for q in (.05,.25,.5,.75,.95):
        t=tan(pi*q/2)**2
        close(a*h_of_t(a,b,t),b*t,8e-7)

print(f"VERIFICATION_OK checks={checks}")
