#!/usr/bin/env python3
"""Finite checks for the 2-adic image of binomial(3n,n)."""
from math import comb

def chooser_mod(p,k,n):
    assert p==2 and k>=1
    mod=1<<k
    odd_prefix=[1]*(mod+1)
    for i in range(1,mod+1):
        odd_prefix[i]=odd_prefix[i-1]*(i if i&1 else 1)%mod
    cycle=odd_prefix[-1]
    def O(z):
        q,r=divmod(z,mod)
        return pow(cycle,q,mod)*odd_prefix[r]%mod
    def oddfactor(z):
        v=1
        while z:
            v=v*O(z)%mod;z//=2
        return v
    def vfact(z):
        ans=0
        while z:z//=2;ans+=z
        return ans
    A=3*n; B=n; C=2*n
    v=vfact(A)-vfact(B)-vfact(C)
    if v>=k:return 0
    den=oddfactor(B)*oddfactor(C)%mod
    return ((1<<v)*oddfactor(A)*pow(den,-1,mod))%mod

def run():
    for k in range(1,9):
        mod=1<<k
        for n in range(350):
            assert chooser_mod(2,k,n)==comb(3*n,n)%mod,(k,n)
        # Scaling stabilizes at high dyadic exponent.
        u1=chooser_mod(2,k,1<<(k+3));u9=chooser_mod(2,k,9<<(k+3))
        for b in [1,3,5,9,17,21,33]:
            vals=[chooser_mod(2,k,b<<(k+j)) for j in (1,2,3)]
            assert len(set(vals))==1,(k,b,vals)
        for a in [1,3,5,9]:
            for b in [1,3,9]:
                for t in [0,1,2]:
                    r=k+((3*a).bit_length())+3
                    x=(a<<t)+(b<<(t+r))
                    lhs=chooser_mod(2,k,x)
                    rhs=chooser_mod(2,k,a<<t)*chooser_mod(2,k,b<<(t+r))%mod
                    assert lhs==rhs,(k,a,b,t)
        # Find all residue classes in multiplicative monoid generated by u1,u9.
        generated={pow(u1,e,mod)*pow(u9,f,mod)%mod
                   for e in range(2*mod) for f in range(2*mod)}
        assert generated=={j for j in range(mod) if j%2}
        # Verify exact spectrum by evaluating modest indices, or explicit separated blocks.
        N=35000 if k<=7 else 130000
        # Prime-power direct modular recurrence via factorial odd parts is expensive;
        # computed indices are sampled so this remains bounded.
        residues={chooser_mod(2,k,n) for n in range(0,min(N,10000))}
        want={j for j in range(mod) if j%4!=2}
        assert residues.issubset(want)
        # A certificate that each permitted residue is generated by a product of stabilized blocks.
        semigroup=set()
        for s in [0]+list(range(2,k)):
            if s==0:seed=1
            else:seed=chooser_mod(2,k,(2**s-1)<<(k+3))
            semigroup.update(seed*u%mod for u in generated)
        semigroup.add(0)
        assert semigroup==want,(k,semigroup^want)
    assert (chooser_mod(2,3,8),chooser_mod(2,3,72))==(7,5)
    print('VERIFY_OK exact_small_binomials=2800 block_cases=288 stabilization_cases=56 multiplicative_unit_groups=8 expected_spectra=1..8')
if __name__=='__main__':run()
