"""Independent standard-library numerical tests of orthogonal-disc Minkowski sums.

This is a finite consistency check; the accompanying analytic proof supplies the
continuum theorem. Run with: python3 checks/dice_volume_check.py
"""
import math
from itertools import combinations


def hypergeom_partial(n=100000):
    # Ordinary, absolutely convergent generalized hypergeometric power series.
    term = 1.0
    total = 1.0
    for j in range(n):
        term *= (j - .25) * (j + .25) * (j + .5) / (j + 1) ** 3
        total += term
    return total


def det(p, q, r):
    return (p[0] * (q[1]*r[2]-q[2]*r[1])
            - p[1] * (q[0]*r[2]-q[2]*r[0])
            + p[2] * (q[0]*r[1]-q[1]*r[0]))


def approximate_minkowski_volume(a, b, c, m):
    # A planar unit disk is the limit of the centrally symmetric polygon
    # generated by half of its successive chord vectors.  A zonotope with
    # generators g_i has volume sum_{i<j<k} 8 |det(g_i,g_j,g_k)|.
    angles = [math.pi * j / m for j in range(m + 1)]
    edges = [(math.cos(angles[j+1]) - math.cos(angles[j]),
              math.sin(angles[j+1]) - math.sin(angles[j])) for j in range(m)]
    g = []
    for typ, weight in enumerate((a, b, c)):
        for x, y in edges:
            if typ == 0:
                g.append((weight*x/2, weight*y/2, 0.0))
            elif typ == 1:
                g.append((0.0, weight*x/2, weight*y/2))
            else:
                g.append((weight*y/2, 0.0, weight*x/2))
    return 8 * math.fsum(abs(det(g[i], g[j], g[k]))
                          for i, j, k in combinations(range(len(g)), 3))


def volume_formula(a, b, c, C):
    return (2 * math.pi * (a*a*b + a*a*c + b*b*a + b*b*c + c*c*a + c*c*b)
            + C*a*b*c)


def run():
    F = hypergeom_partial()
    C = math.sqrt(2) * math.pi**2 * F
    assert 4*math.pi < C < 6*math.pi
    print('triple-mixed constant, finite series approximate: %.7f' % C)
    # Check a family of genuinely three-dimensional bodies, independent of
    # the determinant-integral expansion used in the proof.
    for a, b, c in ((1., 1., 1.), (1.3, .7, .4), (1., 1., 0.), (0., 2., 1.)):
        exact = volume_formula(a, b, c, C)
        estimates = [approximate_minkowski_volume(a, b, c, m)
                     for m in (8, 16, 32)]
        print('weights', (a,b,c), 'exact', round(exact, 9),
              'zonotope refinements', [round(x, 8) for x in estimates])
        assert estimates[0] < estimates[1] < estimates[2] < exact
        assert (exact-estimates[2])/exact < 0.002
    # The sharp stability constant has equality at equal weights and at
    # the boundary midpoint (S/2,S/2,0). Finite tests sample also interiors.
    S = 3.0
    alpha = S*(2*C-3*math.pi)/9
    ideal = volume_formula(1,1,1,C)
    for a,b,c in ((1.,1.,1.),(1.5,1.5,0.),(3.,0.,0.),
                  (2.,.5,.5),(1.5,.75,.75),(.1,1.1,1.8)):
        q = sum((z-S/3)**2 for z in (a,b,c))
        gap = ideal-volume_formula(a,b,c,C)
        assert gap >= alpha*q-1e-10
        if (a,b,c) in ((1.,1.,1.),(1.5,1.5,0.)):
            assert abs(gap-alpha*q)<1e-10
    print('DICE_WEIGHTED_VOLUME_AND_SHARP_STABILITY_CHECKS_PASSED')


if __name__ == '__main__':
    run()
