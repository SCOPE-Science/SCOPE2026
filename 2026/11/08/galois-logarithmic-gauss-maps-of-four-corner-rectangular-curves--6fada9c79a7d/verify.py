"""Exact symbolic checks for the four-corner logarithmic-Gauss covering.
Run: python verify.py (requires SymPy). All assertions use exact arithmetic.
This code checks algebraic identities and sample cases; the general theorem
also uses geometric smoothness, Kummer irreducibility and local valuations.
"""
import sympy as s
U,V,L,t=s.symbols('U V L t',nonzero=True)
m,n=s.symbols('m n',integer=True,positive=True)
f=1+U+V+L*U*V
v=-(1+U)/(1+L*U)
c=s.Rational(1,1)*m*(L-1)/n
h=s.factor(c*U/((1+U)*(1+L*U)))
ratio=m*U*(1+L*V)/(n*V*(1+L*U))
assert s.cancel(ratio.subs(V,v)-h)==0
assert s.cancel(L*U*V*f.subs({U:1/(L*U),V:1/(L*V)}, simultaneous=True)-f)==0
assert s.cancel(h-h.subs(U,1/(L*U)))==0
num=s.fraction(s.diff(h,U))[0]
assert s.factor(num)==c*(1-L*U**2) or s.factor(s.cancel(s.diff(h,U)/h)-(1-L*U**2)/(U*(1+U)*(1+L*U)))==0
quadratic=s.expand(t*(1+U)*(1+L*U)-c*U)
discr=s.factor(s.discriminant(quadratic,U))
expected=s.factor((t*(1+L)-c)**2-4*L*t*t)
assert s.simplify(discr-expected)==0
assert s.factor(expected)==s.factor((L-1)**2*t**2-2*c*(1+L)*t+c**2)
# For integer lambda=4, base ramification parameters are u=+/-1/2.
for mi,ni,li in [(2,2,4),(2,3,4),(3,5,9),(4,2,16),(7,6,25)]:
 hi=h.subs({m:mi,n:ni,L:li})
 roots=s.solve(s.diff(hi,U),U)
 assert set(roots)=={-s.sqrt(li)**-1,s.sqrt(li)**-1}
 vals={s.factor(hi.subs(U,root)) for root in roots}
 predicted={s.Rational(mi,ni)*(s.sqrt(li)-1)/(s.sqrt(li)+1),
            s.Rational(mi,ni)*(s.sqrt(li)+1)/(s.sqrt(li)-1)}
 assert vals==predicted, (mi,ni,li,vals,predicted)
 degree=2*mi*ni
 # The ordered branch partitions: 0, infinity, the two simple slopes.
 partitions=[[mi]*(2*ni),[ni]*(2*mi),[2]*(mi*ni),[2]*(mi*ni)]
 assert all(sum(part)==degree for part in partitions)
 genus=(mi-1)*(ni-1)
 assert sum(sum(e-1 for e in part) for part in partitions)==2*genus-2+2*degree
 # Group generated by the two Kummer rotations and the reciprocal involution.
 labels=[(epsilon,i,j) for epsilon in (0,1) for i in range(mi) for j in range(ni)]
 def rotm(z):
  epsilon,i,j=z; return (epsilon,(i+1)%mi,j)
 def rotn(z):
  epsilon,i,j=z; return (epsilon,i,(j+1)%ni)
 def refl(z):
  epsilon,i,j=z; return (1-epsilon,(-i)%mi,(-j)%ni)
 def perm(fn): return tuple(labels.index(fn(z)) for z in labels)
 def compose(a,b): return tuple(a[b[k]] for k in range(len(labels)))
 gens=[perm(rotm),perm(rotn),perm(refl)]
 identity=tuple(range(len(labels)))
 group={identity}; fringe=[identity]
 while fringe:
  g=fringe.pop()
  for generator in gens:
   hperm=compose(g,generator)
   if hperm not in group: group.add(hperm);fringe.append(hperm)
 assert len(group)==degree
 assert compose(gens[2],compose(gens[0],gens[2]))==tuple(gens[0].index(i) for i in range(degree))
 assert compose(gens[2],compose(gens[1],gens[2]))==tuple(gens[1].index(i) for i in range(degree))
 print('CASE',mi,ni,li,'genus',genus,'degree',degree,'critical slopes',sorted(vals),
       'partitions',[[e,len(part)] for part in partitions for e in [part[0]]])
print('ALL_CHECKS_PASSED')
