#!/usr/bin/env python3
"""Deterministic finite checks for fixed loci of clique-free graph complexes.
Python 3 standard library only. Enumerates faces by their graph-induced clique number,
then independently enumerates invariant orbit faces and computes mod-2 homology.
"""
import itertools, math

def closure(n, gens):
    e=tuple(range(n)); group={e}; todo=[e]
    while todo:
        p=todo.pop()
        for g in gens:
            for q in (tuple(p[g[i]] for i in range(n)), tuple(g[p[i]] for i in range(n))):
                if q not in group:group.add(q);todo.append(q)
    return group

def orbits(n, group):
    rem=set(range(n)); blocks=[]
    while rem:
        i=min(rem); o=frozenset(g[i] for g in group); rem-=o; blocks.append(tuple(sorted(o)))
    return blocks

def bitrank(vectors):
    pivots={}
    for v in vectors:
        while v:
            p=v.bit_length()-1
            if p in pivots:v^=pivots[p]
            else:pivots[p]=v;break
    return len(pivots)

def betti(faces):
    faces=[tuple(sorted(f)) for f in faces]
    if not faces:return {-1:1} # empty realization
    bydim={d:sorted([f for f in faces if len(f)==d+1]) for d in set(len(f)-1 for f in faces)}
    ranks={}
    for d in range(1,max(bydim)+1):
        dom=bydim.get(d,[]);cod={f:j for j,f in enumerate(bydim.get(d-1,[]))}
        ranks[d]=bitrank([sum(1<<cod[f[:j]+f[j+1:]] for j in range(len(f))) for f in dom])
    out={}
    for d, ff in bydim.items():
        b=len(ff)-ranks.get(d,0)-ranks.get(d+1,0)
        if d==0:b-=1
        if b:out[d]=b
    return out

def graph_clique(face,parts):
    # Independently find max clique using adjacency and combination search.
    for size in range(len(face),0,-1):
        for sub in itertools.combinations(face,size):
            if all(parts[u]!=parts[v] for u,v in itertools.combinations(sub,2)):
                return size
    return 0

def run_case(sizes,t,gens):
    n=sum(sizes);parts=tuple(j for j,a in enumerate(sizes) for _ in range(a))
    H=closure(n,gens)
    orb=orbits(n,H); k=len(orb)
    assert len(H)<=300 and k<=15
    def admissible(mask):
        U=tuple(v for j,b in enumerate(orb) if mask>>j&1 for v in b)
        return graph_clique(U,parts)<t
    faces={tuple(j for j in range(k) if mask>>j&1) for mask in range(1,1<<k) if admissible(mask)}
    # Invariant nonempty simplices are exactly unions of vertex orbits.
    for mask in range(1<<k):
        selected=tuple(j for j in range(k) if mask>>j&1)
        U={v for j in selected for v in orb[j]}
        assert admissible(mask)==(max([0]+[len(set(parts[v] for v in sub)) for r in range(1,min(len(U),t)+1) for sub in itertools.combinations(U,r)])<t)
    part_orbs=[]; unused=set(range(len(sizes)))
    while unused:
        j=min(unused)
        # graph part orbit generated by actual vertex action
        o=set(parts[g[next(i for i,p in enumerate(parts) if p==j)]] for g in H)
        unused-=o;part_orbs.append(tuple(sorted(o)))
    weights=sorted(len(o) for o in part_orbs)
    T=t-1
    if not weights or weights[0]>T:expect={-1:1}
    else:
        a=weights[0]
        expect={}
        for mask in range(1,1<<max(0,len(weights)-1)):
            S=[weights[j+1] for j in range(len(weights)-1) if mask>>j&1]
            if T-a<sum(S)<=T:
                d=len(S)-1;expect[d]=expect.get(d,0)+1
        # When critical 0-cells occur, wedge of S0 has components count+1.
    got=betti(faces)
    assert got==expect,(sizes,t,weights,got,expect,len(faces))
    # Verify orbit faces exactly weighted threshold over *all* vertex orbits
    for face in faces:
        parts_used=set(parts[v] for j in face for v in orb[j]);assert len(parts_used)<=T
    return (sizes,t,len(H),len(orb),tuple(weights),len(faces),expect)

def main():
    cases=[]
    for sizes in [(2,2,2),(2,2,2,2),(2,2,2,2,2),(2,2,2,2,2,2,2),(1,2,3),(2,2,3),(2,2,2,3),(2,2,2,2,2,2)]:
        n=sum(sizes); offsets=list(itertools.accumulate((0,)+sizes))[:-1]
        gens=[tuple(range(n))]
        if len(sizes)>=3 and sizes[0]==sizes[1]:
            g=list(range(n));a=sizes[0]
            for i in range(a):g[offsets[0]+i]=offsets[1]+i;g[offsets[1]+i]=offsets[0]+i
            gens.append(tuple(g))
        if sizes[0]>=2:
            g=list(range(n));g[0],g[1]=g[1],g[0];gens.append(tuple(g))
        if len(sizes)==7:
            g=list(range(n))
            for a,b in ((3,4),(5,6)):
                for i in range(sizes[a]):g[offsets[a]+i]=offsets[b]+i;g[offsets[b]+i]=offsets[a]+i
            gens.append(tuple(g))
        variants=[[],gens[1:2],gens[-1:],gens[1:]]
        if len(sizes)==7:variants.extend([[gens[-1]], [gens[-1],gens[1]]])
        for variant in variants:
            for t in range(2,min(len(sizes)+2,6)):
                z=run_case(sizes,t,variant)
                cases.append(z)
                if sizes==(2,2,2,2,2,2,2) and t==5 and tuple(z[4])==(1,1,1,2,2):
                    assert z[-1]=={1:1,2:2}
                    print('MIXED_DIMENSION_EXAMPLE_OK',z)
    # Special empty fixed case: 3-cycle permuting three parts.
    n=6;cycle=(2,3,4,5,0,1)
    z=run_case((2,2,2),3,[cycle]);assert z[-1]=={-1:1};print('EMPTY_FIXED_LOCUS_OK',z)
    print('PARAMETER_GROUP_CASES',len(cases))
    print('TOTAL_ORBIT_FACES',sum(z[5] for z in cases))
    print('ALL_VERIFY_OK')
if __name__=='__main__':main()
