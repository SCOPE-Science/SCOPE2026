#!/usr/bin/env python3
"""Exact orbit-face checks for coordinate-transitive scale-two binary-cube Rips fixed spaces."""
from itertools import combinations


def permute_bits(mask, perm):
    return sum(((mask >> i) & 1) << perm[i] for i in range(len(perm)))


def orbits_on(values, generators, action):
    unseen = set(values)
    answer = []
    while unseen:
        seed = min(unseen)
        orbit = {seed}
        queue = [seed]
        for x in queue:
            for p in generators:
                y = action(x, p)
                if y not in orbit:
                    orbit.add(y)
                    queue.append(y)
        unseen.difference_update(orbit)
        answer.append(frozenset(orbit))
    return answer


def choices(n):
    unit = tuple(range(n))
    if n == 1:
        yield 'trivial', [unit]
        return
    cyclic = tuple((i + 1) % n for i in range(n))
    flip = tuple(n - 1 - i for i in range(n))
    swap = tuple([1, 0] + list(range(2, n)))
    yield 'cyclic', [cyclic]
    yield 'dihedral', [cyclic, flip]
    yield 'symmetric', [cyclic, swap]
    if n >= 3:
        three = tuple([1, 2, 0] + list(range(3, n)))
        # A_n from conjugating an initial 3-cycle by a long cycle.
        if n % 2 == 1:
            yield 'alternating', [cyclic, three]
        else:
            two = tuple([1, 2, 0, 3] + list(range(4, n)))
            gen = tuple((i+2) % n for i in range(n))
            # A_n generated by adjacent 3-cycles.
            generators = [tuple(list(range(i)) + [i+1, i+2, i] + list(range(i+3,n))) for i in range(n-2)]
            yield 'alternating', generators
    if n % 2 == 0 and n >= 4:
        rotate_pairs = tuple(2*((i//2+1)%(n//2)) + i%2 for i in range(n))
        within_pair = tuple([1, 0] + list(range(2,n)))
        yield 'imprimitive_pairs', [rotate_pairs, within_pair]
    if n == 4:
        yield 'klein_four', [(1,0,3,2), (2,3,0,1)]


def rank_mod2(rows):
    pivots = {}
    for row in rows:
        x = row
        while x:
            p = x.bit_length()-1
            if p in pivots:
                x ^= pivots[p]
            else:
                pivots[p] = x
                break
    return len(pivots)


def betti_from_faces(faces):
    fs = {d: sorted([f for f in faces if len(f)==d+1]) for d in range(max(map(len, faces)))}
    ranks = {}
    for d in range(1, max(fs)+1):
        low = {f:i for i,f in enumerate(fs[d-1])}
        rows = [sum(1 << low[tuple(v for v in f if v!=omit)] for omit in f) for f in fs[d]]
        ranks[d] = rank_mod2(rows)
    betti = [len(fs[d])-ranks.get(d,0)-ranks.get(d+1,0) for d in range(max(fs)+1)]
    while len(betti)>1 and betti[-1]==0:
        betti.pop()
    return tuple(betti)


def classify(n, generators):
    coord_orbit = orbits_on(range(n), generators, lambda x,p:p[x])
    assert len(coord_orbit) == 1, (n, 'nontransitive')
    ors = orbits_on(range(1<<n), generators, permute_bits)
    admissible = [o for o in ors if all((a^b).bit_count()<=2 for a in o for b in o)]
    faces = {()}
    for d in range(1,len(admissible)+1):
        for face in combinations(range(len(admissible)),d):
            union = set().union(*(admissible[i] for i in face))
            if all((a^b).bit_count()<=2 for a in union for b in union):
                faces.add(face)
    actual = betti_from_faces(faces)
    # Ordinary non-reduced Betti: interval/disk (1,), circle (1,1), two intervals (2,).
    predicted = (1,) if n <=2 else ((1,1) if n==3 else (2,))
    assert actual == predicted, (n, actual, predicted)
    sizes = sorted(len(o) for o in admissible)
    assert sizes == (sorted([1,1]) if n==1 else sorted([1,1,n] if n==2 else [1,1,n,n])), (n,sizes)
    exp_faces = 4 if n==1 else (8 if n==2 else 9 if n==3 else 7)
    # For n=3: 1 empty +4 singletons +4 edges =9; n>=4: 1 +4 +2=7.
    assert len(faces)==exp_faces,(n,len(faces),exp_faces)
    return len(ors),len(admissible),len(faces),actual


def main():
    total=0
    for n in range(1,9):
        for name,gens in choices(n):
            data=classify(n,gens)
            total+=1
            print('CASE',n,name,'orbits',data[0],'admissible',data[1], 'faces',data[2], 'betti',data[3])
    print('ALL_VERIFY_OK cases='+str(total))

if __name__ == '__main__': main()
