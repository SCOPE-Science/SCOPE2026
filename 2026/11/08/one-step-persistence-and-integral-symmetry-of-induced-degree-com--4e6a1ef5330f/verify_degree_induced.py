"""Exact independent finite checks for induced-degree-bounded vertex complexes.
Only uses Python's standard library; certificates are finite, not a substitute for a uniform proof.
"""
from itertools import combinations, permutations, product
from math import comb

def faces(m,n,r):
    out={-1:[()]}
    for size in range(1,m+n+1):
        q=[]
        for s in combinations(range(m+n),size):
            a=sum(i<m for i in s); b=size-a
            if not a or not b or max(a,b)<=r: q.append(s)
        if q: out[size-1]=q
    return out

def rank_mod(vectors,p):
    piv={}; rank=0
    for v in vectors:
        v={i:x%p for i,x in v.items() if x%p}
        while v:
            j=min(v)
            if j not in piv:
                fac=pow(v[j],-1,p)
                piv[j]={i:(x*fac)%p for i,x in v.items()}
                rank+=1; break
            a=v[j]
            for i,x in piv[j].items():
                y=(v.get(i,0)-a*x)%p
                if y:v[i]=y
                else:v.pop(i,None)
    return rank

def betti(m,n,r,p):
    fs=faces(m,n,r); maxd=max(fs)
    ranks={maxd+1:0,-1:0}
    for d in range(maxd+1):
        prev={s:i for i,s in enumerate(fs[d-1])}
        cols=[]
        for s in fs[d]:
            cols.append({prev[s[:j]+s[j+1:]]:(-1)**j for j in range(len(s))})
        ranks[d]=rank_mod(cols,p)
    return [len(fs.get(d,[]))-ranks.get(d,0)-ranks.get(d+1,0) for d in range(maxd+1)]

def aug_wedge_chi(perm,r):
    # exact elementary-symmetric character via det(1+z P)/(1+z)
    n=len(perm); lengths=[]; seen=set()
    for i in range(n):
        if i in seen:continue
        j=i; length=0
        while j not in seen:
            seen.add(j);length+=1;j=perm[j]
        lengths.append(length)
    coeff=[1]+[0]*r
    for length in lengths:
        for i in range(r,length-1,-1):
            coeff[i]+=((-1)**(length-1))*coeff[i-length]
    # divide by 1+z
    q=0
    for c in coeff: q=c-q
    return q

def act(verts,m,n,pa,pb,swap=False):
    if swap:
        assert m==n
        return [(m+pb[i] if i<m else pa[i-m]) for i in verts]
    return [(pa[i] if i<m else m+pb[i-m]) for i in verts]

def parity(values):
    inversions=sum(values[i]>values[j] for i in range(len(values)) for j in range(i+1,len(values)))
    return (-1)**inversions

def lefschetz(m,n,r,pa,pb,swap=False):
    value=0
    for d,simplices in faces(m,n,r).items():
        for s in simplices:
            img=act(s,m,n,pa,pb,swap)
            if sorted(img)!=list(s):continue
            value+=(-1)**d*parity(img)
    return value

def comp(p,q):
    return tuple(p[q[i]] for i in range(len(p)))

