"""Reproducibility checks for sharp sign-area bounds on quadratic spherical harmonics.

Analytical universal arguments are in RESULT.md. Finite checks below do not prove them.
"""
from fractions import Fraction
from math import cos, sin, pi, sqrt, asin

# Exact endpoint algebra and normalization.
assert Fraction(1, 2) + Fraction(1, 2) - 1 == 0
assert Fraction(1, 1) + 0 - 1 == 0
assert abs((2 / pi) * asin(1 / sqrt(2)) - .5) < 3e-15
assert abs(sqrt(Fraction(1, 2) / Fraction(3, 2)) - 1 / sqrt(3)) < 1e-15
print('EXACT_ENDPOINT_REDUCTIONS_OK')

# Exact calculation for the curvature lower bound from g''(1).
# -g''(c)=(1+4c)/(4*c^(3/2)*(1+c)^(5/2)).
assert abs(5 / (4 * 2**2.5) - 5 / (16*sqrt(2))) < 1e-15
print('CURVATURE_BOUND_ENDPOINT_IDENTITY_OK')

def H(u, n=120000):
    h = 2*pi/n
    vals = 0.0
    for j in range(n):
        t=(j+.5)*h
        c=u*cos(t)**2+(1-u)*sin(t)**2
        vals += sqrt(c/(1+c))
    return vals/n

xs=[.5,.55,.65,.75,.85,.95,1.0]
ys=[H(u) for u in xs]
assert abs(ys[0]-1/sqrt(3)) < 2e-12
assert abs(ys[-1]-.5) < 2e-10
assert all(ys[i] > ys[i+1] for i in range(len(ys)-1))
k=5/(64*sqrt(2))
for u,y in zip(xs,ys):
    assert 1/sqrt(3)-y + 1e-12 >= k*(u-.5)**2
    assert .5-1e-10 <= y <= 1/sqrt(3)+1e-10
    assert 1-1/sqrt(3)-1e-10 <= 1-y <= .5+1e-10
print('INDEPENDENT_ANGULAR_PROFILE_AND_RIGIDITY_CHECKS_OK',len(xs))

# Independent sphere integral with a Fibonacci grid, whose points are not
# generated by the conditional-angle formula used in the proof.
N=400001
a=(sqrt(5)-1)/2
for u in (.5,.71,.91,1):
    cnt=0
    for j in range(N):
        z=-1+2*(j+.5)/N
        ang=2*pi*((j*a)%1)
        x=sqrt(1-z*z)*cos(ang)
        y=sqrt(1-z*z)*sin(ang)
        q=u*x*x+(1-u)*y*y-z*z
        if q>0: cnt+=1
    assert abs(cnt/N-H(u,100000))<.00008, (u,cnt/N,H(u,100000))
print('INDEPENDENT_SPHERE_AREA_INTEGRATION_OK',4)
print('ALL_QUADRATIC_SPHERICAL_SIGN_AREA_CHECKS_OK')
