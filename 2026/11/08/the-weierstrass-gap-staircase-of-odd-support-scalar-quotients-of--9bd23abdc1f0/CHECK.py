#!/usr/bin/env python3
"""Exact-arithmetic checks of the marked pole semigroup formulas.

This finite computation supplements the general invariant-ring proof.
No external packages or files are required.
"""
from math import gcd


def one_case(r, h):
    assert r >= 3 and r % 2 == 1 and h >= 1
    d, t, N = r - 1, (r - 1) // 2, r**h + 1
    S = (r**(h-1) - 1) // d
    assert (r**(h-1) - 1) % d == 0
    L = r*S - 1
    q = []
    for j in range(r):
        i = (-2*j) % d
        num = r*i + N*j
        assert num % d == 0
        w = num // d
        q.append(w)
        if j:
            expected = r*(j*S + int(j > t)) + (r-j)
        else:
            expected = 0
        assert w == expected, (r, h, j, w, expected)
    assert len({w % r for w in q}) == r
    apery = {w % r: w for w in q}
    contains = lambda z: z >= 0 and z >= apery[z % r]
    generators = [r] + q[1:t+1]
    assert all(g > 0 for g in generators) and gcd(*generators) == 1
    # The pole-order union is exactly the monoid generated by this list:
    # one inclusion uses q_{t+b}=q_t+q_b, q_{2t}=2q_t;
    # the other follows from the Apéry representation and closure.
    for j in range(1, t):
        assert q[t+j] == q[t] + q[j]
    assert q[2*t] == 2*q[t]
    # Independent numerical-semigroup membership enumeration (small cases).
    if r <= 11 and h <= 3:
        upper = max(q) + r
        dp = [False]*(upper+1)
        dp[0] = True
        for z in range(1, upper+1):
            dp[z] = any(z >= g and dp[z-g] for g in generators)
            assert dp[z] == contains(z), (r, h, z)
    ns = [0] + [j*S + int(j > t) for j in range(1, r)]
    genus = sum(ns)
    assert genus == (r**h - 1)//2
    gap_sum = sum(n*(r-j) + r*n*(n-1)//2 for j,n in enumerate(ns) if j)
    weight = gap_sum - genus*(genus+1)//2
    numer = r*(r+1)*(r**(h-1)-1)*(r**h-1)
    denom = 24*(r-1)
    assert numer % denom == 0
    assert weight == numer // denom
    possible = [w-r for w in q if w > 0 and not contains(w-r)]
    pf = [w for w in possible if all(contains(w+g) for g in generators)]
    expected_pf = [q[j]-r for j in range(t+1, r)]
    assert sorted(pf) == sorted(expected_pf), (r,h,pf,expected_pf)
    assert len(pf) == t
    f = max(pf)
    assert all(contains(z) for z in range(f+1, f+r+1))
    if h == 1:
        assert f == t
    else:
        assert f == r**h + 1 - r
    # Check minimality against all other generators by DP for bounded samples.
    if r <= 11 and h <= 3:
        for g in generators:
            alt = [x for x in generators if x != g]
            available = bytearray(g+1)
            available[0] = 1
            for v in range(1,g+1):
                available[v] = any(v >= x and available[v-x] for x in alt)
            assert not available[g], (r,h,g)
    return genus, len(pf), weight, f, generators


def run():
    count = 0
    for r in (3,5,7,9,11,13,25):
        for h in (1,2,3,4):
            genus, typ, weight, f, generators = one_case(r, h)
            count += 1
            if r in (3,5,7,9) and h in (1,2,3):
                print(f"r={r} h={h} genus={genus} type={typ} weight={weight} Frobenius={f}")
    print(f"APERY_GAPS_PSEUDOFROBENIUS_WEIGHTS_OK {count}")
    print("CERTIFICATE_OK")

if __name__ == '__main__':
    run()
