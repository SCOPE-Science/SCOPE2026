"""Exhaustive tests for transitive bipartite matching-complex fixed points.

Pure standard Python; the tests compare invariant ordinary rook matchings
with matchings predicted from complete edge orbits, for invariant bipartite
edge sets in small nonidentical/equal transitive permutation actions.
"""
from itertools import permutations, product


def compose(a,b):
    return tuple(a[b[i]] for i in range(len(a)))


def generate_group(generators):
    m=len(generators[0][0]); n=len(generators[0][1])
    ident=(tuple(range(m)),tuple(range(n)))
    out={ident}; stack=[ident]
    while stack:
        x,y=stack.pop()
        for p,q in generators:
            nxt=(compose(p,x),compose(q,y))
            if nxt not in out:
                out.add(nxt);stack.append(nxt)
    return out


def edge_orbits(group,m,n):
    remaining={(i,j) for i in range(m) for j in range(n)}
    orbits=[]
    while remaining:
        seed=next(iter(remaining))
        orb=frozenset((p[seed[0]],q[seed[1]]) for p,q in group)
        assert orb <= remaining
        orbits.append(orb)
        remaining -= orb
    return orbits


def matchings(edges,m,n):
    edge_list=sorted(edges)
    out={frozenset()}
    for e in edge_list:
        out |= {f|frozenset([e]) for f in tuple(out) if all(x!=e[0] and y!=e[1] for x,y in f)}
    return out


def check_action(gens):
    group=generate_group(gens)
    m=len(gens[0][0]); n=len(gens[0][1])
    assert {p[0] for p,q in group}==set(range(m))
    assert {q[0] for p,q in group}==set(range(n))
    orbits=edge_orbits(group,m,n)
    graph_count=0; matched_orbits=0
    for mask in range(1<<len(orbits)):
        edge_set=frozenset(x for idx,o in enumerate(orbits) if mask>>idx&1 for x in o)
        valid=[o for o in orbits if o <= edge_set and len({x for x,y in o})==len(o) and len({y for x,y in o})==len(o)]
        assert len(valid)==0 if m!=n else True
        all_matchings=matchings(edge_set,m,n)
        invariant={f for f in all_matchings if all(frozenset((p[i],q[j]) for i,j in f)==f for p,q in group)}
        assert invariant == {frozenset()} | set(valid), (gens,mask,invariant,valid)
        bijections=[o for o in valid if len(o)==m==n]
        assert len(valid)==len(bijections)
        graph_count+=1; matched_orbits+=len(valid)
    return graph_count,matched_orbits,len(group)


def cycle(n):
    return tuple((i+1)%n for i in range(n))


def main():
    actions=0; graphs=0; admissible=0; group_sum=0
    # All generated cyclic transitive actions with shores up to four vertices.
    for m,n in product(range(1,5),repeat=2):
        gm=cycle(m); gn=cycle(n)
        g,a,s=check_action([(gm,gn)])
        actions+=1;graphs+=g;admissible+=a;group_sum+=s
    # Diagonal cyclic and symmetric groups on 2..6 points.
    for n in range(2,7):
        rho=cycle(n)
        g,a,s=check_action([(rho,rho)])
        actions+=1;graphs+=g;admissible+=a;group_sum+=s
        transposition=tuple((1 if i==0 else 0 if i==1 else i) for i in range(n))
        g,a,s=check_action([(rho,rho),(transposition,transposition)])
        actions+=1;graphs+=g;admissible+=a;group_sum+=s
    # A regular Klein-four example (not generated by a 4-cycle).
    a=(1,0,3,2);b=(2,3,0,1)
    g,h,s=check_action([(a,a),(b,b)])
    actions+=1;graphs+=g;admissible+=h;group_sum+=s
    # Dihedral action on four vertices.
    ref=(0,3,2,1)
    g,h,s=check_action([(cycle(4),cycle(4)),(ref,ref)])
    actions+=1;graphs+=g;admissible+=h;group_sum+=s
    print('ALL_VERIFY_OK actions',actions,'invariant_graphs',graphs,'valid_orbit_samples',admissible,'group_sizes_sum',group_sum)
    # Explicit centralizer checks for all transitive cyclic and full symmetric actions.
    for n in range(1,7):
        for gens in [[(cycle(n),cycle(n))],[(cycle(n),cycle(n)),
                    (tuple((1 if i==0 else 0 if i==1 else i) for i in range(n)),)*2]] if n>=2 else [[(cycle(1),cycle(1))]]:
            group=generate_group(gens)
            orbits=edge_orbits(group,n,n)
            rook_orbits=[o for o in orbits if len(o)==n]
            centralizer=[p for p in permutations(range(n)) if all(compose(p,g[0])==compose(g[0],p) for g in group)]
            assert len(rook_orbits)==len(centralizer),(n,len(rook_orbits),len(centralizer))
    print('CENTRALIZER_VERIFY_OK degrees_1_to_6')


if __name__=='__main__':
    main()
