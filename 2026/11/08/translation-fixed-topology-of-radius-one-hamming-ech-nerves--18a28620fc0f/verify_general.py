"""Exhaustive fixed-orbit nerve check for additive Hamming products.

The test constructs the original radius-one graph-ball nerve and subgroup
cosets independently of the asserted component classification.
"""
from itertools import product
from collections import deque
from math import prod


def plus(x, y, shape):
    return tuple((a+b) % m for a,b,m in zip(x,y,shape))


def subgroups(shape):
    group = list(product(*[range(m) for m in shape]))
    identity = tuple(0 for _ in shape)
    done={frozenset([identity])}
    order=[frozenset([identity])]
    for h in order:
        for v in group:
            if v in h:
                continue
            # closure generated by H and v, with no field assumption
            acc=set(h)
            frontier=list(h)
            while frontier:
                x=frontier.pop()
                y=plus(x,v,shape)
                if y not in acc:
                    acc.add(y)
                    frontier.append(y)
            ext=frozenset(acc)
            if ext not in done:
                done.add(ext);order.append(ext)
    return group, order


def ball(c,shape):
    out={c}
    for i,m in enumerate(shape):
        for a in range(m):
            y=list(c);y[i]=a;out.add(tuple(y))
    return out


def predicted(h,shape):
    if len(h)==1:
        return None
    occupied={i for v in h for i,a in enumerate(v) if a}
    if len(occupied)==1:
        i=next(iter(occupied))
        return (prod(shape)//shape[i],shape[i]//len(h))
    if len(h)==2 and len(occupied)==2:
        return (prod(shape)//2,1)
    return (0,0)


def check(shape):
    g,spaces=subgroups(shape)
    checked=0
    for h in spaces:
        if len(h)==1:
            continue
        cosets=set(frozenset(plus(x,v,shape) for v in h) for x in g)
        supports=[]
        for c in g:
            b=ball(c,shape)
            supports.append(frozenset(O for O in cosets if O <= b))
        allowable=set().union(*supports)
        # graph components of orbit-complex: an edge is any pair of orbits in a ball
        adj={o:{o} for o in allowable}
        for s in supports:
            for o in s:
                adj[o].update(s)
        components=[]
        remaining=set(allowable)
        while remaining:
            root=remaining.pop()
            seen={root};frontier=[root]
            while frontier:
                for nxt in adj[frontier.pop()]:
                    if nxt not in seen:
                        seen.add(nxt);frontier.append(nxt)
            remaining-=seen
            components.append(seen)
        guess=predicted(h,shape)
        assert len(components)==guess[0],(shape,sorted(h),len(components),guess)
        assert all(len(s)==guess[1] for s in components),(shape,sorted(h),[len(s) for s in components],guess)
        for part in components:
            # all-orbits simplex, not merely connected component
            assert any(part <= s for s in supports), (shape,sorted(h),part)
        checked+=1
    return checked,len(spaces)


def main():
    shapes=[(2,2),(2,3),(3,3),(2,4),(3,4),(4,4),(2,2,2),(2,2,3),(2,2,4),(2,3,3),(2,2,2,2),(2,6),(3,6),(4,6)]
    count=0
    for shape in shapes:
        c,s=check(shape)
        print('factors=%s subgroup_count=%d nontrivial=%d PASS' % (shape,s,c))
        count+=c
    print('ALL_VERIFY_OK nontrivial_subgroups=%d' % count)

if __name__=='__main__':
    main()
