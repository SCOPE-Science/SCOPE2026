#!/usr/bin/env python3
"""Exact characteristic-two identities and finite-field Cartier rank checks.

The formal ideal is (y^2+y+t^3, v^2+v+y^3+c^2*y).
GF(4) is represented using alpha^2+alpha+1=0.
"""
from itertools import product

# Binary sparse polynomials in t,y,v,c; coefficients are in F_2.
def mon(t=0, y=0, v=0, c=0):
    return frozenset({(t,y,v,c)})
def add(*terms):
    out=set()
    for term in terms:
        out.symmetric_difference_update(term)
    return frozenset(out)
def mul(a,b):
    out=set()
    for i in a:
        for j in b:
            z=tuple(i[k]+j[k] for k in range(4))
            if z in out: out.remove(z)
            else: out.add(z)
    return frozenset(out)
def pw(a,n):
    r=mon()
    while n:
        if n&1:r=mul(r,a)
        a=mul(a,a);n>>=1
    return r
T,Y,V,C=mon(t=1),mon(y=1),mon(v=1),mon(c=1)
def reduce_poly(p):
    a=set(p)
    while True:
        bad=next((z for z in a if z[2]>=2 or z[1]>=2),None)
        if bad is None: return frozenset(a)
        a.remove(bad)
        t,y,v,c=bad
        if v>=2:
            # v^2 = v+y^3+c^2*y
            new=add(mon(t,y,v-1,c),mon(t,y+3,v-2,c),mon(t,y+1,v-2,c+2))
        else:
            # y^2 = y+t^3
            new=add(mon(t,y-1,v,c),mon(t+3,y-2,v,c))
        a.symmetric_difference_update(new)
def check(lhs,rhs,label):
    assert not reduce_poly(add(lhs,rhs)), label

def expr_sq_plus_t(a,b):return add(pw(a,2),mul(T,pw(b,2)))

check(pw(Y,2),add(Y,pw(T,3)),"first Artin-Schreier equation")
check(pw(V,2),add(V,pw(Y,3),mul(pw(C,2),Y)),"second Artin-Schreier equation")
check(pw(Y,3),expr_sq_plus_t(add(Y,pw(T,3)),mul(T,Y)),"decomposition of y^3")
check(Y,expr_sq_plus_t(Y,T),"decomposition of y")
check(mul(T,Y),expr_sq_plus_t(pw(T,2),Y),"decomposition of ty")  # t*y = t^4+t*y^2
check(V,expr_sq_plus_t(add(V,Y,pw(T,3),mul(C,Y)),mul(T,add(Y,C))),"decomposition of v")
print("FORMAL_CHAR2_POLYNOMIAL_IDENTITIES_OK")

def gf_mul(x,y):
    val=0
    for i in range(2):
        for j in range(2):
            if ((x>>i)&1) and ((y>>j)&1): val^=1<<(i+j)
    if val&4:val^=7
    return val
def gf_sq(x):return gf_mul(x,x)
def gf_root(x):return gf_sq(gf_sq(x))
def gf_inv(x):
    assert x
    for v in (1,2,3):
        if gf_mul(v,x)==1:return v
    raise ValueError
# Coordinates: dt, t dt, y dt, t^2 dt, v dt, ty dt
# C images are: 0, dt, t dt, 0, ty dt + c*t dt, y dt.
def cart(vec,c):
    r=[0]*6
    r[0]=gf_root(vec[1]);r[1]=gf_root(vec[2])^gf_mul(gf_root(vec[4]),c)
    r[2]=gf_root(vec[5]);r[5]=gf_root(vec[4]);return r

def rank(vectors):
    a=[list(v) for v in vectors]
    m=0
    for j in range(6):
        k=next((i for i in range(m,len(a)) if a[i][j]),None)
        if k is None:continue
        a[m],a[k]=a[k],a[m]
        scale=gf_inv(a[m][j]);a[m]=[gf_mul(v,scale) for v in a[m]]
        for i in range(len(a)):
            if i!=m and a[i][j]:
                scale=a[i][j];a[i]=[v^gf_mul(scale,w) for v,w in zip(a[i],a[m])]
        m+=1
        if m==len(a):break
    return m
for c in range(4):
    vectors=[[int(i==j) for i in range(6)] for j in range(6)]
    ranks=[rank(vectors)]
    for power in range(1,6):
        vectors=[cart(v,c) for v in vectors]
        ranks.append(rank(vectors))
    assert ranks==[6,4,3,2,1,0],(c,ranks)
print("GF4_CARTIER_POWER_RANKS_OK 6,4,3,2,1,0 (4 parameter values)")
# Semigroup generated by pole orders 4,6,9 has exactly six gaps.
S={4*a+6*b+9*c for a,b,c in product(range(6),repeat=3)}
gaps=[i for i in range(1,12) if i not in S]
assert gaps==[1,2,3,5,7,11],gaps
assert all(i in S for i in range(12,24))
print("WEIERSTRASS_SEMIGROUP_GAPS_OK 1,2,3,5,7,11")
print("CERTIFICATE_OK")
