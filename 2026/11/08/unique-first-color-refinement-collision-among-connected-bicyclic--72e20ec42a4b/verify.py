"""Exact finite census of connected simple bicyclic graphs through six vertices.
Pure Python 3, no external graph library. All graphs generated by edge masks.
"""
from itertools import combinations,permutations
from collections import Counter,defaultdict

def connected(a):
    seen=1
    while True:
        new=seen
        for i,nb in enumerate(a):
            if seen>>i & 1:new|=nb
        if new==seen:return seen==(1<<len(a))-1
        seen=new

def wl(a,intern):
    n=len(a);cs=(0,)*n
    for t in range(n):
        ss=[]
        for i in range(n):
            ss.append((t,cs[i],tuple(sorted(cs[j] for j in range(n) if a[i]>>j&1))))
        cs=tuple(intern.setdefault(s,len(intern)) for s in ss)
    return tuple(sorted(Counter(cs).items()))

def isomorphic(a,b):
    n=len(a)
    da=[v.bit_count() for v in a];db=[v.bit_count() for v in b]
    if sorted(da)!=sorted(db):return False
    options=[[j for j in range(n) if db[j]==da[i]] for i in range(n)]
    order=sorted(range(n),key=lambda i:(len(options[i]),-da[i]))
    mapping={};used=set()
    def rec(k):
        if k==n:return True
        i=order[k]
        for j in options[i]:
            if j in used:continue
            if any(((a[i]>>ii)&1)!=((b[j]>>jj)&1) for ii,jj in mapping.items()):continue
            used.add(j);mapping[i]=j
            if rec(k+1):return True
            used.remove(j);del mapping[i]
        return False
    return rec(0)

def count_triangles(a):
    n=len(a)
    return sum((a[i]>>j&1) and (a[i]>>k&1) and (a[j]>>k&1)
               for i in range(n) for j in range(i+1,n) for k in range(j+1,n))

def census(n):
    edges=list(combinations(range(n),2));sigs=defaultdict(list);intern={}
    for selection in combinations(range(len(edges)),n+1):
        aa=[0]*n
        for z in selection:
            i,j=edges[z];aa[i]|=1<<j;aa[j]|=1<<i
        a=tuple(aa)
        if not connected(a):continue
        sigs[wl(a,intern)].append(a)
    reps=defaultdict(list)
    for s,ls in sigs.items():
        for a in ls:
            if not any(isomorphic(a,b) for b in reps[s]):reps[s].append(a)
    types=sum(len(v) for v in reps.values())
    bad=[v for v in reps.values() if len(v)>1]
    return types,len(reps),[[count_triangles(a) for a in v] for v in bad]

if __name__=='__main__':
    for n in (4,5,6):print(n,*census(n),flush=True)
    assert census(4)==(1,1,[])
    assert census(5)==(5,5,[])
    assert census(6)==(19,18,[[0,2]]) or census(6)==(19,18,[[2,0]])
    print('CENSUS_OK')

def pair(t,variant):
    n=6+t;a=[0]*n
    def edge(i,j):a[i]|=1<<j;a[j]|=1<<i
    for i,j in ((0,2),(0,3),(1,4),(1,5)):edge(i,j)
    for i,j in (((2,3),(4,5)) if variant==0 else ((2,4),(3,5))):edge(i,j)
    path=[0]+list(range(6,n))+[1]
    for i,j in zip(path,path[1:]):edge(i,j)
    return tuple(a)

