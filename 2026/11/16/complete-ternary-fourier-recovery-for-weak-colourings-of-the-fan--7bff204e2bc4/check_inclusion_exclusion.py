#!/usr/bin/env python3
"""Independent character-counting by hyperedge inclusion-exclusion and Fano orbits."""
from collections import Counter
from itertools import product

edges=tuple(sorted({tuple(sorted((a-1,b-1,(a^b)-1))) for a in range(1,8) for b in range(a+1,8)}))
assert len(edges)==7

def charge(z):
    return tuple((z//(3**j))%3 for j in range(7))

def integer(z):
    return sum(z[j]*3**j for j in range(7))

# For a subset of monochromatic constraints, union each line into one color component.
# Every component contributes either 3 (if its total character charge is 0)
# or 0. All coefficients are ordinary integers, without complex rounding.
component_partitions=[]
for mask in range(128):
    parent=list(range(7))
    def root(a):
        while parent[a]!=a:
            a=parent[a]
        return a
    for j,(a,b,c) in enumerate(edges):
        if (mask>>j)&1:
            parent[root(b)]=root(a)
            parent[root(c)]=root(a)
    classes={}
    for a in range(7):
        classes.setdefault(root(a),[]).append(a)
    cc=tuple(tuple(z) for z in classes.values())
    component_partitions.append(((-1)**mask.bit_count()*3**len(cc),cc))

def Fourier(k):
    return sum(weight for weight,parts in component_partitions
               if all(sum(k[i] for i in block)%3==0 for block in parts))

F={}
for z in range(3**7):
    k=charge(z)
    F[z]=Fourier(k)

expected={0:1458,882:1,-171:14,-90:42,72:56,18:252,-9:364}
assert Counter(F.values())==expected, Counter(F.values())
assert all((F[z]==0)==(sum(charge(z))%3!=0) for z in F)

# All 168 invertible linear maps of F_2^3, generated by choices of basis images.
perms=set()
for a,b,c in product(range(1,8),repeat=3):
    if a==b or c in (a,b,a^b):continue
    perms.add(tuple(((a if x&1 else 0)^(b if x&2 else 0)^(c if x&4 else 0))-1 for x in range(1,8)))
assert len(perms)==168

orbit_data=[]; seen=set()
for z in range(3**7):
    k=charge(z)
    if sum(k)%3 or z in seen:continue
    orbit=set()
    for p in perms:
        for scale in (1,2):
            transformed=[0]*7
            for i in range(7):transformed[p[i]]=scale*k[i]%3
            orbit.add(integer(transformed))
    assert all(F[v]==F[z] for v in orbit)
    seen.update(orbit)
    rep=min(orbit)
    orbit_data.append((''.join(map(str,charge(rep))),len(orbit),F[z]))

expected_orbits={
  '0000000':(1,882), '1110000':(14,-171), '2100000':(42,-90),
  '1101000':(56,72), '2211000':(168,18), '0221100':(42,18),
  '2211111':(42,18), '1211100':(168,-9), '2122110':(84,-9),
  '2221110':(56,-9), '2111100':(42,-9), '1111110':(14,-9)}
assert len(orbit_data)==12
assert {rep:(n,v) for rep,n,v in orbit_data}==expected_orbits,orbit_data
assert len(seen)==3**6
print('INCLUSION_EXCLUSION_PASS', 'orbit_classes',len(orbit_data),
      'Fourier_rank',len(seen),'spectrum',sorted(Counter(F.values()).items()))
for rep,n,v in sorted(orbit_data, key=lambda x:(-x[1],x[0])):
    print('ORBIT',rep,n,v)
