"""Exact binary certificate for quadratic sampling on ordinary n-queens boards.

The degree-two Boolean monomial restriction is generated by two-queen
incidence columns. A full row rank over GF(2) is a certificate of full
row rank over the reals; row reduction uses exact arbitrary-size integers.
"""
import json
from collections import Counter
from hashlib import sha256
from itertools import combinations
from pathlib import Path


def queens(n):
    total = (1 << n) - 1
    result = []

    def visit(row, used_columns, used_diff, used_sum, placement):
        if row == n:
            result.append(tuple(placement))
            return
        free = total & ~used_columns
        while free:
            bit = free & -free
            free -= bit
            column = bit.bit_length() - 1
            d = 1 << (row - column + n - 1)
            s = 1 << (row + column)
            if (used_diff & d) or (used_sum & s):
                continue
            placement.append(column)
            visit(row + 1, used_columns | bit, used_diff | d,
                  used_sum | s, placement)
            placement.pop()

    visit(0, 0, 0, 0, [])
    return result


def index(n, i, a, j, b):
    assert i < j and a != b
    row_pair = i * (2 * n - i - 1) // 2 + (j - i - 1)
    return row_pair * n * (n - 1) + a * (n - 1) + b - (b > a)


def row_bits(n, permutation):
    bits = 0
    for i, j in combinations(range(n), 2):
        bits |= 1 << index(n, i, permutation[i], j, permutation[j])
    return bits


def eliminate(rows):
    pivots = {}
    witness = []
    for bits in rows:
        while bits:
            pos = bits.bit_length() - 1
            if pos not in pivots:
                pivots[pos] = bits
                witness.append(pos)
                break
            bits ^= pivots[pos]
        else:
            witness.append(None)
    return len(pivots), witness


def checks():
    observations = []
    certificate = {}
    for n in range(4, 13):
        sols = queens(n)
        obs = {'n': n, 'solutions': len(sols)}
        counts = Counter((i, p[i], j, p[j]) for p in sols
                         for i, j in combinations(range(n), 2))
        obs['used_queen_pairs'] = len(counts)
        obs['minimum_pair_completions'] = min(counts.values())
        obs['singleton_pairs'] = sum(v == 1 for v in counts.values())
        if n <= 11:
            rank, pivots = eliminate(row_bits(n, p) for p in sols)
            obs['pair_incidence_rank_mod2'] = rank
            obs['full_rank'] = rank == len(sols)
            if n >= 7:
                assert rank == len(sols), (n, rank, len(sols))
                certificate[str(n)] = pivots
        observations.append(obs)
    assert [x['solutions'] for x in observations] == [2, 10, 4, 40, 92, 352, 724, 2680, 14200]
    assert observations[-2]['minimum_pair_completions'] == 2
    assert observations[-2]['singleton_pairs'] == 0
    assert observations[-1]['solutions'] > 12 * 11 * 66
    out = {'observations': observations,
           'n12_degree2_dimension_upper_bound': 12 * 11 * 66,
           'n12_minimum_nullity': 14200 - 12 * 11 * 66,
           'certificate': certificate}
    return out


if __name__ == '__main__':
    output = checks()
    here = Path(__file__).resolve().parent
    (here / 'rank_certificate.json').write_text(
        json.dumps(output, separators=(',', ':'), ensure_ascii=False) + '\n',
        encoding='utf-8')
    print(json.dumps({'observations': output['observations'],
                      'n12_degree2_dimension_upper_bound': output['n12_degree2_dimension_upper_bound'],
                      'n12_minimum_nullity': output['n12_minimum_nullity'],
                      'certificate_sha256': sha256((here / 'rank_certificate.json').read_bytes()).hexdigest()},
                     separators=(',', ':'), ensure_ascii=False))
