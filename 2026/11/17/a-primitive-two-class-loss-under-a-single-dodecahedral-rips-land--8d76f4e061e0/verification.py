#!/usr/bin/env python3
"""Deterministic independent face enumeration and complete directed-Hasse tests.
Run with Python 3; no external packages are required.
"""
from collections import Counter, deque

N=20
EDGES=set()
def add(a,b): EDGES.add(tuple(sorted((a,b))))
for i in range(10):
    add(i,(i+1)%10)
    add(i,10+i)
    add(10+i,10+(i+2)%10)
assert len(EDGES)==30
# Rotation and one outer-to-inner symmetry generate a vertex-transitive action.
ROT=[(i+1)%10 if i<10 else 10+(i-9)%10 for i in range(N)]
SWAP=[10,0,1,11,13,15,5,6,16,18,12,9,2,19,3,17,4,7,14,8]
for perm in (ROT,SWAP):
    assert sorted(perm)==list(range(N))
    assert {tuple(sorted((perm[a],perm[b]))) for a,b in EDGES}==EDGES
assert SWAP[0]==10
ADJ=[set() for _ in range(N)]
for a,b in EDGES:
    ADJ[a].add(b);ADJ[b].add(a)
DIST=[]
for i in range(N):
    d=[-1]*N;d[i]=0;Q=deque([i])
    while Q:
        x=Q.popleft()
        for y in ADJ[x]:
            if d[y]<0:
                d[y]=d[x]+1;Q.append(y)
    DIST.append(d)
assert Counter(DIST[i][j] for i in range(N) for j in range(i+1,N))==Counter({1:30,2:60,3:60,4:30,5:10})

def complex_at(radius):
    # Every clique is generated by adjoining vertices in increasing order.
    faces={1<<i for i in range(N)}
    queue=list(faces)
    for sigma in queue:
        top=sigma.bit_length()
        for v in range(top,N):
            if all(DIST[v][u]<=radius for u in range(N) if sigma&(1<<u)):
                candidate=sigma|(1<<v)
                faces.add(candidate);queue.append(candidate)
    assert len(queue)==len(faces)
    return faces

def matching(faces, order):
    remaining=set(faces);pairs=set()
    for vertex in order:
        bit=1<<vertex
        lower=[s for s in remaining if s&bit==0 and s|bit in remaining]
        for low in lower:
            high=low|bit
            assert low in remaining and high in remaining
            remaining.remove(low);remaining.remove(high)
            pairs.add((low,high))
    return pairs,remaining

def certify(faces, order, expected):
    pairs,crit=matching(faces,order)
    assert Counter(s.bit_count()-1 for s in crit)==Counter(expected)
    # Up-arrow for matched Hasse edges, down-arrow for every other Hasse edge.
    indeg={s:0 for s in faces}
    outgoing={s:[] for s in faces}
    covers=0
    for high in faces:
        bits=high
        while bits:
            b=bits&-bits;bits-=b
            low=high^b
            if low==0: continue
            assert low in faces
            if (low,high) in pairs:
                src,dst=low,high
            else:
                src,dst=high,low
            outgoing[src].append(dst);indeg[dst]+=1;covers+=1
    q=deque(s for s,d in indeg.items() if d==0)
    visited=0
    while q:
        x=q.popleft();visited+=1
        for y in outgoing[x]:
            indeg[y]-=1
            if indeg[y]==0:q.append(y)
    assert visited==len(faces), 'a directed Hasse cycle exists'
    return dict(faces=len(faces),pairs=len(pairs),critical=dict(Counter(s.bit_count()-1 for s in crit)),covers=covers,acyclic=True)

if __name__=='__main__':
    F=complex_at(3)
    D={s for s in F if not s&1}
    L={(s^1)>>1 for s in F if s&1 and s!=1}
    assert len(F)==3272 and len(D)==2550 and len(L)==721, (len(F),len(D),len(L))
    assert D.isdisjoint({s for s in F if s&1})
    # The three vertex orders were chosen prior to certification and are explicit data.
    ORDERS={
        'full': list(range(N)),
        'deletion':list(range(N)),
        'link':list(range(N-1)),
    }
    for tag,faces,want in [('full',F,{0:1,3:9}),('deletion',D,{0:1,3:7}),('link',L,{0:1,2:2})]:
        print(tag,certify(faces,ORDERS[tag],want))
