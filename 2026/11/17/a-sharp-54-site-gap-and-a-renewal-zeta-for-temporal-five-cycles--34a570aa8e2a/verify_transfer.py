#!/usr/bin/env python3
"""Exhaustive finite transfer-graph certificate for Rule 22 temporal period five.
Pure Python 3; no external dependencies.
"""
from collections import deque, Counter


def make_graph(T):
    N = 1 << T
    G = [[] for _ in range(N * N)]
    for a in range(N):
        for b in range(N):
            u = a*N+b
            for c in range(N):
                good = True
                for t in range(T):
                    x = (a >> t)&1
                    y = (b >> t)&1
                    z = (c >> t)&1
                    nxt = (b >> ((t+1) % T))&1
                    if ((x+y+z == 1) != bool(nxt)):
                        good = False
                        break
                if good: G[u].append(b*N+c)
    return G


def scc(G):
    N=len(G); seen=[False]*N; order=[]
    for v in range(N):
        if seen[v]:continue
        seen[v]=True; stack=[(v,0)]
        while stack:
            u,i=stack[-1]
            if i>=len(G[u]):
                order.append(u);stack.pop();continue
            w=G[u][i]; stack[-1]=(u,i+1)
            if not seen[w]:seen[w]=True;stack.append((w,0))
    R=[[] for _ in G]
    for u,vs in enumerate(G):
        for v in vs:R[v].append(u)
    seen=[False]*N; comps=[]
    for v in reversed(order):
        if seen[v]:continue
        seen[v]=True; stack=[v]; S=[]
        while stack:
            u=stack.pop();S.append(u)
            for w in R[u]:
                if not seen[w]:seen[w]=True;stack.append(w)
        if len(S)>1 or v in G[v]:comps.append(sorted(S))
    return comps


def simple_cycles(G,S):
    # Every directed simple cycle has one unique least-numbered vertex.
    allowed=set(S); found=[]
    for root in S:
        def visit(u,path,used):
            for v in G[u]:
                if v==root:
                    found.append(tuple(path))
                elif v>root and v in allowed and v not in used:
                    visit(v,path+[v],used|{v})
        visit(root,[root],{root})
    return found


def trace_closed_walks(G,S,limit):
    res=[0]*(limit+1); allowed=set(S)
    for root in S:
        d={root:1}
        for n in range(1,limit+1):
            nxt={}
            for u,count in d.items():
                for v in G[u]:
                    if v in allowed:nxt[v]=nxt.get(v,0)+count
            d=nxt
            res[n]+=d.get(root,0)
    return res


def main():
    G1=make_graph(1); C1=scc(G1)
    assert len(G1)==4
    assert sorted((len(S),len(simple_cycles(G1,S))) for S in C1)==[(1,1),(2,1)]
    G=make_graph(5); comps=scc(G)
    assert len(G)==1024 and sum(map(len,G))==1023
    assert sorted(Counter(map(len,comps)).items())==[(1,1),(2,1),(16,5)]
    large=[]
    for S in comps:
        cyc=simple_cycles(G,S)
        if len(S)==16:
            e=sum(len([v for v in G[u] if v in S]) for u in S)
            assert e==18
            assert sorted(map(len,cyc))==[11,12,13]
            assert set.intersection(*(set(c) for c in cyc))
            large.append(S)
        elif len(S)==2: assert sorted(map(len,cyc))==[2]
        else: assert len(S)==1 and len(cyc)==1 and len(cyc[0])==1
    # The closed-walk generating function of a strongly connected component
    # with three simple cycles sharing a vertex is -zQ'(z)/Q(z),
    # Q=1-z^11-z^12-z^13. Check this independently by direct walks.
    limit=70
    s=[0]*(limit+1)
    for n in range(1,limit+1):
        if n in (11,12,13):s[n]+=n
        if n>13:s[n]+=s[n-11]+s[n-12]+s[n-13]
    for S in large:
        brute=trace_closed_walks(G,S,limit)
        assert brute==s
    # Verify full transfer fixed-point trace for all n up to 70.
    full=[0]*(limit+1)
    for S in comps:
        part=trace_closed_walks(G,S,limit)
        full=[x+y for x,y in zip(full,part)]
    for n in range(1,limit+1):
        assert full[n]==1+2*(n%2==0)+5*s[n]
    gaps=[n for n in range(1,55) if s[n]==0]
    assert gaps==list(range(1,11))+list(range(14,22))+list(range(27,33))+list(range(40,44))+[53,54]
    assert all(s[n]>0 for n in range(55,limit+1))
    print('rule=22 time=5 vertices=1024 edges=1023')
    print('recurrent-components: singleton=1 two-vertex=1 sixteen-vertex=5')
    print('five large components: 18 edges each; three simple cycles of lengths 11,12,13 with a common vertex')
    print('period-five orbit generating function: (11*z^11+12*z^12+13*z^13)/(1-z^11-z^12-z^13)')
    print('positive exactly on additive semigroup generated by 11,12,13; conductor 55')
    print('sample n:C5(n):',','.join(f'{n}:{s[n]}' for n in [11,12,13,22,23,24,25,26,33,39,44,52,53,54,55,56,57,58,60]))
    print('transfer checks=PASS')
if __name__=='__main__':main()
