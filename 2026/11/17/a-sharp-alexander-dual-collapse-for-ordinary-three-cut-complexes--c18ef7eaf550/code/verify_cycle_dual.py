#!/usr/bin/env python3
"""Independent finite verification of a near-pair elementary collapse.
Inputs are positive integers p,n; no external dependencies.
"""
from itertools import combinations
from collections import Counter
import sys

def check(p,n,exhaustive=True):
    assert p>=1 and n>=4*p+1
    vertices=range(n)
    dist=lambda a,b:min((a-b)%n,(b-a)%n)
    adj=lambda a,b:0<dist(a,b)<=p
    nonedges=[(a,b) for a,b in combinations(vertices,2) if not adj(a,b)]
    near=[(a,b) for a,b in nonedges if dist(a,b)<=2*p]
    far=[(a,b) for a,b in nonedges if dist(a,b)>=2*p+1]
    # Directly verify common-neighbor intervals, nonadjacent-edge disjointness.
    near_neigh={}
    for a,b in nonedges:
        common=tuple(x for x in vertices if adj(x,a) and adj(x,b))
        assert all(adj(x,y) for x,y in combinations(common,2))
        assert (len(common)==max(0,2*p-dist(a,b)+1))
        if common:near_neigh[a,b]=common
    assert len(far)==n*(n-4*p-1)//2
    assert len(near)==n*p
    # Independently build the Alexander dual by exclusion of all disconnected triples.
    if exhaustive:
        disconnected=[sum(1<<v for v in t) for t in combinations(vertices,3)
                      if sum(adj(a,b) for a,b in combinations(t,2))<=1]
        K={mask for mask in range(1<<n)
           if all((mask&t)!=t for t in disconnected)}
        X={mask for mask in range(1<<n)
           if all(adj(a,b) for a,b in combinations((i for i in vertices if mask>>i&1),2))}
        Y=X|{(1<<a)|(1<<b) for a,b in far}
        assert Y.issubset(K)
        # Independently derive the new-face decomposition and all collapse pairs.
        all_pairs=[]
        for a,b in near:
            C=near_neigh[a,b]
            pivot=C[0]
            others=[x for x in C if x!=pivot]
            for k in range(len(others),-1,-1):
                for T in combinations(others,k):
                    lo=(1<<a)|(1<<b)|sum(1<<x for x in T)
                    hi=lo|(1<<pivot)
                    all_pairs.append((lo,hi))
        assert len({z for pair in all_pairs for z in pair})==2*len(all_pairs)
        assert {z for pair in all_pairs for z in pair}==K-Y
        active=set(K)
        # Each proposed low face is a free face when its turn arrives.
        for lo,hi in all_pairs:
            assert lo in active and hi in active
            # Any coface of low is generated by an allowable single-vertex extension.
            extensions=[lo |(1<<v) for v in vertices if not(lo>>v&1) and lo|(1<<v) in active]
            assert extensions==[hi],(p,n,lo,hi,extensions)
            active.remove(lo);active.remove(hi)
        assert active==Y
        # The resulting graph Y has connected circle clique subcomplex and M extra chords;
        # verify its Euler characteristic by counting all simplices of the model.
        euler=sum((-1)**(mask.bit_count()-1) for mask in Y if mask)
        assert euler==1-(1+len(far)),(p,n,euler,len(far))
        print(f'p={p} n={n} K_faces={len(K)} X_faces={len(X)} far_chords={len(far)} elementary_pairs={len(all_pairs)} resulting_chi={euler}: PASS')
    else:
        # Check the unique-missing-edge obstruction by direct independent scan of triples.
        for a,b in nonedges:
            common=set(v for v in vertices if adj(v,a) and adj(v,b))
            assert all(adj(x,y) for x,y in combinations(common,2))
        print(f'p={p} n={n} near_nonedges={len(near)} far_chords={len(far)} local_clique_test: PASS')

if __name__=='__main__':
    for p,n in [(1,5),(2,9),(2,10),(2,11),(3,13),(3,14),(4,17)]:
        check(p,n)
    for p,n in [(5,21),(5,22),(6,25),(8,33)]:
        check(p,n,False)
    print('CYCLE_POWER_THREE_CUT_DUAL_COLLAPSE_PASS')
