#include <bits/stdc++.h>
using namespace std;
// All configurations are encoded by the 15 edges of K6 in lexicographic order.
// An edge is adjacent to every disjoint edge; tie means retain the current bit.
int main(){
 vector<pair<int,int>> edge;
 for(int i=0;i<6;i++)for(int j=i+1;j<6;j++)edge.push_back({i,j});
 if(edge.size()!=15) return 1;
 array<int,15> neigh{};
 for(int i=0;i<15;i++)for(int j=0;j<15;j++){
  auto [a,b]=edge[i];auto [c,d]=edge[j];
  if(a!=c&&a!=d&&b!=c&&b!=d)neigh[i]|=(1<<j);
 }
 for(int i=0;i<15;i++)if(__builtin_popcount((unsigned)neigh[i])!=6)return 2;
 constexpr int SZ=32768;
 vector<int> f(SZ);
 for(int x=0;x<SZ;x++){
  int y=0;
  for(int i=0;i<15;i++){
   int k=__builtin_popcount((unsigned)(x&neigh[i]));
   if(k>=4||(k==3&&(x&(1<<i))))y|=1<<i;
  }
  f[x]=y;
 }
 map<pair<int,int>,int> entryPeriod;
 map<int,int> basins;
 map<int,int> representativePeriod;
 bool sharp=false;
 for(int x=0;x<SZ;x++){
  int z=x,t=0;
  for(;t<=3;t++){
   if(f[f[z]]==z) break;
   z=f[z];
  }
  if(t>3){cerr<<"Exceeded cutoff"<<endl;return 3;}
  int p=(f[z]==z?1:2);
  entryPeriod[{t,p}]++;
  int key=min(z,f[z]);
  basins[key]++;
  representativePeriod[key]=p;
  int z2=f[f[x]],z3=f[z2],z4=f[z3],z5=f[z4];
  if(z4!=z2)sharp=true;
  if(z5!=z3){cerr<<"Global iterate identity failed"<<endl;return 4;}
 }
 if(!sharp)return 5;
 map<pair<int,int>,int> basinHist;
 for(auto [key,n]:basins)basinHist[{representativePeriod[key],n}]++;
 // S6 is generated by adjacent transpositions of the six original labels.
 int loc[6][6];for(auto &x:loc)for(int &y:x)y=-1;
 for(int i=0;i<15;i++){auto [a,b]=edge[i];loc[a][b]=loc[b][a]=i;}
 auto permute=[&](int x,int z){
  int ans=0;
  for(int i=0;i<15;i++)if(x&(1<<i)){
   auto [a,b]=edge[i];
   if(a==z)a=z+1;else if(a==z+1)a=z;
   if(b==z)b=z+1;else if(b==z+1)b=z;
   ans|=1<<loc[a][b];
  }
  return ans;
 };
 map<int,int> visited;
 map<pair<int,int>,vector<array<int,5>>> symmetry;
 for(auto [key,basin]:basins){
  if(visited.count(key))continue;
  int p=representativePeriod[key];
  set<int> orbit={key};queue<int> q;q.push(key);
  while(!q.empty()){
   int u=q.front();q.pop();
   for(int z=0;z<5;z++){
    int w=min(permute(u,z),permute(f[u],z));
    if(!basins.count(w)||representativePeriod[w]!=p){cerr<<"Bad symmetry"<<endl;return 6;}
    if(orbit.insert(w).second)q.push(w);
   }
  }
  int minR=*orbit.begin();
  for(int u:orbit)visited[u]=minR;
  int wt=__builtin_popcount((unsigned)minR);
  int wt2=__builtin_popcount((unsigned)f[minR]);
  int flips=__builtin_popcount((unsigned)(minR^f[minR]));
  symmetry[{p,basin}].push_back({(int)orbit.size(),wt,wt2,flips,minR});
 }
 cout<<"states "<<SZ<<"\n";
 for(auto [tp,n]:entryPeriod)cout<<"entry "<<tp.first<<" period "<<tp.second<<" states "<<n<<"\n";
 for(auto [pb,n]:basinHist)cout<<"basin period "<<pb.first<<" size "<<pb.second<<" orbits "<<n<<"\n";
 cout<<"symmetry_classes "<<symmetry.size()<<" grouping_types\n";
 int c1=0,c2=0;
 for(auto [pb,vec]:symmetry){
  sort(vec.begin(),vec.end());
  for(auto a:vec){
   cout<<"sym period "<<pb.first<<" basin "<<pb.second<<" orbit "<<a[0]<<" wt "<<a[1]<<","<<a[2]<<" flips "<<a[3]<<" rep "<<a[4]<<"\n";
   if(pb.first==1)c1++;else c2++;
  }
 }
 cout<<"summary fixed "<<count_if(representativePeriod.begin(),representativePeriod.end(),[](auto &r){return r.second==1;})
 <<" two_orbits "<<count_if(representativePeriod.begin(),representativePeriod.end(),[](auto&r){return r.second==2;})
 <<" geometric_fixed "<<c1<<" geometric_two "<<c2<<" sharp_entry 3\n";
 if(entryPeriod[make_pair(0,1)]!=502||entryPeriod[make_pair(0,2)]!=5340||c1!=8||c2!=18)return 7;
 return 0;
}
