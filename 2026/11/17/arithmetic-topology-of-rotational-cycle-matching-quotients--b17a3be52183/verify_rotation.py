#!/usr/bin/env python3
"""Exact combinatorial checks for rotation quotients of cycle matching complexes.

Uses only Python's standard library. No floating point or inferred topology.
"""
from itertools import combinations
from math import gcd

def independent(mask,n):
    return not (mask & (((mask << 1)|(mask >> (n-1))) & ((1<<n)-1)))

def all_faces(n):
    return [s for s in range(1,1<<n) if independent(s,n)]

def rotate(mask,n,k):
    whole=(1<<n)-1
    k %= n
    return ((mask<<k) | (mask>>(n-k)))&whole if k else mask

def chi(n):
    # exact independent-set alternating sum of all nonempty faces
    return sum((-1)**(m.bit_count()-1) for m in all_faces(n))

def expected_cycle_homology(n):
    k,r=divmod(n,3)
    if r==0:return (k-1,2)
    if r==1:return (k-1,1)
    return (k,1)

def characteristic_sign(mask,n,k):
    inds=[i for i in range(n) if mask>>i&1]
    p=[(i+k)%n for i in inds]
    inversions=sum(p[i]>p[j] for i in range(len(p)) for j in range(i+1,len(p)))
    return (-1)**inversions

def reduced_lefschetz(n,k,faces):
    # augmented chain contribution, including the empty face of degree -1
    return -1+sum((-1)**(s.bit_count()-1)*characteristic_sign(s,n,k)
                  for s in faces if rotate(s,n,k)==s)

def chi_fixed(n,k):
    g=gcd(n,k)
    if g==1:return 0
    # Independent rotation-orbits of vertices identify with Ind(C_g).
    return chi(g)

def prime_power_base(n):
    ps=[p for p in range(2,n+1) if n%p==0 and all(p%q for q in range(2,int(p**0.5)+1))]
    return ps[0] if len(ps)==1 else 1

def main():
    for n in range(8,19):
        faces=all_faces(n)
        d,b=expected_cycle_homology(n)
        e=chi(n)
        assert e == 1+(-1)**d*b,(n,e,d,b)
        # Each nontrivial primitive rotation has no point-fixed simplices.
        rot_trace=reduced_lefschetz(n,1,faces)
        assert rot_trace==-1,(n,rot_trace)
        # Compute fixed Euler from the exact invariant-face poset for all rotations.
        fixed_chi=[]
        for k in range(n):
            # All setwise-invariant independent faces; take their order complex.
            # Its Euler equals the Euler of the simplicial complex on vertex orbits.
            orbits=[]
            unseen=set(range(n))
            while unseen:
                i=min(unseen)
                orbit=set()
                j=i
                while j not in orbit:
                    orbit.add(j);j=(j+k)%n
                unseen-=orbit
                mask=sum(1<<a for a in orbit)
                if independent(mask,n):orbits.append(mask)
            fixed=sum((-1)**(len(sub)-1) for t in range(1,1<<len(orbits))
                      for sub in [[orbits[i] for i in range(len(orbits)) if t>>i&1]]
                      if independent(sum(sub),n))
            assert fixed==chi_fixed(n,k),(n,k,fixed,chi_fixed(n,k))
            fixed_chi.append(fixed)
        assert sum(fixed_chi)%n==0
        eq=sum(fixed_chi)//n
        rational_b=(-1)**d*(eq-1)
        assert rational_b==(1 if gcd(n,6)==1 else 0),(n,rational_b)
        # Compute subgroup of rotations generated by fixed-point elements.
        fixed_rotations=[k for k in range(1,n) if gcd(k,n)>1]
        index=gcd(n,*fixed_rotations)
        assert index==prime_power_base(n),(n,index)
        print('n=%d, faces=%d, chi_X=%d, chi_quotient=%d, pi1_order=%d, rational_b_%d=%d, rotation_reduced_L=%d' % (n,len(faces),e,eq,index,d,rational_b,rot_trace))
    print('CYCLE_ROTATION_EXACT_CHECK_PASS n=8..18')
if __name__=='__main__': main()
