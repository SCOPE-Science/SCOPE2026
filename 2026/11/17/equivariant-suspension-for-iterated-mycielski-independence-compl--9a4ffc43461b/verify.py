#!/usr/bin/env python3
"""Finite tests of fixed-space suspension for ordinary Mycielski graphs.

Usage: python3 verify.py. Standard library only. Tests corroborate, not prove,
the all-graph equivariant homotopy statement.
"""
from itertools import combinations, permutations
from collections import Counter


def mycielski(n, edges):
    # Original vertices 0,...,n-1; shadows n,...,2*n-1; apex 2*n.
    edges = {tuple(sorted(e)) for e in edges}
    out = set(edges)
    for u, v in edges:
        out.add((min(u, n + v), max(u, n + v)))
        out.add((min(v, n + u), max(v, n + u)))
    out.update((n + u, 2*n) for u in range(n))
    return 2*n+1, out


def lift(p):
    n=len(p)
    return tuple(p)+tuple(n+x for x in p)+(2*n,)


def graph_automorphism(n, edges, p):
    return {tuple(sorted((p[u],p[v]))) for u,v in edges}==edges


def orbit_conflict(n,edges,p):
    # Orbits of the cyclic group generated by a graph automorphism.
    seen=set(); orbit=[]
    for v in range(n):
        if v not in seen:
            O=[]; u=v
            while u not in seen:
                seen.add(u); O.append(u); u=p[u]
            orbit.append(tuple(O))
    index={v:i for i,O in enumerate(orbit) for v in O}
    bad=set(); internal=set()
    for u,v in edges:
        a,b=index[u],index[v]
        if a==b: internal.add(a)
        else: bad.add((min(a,b),max(a,b)))
    keep=[i for i in range(len(orbit)) if i not in internal]
    rename={v:i for i,v in enumerate(keep)}
    newedges={(rename[u],rename[v]) for u,v in bad if u in rename and v in rename}
    return len(keep),newedges




def orbit_conflict_generators(n, edges, generators):
    # Orbit partition under a subgroup given by a generating set.
    for g in generators: assert graph_automorphism(n, edges, g)
    seen=set(); orbits=[]
    for start in range(n):
        if start not in seen:
            O={start}; todo=[start]
            while todo:
                x=todo.pop()
                for g in generators:
                    y=g[x]
                    if y not in O: O.add(y); todo.append(y)
            seen.update(O); orbits.append(tuple(sorted(O)))
    idx={v:i for i,O in enumerate(orbits) for v in O}
    invalid={idx[u] for u,v in edges if idx[u]==idx[v]}
    valid=[i for i in range(len(orbits)) if i not in invalid]
    relabel={v:i for i,v in enumerate(valid)}
    clashes={(min(idx[u],idx[v]),max(idx[u],idx[v])) for u,v in edges if idx[u]!=idx[v]}
    return len(valid), {(relabel[a],relabel[b]) for a,b in clashes if a in relabel and b in relabel}

def faces(n,edges):
    # Includes the empty simplex for reduced homology.
    masks=[0]*n
    for u,v in edges:
        masks[u]|=1<<v; masks[v]|=1<<u
    ff=[()]
    for mask in range(1,1<<n):
        selected=[]
        for i in range(n):
            if mask>>i&1:
                if masks[i]&mask:
                    break
                selected.append(i)
        else: ff.append(tuple(selected))
    return ff


def rank_mod2(vectors):
    pivots={}
    for v in vectors:
        while v:
            k=v.bit_length()-1
            if k in pivots: v^=pivots[k]
            else:
                pivots[k]=v; break
    return len(pivots)


def betti(n,edges):
    ff=faces(n,edges)
    buckets={}
    for f in ff: buckets.setdefault(len(f)-1,[]).append(f)
    # Reduced chain complex includes degree -1 empty simplex.
    ranks={}
    for degree in range(0,max(buckets.keys(),default=-1)+1):
        prev_index={s:i for i,s in enumerate(buckets.get(degree-1,[]))}
        columns=[]
        for simplex in buckets.get(degree,[]):
            col=0
            for i in range(len(simplex)):
                face=simplex[:i]+simplex[i+1:]
                col^=1<<prev_index[face]
            columns.append(col)
        ranks[degree]=rank_mod2(columns)
    return {d:len(buckets[d])-ranks.get(d,0)-ranks.get(d+1,0)
            for d in buckets if d>=-1 and len(buckets[d])-ranks.get(d,0)-ranks.get(d+1,0)}


def suspension(b):
    # Formal reduced homology of an unreduced suspension. Empty fixed space:
    # the unique reduced (-1)-homology class shifts to degree zero.
    return {d+1:k for d,k in b.items()}


def ensure_contraction(n,edges):
    # Check contiguity of the old->shadow simplicial map with the identity:
    # every independent face remains independent after adjoining shadows
    # of all old vertices contained in it.
    face_set=set(faces(2*n+1,edges))
    no_apex=[f for f in face_set if 2*n not in f]
    for f in no_apex:
        union=tuple(sorted(set(f)|{n+u for u in f if u<n}))
        assert union in face_set
    return len(no_apex)


def check_case(n,edges,p,second=False):
    assert graph_automorphism(n,edges,p)
    size,edge1=mycielski(n,edges)
    assert ensure_contraction(n,edge1)>0
    o0,e0=orbit_conflict(n,edges,p)
    o1,e1=orbit_conflict(size,edge1,lift(p))
    b0=betti(o0,e0); b1=betti(o1,e1)
    assert b1==suspension(b0),(n,edges,p,b0,b1)
    if second:
        size2,edge2=mycielski(size,edge1)
        o2,e2=orbit_conflict(size2,edge2,lift(lift(p)))
        b2=betti(o2,e2)
        assert b2==suspension(b1),(n,edges,p,b1,b2)
    return (o0,o1)


def main():
    tested=0; counts=Counter()
    for n in range(1,5):
        allpairs=list(combinations(range(n),2))
        for subset in range(1<<len(allpairs)):
            edges={e for j,e in enumerate(allpairs) if subset>>j&1}
            for p in permutations(range(n)):
                if graph_automorphism(n,edges,p):
                    a,b=check_case(n,edges,p)
                    tested+=1; counts[n]+=1
    # Iterated case including all cyclic symmetries of C5 and K2.
    iterated=0
    for n,edges in [(2,{(0,1)}),(5,{tuple(sorted((i,(i+1)%5))) for i in range(5)})]:
        for p in permutations(range(n)):
            if graph_automorphism(n,edges,p):
                check_case(n,edges,p,second=True)
                iterated+=1
    # Noncyclic whole D5 subgroup on C5, both the original and two iterations.
    n=5
    E={tuple(sorted((i,(i+1)%5))) for i in range(5)}
    gen=[tuple((i+1)%5 for i in range(5)),tuple((-i)%5 for i in range(5))]
    a,b=orbit_conflict_generators(n,E,gen)
    assert betti(a,b)=={-1:1}
    for iteration in (1,2):
        n,E=mycielski(n,E);gen=[lift(p) for p in gen]
        a,b=orbit_conflict_generators(n,E,gen)
        assert betti(a,b)=={iteration-1:1}
    print('FULL_DIHEDRAL_C5_TWO_ITERATIONS_PASS')
    print('FULL_GRAPH_AUTOMORPHISM_CASES',tested,dict(sorted(counts.items())))
    print('SECOND_ITERATION_CASES',iterated)
    print('MYCIELSKI_FIXED_SUSPENSION_TESTS_PASS')

if __name__=='__main__': main()
