#!/usr/bin/env python3
"""Reproducibility checks for the fractional-to-integral stable-set polytope gap.
Independent vertices are generated by halfspace intersection, and projections
are checked by constrained numerical minimization; exact threshold values use
rational arithmetic.  This finite check is not an infinite-dimensional proof.
"""
from fractions import Fraction as Q
from itertools import product
import numpy as np
from scipy.optimize import minimize
from scipy.spatial import HalfspaceIntersection

def threshold(a):
    a=[Q(v) for v in a]
    r=len(a)
    S=Q(r-2,2)
    # Locate the solution by exact active-set evaluation.
    for j in range(r+1):
        order=sorted(range(r),key=lambda i:a[i])
        saturated=order[:j]
        active=order[j:]
        if not active: continue
        lam=(S-Q(j,2))/sum((1/a[i] for i in active),Q(0))
        if lam<0: continue
        if all(lam/a[i]>=Q(1,2) for i in saturated) and all(lam/a[i]<=Q(1,2) for i in active):
            s=[min(Q(1,2),lam/v) for v in a]
            assert sum(s)==S
            return sum(v*t*t for v,t in zip(a,s)),s
    raise RuntimeError(a)

def graph(a):
    groups=sum(([i]*m for i,m in enumerate(a)),[])
    return groups,[(i,j) for i in range(len(groups)) for j in range(i+1,len(groups)) if groups[i]!=groups[j]]

def exact_vertex_types(a):
    groups,edges=graph(a); n=len(groups)
    H=[]
    for i in range(n):
        v=np.zeros(n); v[i]=-1
        H.append(np.r_[v,0.])
    for i,j in edges:
        v=np.zeros(n); v[i]=v[j]=1
        H.append(np.r_[v,-1.])
    h=np.array(H)
    vertices=HalfspaceIntersection(h,np.full(n,.1)).intersections
    enc={tuple(int(round(2*x)) for x in v) for v in vertices}
    assert len(enc)==len(vertices)
    for v in enc:
        assert all(x in (0,1,2) for x in v)
        present={groups[i] for i,x in enumerate(v) if x}
        assert (set(v)<= {0,2} and len(present)<=1) or (set(v)<= {0,1} and len(present)>=3), (a,v)
    # All-half vertex exists and is found.
    assert (1,)*n in enc
    return enc

def projection(a, point=None):
    n=sum(a); groups,_=graph(a)
    h=np.full(n,.5) if point is None else np.array(point,dtype=float)
    def con(x):
        return 1-sum(max(x[j] for j in range(n) if groups[j]==i) for i in range(len(a)))
    # Direct coordinate projection into STAB with epigraph block maxima.
    r=len(a)
    def obj(z): return sum((z[:n]-h)**2)
    cons=[{'type':'ineq','fun':lambda z:1-sum(z[n:])}]
    for j,g in enumerate(groups):cons.append({'type':'ineq','fun':lambda z,j=j,g=g: z[n+g]-z[j]})
    bnds=[(0,1)]*n+[(0,1)]*r
    x0=np.r_[np.full(n,1/r),np.full(r,1/r)]
    res=minimize(obj,x0,method='SLSQP',bounds=bnds,constraints=cons,options={'ftol':1e-12,'maxiter':3000})
    assert res.success, (a,res.message)
    return res.fun

def run():
    cases=[(1,1,1),(2,1,1),(2,2,1),(2,2,2),(3,1,1),(3,2,1),
        (1,1,1,1),(2,1,1,1),(2,2,1,1),(3,1,1,1),
        (1,3,3,3),(2,4,4,4),(1,4,4,4),(3,8,8,8),
        (1,2,3,4,5),(2,2,2,2,2),(1,10,10,10)]
    nv=0; npj=0
    for a in cases:
        d,s=threshold(a)
        # Independent direct convex projection with conventional coordinates
        p=projection(a)
        assert abs(float(d)-p)<1e-8,(a,d,p)
        npj+=1
        if sum(a)<=6:
            verts=exact_vertex_types(a)
            nv+=len(verts)
            for v in verts:
                dtest=projection(a, [x/2 for x in v])
                if v==(1,)*sum(a): assert abs(dtest-float(d))<1e-7
                else: assert dtest<float(d)-1e-6,(a,v,dtest,d)
        if len(a)==3:
            assert d==Q(1,4)/sum((Q(1,v) for v in a),Q(0))
        if len(a)==4 and a[1:]==(a[1],)*3 and a[0]<=a[1]:
            aa,bb=a[0],a[1]
            ex=Q(aa,4)+Q(bb,12) if 3*aa<=bb else Q(aa*bb,bb+3*aa)
            assert d==ex,(a,d,ex)
    # Balanced / maximally concentrated bounds checked for integer profiles.
    from itertools import combinations_with_replacement
    nprofiles=0
    for r in range(3,6):
        for n in range(r,r+11):
            L=[tuple(v) for v in combinations_with_replacement(range(1,n-r+2),r) if sum(v)==n]
            if not L: continue
            scored={v:threshold(v)[0] for v in L}
            bal=tuple(sorted([n//r]*(r-n%r)+[n//r+1]*(n%r)))
            extreme=(1,)*(r-1)+(n-r+1,)
            assert all(scored[bal]>=f>=scored[extreme] for f in scored.values())
            assert all(f<scored[bal] for v,f in scored.items() if v!=bal)
            assert all(f>scored[extreme] for v,f in scored.items() if v!=extreme)
            nprofiles+=len(L)
    print(f'MULTIPARTITE_HAUSDORFF_PASS numerical_projections={npj} independent_halfspace_vertices={nv} exact_majorization_profiles={nprofiles}')

if __name__=='__main__':run()
