#!/usr/bin/env python3
"""Reproducible algebraic and finite-truncation checks for the renewal-pressure theorem.

All checks concern the explicit binary symbolic system generated by 0^m 1^(km), m>=1.
Finite tests corroborate, but do not prove, the all-parameter variational argument.
"""
from math import exp, log, log1p, isclose

def pressure(k, a, b, c, d):
    s = b + c - a - d
    L = log1p(exp(s)) if s < 700 else s + log1p(exp(-s))
    return max(a, d, (a+k*d+L)/(k+1))

def bulk(k, a, b, c, d):
    s = b+c-a-d
    L = log1p(exp(s)) if s < 700 else s+log1p(exp(-s))
    theta = exp(s)/(1+exp(s))
    return (a+k*d+L)/(k+1), theta

def root_finite(k,a,b,c,d,M):
    s=b+c-a-d
    def f(p):
        return sum(exp(min(700, m*(a+k*d-(k+1)*p)+s)) for m in range(1,M+1))
    lo,hi=min(a,d)-100,max(a,d)+100
    for i in range(140):
        mid=(lo+hi)/2
        if f(mid)>1:lo=mid
        else:hi=mid
    return (lo+hi)/2

def check():
    count=0
    for k in range(1,8):
        for a,b,c,d in [(0,0,0,0),(0.9,0,0,0),(0,0,0,0.9),(-0.2,0.6,-0.3,0.5),(-1.0,2.0,-0.25,-0.4),(.3,.9,-.4,.8)]:
            p,theta=bulk(k,a,b,c,d)
            s=b+c-a-d
            t=exp(a+k*d-(k+1)*p)
            # Exact geometric normalization identity, evaluated numerically.
            assert isclose(exp(s)*t/(1-t),1,abs_tol=5e-12)
            probs=[(1-theta)/(k+1),theta/(k+1),theta/(k+1),(k-theta)/(k+1)]
            assert isclose(sum(probs),1,abs_tol=1e-14)
            H=-theta*log(theta)-(1-theta)*log(1-theta)
            assert isclose(H/(k+1)+sum(x*y for x,y in zip(probs,(a,b,c,d))),p,abs_tol=2e-13)
            # Truncated roots strictly increase toward the infinite generator root.
            roots=[root_finite(k,a,b,c,d,M) for M in (1,2,5,10,20,60)]
            assert all(roots[i]<roots[i+1]+1e-12 for i in range(len(roots)-1))
            assert roots[-1] <= p + 1e-10
            assert isclose(1-sum(exp(m*(a+k*d-(k+1)*p)+s) for m in range(1,61)), (1-theta)**60, abs_tol=2e-12)
            count += 1
    # Analytically identified single-edge freezing points.
    gold=(1+5**.5)/2
    for k in range(1,12):
        lo,hi=1.,2.
        for _ in range(100):
            mid=(lo+hi)/2
            if mid**(k+1)>mid+1:hi=mid
            else:lo=mid
        root=(lo+hi)/2
        t=log(root)
        assert isclose(log1p(exp(t))/(k+1),t,abs_tol=2e-14)
        if k==1:assert isclose(root,gold,abs_tol=1e-14)
        if k==2:assert isclose(root**3,root+1,abs_tol=1e-14)
        t2=log(gold)
        p2,_=bulk(k,0,0,0,t2)
        assert isclose(p2,t2,abs_tol=3e-14)
    # Transition counts per generator and cyclic-edge score.
    for k in range(1,9):
        for m in range(1,12):
            w='0'*m+'1'*(k*m)
            zz=w+'0'
            counts=[sum(zz[i:i+2]==edge for i in range(len(w))) for edge in ('00','01','10','11')]
            assert counts==[m-1,1,1,k*m-1]
    print('VERIFY_OK cases=%d finite_roof_roots=6 per_case critical_roots=11 exact_word_checks=88'%count)
if __name__=='__main__': check()
