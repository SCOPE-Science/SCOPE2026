#!/usr/bin/env python3
"""Finite verification of orbit models for dominance complexes of forests.

Requires networkx. This checks finite instances only, not the universal theorem.
"""
from itertools import combinations
from collections import defaultdict
import networkx as nx


def partitions_into_orbits(n, group):
    unseen=set(range(n)); orbits=[]
    while unseen:
        v=min(unseen); orb=frozenset(g[v] for g in group)
        assert orb <= unseen
        orbits.append(orb); unseen-=orb
    return orbits


def closure(n, generators):
    identity=tuple(range(n)); group={identity}; frontier=[identity]
    while frontier:
        g=frontier.pop()
        for h in generators:
            for p in (tuple(g[h[i]] for i in range(n)),tuple(h[g[i]] for i in range(n))):
                if p not in group:
                    group.add(p); frontier.append(p)
    return group


def faces_dom(G):
    n=len(G); neighborhoods=[{v}|set(G.neighbors(v)) for v in range(n)]
    return {mask for mask in range(1<<n)
            if all(not all(mask>>v&1 for v in N) for N in neighborhoods)}


def quotient(G, orbit_list):
    Q=nx.Graph(); Q.add_nodes_from(range(len(orbit_list)))
    owner={v:j for j,o in enumerate(orbit_list) for v in o}
    for u,v in G.edges():
        i,j=owner[u],owner[v]
        if i!=j: Q.add_edge(i,j)
    return Q


def independent_fixed_face_masks(G,orbits):
    original=faces_dom(G); fixed=set()
    for mask in range(1<<len(orbits)):
        support=sum(1<<v for j,o in enumerate(orbits) if mask>>j&1 for v in o)
        if support in original: fixed.add(mask)
    return fixed


def matching_number(G):
    return len(nx.algorithms.matching.max_weight_matching(G,maxcardinality=True))


def trace_on_augmented_chains(faces,g):
    tr=0
    for m in faces:
        vertices=[v for v in range(len(g)) if m>>v&1]
        if any(not (m>>g[v]&1) for v in vertices): continue
        pairs=sum(g[vertices[i]]>g[vertices[j]] for i in range(len(vertices)) for j in range(i+1,len(vertices)))
        tr += (-1 if len(vertices)%2==0 else 1)*(-1 if pairs%2 else 1)
    return tr


def mod2_rank(vectors):
    pivots={}
    for x in vectors:
        while x:
            i=x.bit_length()-1
            if i in pivots: x^=pivots[i]
            else:
                pivots[i]=x; break
    return len(pivots)


def augmented_bettis(G):
    faces=faces_dom(G); n=len(G)
    levels=defaultdict(list)
    for m in faces: levels[m.bit_count()-1].append(m)
    maxdim=max(levels)
    ranks={}
    for d in range(0,maxdim+1):
        lower={m:i for i,m in enumerate(levels[d-1])}
        columns=[]
        for m in levels[d]:
            bits=0
            for i in range(n):
                if m>>i&1: bits ^= 1<<lower[m^(1<<i)]
            columns.append(bits)
        ranks[d]=mod2_rank(columns)
    return {d:len(levels[d])-ranks.get(d,0)-ranks.get(d+1,0)
            for d in range(-1,maxdim+1) if len(levels[d])-ranks.get(d,0)-ranks.get(d+1,0)}


def main():
    graphs=0; actions=0; faces=0; traces=0; subgroup_actions=0; homology=0; noncyclic=0
    examples=[]
    atlas=nx.graph_atlas_g()
    all_graphs=[g for g in atlas if 1<=len(g)<=6 and nx.is_forest(g)]
    for G0 in all_graphs:
        G=nx.convert_node_labels_to_integers(G0)
        n=len(G); graphs+=1
        gm=nx.algorithms.isomorphism.GraphMatcher(G,G)
        auts=[tuple(f[i] for i in range(n)) for f in gm.isomorphisms_iter()]
        if n>=2:
            assert len(auts)==len(set(auts))
        Ffaces=faces_dom(G)
        nu=matching_number(G)
        assert augmented_bettis(G)=={nu-1:1}
        homology+=1
        testgroups={frozenset((tuple(range(n)),)): 'trivial', frozenset(auts):'full'}
        for a in auts:
            group=frozenset(closure(n,[a]))
            testgroups[group]='cyclic'
        if len(auts)>=4:
            # Add genuinely noncyclic subgroups generated by two sampled automorphisms.
            for a in auts[:min(8,len(auts))]:
                for b in auts[-min(8,len(auts)):]:
                    group=frozenset(closure(n,[a,b]))
                    testgroups[group]='two-generators'
        for group,tag in testgroups.items():
            orbits=partitions_into_orbits(n,group)
            Q=quotient(G,orbits)
            assert nx.is_forest(Q)
            actual=independent_fixed_face_masks(G,orbits)
            pred=faces_dom(Q)
            assert actual==pred,(n,G.edges(),tag,orbits,actual,pred)
            nuQ=matching_number(Q)
            bet=augmented_bettis(Q)
            assert bet=={nuQ-1:1},(n,nuQ,bet)
            actions+=1; faces+=1<<len(orbits); homology+=1
            if len(group)>1 and all(len(closure(n,[g]))<len(group) for g in group):noncyclic+=1
            if tag=='full' and n in (4,5,6) and len(group)>1:
                examples.append((n,sorted(G.edges()),len(group),len(orbits),nu,nuQ))
        for g in auts:
            ggroup=closure(n,[g]); Q=quotient(G,partitions_into_orbits(n,ggroup)); nuQ=matching_number(Q)
            trace=trace_on_augmented_chains(Ffaces,g)
            assert trace==(-1)**(nuQ-1),(n,g,trace,nuQ)
            predicted_degree=(-1)**(nu-nuQ)
            assert trace==(-1)**(nu-1)*predicted_degree
            traces+=1
    for m in range(2,6):
        F=nx.Graph(); F.add_nodes_from(range(2*m+1))
        for i in range(m): F.add_edge(0,2*i+1); F.add_edge(2*i+1,2*i+2)
        assert matching_number(F)==m
        # Check the full symmetric group on arms and its fixed sphere dimension.
        from itertools import permutations
        perms=[]
        for p in permutations(range(m)):
            g=[0]*(2*m+1); g[0]=0
            for i,j in enumerate(p): g[2*i+1]=2*j+1;g[2*i+2]=2*j+2
            perms.append(tuple(g))
        Q=quotient(F,partitions_into_orbits(2*m+1,perms))
        assert len(Q)==3 and matching_number(Q)==1
        assert independent_fixed_face_masks(F,partitions_into_orbits(2*m+1,perms))==faces_dom(Q)
        for g in perms:
            P=[g[2*i+1]//2 for i in range(m)]
            inversions=sum(P[i]>P[j] for i in range(m) for j in range(i+1,m))
            cycles=(len(partitions_into_orbits(2*m+1,closure(2*m+1,[g])))-1)//2
            assert (-1)**(m-cycles)==(-1)**inversions
        print(f'rooted_two_edge_spider_arms={m} full_symmetry_fixed_S0 sign_character_verified')
    print('DOMINANCE_FOREST_ORBIT_EQUIVALENCE_PASS')
    print(f'unlabeled_forests={graphs} subgroup_actions={actions} orbit_face_subsets={faces} noncyclic_action_instances={noncyclic}')
    print(f'automorphism_lefschetz_checks={traces} mod2_homology_checks={homology}')
    print('sample_cases', examples[:8])

if __name__=='__main__': main()
