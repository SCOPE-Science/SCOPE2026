# Regenerate the human-readable orbit certificate from the exact finite checker.
import contextlib, io, runpy, json
from pathlib import Path
with contextlib.redirect_stdout(io.StringIO()):
    env=runpy.run_path(str(Path(__file__).resolve().parent / 'verify.py'))
G=env['G']; groups=env['subs']; tab=env['tab']; inv=env['inv']; calc=env['quotient']
canonical={}
for H in groups:
    conjugates=[tuple(sorted(tab[tab[g][h]][inv[g]] for h in H)) for g in range(72)]
    canonical[H]=min(conjugates)
rows=[]
for H in sorted(groups,key=lambda h:(len(h),tuple(sorted(h)))):
    typ,vec,bdry,*_=calc(H,True)
    rows.append({'elements_in_group_enumeration':sorted(H),'group_order':len(H),
                 'conjugacy_representative':list(canonical[H]),
                 'surface':{'orientability':typ[0],'genus_or_crosscaps':typ[1],'boundary_components':typ[2]},
                 'quotient_barycentric_cells':{'vertices':vec[0],'edges':vec[1],'triangles':vec[2]},
                 'boundary_edges':bdry})
summary={
    'description':'Unordered two-point discretized configuration surface of the complete bipartite graph with two three-point classes; full bipartition-preserving and bipartition-exchanging automorphism group.',
    'permutation_group_order':72,
    'group_element_encoding':'Zero-based index in the deterministic breadth-first permutation enumeration of verify.py, generated by the five listed permutations.',
    'subgroup_count':len(groups),
    'subgroup_conjugacy_classes':len(set(canonical.values())),
    'subgroups':rows
}
with open(Path(__file__).resolve().parent / 'orbit_census.json','w',encoding='utf-8') as f:
 json.dump(summary,f,ensure_ascii=False,indent=2);f.write('\n')
print(len(rows),len(set(canonical.values())))
