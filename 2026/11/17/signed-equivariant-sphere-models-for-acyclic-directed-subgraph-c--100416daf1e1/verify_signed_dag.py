#!/usr/bin/env python3
"""Finite corroboration of the signed-permutation fixed-space sphere formula.
No external dependencies; does not replace the equivariant-cover proof.
"""
import itertools
from collections import defaultdict

def compose(a,b):
    pa,ea=a; pb,eb=b
    return (tuple(pa[pb[i]] for i in range(len(pa))),ea*eb)

def closure(n,gens):
    one=(tuple(range(n)),1); sub={one}; queue=[one]
    while queue:
        a=queue.pop()
        for b in gens:
            c=compose(a,b)
            if c not in sub: sub.add(c);queue.append(c)
    return frozenset(sub)

def subgroup_cases(n):
    elements=[(p,e) for p in itertools.permutations(range(n)) for e in (1,-1)]
    candidates=[closure(n,(g,)) for g in elements]
    # Add selected genuinely noncyclic subgroups generated by pairs.
    for a in elements:
        for b in elements:
            if len(candidates)>300: break
            if len(closure(n,(a,b)))>1:candidates.append(closure(n,(a,b)))
        if len(candidates)>300: break
    return list(dict.fromkeys(candidates))

def orbits(points,actions):
    unseen=set(points);ans=[]
    while unseen:
        start=min(unseen); orbit={action(start) for action in actions};
        assert orbit<=unseen or orbit.isdisjoint(unseen)==False
        ans.append(frozenset(orbit));unseen-=orbit
    return ans

def predicted_d(n,H):
    H=list(H); permactions=[lambda i,p=p:p[i] for p,e in H]
    sites=orbits(range(n),permactions)
    odd=any(e==-1 for p,e in H)
    b=0
    for orbit in sites:
        i=min(orbit)
        if all(e==1 for p,e in H if p[i]==i):b+=1
    if not odd:
        assert b==len(sites)
        return b-1
    return b

def acyclic(n,edge_set):
    indeg=[0]*n;out=[[] for i in range(n)]
    for i,j in edge_set: out[i].append(j);indeg[j]+=1
    todo=[i for i in range(n) if indeg[i]==0];k=0
    while todo:
        i=todo.pop();k+=1
        for j in out[i]:
            indeg[j]-=1
            if not indeg[j]:todo.append(j)
    return k==n

def arc_orbits(n,H):
    arcs=[(i,j) for i in range(n) for j in range(n) if i!=j]
    actions=[]
    for p,e in H:
        if e==1:actions.append(lambda a,p=p:(p[a[0]],p[a[1]]))
        else:actions.append(lambda a,p=p:(p[a[1]],p[a[0]]))
    return orbits(arcs,actions)

def homology_mod2(n,H):
    orb=arc_orbits(n,H);m=len(orb)
    faces=defaultdict(list)
    for mask in range(1<<m):
        edges=set().union(*(orb[i] for i in range(m) if (mask>>i)&1))
        if acyclic(n,edges):faces[mask.bit_count()-1].append(mask)
    if not faces[0]:return {-1:1},m,0
    rank={}
    for q in sorted(k for k in faces if k>=0):
        lower=faces.get(q-1,[])
        if q==0:rank[q]=1;continue
        idx={s:i for i,s in enumerate(lower)}
        pivots={}
        for mask in faces[q]:
            vec=0
            for i in range(m):
                if (mask>>i)&1:vec^=1<<idx[mask^(1<<i)]
            while vec:
                lead=vec.bit_length()-1
                if lead not in pivots:pivots[lead]=vec;break
                vec^=pivots[lead]
        rank[q]=len(pivots)
    bets={q:len(faces[q])-rank[q]-rank.get(q+1,0) for q in rank}
    return {q:v for q,v in bets.items() if v},m,sum(len(faces[k]) for k in faces if k>=0)

def main():
    total=0; tested=defaultdict(int); details=[]
    for n in (2,3,4):
        for H in subgroup_cases(n):
            d=predicted_d(n,H)
            hom,m,faces=homology_mod2(n,H)
            expected=({-1:1} if d==0 else {d-1:1})
            assert hom==expected, (n,len(H),d,hom,expected,H)
            total+=1;tested[n]+=1
            if len(H)>1 and d>1:details.append((n,len(H),m,hom))
    # Extra n=5 rich diagonal reversals, and n=6 antipodal involution.
    for n in (5,6):
        p=tuple(i^1 for i in range(n)) if n%2==0 else (1,0,3,2,4)
        H=closure(n,((p,-1),))
        d=predicted_d(n,H);hom,m,faces=homology_mod2(n,H)
        assert hom==({-1:1} if d==0 else {d-1:1}),(n,hom,d)
        tested[n]+=1;total+=1
        details.append((n,len(H),m,hom))
    print('SIGNED_DAG_FINITE_FIXED_HOMOLOGY_CHECKS_PASS')
    print('checked_subgroups_by_n',dict(sorted(tested.items())))
    print('total_checked',total)
    print('examples',details[:8])

if __name__=='__main__':main()
