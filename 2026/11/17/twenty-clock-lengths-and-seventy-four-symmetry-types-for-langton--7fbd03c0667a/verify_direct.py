"""Exact state-space and orbit partition for turn-flip-move Langton ant on a 3x4 torus.

Run: python3 verify_direct.py
All arithmetic is integer; no packages other than Python's standard library.
"""
from collections import Counter, defaultdict

W, H = 3, 4
N = W * H
TOTAL = (1 << N) * N * 4
FULL = (1 << N) - 1

def encode(board, pos, direction):
    return ((board * N + pos) << 2) | direction

def decode(s):
    return s // (4 * N), (s // 4) % N, s % 4

def move(s):
    board, pos, direction = decode(s)
    bit = (board >> pos) & 1
    direction = (direction + (3 if bit else 1)) % 4
    board ^= 1 << pos
    x, y = pos % W, pos // W
    if direction == 0:
        y = (y - 1) % H
    elif direction == 1:
        x = (x + 1) % W
    elif direction == 2:
        y = (y + 1) % H
    else:
        x = (x - 1) % W
    return encode(board, y * W + x, direction)

def reverse(s):
    board, pos, direction = decode(s)
    x, y = pos % W, pos // W
    if direction == 0:
        y = (y + 1) % H
    elif direction == 1:
        x = (x - 1) % W
    elif direction == 2:
        y = (y - 1) % H
    else:
        x = (x + 1) % W
    oldpos = y * W + x
    oldbit = 1 - ((board >> oldpos) & 1)
    olddir = (direction - (3 if oldbit else 1)) % 4
    return encode(board ^ (1 << oldpos), oldpos, olddir)

# A complete inverse test verifies that the functional graph is a permutation.
for s in range(TOTAL):
    assert reverse(move(s)) == s
    assert move(reverse(s)) == s

cycle_id = [-1] * TOTAL
representatives = []
lengths = []
for start in range(TOTAL):
    if cycle_id[start] >= 0:
        continue
    cycle_num = len(representatives)
    cur, length = start, 0
    while cycle_id[cur] < 0:
        cycle_id[cur] = cycle_num
        length += 1
        cur = move(cur)
    assert cur == start
    representatives.append(start)
    lengths.append(length)
assert sum(lengths) == TOTAL

# Full geometric group of an unequal-sided rectangular square-grid torus:
# translations and the four sign changes; an orientation-reversing map
# is paired with global color exchange to preserve the ant rule.
transformations = []
for sx in (1, -1):
    for sy in (1, -1):
        for tx in range(W):
            for ty in range(H):
                cell_map = [((sx * (p % W) + tx) % W) +
                            W * ((sy * (p // W) + ty) % H)
                            for p in range(N)]
                direct_map = []
                velocity = [(0, -1), (1, 0), (0, 1), (-1, 0)]
                for vx, vy in velocity:
                    direct_map.append(velocity.index((sx * vx, sy * vy)))
                transformations.append((cell_map, direct_map, sx * sy < 0))
assert len(transformations) == 48

def apply(s, g):
    board, pos, direction = decode(s)
    cell_map, direct_map, color_exchange = g
    new_board = 0
    for p in range(N):
        if (board >> p) & 1:
            new_board |= 1 << cell_map[p]
    if color_exchange:
        new_board ^= FULL
    return encode(new_board, cell_map[pos], direct_map[direction])

# Verify commutation on all states for a generating set; the entire group
# is generated by unit translations and two complemented reflections.
def geom(sx, sy, tx, ty):
    ix = (0 if sx == 1 else 1) * (2 * W * H) + \
         (0 if sy == 1 else 1) * (W * H) + tx * H + ty
    return transformations[ix]
for g in (geom(1, 1, 1, 0), geom(1, 1, 0, 1),
          geom(-1, 1, 0, 0), geom(1, -1, 0, 0)):
    for s in range(TOTAL):
        assert apply(move(s), g) == move(apply(s, g))

parent = list(range(len(representatives)))
def find(c):
    while parent[c] != c:
        parent[c] = parent[parent[c]]
        c = parent[c]
    return c

def join(c, d):
    c, d = find(c), find(d)
    if c != d:
        parent[d] = c

for c, state in enumerate(representatives):
    for g in transformations:
        other = cycle_id[apply(state, g)]
        assert lengths[c] == lengths[other]
        join(c, other)

partition = defaultdict(Counter)
for c, length in enumerate(lengths):
    partition[length][find(c)] += 1

print('total_states', TOTAL)
print('total_temporal_cycles', len(representatives))
print('spatial_group_order', len(transformations))
print('total_spatial_temporal_types', sum(map(len, partition.values())))
print('length,cycles,types,orbit_size_histogram')
for length in sorted(partition):
    cycle_total = sum(partition[length].values())
    types = len(partition[length])
    histogram = dict(sorted(Counter(partition[length].values()).items()))
    assert sum(size * count for size, count in histogram.items()) == cycle_total
    print(f'{length},{cycle_total},{types},{histogram}')
assert len(representatives) == 2480
assert sum(map(len, partition.values())) == 74
assert max(lengths) == 312
assert all(length % 8 == 0 for length in lengths)
print('all_checks_passed')
