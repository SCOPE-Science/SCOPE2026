"""Exact small-order replay for automorphic-equivalence classification in cyclic-center class-two groups.
Pure Python standard library. Independent of the general proof; test cases are finite only.
"""
from collections import deque
from itertools import product

def run(p=3,k=2,extended=False):
    m=p**k; z=p**(k-1)
    els=list(product(range(p),range(p),range(m)))
    idx={v:i for i,v in enumerate(els)}
    identity=idx[(0,0,0)]
    N=len(els)
    def mulv(a,b):
        u,v,h=a; w,s,j=b
        return ((u+w)%p,(v+s)%p,(h+j-v*w*z+(u+w)//p*int(extended))%m)
    mul=[[idx[mulv(a,b)] for b in els] for a in els]
    def powi(x,n):
        r=identity
        while n:
            if n&1: r=mul[r][x]
            x=mul[x][x];n//=2
        return r
    order={x:next(j for j in range(1,p**(k+1)+1) if powi(x,j)==identity) for x in range(N)}
    inverse={x:powi(x,order[x]-1) for x in range(N)}
    x,y,c=idx[(1,0,0)],idx[(0,1,0)],idx[(0,0,1)]
    assert powi(c,m)==identity and order[c]==m
    assert powi(x,p)==(c if extended else identity)
    assert order[y]==p
    assert all(mul[mul[a][b]][d]==mul[a][mul[b][d]] for a in range(N) for b in range(N) for d in range(N))
    def comm(a,b): return mul[mul[mul[inverse[a]][inverse[b]]][a]][b]
    zidx=powi(c,z)
    assert comm(x,y)==zidx
    # Enumerate ALL subgroups via closure and overgroups. Exact at this finite order.
    def gen_group(gen):
        gen=tuple(set(gen)|{inverse[i] for i in gen})
        seen={identity};fr=deque([identity]);
        while fr:
            a=fr.popleft()
            for b in gen:
                t=mul[a][b]
                if t not in seen: seen.add(t);fr.append(t)
        return frozenset(seen)
    subs={frozenset({identity})}; todo=deque(subs)
    while todo:
        H=todo.popleft()
        for a in range(N):
            if a in H: continue
            K=gen_group((*H,a))
            if K not in subs: subs.add(K);todo.append(K)
    normals=[]
    for H in subs:
        if all(mul[mul[g][h]][inverse[g]] in H for g in range(N) for h in H):
            normals.append(H)
    # Complete group automorphism census through generator presentations and relators.
    # Distinct generator triples (x',y',c') satisfying all relations and generating G.
    automorphisms=set()
    for xx in range(N):
        if extended and order[xx]!=p**(k+1): continue
        if not extended and order[xx]!=p: continue
        for yy in range(N):
            if order[yy]!=p: continue
            if extended:
                cc=powi(xx,p)
                ccs=(cc,)
            else:
                ccs=tuple(t for t in range(N) if els[t][:2]==(0,0) and order[t]==m)
            for cc in ccs:
                if comm(xx,yy)!=powi(cc,z): continue
                if gen_group((xx,yy,cc))!=frozenset(range(N)): continue
                # images of center, x and y fix normal-form coordinate map
                yp=[powi(yy,j) for j in range(p)]
                xp=[powi(xx,j) for j in range(p)]
                cp=[powi(cc,j) for j in range(m)]
                image=tuple(mul[mul[xp[u]][yp[v]]][cp[h]] for u,v,h in els)
                assert len(set(image))==N
                assert all(image[mul[a][b]]==mul[image[a]][image[b]] for a in range(N) for b in range(N))
                automorphisms.add(image)
    # Orbits under all automorphisms generated by this exhaustive family.
    parent=list(range(N))
    def find(a):
        while parent[a]!=a:
            parent[a]=parent[parent[a]];a=parent[a]
        return a
    def union(a,b): parent[find(a)]=find(b)
    for im in automorphisms:
        for a,b in enumerate(im): union(a,b)
    orbit=[find(a) for a in range(N)]
    eligible=[]
    for H in normals:
        if len(H) in (1,N): continue
        if all(orbit[a]==orbit[mul[a][h]] for a in range(N) if a not in H for h in H):
            eligible.append(H)
    Gprime=frozenset((identity,zidx,powi(zidx,2)))
    omega=frozenset(a for a in range(N) if powi(a,m)==identity)
    expected={Gprime,omega} if extended else {Gprime}
    assert set(eligible)==expected,(extended,[(len(H),sorted(els[i] for i in H)[:5]) for H in eligible],[(len(H), sorted(els[i] for i in H)[:5]) for H in expected])
    return {'p':p,'k':k,'higher_exponent':extended,'group_order':N,'subgroups':len(subs),'normal_subgroups':len(normals),'automorphisms':len(automorphisms),'automorphism_orbits':len(set(map(find,range(N)))),'eligible_pair_subgroup_orders':sorted(len(H) for H in eligible)}

if __name__=='__main__':
    for e in (False,True): print(run(3,2,e))
    print('CYCLIC_CENTER_AUTOMORPHIC_COSET_CHECKS_OK')
