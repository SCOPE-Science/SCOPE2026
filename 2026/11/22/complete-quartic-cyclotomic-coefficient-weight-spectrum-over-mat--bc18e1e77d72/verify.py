"""Exact quartic cyclotomic coefficient-weight census over GF(8).

Pure Python 3, no dependencies. Field GF(8)=GF(2)[u]/(u^3+u+1);
elements represented by three-bit integers. Two independent enumerations:
(1) all monic quartics, irreducibility by the degree-4 gcd test;
(2) Frobenius orbits of elements in GF(8^4), generated by an element
    of order 4095, with minimal polynomials reconstructed from roots.
"""
from collections import Counter, defaultdict
from math import gcd

Q = 8
ORDER = Q**4 - 1
PRIMES = (3, 5, 7, 13)


def gf_mul(a, b):
    z = 0
    while b:
        if b & 1:
            z ^= a
        b >>= 1
        a <<= 1
        if a & 8:
            a ^= 0b1011
    return z


def gf_pow(a, e):
    z = 1
    while e:
        if e & 1:
            z = gf_mul(z, a)
        a = gf_mul(a, a)
        e >>= 1
    return z


def gf_inv(a):
    if a == 0:
        raise ZeroDivisionError
    return gf_pow(a, 6)


def trim(a):
    a = list(a)
    while a and a[-1] == 0:
        a.pop()
    return a


def poly_mul(a, b):
    if not a or not b:
        return []
    z = [0] * (len(a) + len(b) - 1)
    for i, x in enumerate(a):
        for j, y in enumerate(b):
            z[i + j] ^= gf_mul(x, y)
    return trim(z)


def poly_rem(a, f):
    a = trim(a)
    while len(a) >= len(f):
        d = len(a) - len(f)
        v = gf_mul(a[-1], gf_inv(f[-1]))
        for j, y in enumerate(f):
            a[d + j] ^= gf_mul(v, y)
        a = trim(a)
    return a


def poly_gcd(a, b):
    while b:
        a, b = b, poly_rem(a, b)
    return trim(a)


def poly_pow(a, e, f):
    z = [1]
    while e:
        if e & 1:
            z = poly_rem(poly_mul(z, a), f)
        a = poly_rem(poly_mul(a, a), f)
        e >>= 1
    return z


def root_order(f):
    n = ORDER
    for p in PRIMES:
        while n % p == 0 and poly_pow([0, 1], n // p, f) == [1]:
            n //= p
    return n


def enumerated_quartics():
    counts = defaultdict(Counter)
    for a0 in range(1, 8):
        for a1 in range(8):
            for a2 in range(8):
                for a3 in range(8):
                    f = [a0, a1, a2, a3, 1]
                    x64_minus_x = poly_rem([0, 1], f)
                    for _ in range(6):
                        x64_minus_x = poly_rem(poly_mul(x64_minus_x, x64_minus_x), f)
                    x64_minus_x += [0] * (2 - len(x64_minus_x))
                    x64_minus_x[1] ^= 1
                    if len(poly_gcd(f, trim(x64_minus_x))) != 1:
                        continue
                    counts[root_order(f)][sum(bool(x) for x in f)] += 1
    return dict(counts)


# Independent approach: construct F_{8^4} as F_8[z]/(z^4+(u+1)z+1).
# The extension is a field because the quartic is irreducible.
EXT_MOD = [1, 3, 0, 0, 1]


def ext_mul(a, b):
    # Fixed four-coefficient vectors, no invocation of the polynomial gcd code.
    z = [0] * 7
    for i in range(4):
        for j in range(4):
            z[i + j] ^= gf_mul(a[i], b[j])
    for i in range(6, 3, -1):
        z[i - 4] ^= z[i]              # z^4 = (u+1)z + 1
        z[i - 3] ^= gf_mul(3, z[i])
    return tuple(z[:4])


def ext_pow(a, e):
    z = (1, 0, 0, 0)
    while e:
        if e & 1:
            z = ext_mul(z, a)
        a = ext_mul(a, a)
        e >>= 1
    return z


def enumerated_orbits():
    generator = (0, 2, 0, 0)
    assert ext_pow(generator, ORDER) == (1, 0, 0, 0)
    assert all(ext_pow(generator, ORDER // p) != (1, 0, 0, 0)
               for p in PRIMES)
    powers = [(1, 0, 0, 0)]
    for _ in range(ORDER - 1):
        powers.append(ext_mul(powers[-1], generator))
    assert len(set(powers)) == ORDER
    seen = set()
    counts = defaultdict(Counter)
    for k in range(ORDER):
        if k in seen:
            continue
        orb = []
        e = k
        while e not in seen:
            seen.add(e)
            orb.append(e)
            e = 8 * e % ORDER
        if len(orb) != 4:
            continue
        coefficients = [(1, 0, 0, 0)]
        for exponent in orb:
            root = powers[exponent]
            new = [(0, 0, 0, 0)] * (len(coefficients) + 1)
            for j, c in enumerate(coefficients):
                rc = ext_mul(root, c)
                new[j] = tuple(a ^ b for a, b in zip(new[j], rc))
                new[j + 1] = tuple(a ^ b for a, b in zip(new[j + 1], c))
            coefficients = new
        assert all(c[1:] == (0, 0, 0) for c in coefficients)
        weight = sum(c[0] != 0 for c in coefficients)
        n = ORDER // gcd(ORDER, k)
        counts[n][weight] += 1
    return dict(counts)


EXPECTED = {
    5: (0, 0, 1), 13: (0, 0, 3), 15: (2, 0, 0),
    35: (0, 0, 6), 39: (0, 0, 6), 45: (0, 0, 6),
    65: (0, 0, 12), 91: (0, 0, 18), 105: (12, 0, 0),
    117: (0, 6, 12), 195: (0, 6, 18), 273: (0, 0, 36),
    315: (0, 0, 36), 455: (0, 0, 72), 585: (6, 24, 42),
    819: (0, 36, 72), 1365: (0, 36, 108),
    4095: (36, 144, 252),
}


def normalize(counts):
    return {n: tuple(counts[n][j] for j in (3, 4, 5)) for n in counts}


def main():
    a = normalize(enumerated_quartics())
    b = normalize(enumerated_orbits())
    assert a == EXPECTED == b, (a, b)
    assert sum(sum(row) for row in a.values()) == 1008
    assert sum(row[0] for row in a.values()) == 56
    # Local quartic order certificate for the three Frobenius-conjugate
    # quartics X^4+tX+1, t in {3,5,7}.
    f = [1, 3, 0, 0, 1]
    assert poly_pow([0, 1], 585, f) == [1]
    assert all(poly_pow([0, 1], 585 // p, f) != [1] for p in (3, 5, 13))
    assert root_order(f) == 585
    print('PASS: two independent full quartic enumerations; 1008 factors in 18 orders')
    for n in sorted(EXPECTED):
        print(n, *EXPECTED[n])


if __name__ == '__main__':
    main()
