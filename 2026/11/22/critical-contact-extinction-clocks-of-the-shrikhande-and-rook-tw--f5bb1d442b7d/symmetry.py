"""Check all maximal-delay states and their full spatial symmetry orbits.
Run after ./exhaustive; the file shrikhande_last_shell.txt is regenerated by it.
"""
from collections import Counter
from pathlib import Path
from itertools import product

N = 16
MOVES = {(1,0),(3,0),(0,1),(0,3),(1,1),(3,3)}

def xy(i): return (i % 4, i // 4)
def adjacent(u, v):
    x,y=xy(u); a,b=xy(v)
    return ((a-x)%4,(b-y)%4) in MOVES

def det_odd(a,b): return ((a[0]*b[1]-a[1]*b[0])%2)==1

def add(a,b):return ((a[0]+b[0])%4,(a[1]+b[1])%4)
def mul(z,a):return ((z*a[0])%4,(z*a[1])%4)

def automorphisms():
    out=[]
    for a,b in product(sorted(MOVES),repeat=2):
        if not det_odd(a,b):continue
        images={add(mul(u,a),mul(v,b)) for u,v in MOVES}
        if images!=MOVES:continue
        for dx,dy in product(range(4),repeat=2):
            p=[]
            for k in range(N):
                x,y=xy(k)
                xx=(x*a[0]+y*b[0]+dx)%4
                yy=(x*a[1]+y*b[1]+dy)%4
                p.append(xx+4*yy)
            assert len(set(p))==N
            assert all(adjacent(u,v)==adjacent(p[u],p[v]) for u in range(N) for v in range(N))
            out.append(tuple(p))
    assert len(set(out))==192, len(set(out))
    return out

def relabel(code,p):
    out=[0]*N
    for i in range(N):
        out[p[i]]=code%3
        code//=3
    assert not code
    return sum(out[i]*3**i for i in range(N))

def main():
    text=Path('shrikhande_last_shell.txt').read_text(encoding='utf8')
    ids=[int(t) for t in text.splitlines()]
    assert len(ids)==1088 and len(set(ids))==1088
    assert min(ids)>=0 and max(ids)<3**N
    perms=automorphisms()
    rem=set(ids); orbits=[]
    while rem:
        representative=min(rem)
        orb={relabel(representative,p) for p in perms}
        assert orb<=rem
        rem-=orb
        orbits.append((representative,len(orb)))
    assert orbits==[(563061,192),(627004,96),(640093,192),
      (685291,192),(2228096,96),(2382581,192),(2915821,96),(2933623,32)]
    print('automorphism_group_order=192')
    print('maximal_shell_symmetry_orbits=8')
    print('orbit_sizes=',dict(sorted(Counter(size for _,size in orbits).items())))
    print('orbit_representatives=',orbits)
    print('SYMMETRY_OK')
if __name__=='__main__':main()
