#!/usr/bin/env python3
"""Independent finite checks for exact critical-orbit portraits under ideal-power reduction.
Mathematical claims and proof are separate; these computations test finite instances.
"""
from math import isqrt, lcm
from itertools import product


def mul(z,w):
    a,b=z; c,d=w
    return a*c-b*d,a*d+b*c


def sub(z,w):
    return z[0]-w[0],z[1]-w[1]


def add(z,w):
    return z[0]+w[0],z[1]+w[1]


def div_exact(z,prime):
    a,b=z; u,v=prime; n=u*u+v*v
    x=a*u+b*v; y=b*u-a*v
    if x % n or y % n:
        return None
    return x//n,y//n


def valuation(z,prime):
    if z==(0,0): return 10**9
    v=0
    while (w:=div_exact(z,prime)) is not None:
        z=w;v+=1
    return v


def orbit_gaussian(c,length=9):
    x=(0,0);out=[]
    for _ in range(length):
        out.append(x)
        x=add(mul(x,x),c)
    return out


def portrait(a,equivalent):
    for j in range(1,len(a)):
        for i in range(j):
            if equivalent(a[i],a[j]):
                return i,j-i
    raise RuntimeError('No repeat in tested orbit')


def expected_gaussian(c,pi,k):
    if c==(0,1) or c==(0,-1):
        if div_exact((2,0),pi) is not None:  # ramified over 2, pi=1+i
            return ((0,2),(1,2),(2,2))[min(k,3)-1]
        if div_exact(sub(mul((2,0),c),(1,0)),pi) is not None:
            return (2,1) if k==1 else (2,2)
        return 2,2
    raise ValueError(c)


def primes(n):
    return [x for x in range(2,n+1) if all(x%d for d in range(2,isqrt(x)+1))]


def main():
    tests=0
    for c in [(0,1),(0,-1)]:
        entries=orbit_gaussian(c)
        for p in primes(101):
            if p==2:
                pis=[(1,1)]
            elif p%4==3:
                pis=[(p,0)]
            else:
                found=next((a,b) for a in range(1,isqrt(p)+1)
                            for b in range(1,isqrt(p)+1) if a*a+b*b==p)
                pis=[found,(found[0],-found[1])]
            for pi in pis:
                for k in range(1,8):
                    got=portrait(entries,lambda z,w: valuation(sub(z,w),pi)>=k)
                    want=expected_gaussian(c,pi,k)
                    assert got==want,(c,pi,k,got,want)
                    tests+=1

    for p in primes(101):
        for c in (0,-1,-2):
            arr=[0];x=0
            for _ in range(8):
                x=x*x+c;arr.append(x)
                if abs(x)>10**100: break
            for k in range(1,8):
                mod=p**k
                got=portrait(arr,lambda a,b:(a-b)%mod==0)
                want=((0,1) if k==1 else (1,1) if k==2 else (2,1)) if (c==-2 and p==2) else ((0,1) if c==0 else (0,2) if c==-1 else (2,1))
                assert got==want,(p,c,k,got,want)
                tests+=1

    # Exact quotient-ring checks for ideals generated by products of prime powers.
    composite_checks=0
    pi_choices=[(1,1),(-1,2),(-1,-2),(2,3),(3,0)]
    for c in [(0,1),(0,-1)]:
        entries=orbit_gaussian(c)
        for exponents in product(range(3),repeat=len(pi_choices)):
            if not any(exponents): continue
            ideal=(1,0);local=[]
            for pi,k in zip(pi_choices,exponents):
                if k:
                    for _ in range(k): ideal=mul(ideal,pi)
                    local.append(expected_gaussian(c,pi,k))
            got=portrait(entries,lambda z,w: div_exact(sub(z,w),ideal) is not None)
            want=(max(m for m,n in local),lcm(*(n for m,n in local)))
            assert got==want,(c,ideal,exponents,got,want)
            composite_checks+=1

    # Independently test all prime-field reductions of root-of-unity PCF branches.
    dptests=0
    for d in range(3,121):
        n=d-1
        extra=(d%6 in (0,1))
        for p in primes(97):
            targets={p-1:(0,2)}
            if extra:
                for t in range(p):
                    if (t*t+t+1)%p==0:
                        targets[t]=(2,1) if d%6==0 else (0,3)
            for c in range(p):
                want=(0,1) if c==0 else targets.get(pow(c,n,p))
                if want is None:continue
                arr=[0]; x=0
                for _ in range(10):
                    x=(pow(x,d,p)+c)%p;arr.append(x)
                got=portrait(arr,lambda a,b:a==b)
                assert got==want,(d,p,c,got,want)
                dptests+=1
    print(f'PASS: {tests} prime-power portraits, {composite_checks} composite-ideal portraits, and {dptests} finite-field cyclotomic-branch portraits')

if __name__=='__main__': main()
