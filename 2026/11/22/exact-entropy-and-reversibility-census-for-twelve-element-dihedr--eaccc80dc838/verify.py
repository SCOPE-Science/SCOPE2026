#!/usr/bin/env python3
"""Exact small-alphabet cross-checks for the group cellular automaton classification.
Run with: python3 verify.py
"""
from itertools import product
G = list(product(range(3), range(2), range(2)))
e = (0,0,0)
def mul(x,y):
    return ((x[0]+(-1 if x[1] else 1)*y[0])%3, (x[1]+y[1])%2, (x[2]+y[2])%2)
def power(x,n):
    out=e
    for _ in range(n): out=mul(out,x)
    return out
def inv(x):
    return next(y for y in G if mul(x,y)==e and mul(y,x)==e)
def genmap(a,b,z):
    return {g:mul(mul(power(a,g[0]),power(b,g[1])),power(z,g[2])) for g in G}
A=(1,0,0); B=(0,1,0); Z=(0,0,1)
endos=[]
for a,b,z in product(G,repeat=3):
    if power(a,3)!=e or power(b,2)!=e or power(z,2)!=e:continue
    if mul(mul(b,a),b)!=inv(a):continue
    if mul(z,a)!=mul(a,z) or mul(z,b)!=mul(b,z):continue
    h=genmap(a,b,z)
    if any(h[mul(x,y)]!=mul(h[x],h[y]) for x,y in product(G,repeat=2)):
        raise AssertionError('generator-presentation homomorphism mismatch')
    endos.append(h)
print('Endomorphisms of S3 x C2:',len(endos))
# The subgroup of the output S3 generated by the images of the input S3.
def s3_projection(g):return g[:2]
labels=[]
for h in endos:
    im_s3={s3_projection(h[g]) for g in G}
    central_p=h[Z][2]
    sign_q=h[B][2]
    labels.append((len(im_s3)==6,central_p,sign_q))
assert sum(1 for x in labels if x[0])==6*2*2
assert sum(1 for x in labels if not x[0] and x[1]==0 and x[2]==0)>=1
print('Full S3-projection endomorphisms:',sum(x[0] for x in labels))
for r in (1,2):
    cnt=0;rev=0
    for hs in product(range(len(endos)),repeat=r):
        maps=[endos[i] for i in hs]
        if r==2 and any(mul(maps[0][x],maps[1][y])!=mul(maps[1][y],maps[0][x]) for x,y in product(G,repeat=2)):
            continue
        is_base=[labels[i][0] for i in hs]
        if sum(is_base)!=1:continue
        ps=[labels[i][1] for i in hs]
        if not any(ps):continue
        # Confirm full form: each non-base map has trivial projected S3, and base map projects by an S3 automorphism.
        k=is_base.index(True)
        assert all(s3_projection(maps[j][g])==(0,0) for j in range(r) if j!=k for g in G)
        assert all(s3_projection(maps[k][g])==s3_projection(maps[k][(g[0],g[1],0)]) for g in G)
        cnt+=1
        if sum(ps)==1:rev+=1
    expected=6*r*(2**r-1)*2**r
    assert cnt==expected,(r,cnt,expected)
    assert rev==6*r*r*2**r,(r,rev)
    print(f'{r}-site rules: {cnt} surjective, {rev} reversible')
# Entropy profile for contiguous nonnegative offsets, and combinatorial polynomials.
for r in range(1,8):
    buckets={}
    for k in range(r):
        for pbits in range(1,1<<r):
            d=pbits.bit_length()-1
            buckets[k,d]=buckets.get((k,d),0)+6*(1<<r)
    assert sum(buckets.values())==6*r*(2**r-1)*(2**r)
    assert all(buckets[k,d]==6*(2**r)*(2**d) for k in range(r) for d in range(r))
print('Entropy generating polynomials verified for r=1..7')
# Independent direct enumeration of every onto two-site local homomorphism.
# A local rule is onto if its 144 input pairs cover the twelve target elements.
# This check does not use the proposed P/Q representation.
local_onto=0
for h1,h2 in product(endos,repeat=2):
    if not all(mul(h1[x],h2[y])==mul(h2[y],h1[x]) for x,y in product(G,repeat=2)):
        continue
    image={mul(h1[x],h2[y]) for x,y in product(G,repeat=2)}
    if len(image)==len(G):local_onto+=1
assert local_onto==168,local_onto
print('Independent direct local-image enumeration:',local_onto)
