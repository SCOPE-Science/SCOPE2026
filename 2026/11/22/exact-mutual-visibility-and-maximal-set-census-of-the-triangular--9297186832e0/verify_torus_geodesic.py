#!/usr/bin/env python3
"""Independent exhaustive ordinary-mutual-visibility census for C3 Cartesian C8.
Vertex IDs are 3*column+row. Geodesics are generated by Cartesian interleavings,
not by graph search. No third-party dependencies.
"""
from collections import Counter

WIDTH = 8
N = 3 * WIDTH
FULL = (1 << N) - 1


def path_interiors(a, b):
    x, r = divmod(a, 3)
    y, s = divmod(b, 3)
    forward = (y - x) % WIDTH
    backward = (x - y) % WIDTH
    d = min(forward, backward)
    directions = []
    if forward == d:
        directions.append(1)
    if backward == d and d != 0:
        directions.append(-1)
    if d == 0:
        directions = [1]
    answers = set()
    for direction in directions:
        columns = [(x + direction * step) % WIDTH for step in range(d + 1)]
        if r == s:
            seq = [3 * col + r for col in columns]
            answers.add(sum(1 << v for v in seq[1:-1]))
        else:
            # Only one vertical edge is possible in a shortest path. Its column
            # can occur before, after or between the horizontal moves.
            for switch in range(d + 1):
                seq = [3 * col + r for col in columns[:switch + 1]]
                seq += [3 * col + s for col in columns[switch:]]
                assert len(seq) == d + 2
                assert seq[0] == a and seq[-1] == b
                answers.add(sum(1 << v for v in seq[1:-1]))
    return tuple(sorted(answers))

WITNESSES = [[() for _ in range(N)] for _ in range(N)]
for u in range(N):
    for v in range(u + 1, N):
        WITNESSES[u][v] = path_interiors(u, v)
        assert WITNESSES[u][v]


def visible(s):
    pending = s
    while pending:
        bit = pending & -pending
        pending ^= bit
        u = bit.bit_length() - 1
        second = pending
        while second:
            nextbit = second & -second
            second ^= nextbit
            v = nextbit.bit_length() - 1
            if not any((interior & s) == 0 for interior in WITNESSES[u][v]):
                return False
    return True

feasible = Counter()
maximal = Counter()
examples = {}


def traverse(current, next_vertex):
    cardinality = current.bit_count()
    feasible[cardinality] += 1
    outside = FULL ^ current
    is_maximal = True
    # A hereditary property: inclusion-maximal iff no one-vertex extension.
    while outside:
        bit = outside & -outside
        outside ^= bit
        if visible(current | bit):
            is_maximal = False
            break
    if is_maximal:
        maximal[cardinality] += 1
        examples.setdefault(cardinality, current)
    for v in range(next_vertex, N):
        trial = current | (1 << v)
        if visible(trial):
            traverse(trial, v + 1)


if __name__ == '__main__':
    traverse(0, 0)
    for k in sorted(feasible):
        print(f'{k} {feasible[k]} {maximal[k]}')
    print('total_feasible', sum(feasible.values()))
    print('total_maximal', sum(maximal.values()))
    for k in sorted(examples):
        print('maximal_example', k, [v for v in range(N) if examples[k] >> v & 1])
