"""Independent finite diagnostics for a stadium's optimal inscribed triangle and covering lattice.
Run: python3 checker.py. No nonstandard dependencies. The continuum proof is in RESULT.md.
"""
import math
import random

PI = math.pi

def model(a, r):
    t = a / r
    # correction: rationalized root is 2/(sqrt(M^2+8)+M)
    c = 2 / (math.sqrt((1+2*t)**2+8) + (1+2*t))
    s = math.sqrt(1-c*c)
    w = a + r*c
    u = a + r
    h = r*s
    return c,s,w,u,h,h*(w+u)

def area(p,q,z):
    return abs((q[0]-p[0])*(z[1]-p[1])-(q[1]-p[1])*(z[0]-p[0]))/2

def in_hex(p, w, u, h, tol=1e-10):
    x,y=p
    if abs(y)>h+tol:
        return False
    return abs(x)<=u-(u-w)*abs(y)/h+tol

def covered(p, w,u,h):
    # Lattice generated by (0,2h) and (u+w,h).
    for i in range(-8,9):
        for j in range(-8,9):
            q=(p[0]-j*(u+w),p[1]-(2*i+j)*h)
            if in_hex(q,w,u,h):
                return True
    return False

def point_on_capsule(a,r,rng):
    # Independent random points in the Minkowski representation K=[-a,a]e_x+rB.
    center=rng.uniform(-a,a)
    radius=r*math.sqrt(rng.random())
    theta=rng.uniform(0,2*PI)
    return (center+radius*math.cos(theta),radius*math.sin(theta))

def run():
    rng=random.Random(20261115)
    cases=[0,.005,.05,.25,.5,1,2,6,20,100]
    for t in cases:
        a=t
        r=1.0
        c,s,w,u,h,f=model(a,r)
        assert abs(2*c*c+(1+2*t)*c-1) < 3e-14, ('root',t)
        verts=[(-w,h),(-w,-h),(u,0)]
        assert abs(area(*verts)-f)<1e-12, ('triangle',t)
        assert abs(f/(PI+4*t) - h*(w+u)/(PI+4*t))<1e-14
        density=(PI+4*t)/(2*f)
        if t==0:
            assert abs(f-3*math.sqrt(3)/4)<1e-12
            assert abs(density-2*PI/(3*math.sqrt(3)))<1e-12
        else:
            assert 3*math.sqrt(3)/(4*PI)<f/(PI+4*t)<.5
            assert 1<density<2*PI/(3*math.sqrt(3))
        # Independent random triangles (interior points), not an exhaustive certification.
        for _ in range(6000):
            p,q,z=[point_on_capsule(a,r,rng) for _j in range(3)]
            if area(p,q,z)>f+1e-10:
                raise AssertionError(('random triangle',t,p,q,z,area(p,q,z),f))
        # Exact symmetric hexagon tiling candidate; random coverage checks.
        for _ in range(900):
            p=(rng.uniform(-2*u,2*u),rng.uniform(-2*h,2*h))
            if not covered(p,w,u,h):
                raise AssertionError(('random hex lattice cover',t,p))
        # Envelope theorem derivative and strict monotonic filling fraction.
        if t>0:
            dt=1e-6*max(1,t)
            fplus=model(a+dt,r)[-1]
            fminus=model(max(a-dt,0),r)[-1]
            df=(fplus-fminus)/(dt+min(dt,a))
            assert abs(df-2*s)<2e-5,('envelope',t,df,2*s)
            analytic_eta_prime=2*s*(PI-2-2*c)/(PI+4*t)**2
            assert analytic_eta_prime>0
    print('STADIUM_TRIANGLE_COVERING_CHECKS_OK cases=10 random_triangles=60000 hex_samples=9000')

if __name__=='__main__': run()
