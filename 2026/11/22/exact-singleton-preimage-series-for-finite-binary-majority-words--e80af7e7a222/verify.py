#!/usr/bin/env python3
"""Exact integer check of a majority-rule singleton-predecessor series.

No external packages. A length-m output is generated by the majority of
successive triples in a length-(m+2) input with free end bits.
"""
from collections import Counter, deque


def successor(v, bit):
    w = [0] * 4
    for pair, count in enumerate(v):
        for appended in (0, 1):
            if ((pair >> 1) + (pair & 1) + appended >= 2) == bool(bit):
                dest = ((pair & 1) << 1) | appended
                w[dest] = min(2, w[dest] + count)
    return tuple(w)


def saturated_automaton():
    initial = (1, 1, 1, 1)
    states = [initial]
    index = {initial: 0}
    queue = deque([initial])
    while queue:
        state = queue.popleft()
        for bit in (0, 1):
            nxt = successor(state, bit)
            if nxt not in index:
                index[nxt] = len(states)
                states.append(nxt)
                queue.append(nxt)
    transitions = [tuple(index[successor(v, b)] for b in (0, 1)) for v in states]
    return states, transitions


def apply_matrix(transitions, vector):
    return [vector[i0] + vector[i1] for i0, i1 in transitions]


def output_series(transitions, terminal, upper):
    state = terminal
    out = []
    for _ in range(upper + 1):
        out.append(state[0])
        state = apply_matrix(transitions, state)
    return out


def direct_counts(length):
    result = Counter()
    for x in range(1 << (length + 2)):
        output = 0
        for i in range(length):
            bit = int(((x >> i) & 1) + ((x >> (i + 1)) & 1) + ((x >> (i + 2)) & 1) >= 2)
            output |= bit << i
        result[output] += 1
    return sum(value == 1 for value in result.values())


def coefficients(num, den, count):
    a = []
    for n in range(count):
        v = num[n] if n < len(num) else 0
        for j in range(1, min(n, len(den) - 1) + 1):
            v -= den[j] * a[n-j]
        a.append(v)
    return a


def main():
    states, edges = saturated_automaton()
    assert len(states) == 30
    assert len({tuple(e) for e in states}) == 30
    assert len([s for s in states if sum(s) == 1]) == 4
    assert all(0 <= q < 30 for pair in edges for q in pair)
    terminal = [int(sum(v) == 1) for v in states]

    # P(T) f = -2 e_0, with T the integer transition-count matrix.
    # P(t)=t^9-t^8-t^7+t^6-2t^4-t^3-t-1.
    powers = [terminal]
    for i in range(9):
        powers.append(apply_matrix(edges, powers[-1]))
    identity = [powers[9][i]-powers[8][i]-powers[7][i]+powers[6][i]
                -2*powers[4][i]-powers[3][i]-powers[1][i]-powers[0][i]
                for i in range(len(states))]
    assert identity == [-2] + [0]*29, identity
    # No transition into state 0: consequently TP(T)f=0.
    assert all(0 not in pair for pair in edges)

    # D(z)=1-z-z^2+z^3-2z^5-z^6-z^8-z^9.
    # N(z)=2z^3+6z^4-2z^5+2z^7-2z^8-2z^9.
    den = [1,-1,-1,1,0,-2,-1,0,-1,-1]
    num = [0,0,0,2,6,-2,0,2,-2,-2]
    from_automaton = output_series(edges, terminal, 120)
    from_fraction = coefficients(num, den, 121)
    assert from_automaton == from_fraction
    assert from_automaton[:14] == [0,0,0,2,8,8,14,16,24,42,74,130,218,354]

    for m in range(1, 14):
        assert direct_counts(m) == from_automaton[m], (m, direct_counts(m),from_automaton[m])
    print('VERIFY_OK states=30 terminal_states=4 polynomial_vector_identity=PASS')
    print('VERIFY_OK rational_series_coefficients_0_to_120=PASS exhaustive_1_to_13=PASS')
    print('first_counts_1_to_16=', from_automaton[1:17])


if __name__ == '__main__':
    main()
