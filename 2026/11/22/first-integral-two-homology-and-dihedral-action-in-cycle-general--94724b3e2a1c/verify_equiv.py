#!/usr/bin/env python3
"""Exact rational-chain action of the D9 automorphisms on H_2 of the cycle C9 GP complex."""
from fractions import Fraction
from itertools import combinations
from verify import metric_valid

N=9
triples=[t for t in combinations(range(N),3) if metric_valid(N,t)]
edge=list(combinations(range(N),2)); edge_id={e:i for i,e in enumerate(edge)}
tri_id={t:i for i,t in enumerate(triples)}
B=[[Fraction(0) for _ in triples] for e in edge]
for j,(a,b,c) in enumerate(triples):
    B[edge_id[(b,c)]][j]+=1
    B[edge_id[(a,c)]][j]-=1
    B[edge_id[(a,b)]][j]+=1

def rref_null(A):
    original=[row[:] for row in A]
    A=[list(map(Fraction, row)) for row in A];m=len(A);p=len(A[0]); pivots=[];r=0
    for col in range(p):
        nonzero=next((i for i in range(r,m) if A[i][col]!=0),None)
        if nonzero is None:continue
        A[r],A[nonzero]=A[nonzero],A[r]
        z=A[r][col];A[r]=[x/z for x in A[r]]
        for i in range(m):
            if i!=r and A[i][col]:
                z=A[i][col];A[i]=[a-z*b for a,b in zip(A[i],A[r])]
        pivots.append(col);r+=1
        if r==m:break
    free=[j for j in range(p) if j not in pivots]
    K=[]
    for j in free:
        v=[Fraction(0)]*p;v[j]=Fraction(1)
        for ri,pi in enumerate(pivots):v[pi]=-A[ri][j]
        assert all(sum(x*y for x,y in zip(row,v))==0 for row in original)
        K.append(v)
    return free,K

free,K=rref_null(B)
assert len(K)==3 and all(v.denominator==1 for b in K for v in b)

def action_on_triangles(g, vector):
    out=[Fraction(0) for _ in triples]
    for j, t in enumerate(triples):
        if not vector[j]: continue
        raw=list(map(g,t)); dest=tuple(sorted(raw))
        parity=sum(raw[a]>raw[b] for a in range(3) for b in range(a+1,3))%2
        out[tri_id[dest]]+=(-1 if parity else 1)*vector[j]
    return out

def mat_mul(A,B):return [[sum(A[i][k]*B[k][j] for k in range(len(B))) for j in range(len(B[0]))] for i in range(len(A))]
def eye(n):return [[int(i==j) for j in range(n)] for i in range(n)]
def trace(A):return sum(A[i][i] for i in range(len(A)))

def mat_action(g):
    cols=[]
    for b in K:
        v=action_on_triangles(g,b)
        co=[v[i] for i in free]
        assert all(v[i]==sum(co[j]*K[j][i] for j in range(3)) for i in range(len(triples)))
        cols.append(co)
    return [[cols[j][i] for j in range(3)] for i in range(3)]
R=mat_action(lambda x:(x+1)%N)
F=mat_action(lambda x:(-x)%N)
assert mat_mul(mat_mul(R,R),R)==eye(3)
assert mat_mul(F,F)==eye(3)
assert mat_mul(mat_mul(F,R),F)==mat_mul(R,R)
assert trace(R)==0 and trace(F)==1
# The R-fixed line is generated by the third free-coordinate basis vector.
v=[Fraction(0),Fraction(0),Fraction(1)]
assert [sum(R[i][j]*v[j] for j in range(3)) for i in range(3)]==v
assert [sum(F[i][j]*v[j] for j in range(3)) for i in range(3)]==v
# Direct rank computation ensures it is the ONLY rotation-invariant line.
rows=[[R[i][j]-(i==j) for j in range(3)] for i in range(3)]
assert len(rref_null(rows)[1])==1

# Simplicial chain traces under reflection: fixed oriented simplices with signs.
def trace_of_face_action(k):
    count=0
    faces=(list(combinations(range(N),k)) if k<=2 else triples)
    for t in faces:
        w=[(-x)%N for x in t]
        if sorted(w)==list(t):
            inversion=sum(w[i]>w[j] for i in range(k) for j in range(i+1,k))
            count+=(-1)**inversion
    return count
traces=[trace_of_face_action(k) for k in (1,2,3)]
assert traces==[1,-4,-2]
L=traces[0]-traces[1]+traces[2]
assert L==3
# The Lefschetz identity is L=1-tr(H1)+tr(H2), so H1 reflection sign=-1.
assert (1+trace(F)-L)==-1
print('C9 H2 integral rank',len(K),'canonical free-coordinate indices',free)
print('rotation matrix:',R)
print('reflection matrix:',F)
print('rotation trace',trace(R),'reflection trace',trace(F),'rotation order 3; reflection involutive')
print('reflection simplex traces C0,C1,C2:',traces,'Lefschetz number',L,'H1 reflection sign -1')
print('D9 invariant rational H2 dimension 1; H1 invariant dimension 0; quotient reduced rational homology Q in degree 2 only')
print('PASS: exact rational linear algebra, integral kernel vectors, chain actions, relations, Lefschetz traces')
