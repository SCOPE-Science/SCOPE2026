"""Exact certificate for the geometric polarized stabilizer of an explicit binary K3 quartic.

Requires Python 3 and SymPy. All polynomial calculations occur over GF(2).
"""
from itertools import combinations
import sympy as sp

x = sp.symbols('x0:4')
s, t = sp.symbols('s t')
F = sum(x[i]**2*x[i+1]**2 + x[i]*x[i+1]**3 for i in range(3)) + x[0]**3*x[3]+x[0]*x[3]**3

# Smoothness: in each of the four standard affine charts, no zero of the Jacobian ideal.
for i in range(4):
    rest = [v for j,v in enumerate(x) if j != i]
    eqs = [sp.Poly(e.subs(x[i], 1), *rest, modulus=2).as_expr() for e in [F]+[sp.diff(F, z) for z in x]]
    G = sp.groebner(eqs, *rest, order='lex', modulus=2)
    assert [g.as_expr() for g in G.polys] == [sp.Integer(1)], (i,G)

# All Grassmannian affine row-reduced cells for geometric line points in P^3.
# The argument in RESULT.md treats infinitesimal directions transverse to the cells.
# The ideal is generated by the five coefficients of F restricted to the universal line.
expected = {
    (0,1): ('a0+a2','a1+a2+a3','a2**2+a2','a2*a3+a2+a3+1','a3**2+a3'),
    (0,2): ('a0','a1','a2'),
    (0,3): ('1',),
    (1,2): ('1',),
    (1,3): ('a0',),
    (2,3): ('1',),
}
for a,b in combinations(range(4),2):
    params=[]; rows=[[sp.Integer(0)]*4 for _ in range(2)]
    rows[0][a]=sp.Integer(1); rows[1][b]=sp.Integer(1)
    for i,piv in enumerate((a,b)):
        for j in range(piv+1,4):
            if j in (a,b): continue
            z=sp.symbols('a'+str(len(params)))
            params.append(z);rows[i][j]=z
    linear=[s*rows[0][j]+t*rows[1][j] for j in range(4)]
    restr=sp.Poly(sp.expand(F.xreplace(dict(zip(x,linear)))),s,t)
    coeffs=[restr.coeff_monomial(s**k*t**(4-k)) for k in range(5)]
    if params:
        poly=[sp.Poly(c,*params,modulus=2).as_expr() for c in coeffs]
        G=sp.groebner(poly,*params,modulus=2,order='lex')
        basis=tuple(str(g.as_expr()) for g in G.polys)
    else:
        basis=('1',) if any(int(c)%2 for c in coeffs) else tuple()
    assert tuple(z.replace(" ", "") for z in basis)==expected[(a,b)], ((a,b),basis)

# In the first cell (0,1), two variables obey a^2+a=b^2+b=0
# and (a+1)(b+1)=0, giving precisely 3 distinct F2 solutions.
# The other nonempty cells each give a single reduced F2 solution.
# Their 2-planes in GF(2)^4 are represented by all 3 nonzero vectors.
lines = [ (1,4,5), (2,8,10), (3,9,10), (5,11,14), (6,11,13) ]
assert [tuple(sorted((L[0],L[1],L[0]^L[1]))) for L in lines]==lines
adj={tuple(sorted((i,j))) for i in range(5) for j in range(i+1,5) if set(lines[i])&set(lines[j])}
assert adj=={(0,3),(3,4),(1,2)},adj

def dot(u,v):return (u&v).bit_count()%2

def two_annihilators(a,b):
    arr=[u for u in range(1,16) if dot(u,a)==dot(u,b)==0]
    assert len(arr)==3
    return arr[:2]

def gauss_nullity_and_basis(eqs):
    R=list(eqs); piv=[];r=0
    for j in range(16):
        k=next((k for k in range(r,len(R)) if R[k]&(1<<j)),None)
        if k is None:continue
        R[r],R[k]=R[k],R[r]
        for k in range(len(R)):
            if k!=r and R[k]&(1<<j):R[k]^=R[r]
        piv.append(j);r+=1
        if r==len(R):break
    R=[v for v in R if v]
    free=[j for j in range(16) if j not in piv]
    out=[]
    for f in free:
        v=1<<f
        for row,p in zip(R,piv):
            if row&(1<<f):v|=1<<p
        out.append(v)
    assert all(all((e&v).bit_count()%2==0 for e in eqs) for v in out)
    return out

def constraint_solutions(perm):
    eq=[]
    for i,j in enumerate(perm):
        src=lines[i][:2];dst=lines[j][:2]
        for v in src:
            for u in two_annihilators(*dst):
                e=0
                for k in range(4):
                    for l in range(4):
                        if (u>>k)&1 and (v>>l)&1:e^=1<<(4*k+l)
                eq.append(e)
    return gauss_nullity_and_basis(eq)

def matrows(bits):
    return [sum(1<<j for j in range(4) if (bits>>(4*i+j))&1) for i in range(4)]

def rank(rows):
    piv={}
    for a in rows:
        while a:
            j=a.bit_length()-1
            if j not in piv:piv[j]=a;break
            a^=piv[j]
    return len(piv)

# Two independent path reversals generate the entire graph automorphism group.
identity=[0,1,2,3,4]
for swap_a2 in (False,True):
    for swap_a3 in (False,True):
        P=identity[:]
        if swap_a2:P[1],P[2]=P[2],P[1]
        if swap_a3:P[0],P[4]=P[4],P[0]
        B=constraint_solutions(P)
        assert len(B)==1,(P,B)
        R=matrows(B[0])
        if swap_a3:
            assert rank(R)<4,(P,R)
        elif not swap_a2:
            assert R==[1,2,4,8]
        else:
            assert R==[11,8,4,2],R
            # The surviving nonidentity invertible matrix does not stabilize F.
            forms=[sum(x[j] for j in range(4) if (v>>j)&1) for v in R]
            changed=sp.Poly(sp.expand(F.xreplace(dict(zip(x,forms)))),*x,modulus=2)
            assert changed.coeff_monomial(x[0]**2*x[3]**2)==1
            assert sp.Poly(F,*x,modulus=2).coeff_monomial(x[0]**2*x[3]**2)==0

print('PASS: smooth quartic; five geometric line points in the cells; A3+A2 graph; four one-dimensional linear lifting spaces; only identity preserves the quartic.')
