#!/usr/bin/env python3
"""Exact integral chain verification for the four-cut dual of the folded five-cube.
Python 3 standard library only. Vertex and simplex orders are increasing.
"""
from itertools import combinations
from collections import Counter
from hashlib import sha256

VERTICES=tuple(range(16))
DIRECTIONS=(1,2,4,8,15)
NEIGH={v:{v^d for d in DIRECTIONS} for v in VERTICES}
assert all(len(NEIGH[v])==5 for v in VERTICES)
assert all((u in NEIGH[v])==(v in NEIGH[u]) for u in VERTICES for v in VERTICES)
assert sum(map(len,NEIGH.values()))//2==40
assert all(not ((NEIGH[u]&NEIGH[v])-{u,v}) for u in VERTICES for v in NEIGH[u])
assert all(len(NEIGH[u]&NEIGH[v])==2 for u in VERTICES for v in VERTICES if u!=v and v not in NEIGH[u])

def connected(s):
    pending=set(s)
    if not pending:return True
    todo=[pending.pop()]
    while todo:
        k=todo.pop()
        new=pending & NEIGH[k]
        pending.difference_update(new)
        todo.extend(new)
    return not pending

four=tuple(q for q in combinations(VERTICES,4) if connected(q))
four_set=set(four)
assert len(four)==680
five=tuple(q for q in combinations(VERTICES,5) if all(s in four_set for s in combinations(q,4)))
five_set=set(five)
assert len(five)==192
assert all(sum(v in NEIGH[u] for v in q if v!=u)==2 for q in five for u in q)
assert not any(all(t in five_set for t in combinations(q,5)) for q in combinations(VERTICES,6))
assert len(tuple(combinations(VERTICES,4)))-len(four)==1140

F={0:tuple(combinations(VERTICES,1)),1:tuple(combinations(VERTICES,2)),
   2:tuple(combinations(VERTICES,3)),3:four,4:five}
idx={d:{t:i for i,t in enumerate(F[d])} for d in F}
assert tuple(len(F[d]) for d in range(5))==(16,120,560,680,192)

def boundary_cols(d):
    return [{idx[d-1][face[:i]+face[i+1:]]: (-1)**i
             for i in range(d+1)} for face in F[d]]

# Verify the signed simplicial chain condition directly in degree four.
d3=boundary_cols(3); d4=boundary_cols(4)
for col in d4:
    double={}
    for j,coeff in col.items():
        for k,val in d3[j].items():double[k]=double.get(k,0)+coeff*val
    assert all(x==0 for x in double.values())

def integer_unit_pivots(columns, nrows):
    """Exact Z column elimination, without rational or modular division.
    Every chosen pivot is +/-1. Remaining columns must be identically zero.
    Each operation preserves the integral column-span as a sublattice.
    """
    columns=[dict(c) for c in columns]
    active=set(range(len(columns)))
    chosen=[]
    for row in range(nrows):
        eligible=next((j for j in sorted(active) if abs(columns[j].get(row,0))==1),None)
        if eligible is None:
            assert all(columns[j].get(row,0)==0 for j in active),('nonunit',row)
            continue
        pivot=columns[eligible]
        sign=pivot[row]
        for j in sorted(active):
            if j==eligible:continue
            coeff=columns[j].get(row,0)*sign
            if coeff==0:continue
            for k,v in pivot.items():
                new=columns[j].get(k,0)-coeff*v
                if new:columns[j][k]=new
                else:columns[j].pop(k,None)
            assert row not in columns[j]
        active.remove(eligible)
        chosen.append(eligible)
    assert all(not columns[j] for j in active)
    return len(chosen),len(active),sha256(','.join(map(str,chosen)).encode()).hexdigest()

# The free group of two-cycles of the complete 2-skeleton is generated by
# boundaries of tetrahedra containing vertex 0; coordinate = coefficient
# on the unique triangle not containing 0. Thus there are C(15,3)=455 rows.
tri_nonzero=tuple(t for t in F[2] if 0 not in t)
tri_idx={t:i for i,t in enumerate(tri_nonzero)}
d3_cycle=[]
for q in F[3]:
    c={}
    for j in range(4):
        face=q[:j]+q[j+1:]
        if 0 not in face:c[tri_idx[face]]=(-1)**j
    d3_cycle.append(c)
assert len(tri_nonzero)==455
r3,z3,hash3=integer_unit_pivots(d3_cycle,455)
r4,z4,hash4=integer_unit_pivots(d4,len(F[3]))
assert (r3,z3,r4,z4)==(455,225,191,1)
assert len(F[3])-r3-r4==34
assert len(F[4])-r4==1
# These Z-unit pivots prove primitive images (no hidden torsion), not just Q-ranks.
print('graph: 16 vertices, 40 edges, strongly regular parameters (16,5,0,2)')
print('connected quadruples: 680; disconnected quadruples: 1140')
print('Alexander dual f-vector: 16 120 560 680 192; no faces of size six')
print('pentagon five-faces: 192; all induced five-cycles')
print('exact integer boundary ranks: d3=455, d4=191 (all unit pivots)')
print('unit-pivot digest d3:',hash3)
print('unit-pivot digest d4:',hash4)
print('dual integral homology: H3=Z^34, H4=Z, otherwise reduced zero')
print('dual homotopy: wedge of 34 S^3 and one S^4')
print('ordinary four-cut reduced integral homology: H9=Z, H10=Z^34')
print('VERIFY_OK')
