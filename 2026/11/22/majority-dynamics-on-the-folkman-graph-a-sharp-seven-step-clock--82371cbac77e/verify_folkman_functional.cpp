// Independent exhaustive functional-graph decomposition; requires C++17 only.
#include <algorithm>
#include <array>
#include <cstdint>
#include <iostream>
#include <fstream>
#include <map>
#include <set>
#include <vector>
using namespace std;
int main(){
 constexpr uint32_t N=(1u<<20);
 array<uint32_t,20> masks{};
 int k=10;
 for(int i=0;i<5;i++)for(int j=i+1;j<5;j++,k++){
   uint32_t ends=(1u<<i)|(1u<<(5+i))|(1u<<j)|(1u<<(5+j));masks[k]=ends;
   for(int u:{i,5+i,j,5+j})masks[u]|=(1u<<k);
 }
 for(auto z:masks)if(__builtin_popcount(z)!=4)return 1;
 vector<uint32_t> F(N);vector<int32_t> indeg(N,0);
 for(uint32_t x=0;x<N;x++){
   uint32_t y=0;
   for(int i=0;i<20;i++){
     int c=__builtin_popcount(masks[i]&x);
     y|=uint32_t((c>=3)||(c==2&&(x&(1u<<i))))<<i;
   }
   F[x]=y;indeg[y]++;
 }
 vector<uint32_t> queue; queue.reserve(N);
 for(uint32_t x=0;x<N;x++)if(!indeg[x])queue.push_back(x);
 for(size_t p=0;p<queue.size();p++){
   uint32_t y=F[queue[p]];
   if(--indeg[y]==0)queue.push_back(y);
 }
 vector<uint32_t> root(N,UINT32_MAX);vector<uint8_t> period(N,0),dist(N,0);
 int fix=0,two=0;
 for(uint32_t x=0;x<N;x++)if(indeg[x]>0 && root[x]==UINT32_MAX){
   vector<uint32_t> cycle;uint32_t y=x;
   do{cycle.push_back(y);y=F[y];}while(y!=x);
   int p=cycle.size();if(p>2){cerr<<"long cycle "<<p<<"\n";return 2;}
   if(p==1)fix++;else two++;
   uint32_t key=*min_element(cycle.begin(),cycle.end());
   for(uint32_t z:cycle){root[z]=key;period[z]=p;dist[z]=0;}
 }
 for(auto it=queue.rbegin();it!=queue.rend();++it){
   uint32_t x=*it,y=F[x];root[x]=root[y];period[x]=period[y];dist[x]=dist[y]+1;
 }
 map<int,int> entries,peri;
 map<uint32_t,uint64_t> basins;
 for(uint32_t x=0;x<N;x++){
   if(root[x]==UINT32_MAX)return 3;
   entries[dist[x]]++;peri[period[x]]++;basins[root[x]]++;
 }
 map<int,int> spectrum;for(auto [k,n]:basins)spectrum[int(n)]++;
 const map<int,int> expected_entry={{0,4738},{1,204618},{2,286060},{3,338240},{4,178600},{5,33440},{6,1920},{7,960}};
 const map<int,int> expected_period={{1,959624},{2,88952}};
 const map<int,int> expected_spectrum={{1,384},{2,60},{3,480},{4,120},{16,240},{18,160},{21,120},{25,120},{28,120},{30,240},{38,60},{55,720},{56,720},{72,120},{76,240},{86,120},{124,120},{152,60},{284,20},{899,40},{1368,60},{4038,10},{4249,40},{8652,1},{12190,10},{207670,2}};
 if(fix!=4036||two!=351||entries!=expected_entry||peri!=expected_period||spectrum!=expected_spectrum){cerr<<"DIFFERENCE\n";return 4;}
 if(basins[0]!=207670||basins[N-1]!=207670||dist[64030]!=7) return 5;
 // All spatial symmetries are generated by permuting the five K5 sites
 // and swapping a chosen twin pair (conjugation gives the other four swaps).
 vector<array<int,20>> generators;
 vector<array<int,5>> gp={{{1,0,2,3,4}},{{1,2,3,4,0}},{{0,1,2,3,4}}};
 for(int g=0;g<3;g++){
   array<int,20> perm{};
   for(int i=0;i<5;i++)for(int e=0;e<2;e++)perm[i+5*e]=gp[g][i]+5*(e^(g==2&&i==0));
   int ix=10;
   for(int i=0;i<5;i++)for(int j=i+1;j<5;j++,ix++){
     int a=gp[g][i],b=gp[g][j];if(a>b)swap(a,b);
     int target=10;
     for(int u=0;u<5;u++)for(int v=u+1;v<5;v++,target++)if(u==a&&v==b)perm[ix]=target;
   }
   // Verify edge preservation without trusting the symmetry description.
   for(int u=0;u<20;u++){
     uint32_t transmask=0;
     for(int v=0;v<20;v++)if((masks[u]>>v)&1)transmask|=1u<<perm[v];
     if(transmask!=masks[perm[u]])return 6;
   }
   generators.push_back(perm);
 }
 auto image=[&](uint32_t x,const array<int,20>& p){
   uint32_t y=0;
   for(int j=0;j<20;j++)if((x>>j)&1)y|=(1u<<p[j]);
   return min(y,F[y]);
 };
 set<uint32_t> unseen;
 for(auto [key,count]:basins)unseen.insert(key);
 map<int,int> symmetry_classes;
 while(!unseen.empty()){
   uint32_t starter=*unseen.begin();vector<uint32_t> active={starter};unseen.erase(starter);
   for(size_t z=0;z<active.size();z++)for(const auto &p:generators){
     uint32_t y=image(active[z],p);
     if(!basins.count(y))return 7;
     if(unseen.erase(y))active.push_back(y);
   }
   symmetry_classes[period[starter]]++;
 }
 if(symmetry_classes!=map<int,int>{{1,44},{2,8}})return 8;
 ofstream cat("basin_catalog.tsv");
 cat<<"periodic_representative\tleast_period\tbasin_size\n";
 for(auto [key,count]:basins)cat<<key<<"\t"<<int(period[key])<<"\t"<<count<<"\n";
 cat.close();
 cout<<"Symmetry: 44 fixed classes and 8 two-cycle classes under 3840 automorphisms.\n";
 cout<<"PASS all "<<N<<" labelled states; fixed "<<fix<<" two-cycles "<<two
   <<" max-entry "<<entries.rbegin()->first<<" witness 64030\n";
 cout<<"Exact first-entry, eventual-period, complete basin spectrum and two unanimous basins verified.\n";
 return 0;
}
