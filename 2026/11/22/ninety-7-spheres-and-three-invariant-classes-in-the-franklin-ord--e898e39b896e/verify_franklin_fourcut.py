#!/usr/bin/env python3
"""Exact finite witness for the ordinary four-cut complex of the Franklin graph.
Only Python's standard library is required. All calculations use integer sets.
"""
from collections import Counter
from itertools import combinations

N = 12
FULL = (1 << N) - 1
ADJ = [0] * N
for v in range(N):
    for w in ((v + 1) % N, (v - 1) % N, (v + (5 if v % 2 == 0 else -5)) % N):
        ADJ[v] |= 1 << w
assert all(bool(ADJ[u] & (1 << v)) == bool(ADJ[v] & (1 << u)) for u in range(N) for v in range(N))
assert all(x.bit_count() == 3 for x in ADJ)
assert sum(x.bit_count() for x in ADJ) == 36


def connected(mask):
    if not mask:
        return False
    reached = mask & -mask
    while True:
        new = reached
        for v in range(N):
            if reached & (1 << v):
                new |= ADJ[v] & mask
        if new == reached:
            return reached == mask
        reached = new


def choose_masks(k):
    return [sum(1 << i for i in xs) for xs in combinations(range(N), k)]


def cycle_type(p):
    seen = set()
    lengths = []
    for i in range(N):
        if i in seen:
            continue
        j, count = i, 0
        while j not in seen:
            seen.add(j)
            j, count = p[j], count + 1
        lengths.append(count)
    return tuple(sorted(lengths, reverse=True))


def orientation_sign(values):
    inversions = sum(values[i] > values[j] for i in range(len(values)) for j in range(i + 1, len(values)))
    return -1 if inversions % 2 else 1


four = choose_masks(4)
connected_four = [s for s in four if connected(s)]
disconnected_four = [s for s in four if not connected(s)]
assert len(four) == 495 and len(connected_four) == 75 and len(disconnected_four) == 420
squares = []
for m in connected_four:
    vertices = [i for i in range(N) if m & (1 << i)]
    if all((ADJ[v] & m).bit_count() == 2 for v in vertices):
        squares.append(tuple(vertices))
assert squares == [(0, 5, 6, 11), (1, 2, 7, 8), (3, 4, 9, 10)]

# The cut complex is generated by complements of disconnected quadruples.
facets = [FULL ^ s for s in disconnected_four]
cut = {s for s in range(1 << N) if any((s & f) == s for f in facets)}
# Its Alexander dual can be defined directly by avoiding every disconnected four-set.
dual = {s for s in range(1 << N) if not any((s & t) == t for t in disconnected_four)}
assert all(((FULL ^ s) not in cut) == (s in dual) for s in range(1 << N))
assert all((s in dual) == (s.bit_count() <= 3 or s in connected_four) for s in range(1 << N))
f_cut = dict(sorted(Counter(s.bit_count() - 1 for s in cut).items()))
f_dual = dict(sorted(Counter(s.bit_count() - 1 for s in dual).items()))
assert f_cut == {-1: 1, 0: 12, 1: 66, 2: 220, 3: 495, 4: 792, 5: 924, 6: 792, 7: 420}
assert f_dual == {-1: 1, 0: 12, 1: 66, 2: 220, 3: 75}

# An explicitly reproducible sequence of 75 elementary collapses, with
# a deterministic greedy choice of the smallest free coface/pair.
remaining_tetrahedra = set(connected_four)
remaining_faces = set(dual)
collapse_pairs = []
while remaining_tetrahedra:
    count = Counter()
    for tetra in remaining_tetrahedra:
        for v in range(N):
            if tetra & (1 << v):
                count[tetra ^ (1 << v)] += 1
    possibilities = [(tetra, tri) for tetra in remaining_tetrahedra
                     for v in range(N) if tetra & (1 << v)
                     for tri in [tetra ^ (1 << v)] if count[tri] == 1]
    assert possibilities, 'A tetrahedral free-face collapse must remain available'
    tetra, tri = min(possibilities)
    assert tetra in remaining_faces and tri in remaining_faces
    assert sum(tri & t == tri for t in remaining_tetrahedra) == 1
    assert not any((tri != other and (tri & other) == tri and other != tetra) for other in remaining_faces)
    remaining_faces.remove(tetra)
    remaining_faces.remove(tri)
    remaining_tetrahedra.remove(tetra)
    collapse_pairs.append((tri, tetra))
assert len(collapse_pairs) == 75
assert all(x.bit_count() <= 3 for x in remaining_faces)
assert len(remaining_faces) == len(dual) - 150
assert Counter(x.bit_count() - 1 for x in remaining_faces) == Counter({-1: 1, 0: 12, 1: 66, 2: 145})
# Full 2-skeleton initially implies simple connectivity. Collapsing does not
# change it. The resulting 2-complex has reduced Euler characteristic 90.
assert 12 - 66 + 145 - 1 == 90
# Thus the dual is a wedge of ninety 2-spheres. Integral Alexander duality
# and the full 6-skeleton of the cut complex imply ninety 7-spheres.

# Enumerate automorphisms without a graph package, by partial adjacency checks.
order = []
seen = {0}
queue = [0]
while queue:
    u = queue.pop(0)
    order.append(u)
    for v in range(N):
        if ADJ[u] & (1 << v) and v not in seen:
            seen.add(v)
            queue.append(v)
assert len(order) == N
perms = []
mapping = {}

def backtrack(index, used):
    if index == N:
        perms.append(tuple(mapping[i] for i in range(N)))
        return
    u = order[index]
    for v in range(N):
        if used & (1 << v):
            continue
        if all(bool(ADJ[u] & (1 << w)) == bool(ADJ[v] & (1 << mapping[w])) for w in order[:index]):
            mapping[u] = v
            backtrack(index + 1, used | (1 << v))
            del mapping[u]

backtrack(0, 0)
assert len(perms) == 48 and len(set(perms)) == 48


def simplex_trace(complex_faces, p, size):
    total = 0
    for f in complex_faces:
        if f.bit_count() != size:
            continue
        images = [p[i] for i in range(N) if f & (1 << i)]
        if set(images) == {i for i in range(N) if f & (1 << i)}:
            total += orientation_sign(images)
    return total

classes = Counter()
character_sum = 0
for p in perms:
    sign = orientation_sign(p)
    assert sign == 1
    trace_dual = -1 + sum((-1) ** (k - 1) * simplex_trace(dual, p, k) for k in range(1, 5))
    trace_cut = 1 - sum((-1) ** (k - 1) * simplex_trace(cut, p, k) for k in range(1, 9))
    assert trace_cut == sign * trace_dual
    classes[(cycle_type(p), trace_cut)] += 1
    character_sum += trace_cut
assert character_sum == 144
assert character_sum // 48 == 3
assert sum(classes.values()) == 48
assert classes[((1,) * N, 90)] == 1

# Verify the ten actual conjugacy classes (not merely cycle-type counts).
unclassified = set(perms)
conjugacy_table = Counter()
while unclassified:
    p = next(iter(unclassified))
    orbit = set()
    for g in perms:
        inverse = [0] * N
        for i, val in enumerate(g):
            inverse[val] = i
        orbit.add(tuple(g[p[inverse[i]]] for i in range(N)))
    assert orbit <= unclassified
    unclassified -= orbit
    trace = 1 - sum((-1) ** (k - 1) * simplex_trace(cut, p, k) for k in range(1, 9))
    assert all(1 - sum((-1) ** (k - 1) * simplex_trace(cut, q, k) for k in range(1, 9)) == trace for q in orbit)
    conjugacy_table[(len(orbit), cycle_type(p), trace)] += 1
assert len(conjugacy_table) == 9 and sum(conjugacy_table.values()) == 10
expected = [
    (1, (1,) * 12, 90),
    (3, (2, 2) + (1,) * 8, 10),
    (3, (2,) * 4 + (1,) * 4, -6),
    (6, (2,) * 6, -2),
    (1, (2,) * 6, 2),
    (6, (2,) * 6, 2),
    (8, (3,) * 4, 3),
    (6, (4, 4, 2, 2), 2),
    (6, (4, 4, 2, 2), 2),
    (8, (6, 6), -1),
]
assert conjugacy_table == Counter(expected)

print('Franklin LCF [5,-5]^6: 12 vertices, 18 edges; 3 disjoint induced squares')
print('connected/disconnected induced quadruples:', len(connected_four), len(disconnected_four))
print('cut faces by dimension:', f_cut)
print('Alexander-dual faces by dimension:', f_dual)
print('verified elementary (triangle,tetrahedron) collapse pairs:', len(collapse_pairs))
print('first and last collapse pairs:', collapse_pairs[:3], collapse_pairs[-3:])
print('remaining dual 2-faces:', 145, '; reduced Euler characteristic:', 90)
print('integral homotopy types: dual wedge(90,S^2), cut wedge(90,S^7)')
print('graph automorphisms:', len(perms), '; all induce even vertex permutations')
for (cyc, tr), count in sorted(classes.items(), key=lambda pair: (pair[0][0], pair[0][1])):
    print('cycle-type', cyc, 'trace', tr, 'multiplicity', count)
print('actual conjugacy classes:', sum(conjugacy_table.values()))
print('rational H7 fixed rank:', character_sum // 48)
print('ALL EXACT TESTS PASSED')
