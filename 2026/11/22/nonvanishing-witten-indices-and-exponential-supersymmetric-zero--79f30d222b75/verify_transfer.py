"""Exact transfer and algebraic-root verification for an indexed GP(n,3) lattice model.

Requires Python 3.10+ and SymPy. Execute: python verify_transfer.py
"""
from itertools import product
import sympy as sp

x = sp.Symbol('x')
states = tuple(product(range(3), repeat=3))
position = {s:i for i,s in enumerate(states)}
T = sp.zeros(27)
for (a,b,c), i in position.items():
    for d in range(3):
        if (c == 1 and d == 1) or (a == 2 and d == 2):
            continue
        T[i,position[(b,c,d)]] = -1 if d else 1
assert sp.expand(T.charpoly(x).as_expr() - x**20 * (x**2-x+1) * (x**5-x+1)) == 0

# The full matrix is checked by exact integer arithmetic, not floating roots.
P=sp.eye(27)
W={}
for n in range(1,45):
    P=P*T
    W[n]=int(sp.trace(P))
expected=[1,3,-11,4,1,6,-12,13,-7,3,-16,29,-18,8,-23,43,-45,30]
assert [W[n] for n in range(7,25)] == expected
assert all(((-1)**n)*W[n]>0 for n in range(13,45))

# Certified rational root-isolating rectangles, generated by exact symbolic isolation.
poly=sp.Poly(x**5-x+1,x)
real, complex_intervals = poly.intervals(eps=sp.Rational(1,10000),all=True)
assert len(real)==1 and len(complex_intervals)==4
low,high=real[0][0]
assert low < high < -sp.Rational(7,6)
for (a,b), multiplicity in complex_intervals:
    assert multiplicity == 1
    max_sq = max(sp.re(a)**2,sp.re(b)**2)+max(sp.im(a)**2,sp.im(b)**2)
    assert max_sq < sp.Rational(121,100)
# Once n>=25, the single negative real eigenvalue dominates all other roots.
assert sp.Rational(7,6)**25 > 4*sp.Rational(11,10)**25+2
# The ratio (7/6)/(11/10) = 35/33 > 1 makes dominance persist.
assert sp.Rational(35,33)>1
print('PASS: exact 27-state transfer determinant, index values, rational root enclosures, sign and exponential lower bound')
print('index n=7..24:', expected)
print('root rectangles:',real,complex_intervals)
