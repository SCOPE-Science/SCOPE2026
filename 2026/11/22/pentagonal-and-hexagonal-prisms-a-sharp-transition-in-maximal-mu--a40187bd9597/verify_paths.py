#!/usr/bin/env python3
"""Exact shortest-geodesic census for the pentagonal and hexagonal prisms."""
import hashlib
import itertools
import json
from collections import Counter, deque


def run(n):
    N=2*n
    adj=[]
    for v in range(N):
        r,c=divmod(v,n)
        adj.append((r*n+(c-1)%n,r*n+(c+1)%n,(1-r)*n+c))
    dist=[]
    for s in range(N):
        d=[-1]*N;d[s]=0;q=deque([s])
        while q:
            a=q.popleft()
            for b in adj[a]:
                if d[b]<0:d[b]=d[a]+1;q.append(b)
        dist.append(d)
    paths={}
    for a in range(N):
        for b in range(a+1,N):
            ims=set()
            def step(v,im):
                if v==b:ims.add(im);return
                for w in adj[v]:
                    if dist[w][b]==dist[v][b]-1:
                        step(w, im | ((1<<w) if w!=b else 0))
            step(a,0)
            paths[a,b]=tuple(sorted(ims))
    def good(mask):
        vs=[i for i in range(N) if mask>>i&1]
        return all(any((pm&mask)==0 for pm in paths[a,b])
                   for a,b in itertools.combinations(vs,2))
    feasible=[good(s) for s in range(1<<N)]
    fac=[s for s in range(1<<N) if feasible[s] and all(
         not feasible[s|(1<<v)] for v in range(N) if not(s>>v&1))]
    counts=Counter(s.bit_count() for s in range(1<<N) if feasible[s])
    facet_counts=Counter(s.bit_count() for s in fac)
    mu=min(facet_counts)
    opt=sorted(s for s in fac if s.bit_count()==mu)
    # Verify the explicit extremal templates, not merely the counts.
    if n==5:
        templates={sum(1 << v for v in (i,(i+1)%n,n+(i+2+eps)%n,n+(i+3+eps)%n))
                   for i in range(n) for eps in (0,1)}
        assert templates==set(opt)
    if n==6:
        sixsets={s for s in range(1<<N) if feasible[s] and s.bit_count()==6}
        alternating={sum(1<<(r*n+c) for r in (0,1) for c in range(n) if c%2==p)
                     for p in (0,1)}
        assert sixsets==alternating
        nonmaxfive={s for s in range(1<<N) if feasible[s] and s.bit_count()==5 and s not in opt}
        assert nonmaxfive=={s&~(1<<v) for s in sixsets for v in range(N) if s>>v&1}
    index={s:i for i,s in enumerate(opt)}

    def moves(mode):
        graph=[]
        for s in opt:
            q=set()
            for u in range(N):
                if not(s>>u&1):continue
                for v in (adj[u] if mode=='slide' else range(N)):
                    if s>>v&1:continue
                    j=index.get(s^(1<<u)^(1<<v))
                    if j is not None:q.add(j)
            graph.append(q)
        components=[];seen=set()
        for i in range(len(opt)):
            if i in seen:continue
            q=[i];seen.add(i)
            for v in q:
                for w in graph[v]:
                    if w not in seen:seen.add(w);q.append(w)
            components.append(len(q))
        ecc=[];hist=Counter()
        for i in range(len(opt)):
            d={i:0};q=deque([i])
            while q:
                v=q.popleft()
                for w in graph[v]:
                    if w not in d:d[w]=d[v]+1;q.append(w)
            ecc.append(max(d.values()))
            for j in range(i+1,len(opt)):
                if j in d:hist[d[j]]+=1
        return {'components':sorted(components),'edges':sum(map(len,graph))//2,
                'radius':min(ecc),'diameter':max(ecc),
                'eccentricity_histogram':dict(sorted(Counter(ecc).items())),
                'distance_histogram':dict(sorted(hist.items()))}
    # The explicitly displayed automorphism group generated by rotations, reflections, and layer swaps.
    def transform(mask,shift,reflect,swap):
        t=0
        for v in range(N):
            if (mask>>v)&1:
                r,c=divmod(v,n)
                if reflect:c=-c
                c=(c+shift)%n
                t|=1<<((r^swap)*n+c)
        return t
    orbits=[];seen=set()
    for s in opt:
        if s in seen:continue
        orb={transform(s,i,j,k) for i in range(n) for j in (0,1) for k in (0,1)}
        assert orb.issubset(index)
        seen|=orb
        orbits.append((len(orb),min(orb)))
    bits=bytes(1 if x else 0 for x in feasible)
    out={'n':n,'feasible_counts':dict(sorted(counts.items())),
         'maximal_counts':dict(sorted(facet_counts.items())),
         'mu_minus':mu,'minimum_count':len(opt),
         'optimal_mask_sha256':hashlib.sha256(','.join(map(str,opt)).encode()).hexdigest(),
         'feasible_bitset_sha256':hashlib.sha256(bits).hexdigest(),
         'symmetry_orbits':[{'size':a,'representative_mask':b} for a,b in sorted(orbits)],
         'jump':moves('jump'),'slide':moves('slide')}
    return out

if __name__=='__main__':
    results=[run(n) for n in (5,6)]
    assert results[0]['feasible_counts']=={0:1,1:10,2:45,3:110,4:115,5:30}
    assert results[0]['maximal_counts']=={4:10,5:30}
    assert results[0]['slide']['components']==[1]*10
    assert results[0]['jump']['components']==[10]
    assert results[0]['jump']['diameter']==5
    assert results[1]['feasible_counts']=={0:1,1:12,2:66,3:208,4:351,5:252,6:2}
    assert results[1]['maximal_counts']=={5:240,6:2}
    assert results[1]['slide']['components']==[240]
    assert (results[1]['slide']['radius'],results[1]['slide']['diameter'])==(6,7)
    assert results[1]['jump']['components']==[240]
    assert (results[1]['jump']['radius'],results[1]['jump']['diameter'])==(5,5)
    print(json.dumps(results,indent=2,sort_keys=True))
    print('PATH_ENUMERATION_OK')
