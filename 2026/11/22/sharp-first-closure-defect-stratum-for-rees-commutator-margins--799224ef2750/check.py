"""Finite consistency checks for marginal closure-defect counts in Rees semigroups.

No finite check is a proof of the universal lower bound.
Run: python3 check.py
"""
from itertools import product
from collections import Counter
import random


def bad_from_matrix(P, center=None):
    # Here entries are permutations for S3; uses multiplication from pair of tuples.
    r, c = len(P), len(P[0])
    total = 0
    for lam in range(r):
        for mu in range(r):
            if center is None:
                classes = Counter(comp(P[lam][i], inverse(P[mu][i])) for i in range(c))
            else:
                classes = Counter(min(comp(comp(P[lam][i], inverse(P[mu][i])), z) for z in center) for i in range(c))
            total += c*c-sum(v*v for v in classes.values())
    return total


def comp(x, y):
    return tuple(x[y[i]] for i in range(len(x)))


def inverse(x):
    ans = [0]*len(x)
    for i,v in enumerate(x): ans[v]=i
    return tuple(ans)


def brute_product_bad(P, central):
    # Actual Rees products of marginal elements, not rectangular identities.
    r,c=len(P),len(P[0]); marginal=[]
    for lam in range(r):
        for i in range(c):
            for z in central:
                marginal.append((i,comp(z,inverse(P[lam][i])),lam))
    count=0
    for i,g,lam in marginal:
        for j,h,mu in marginal:
            prod=comp(comp(g,P[lam][j]),h)
            if comp(prod,P[mu][i]) not in central: count+=1
    return count


# Independent XOR test over the subgroup generated by (01) in S3.
def xor_bad(bits, r, c):
    total=0
    for lam in range(r):
        for mu in range(r):
            for i in range(c):
                for j in range(c):
                    total += bits[lam*c+i]^bits[lam*c+j]^bits[mu*c+j]^bits[mu*c+i]
    return total


def single_defect_gauge(bits,r,c):
    # binary gauge: first row and first column normalized to zero;
    # check all row/column gauge choices by one anomalous entry perturbation.
    for odd in range(r*c):
        stripped=list(bits)
        stripped[odd]^=1
        # a rank-one additive matrix has all 2-by-2 XOR cycles zero.
        if all(stripped[lam*c+i]^stripped[lam*c+j]^stripped[mu*c+i]^stripped[mu*c+j]==0
               for lam in range(r) for mu in range(r)
               for i in range(c) for j in range(c)):
            return True
    return False


n_binary=0; n_min=0
for r in range(2,5):
    for c in range(2,5):
        bound=4*(r-1)*(c-1)
        for bits in product((0,1),repeat=r*c):
            b=xor_bad(bits,r,c)
            if b:
                assert b>=bound, (r,c,b,bits)
                if b==bound:
                    assert single_defect_gauge(bits,r,c), (r,c,bits)
                    n_min+=1
            n_binary+=1
        assert xor_bad(tuple([1]+[0]*(r*c-1)),r,c)==bound

# All S3 permutations; sample noncommuting entries and compare
# direct semigroup multiplication to multiplicity formula.
S3=list(__import__('itertools').permutations(range(3)))
E=(0,1,2)
rng=random.Random(1273)
for t in range(120):
    r,c=2+t%2,2+(t//2)%2
    P=[[rng.choice(S3) for i in range(c)] for lam in range(r)]
    a=bad_from_matrix(P)
    b=brute_product_bad(P,[E])
    assert a==b, (a,b,P)
    assert not a or a>=4*(r-1)*(c-1)

# D8: dihedral group of order 8, center 2, count via group pair multiplication.
# Embed as permutations on four corners.
def rot(i): return (i+1)%4
def refl(i): return (-i)%4
D8=[]
for eps in (0,1):
    for k in range(4):
        D8.append(tuple((k+((-i)%4 if eps else i))%4 for i in range(4)))
center=[tuple(range(4)),tuple((i+2)%4 for i in range(4))]
for t in range(80):
    r,c=2+t%2,2+(t//2)%2
    P=[[rng.choice(D8) for i in range(c)] for lam in range(r)]
    classes=bad_from_matrix(P,center)
    actual=brute_product_bad(P,center)
    assert actual==4*classes, (actual,classes)
    assert not actual or actual>=4*len(center)**2*(r-1)*(c-1)

print('MARGINAL_DEFECT_CHECK_OK',n_binary,'binary matrices',n_min,'equality matrices','200 group instances')

# Exact count of minimum-weight non-flat sandwich matrices over a nonabelian
# group (S3), for small dimensions.  Their center is trivial.
for r,c in [(2,2),(2,3),(3,2)]:
    total_min=0
    for entries in product(S3,repeat=r*c):
        P=[entries[t*c:(t+1)*c] for t in range(r)]
        if bad_from_matrix(P)==4*(r-1)*(c-1):
            total_min+=1
    q=len(S3)
    predicted=r*c*(q-1)*q**(r+c-1) // (2**int(r==2)*2**int(c==2))
    assert total_min==predicted,(r,c,total_min,predicted)

