# Classify the first positive defect stratum for normalized sandwich arrays.
def normalized_extremal_pattern(P):
    r,c=len(P),len(P[0]); e=tuple(range(len(P[0][0])))
    row_sides=[{i} for i in range(1,r)]+[set(range(1,r))]
    col_sides=[{j} for j in range(1,c)]+[set(range(1,c))]
    for A in row_sides:
        for B in col_sides:
            candidates={P[x][y] for x in A for y in B}
            if len(candidates)!=1: continue
            value=next(iter(candidates))
            if value==e:continue
            if all(P[x][y]==(value if x in A and y in B else e)
                   for x in range(r) for y in range(c)):
                return True
    return False

for r,c in [(2,4),(3,3)]:
    count_min=0
    for interior in product(S3,repeat=(r-1)*(c-1)):
        P=[[E]*c for _ in range(r)]
        iterator=iter(interior)
        for x in range(1,r):
            for y in range(1,c):
                P[x][y]=next(iterator)
        bad=bad_from_matrix(P)
        if bad==4*(r-1)*(c-1):
            assert normalized_extremal_pattern(P),(r,c,P)
            count_min+=1
    expected=(r*c*(len(S3)-1))//(2**int(r==2)*2**int(c==2))
    assert count_min==expected,(count_min,expected)
print('NORMALIZED_PATTERNS_OK S3 2x4 3x3')

# Raw nonabelian S3 inputs: gauge-normalize them without assuming Q abelian,
# and verify that every minimum defect has the announced rectangle form.
def normalize(P):
    r,c=len(P),len(P[0]); first=P[0][0]
    return [[comp(comp(comp(inverse(P[x][0]), P[x][y]),inverse(P[0][y])),first)
             for y in range(c)] for x in range(r)]

for t in range(400):
    r,c=2+t%3,2+(t//3)%3
    P=[[rng.choice(S3) for i in range(c)] for lam in range(r)]
    N=normalize(P)
    assert all(N[x][0]==E for x in range(r))
    assert all(N[0][y]==E for y in range(c))
    assert bad_from_matrix(P)==bad_from_matrix(N)
    if bad_from_matrix(P)==4*(r-1)*(c-1):
        assert normalized_extremal_pattern(N),(r,c,P,N)
print('RAW_NORMALIZATION_OK 400 S3 instances')
