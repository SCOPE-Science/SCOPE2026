#!/usr/bin/env python3
"""Exact standard-library verification of a one-swap correction code and upper bound."""
from itertools import combinations, permutations

WORDS = tuple(sorted(set(permutations((0, 0, 1, 1, 2, 2)))))
WORD_SET = set(WORDS)
assert len(WORDS) == 90

def neighbors(w):
    for i in range(5):
        if w[i] != w[i + 1]:
            a = list(w)
            a[i], a[i + 1] = a[i + 1], a[i]
            yield tuple(a)

CLOSE = {w: (set(neighbors(w)) | {z for x in neighbors(w) for z in neighbors(x)}) - {w} for w in WORDS}

def parse(s):
    assert len(s) == 6 and s.count('0') == s.count('1') == s.count('2') == 2
    return tuple(map(int, s))

# A cyclic symbol-relabeling orbit gives eighteen codewords.
CODE_REPS = ('001122', '010221', '011220', '020211', '021102', '021201')
CODE = {tuple((v + offset) % 3 for v in parse(w)) for w in CODE_REPS for offset in range(3)}
assert len(CODE) == 18
assert all(b not in CLOSE[a] for a, b in combinations(sorted(CODE), 2))

# Nine maximal-clique representatives, each with a nonnegative integer weight.
# The weights apply to *every distinct* clique in the orbit under the group
# generated by alphabet relabeling and reversal. All denominators are 19.
ORBIT_SEEDS = (
    (6, ('001122', '001212', '001221', '002112', '010212')),
    (7, ('001122', '001212', '010122', '010212')),
    (7, ('100221', '001221', '010212', '010221', '012021')),
    (6, ('002121', '020112', '020121', '020211', '021021', '200121')),
    (2, ('101220', '011202', '011220', '012120')),
    (3, ('102120', '011220', '012102', '012120', '012210', '021120')),
    (4, ('102021', '010221', '012012', '012021', '012201', '021021')),
    (5, ('102120', '102201', '102210', '012210', '120210')),
    (3, ('102210', '012120', '012201', '012210', '021210')),
)
weights_by_clique = {}
orbit_sizes = []
for numerator, seed in ORBIT_SEEDS:
    K = frozenset(map(parse, seed))
    orbit = set()
    for p in permutations(range(3)):
        for reverse in (False, True):
            orbit.add(frozenset(tuple(p[x] for x in (w[::-1] if reverse else w)) for w in K))
    for clique in orbit:
        assert all(b in CLOSE[a] for a, b in combinations(sorted(clique), 2)), ('not a clique', clique)
        assert clique not in weights_by_clique, ('repeated orbit', clique)
        weights_by_clique[clique] = numerator
    orbit_sizes.append(len(orbit))
assert orbit_sizes == [12, 6, 12, 6, 6, 6, 12, 6, 6], orbit_sizes
assert len(weights_by_clique) == 72
coverage = {w: sum(weight for clique, weight in weights_by_clique.items() if w in clique) for w in WORDS}
assert min(coverage.values()) >= 19, min(coverage.values())
assert sum(weights_by_clique.values()) == 360
assert 19 * len(CODE) <= 360 < 19 * (len(CODE) + 1)

print('alphabet composition:', (2, 2, 2))
print('universe:', len(WORDS))
print('valid code size:', len(CODE))
print('code:', ' '.join(''.join(map(str, w)) for w in sorted(CODE)))
print('clique-orbit sizes:', orbit_sizes)
print('weighted clique-cover numerator:', sum(weights_by_clique.values()))
print('minimum and maximum vertex cover numerators:', min(coverage.values()), max(coverage.values()))
print('upper bound: floor(360/19) =', sum(weights_by_clique.values()) // min(coverage.values()))
print('CERTIFICATE PASSED')
