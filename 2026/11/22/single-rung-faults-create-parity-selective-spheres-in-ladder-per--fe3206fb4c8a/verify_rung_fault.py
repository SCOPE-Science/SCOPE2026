"""Independent finite checks for perfect-matching complexes of two-row ladders.

Standard library only.  Vertices are (column, row), graph edges are indexed
canonically.  Perfect matchings are generated by graph-vertex backtracking,
not by the tiling recursion used in the mathematical proof.
"""
from collections import defaultdict


def edges(n):
    ee = []
    for j in range(n):
        ee.append(((j, 0), (j, 1)))
    for j in range(n - 1):
        ee.append(((j, 0), (j + 1, 0)))
        ee.append(((j, 1), (j + 1, 1)))
    return ee


def perfect_matchings(n, absent=None):
    ee = edges(n)
    byvertex = defaultdict(list)
    for k, (v, w) in enumerate(ee):
        if k == absent:
            continue
        byvertex[v].append((k, w))
        byvertex[w].append((k, v))
    universe = frozenset((j, a) for j in range(n) for a in range(2))

    def rec(unmatched, mask):
        if not unmatched:
            yield mask
            return
        v = min(unmatched)
        for e, w in byvertex[v]:
            if w in unmatched:
                yield from rec(unmatched - {v, w}, mask | (1 << e))

    return set(rec(universe, 0))


def face_set(matchings):
    ans = {0}
    for M in matchings:
        subs = [0]
        while M:
            bit = M & -M
            M -= bit
            subs += [s | bit for s in subs]
        ans.update(subs)
    return ans


def modtwo_homology(faces):
    cells = defaultdict(list)
    for s in faces:
        cells[s.bit_count()].append(s)
    ranks = {0: 0}
    for k in range(1, max(cells) + 1):
        ids = {m: i for i, m in enumerate(cells[k-1])}
        pivots = {}
        for simplex in cells[k]:
            boundary = 0
            m = simplex
            while m:
                b = m & -m
                m -= b
                boundary ^= 1 << ids[simplex ^ b]
            while boundary:
                p = boundary.bit_length() - 1
                if p not in pivots:
                    pivots[p] = boundary
                    break
                boundary ^= pivots[p]
        ranks[k] = len(pivots)
    return {k-1: len(cells[k]) - ranks[k] - ranks.get(k+1, 0)
            for k in range(1, max(cells)+1)
            if len(cells[k]) - ranks[k] - ranks.get(k+1, 0)}


def verify(n, j):
    # 1-based rung j; index j-1 in the canonical graph-edge list.
    j0 = j-1
    all_matchings = perfect_matchings(n)
    fault = perfect_matchings(n, absent=j0)
    assert fault <= all_matchings
    X = face_set(fault)

    if j in (1, n):
        # A missing endpoint rung forces the first/last horizontal pair.
        pair = 0 if j == 1 else n-2
        required = (1 << (n+2*pair)) | (1 << (n+2*pair+1))
        assert fault and all((m & required) == required for m in fault)
        expected = {}
    else:
        A = face_set(m for m in fault if (m >> (n+2*(j-2))) & 1)
        B = face_set(m for m in fault if (m >> (n+2*(j-1))) & 1)
        assert A | B == X
        # Construct the expected join by embedding both shorter ladders.
        emap = {tuple(sorted(e)): k for k,e in enumerate(edges(n))}
        def embed_faces(cols):
            if not cols:
                return {0}
            m = len(cols)
            mapping = {}
            for k, (a,b) in enumerate(edges(m)):
                x = (cols[a[0]],a[1]); y = (cols[b[0]],b[1])
                mapping[k] = emap[tuple(sorted((x,y)))]
            return {sum(1 << mapping[k] for k in mapping if f & (1 << k))
                    for f in face_set(perfect_matchings(m))}
        L = embed_faces(list(range(j-2)))
        R = embed_faces(list(range(j+1,n)))
        target = {x | y for x in L for y in R}
        assert A & B == target, (n,j,len(A&B),len(target))
        # Every facet of each subcomplex contains its chosen horizontal pair.
        expected = {(n-3)//2: 1} if n%2 and j%2==0 else {}

    betti = modtwo_homology(X)
    assert betti == expected, (n,j,betti,expected)
    return len(fault),len(X),betti


def main():
    tests = 0
    for n in range(2,10):
        for j in range(1,n+1):
            verify(n,j)
            tests += 1
    assert tests == 44
    print('PASS: 44 graph-edge-deletion cases n=2..9, exact cone intersection, mod-two Betti profiles')

if __name__ == '__main__':
    main()
