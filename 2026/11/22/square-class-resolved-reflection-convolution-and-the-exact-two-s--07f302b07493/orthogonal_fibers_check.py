"""Standalone finite prime-field matrix checker of quadratic-reflection product fibers."""
from itertools import product
from collections import defaultdict,Counter,deque


def inv(x,p): return pow(x%p,-1,p)
def chi(x,p):
 x%=p
 if x==0:return 0
 return 1 if pow(x,(p-1)//2,p)==1 else -1

def matmul(A,B,p):
 n=len(A)
 return tuple(tuple(sum(A[i][k]*B[k][j] for k in range(n))%p for j in range(n)) for i in range(n))
def eye(n):return tuple(tuple(int(i==j) for j in range(n)) for i in range(n))
def rank(A,p):
 a=[list(map(lambda x:x%p,row)) for row in A]; m=len(a); n=len(a[0]) if m else 0
 r=0
 for c in range(n):
  j=next((i for i in range(r,m) if a[i][c]),None)
  if j is None:continue
  a[r],a[j]=a[j],a[r]
  s=inv(a[r][c],p);a[r]=[x*s%p for x in a[r]]
  for i in range(m):
   if i!=r and a[i][c]:
    s=a[i][c];a[i]=[(x-s*y)%p for x,y in zip(a[i],a[r])]
  r+=1
  if r==m:break
 return r

def colbasis(A,p):
 n=len(A);basis=[]
 for j in range(n):
  v=tuple(A[i][j]%p for i in range(n))
  if rank([list(x) for x in basis+[v]],p)>len(basis):basis.append(v)
 return basis

def det2(A,p):return (A[0][0]*A[1][1]-A[0][1]*A[1][0])%p

def lines(n,p):
 for x in product(range(p),repeat=n):
  if not any(x):continue
  k=next(i for i,a in enumerate(x) if a)
  if x[k]==1:yield x


def solve(A,b,p):
 n=len(A);a=[[A[i][j]%p for j in range(n)]+[b[i]%p] for i in range(n)]; r=0;piv=[]
 for c in range(n):
  k=next((k for k in range(r,n) if a[k][c]),None)
  if k is None:continue
  a[r],a[k]=a[k],a[r]
  z=inv(a[r][c],p);a[r]=[z*t%p for t in a[r]]
  for k in range(n):
   if k!=r:
    z=a[k][c];a[k]=[(x-z*y)%p for x,y in zip(a[k],a[r])]
  piv.append(c);r+=1
  if r==n:break
 assert all(a[k][-1]==0 for k in range(r,n))
 x=[0]*n
 for k,c in enumerate(piv):x[c]=a[k][-1]
 assert all(sum(A[i][j]*x[j] for j in range(n))%p==b[i]%p for i in range(n))
 return tuple(x)

def wall_spinor(G,I,W,diag,p):
 n=len(I);A=tuple(tuple((I[i][j]-G[i][j])%p for j in range(n)) for i in range(n))
 pre=[solve(A,u,p) for u in W]
 wall=tuple(tuple(sum(2*diag[i]*pre[a][i]*W[b][i] for i in range(n))%p for b in range(2)) for a in range(2))
 return chi(det2(wall,p),p)

def verify(p,n,diag,all_group=False):
 I=eye(n)
 def Q(x):return sum(diag[i]*x[i]*x[i] for i in range(n))%p
 def Bhalf(x,y):return sum(diag[i]*x[i]*y[i] for i in range(n))%p
 refl={}
 for v in lines(n,p):
  q=Q(v)
  if q==0:continue
  R=tuple(tuple((int(i==j)-2*v[i]*diag[j]*v[j]*inv(q,p))%p for j in range(n)) for i in range(n))
  assert matmul(R,R,p)==I
  refl[R]=chi(q,p)
 assert len(refl)==len(set(refl))
 count=Counter(); fibers=defaultdict(Counter)
 for U,a in refl.items():
  for V,b in refl.items():fibers[matmul(U,V,p)][(a,b)]+=1
 for G,obs in fibers.items():
  rankg=rank(tuple(tuple((G[i][j]-I[i][j])%p for j in range(n)) for i in range(n)),p)
  if G==I:
   for a in (-1,1):assert obs.get((a,a),0)==sum(t==a for t in refl.values())
   assert not any(x!=y for x,y in obs)
  else:
   assert rankg==2
   W=colbasis(tuple(tuple((G[i][j]-I[i][j])%p for j in range(n)) for i in range(n)),p)
   gram=tuple(tuple(Bhalf(x,y) for y in W) for x in W)
   rg=rank(gram,p)
   if rg==2:
    eta=chi(-det2(gram,p),p)
    predicted={a:(p-eta)//2 for a in (-1,1)}
   elif rg==1:
    a=next(Q(x) for x in W if Q(x)) if any(Q(x) for x in W) else next(Q(tuple((x[i]+y[i])%p for i in range(n))) for x,y in [(W[0],W[1])])
    predicted={1:p if chi(a,p)==1 else 0,-1:p if chi(a,p)==-1 else 0}
   else:predicted={-1:0,1:0}
   theta=wall_spinor(G,I,W,diag,p)
   for b in (-1,1):
    for a in (-1,1):
     expected=predicted[b] if a*b==theta else 0
     assert obs.get((a,b),0)==expected,(p,n,diag,G,gram,theta,a,b,obs,expected)
   count[(rg,tuple(sorted(predicted.values())))] +=1
 if all_group:
  # Full orthogonal group generated by reflections (q odd), test zero and other output fibers.
  group={I};todo=deque([I]);rs=list(refl)
  while todo:
   g=todo.popleft()
   for r in rs:
    h=matmul(g,r,p)
    if h not in group:group.add(h);todo.append(h)
  for G in group:
   obs=fibers.get(G,Counter())
   rg=rank(tuple(tuple((G[i][j]-I[i][j])%p for j in range(n)) for i in range(n)),p)
   if rg in (1,) or rg>2:assert not obs
   if rg==2 and G not in fibers:
    W=colbasis(tuple(tuple((G[i][j]-I[i][j])%p for j in range(n)) for i in range(n)),p)
    assert all(Q(v)==0 for v in (W[0],W[1],tuple((W[0][i]+W[1][i])%p for i in range(n))))
  if n==3:
   refined=Counter()
   for G in fibers:
    if G==I:continue
    W=colbasis(tuple(tuple((G[i][j]-I[i][j])%p for j in range(n)) for i in range(n)),p)
    gram=tuple(tuple(sum(diag[k]*u[k]*v[k] for k in range(n))%p for v in W) for u in W)
    rgram=rank(gram,p)
    eta=chi(-det2(gram,p),p) if rgram==2 else 0
    theta=wall_spinor(G,I,W,diag,p)
    refined[(rgram,eta,theta)]+=1
   exref={
     (2,1,1):p*(p+1)*(p-3)//4,
     (2,1,-1):p*(p+1)*(p-1)//4,
     (2,-1,1):p*(p-1)*(p-1)//4,
     (2,-1,-1):p*(p-1)*(p+1)//4,
     (1,0,1):p*p-1,
   }
   assert refined==Counter({k:v for k,v in exref.items() if v}), (refined,exref)
   print('REFINED_SPINOR_COUNTS',p,sorted(refined.items()))
   observed=Counter(sum(obs.values()) for G,obs in fibers.items() if G!=I)
   theoretical={p-1:p*(p+1)*(p-2)//2,p+1:p*p*(p-1)//2,p:p*p-1}
   assert observed==theoretical,(observed,theoretical)
   assert sum(lenx for lenx in observed.values())==p*(p*p-1)-1
   assert len(group)==2*p*(p*p-1)
   from fractions import Fraction
   avg=Fraction(p**4,p*(p*p-1))
   tv=sum(abs(Fraction(sum(fibers[G].values()),p**4)-Fraction(1,p*(p*p-1))) for G in group if G in fibers)/2
   # Only determinant-one outputs contribute to comparison with uniform SO_3.
   # The entire group has equally many determinant-positive and -negative elements.
   tv=(sum(abs(Fraction(sum(obs.values()),p**4)-Fraction(1,p*(p*p-1))) for obs in fibers.values()))/2
   assert tv==Fraction(p*p-p-1,2*p*p*(p-1)),(p,tv)
   print('TOTAL_VARIATION_SO3',p,str(tv))
   print('THREE_DIMENSION_SPECTRUM',p,sorted(observed.items()))
  print('CHECK',p,n,diag,'reflections',len(refl),'group',len(group),'nonzero targets',len(fibers),'rank2 spectrum',dict(count))
 else:print('CHECK',p,n,diag,'reflections',len(refl),'nonzero targets',len(fibers),'rank2 spectrum',dict(count))

if __name__=='__main__':
 for p,n,d,allg in [
 (3,2,[1,1],True),(3,2,[1,2],True),(5,2,[1,1],True),(5,2,[1,2],True),
 (3,3,[1,1,1],True),(5,3,[1,1,1],True),(7,3,[1,1,1],True),
 (3,4,[1,1,1,1],True),(3,4,[1,1,1,2],True),(5,4,[1,1,1,1],False),
 ]:verify(p,n,d,allg)
