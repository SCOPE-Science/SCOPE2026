#!/usr/bin/env python3
"""Standalone checks for the mathematics of cyclic-label stable-pair complexes.
No dependencies beyond Python's standard library. Finite tests are not the theorem.
"""
from collections import Counter
from itertools import combinations
from math import gcd


def faces_of(m):
    chords = [(i, j) for i in range(m) for j in range(i + 1, m)
              if j - i not in (1, m - 1)]
    meets = {(i, j): bool(set(chords[i]) & set(chords[j]))
             for i in range(len(chords)) for j in range(i + 1, len(chords))}
    faces = [()]
    for j in range(len(chords)):
        faces += [f + (j,) for f in faces[:]
                  if not f or (f[-1] < j and all(meets[(i, j)] for i in f))]
    return chords, faces


def permutation_on_chords(chords, m, a, sign):
    index = {p: i for i, p in enumerate(chords)}
    return [index[tuple(sorted(((a + sign * x) % m,
                                (a + sign * y) % m)))] for x, y in chords]


def parity(values):
    return -1 if sum(values[i] > values[j]
                     for i in range(len(values))
                     for j in range(i + 1, len(values))) % 2 else 1


def signed_trace(faces, perm):
    trace = 0
    fixed = False
    for face in faces[1:]:
        image = [perm[i] for i in face]
        if sorted(image) == list(face):
            fixed = True
            trace += (-1) ** (len(face) - 1) * parity(image)
    return trace - 1, fixed


def published_character(m, a, sign):
    b = (m**3 - 12 * m**2 + 35 * m - 6) // 6
    if sign == 1:
        if a == 0:
            return b
        if m % 2 == 0 and a == m // 2:
            return m // 2 - 1
        if m % 3 == 0 and a in (m // 3, 2 * m // 3):
            return m // 3 - 1
        return -1
    if m % 2:
        return 1
    return (3 - m // 2) if a % 2 == 0 else (m // 2 - 3)


def check():
    tests = 0
    for m in range(8, 13):
        chords, faces = faces_of(m)
        counts = Counter(map(len, faces))
        assert sum((-1)**(size-1) * num for size, num in counts.items()) == \
            (m**3 - 12*m*m + 35*m - 6)//6
        for sign in (1, -1):
            for a in range(m):
                perm = permutation_on_chords(chords, m, a, sign)
                character, fixed = signed_trace(faces, perm)
                assert character == published_character(m, a, sign), (m, a, sign)
                if sign == 1:
                    order = m // gcd(m, a)
                    expected = order in (1, 2, 3)
                else:
                    expected = True
                assert fixed == expected, (m, a, sign, fixed, expected)
                tests += 1
        for d in range(1, m+1):
            if m % d: continue
            # All fixed-point rotations in an order-d group are of order 1,2,3.
            fixed_exponents = [j for j in range(d)
                               if d // gcd(d,j) in (1,2,3)]
            quotient_order = gcd(d, *fixed_exponents)
            # Subgroup generated by those exponents has size d/gcd(d,exponents).
            assert quotient_order == d // gcd(d, 6), (m,d)
    print(f'STABLE_KNESER_ORBIT_CHECK_OK: {tests} group elements, m=8..12')

if __name__ == '__main__':
    check()
