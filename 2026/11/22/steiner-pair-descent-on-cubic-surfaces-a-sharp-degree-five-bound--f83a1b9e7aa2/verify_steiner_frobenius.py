#!/usr/bin/env python3
"""Exact finite-group certificate for Frobenius orbits on 120 cubic-surface Steiner pairs.

Requires only Python 3 standard library. The code enumerates W(E6) as permutations
of the 27 exceptional-curve classes of a blown-up projective plane; it then
constructs the 45 tritangents and all 120 Steiner-pair nine-line supports.
"""
import json
from collections import Counter, defaultdict
from itertools import combinations

I6 = range(6)

def exc(i):
    return (0,) + tuple(1 if j == i else 0 for j in I6)

def sec(i, j):
    return (1,) + tuple(-1 if k in (i, j) else 0 for k in I6)

def conic(i):
    return (2,) + tuple(0 if k == i else -1 for k in I6)

lines = ([exc(i) for i in I6]
         + [sec(i, j) for i, j in combinations(I6, 2)]
         + [conic(i) for i in I6])
assert len(lines) == len(set(lines)) == 27
lookup_line = {d: j for j, d in enumerate(lines)}

tritangents = []
for i in I6:
    for j in I6:
        if i != j:
            tritangents.append(tuple(sorted((lookup_line[exc(i)],
                                             lookup_line[sec(i, j)],
                                             lookup_line[conic(j)]))))
for pairing in combinations(list(combinations(I6, 2)), 3):
    if sorted(u for pair in pairing for u in pair) == list(I6):
        tritangents.append(tuple(sorted(lookup_line[sec(*p)] for p in pairing)))
tritangents = sorted(set(tritangents))
assert len(tritangents) == 45
tri_id = {t: i for i, t in enumerate(tritangents)}

by_support = defaultdict(list)
for t in combinations(range(45), 3):
    nine = [u for i in t for u in tritangents[i]]
    if len(set(nine)) == 9:
        by_support[tuple(sorted(nine))].append(t)
support_distribution = Counter(map(len, by_support.values()))
assert support_distribution == {1: 5040, 2: 120}
# Each repeated nine-line support has exactly two distinct partitions into
# three tritangents. This is the defining Steiner-trihedron pair.
steiner_supports = sorted(s for s, witnesses in by_support.items()
                          if len(witnesses) == 2)
assert len(steiner_supports) == 120
bit_supports = [sum(1 << j for j in s) for s in steiner_supports]
support_id = {m: i for i, m in enumerate(bit_supports)}

def intersection(x, y):
    return x[0] * y[0] - sum(x[j] * y[j] for j in range(1, 7))

roots = [tuple([0] + [-1 if j == i else 1 if j == i + 1 else 0
                     for j in I6]) for i in range(5)]
roots.append((1, -1, -1, -1, 0, 0, 0))
assert all(intersection(a, a) == -2 for a in roots)

def reflection(a):
    return bytes(lookup_line[tuple(x[i] + intersection(x, a) * a[i]
                                   for i in range(7))] for x in lines)

generators = [reflection(a) for a in roots]
assert all(sorted(g) == list(range(27)) for g in generators)

# The group generated by these six Picard-root reflections is exactly W(E6).
group = [bytes(range(27))]
seen = {group[0]}
position = 0
while position < len(group):
    element = group[position]
    position += 1
    for gen in generators:
        next_element = bytes(gen[j] for j in element)
        if next_element not in seen:
            seen.add(next_element)
            group.append(next_element)
assert len(group) == 51840

def apply_support(g, support):
    return support_id[sum(1 << g[j] for j in support)]

def apply_tritangent(g, tri):
    return tri_id[tuple(sorted(g[j] for j in tri))]

# Independent closure test: the six generators preserve the 120-element scheme.
for g in generators:
    assert {sum(1 << g[j] for j in s) for s in steiner_supports} == set(bit_supports)

def cycle_profile(permutation):
    visited = bytearray(len(permutation))
    hist = Counter()
    for j in range(len(permutation)):
        if not visited[j]:
            length, t = 0, j
            while not visited[t]:
                visited[t] = 1
                length += 1
                t = permutation[t]
            hist[length] += 1
    return tuple(sorted(hist.items()))

def least_cycle(permutation):
    return min(size for size, number in cycle_profile(permutation))

min_degree = Counter()
tritangent_without_pair = 0
signatures = Counter()
for g in group:
    on_tri = [apply_tritangent(g, t) for t in tritangents]
    on_pairs = [apply_support(g, s) for s in steiner_supports]
    sig = (cycle_profile(g), cycle_profile(on_tri), cycle_profile(on_pairs))
    signatures[sig] += 1
    least = least_cycle(on_pairs)
    min_degree[least] += 1
    if least > 1 and least_cycle(on_tri) == 1:
        tritangent_without_pair += 1

assert min_degree == {1: 22752, 2: 6480, 3: 5760, 4: 6480, 5: 10368}
assert sum(min_degree.values()) == len(group)
assert tritangent_without_pair == 12960
assert len(signatures) == 25

# Frobenius permutes the first five blowup centers cyclically and fixes the sixth.
# Transport the six exceptional-coefficient labels in the Picard basis.
def five_cycle(c):
    dest = [c[0]] + [0] * 6
    for i in I6:
        dest[1 + ((i + 1) % 5 if i < 5 else 5)] = c[1 + i]
    return tuple(dest)

five_on_lines = bytes(lookup_line[five_cycle(c)] for c in lines)
assert cycle_profile(five_on_lines) == ((1, 2), (5, 5))
five_on_tritangents = [apply_tritangent(five_on_lines, t) for t in tritangents]
five_on_steiner = [apply_support(five_on_lines, s) for s in steiner_supports]
assert cycle_profile(five_on_tritangents) == ((5, 9),)
assert cycle_profile(five_on_steiner) == ((5, 24),)

print(json.dumps({
    'exceptional_curves': len(lines),
    'tritangent_planes': len(tritangents),
    'Steiner_pair_supports': len(steiner_supports),
    'W_E6_order': len(group),
    'distinct_combined_cycle_profiles': len(signatures),
    'minimum_Steiner_extension_degree_group_counts': dict(sorted(min_degree.items())),
    'group_elements_with_rational_tritangent_but_no_rational_Steiner_pair': tritangent_without_pair,
    'five_cycle_27_line_profile': cycle_profile(five_on_lines),
    'five_cycle_45_tritangent_profile': cycle_profile(five_on_tritangents),
    'five_cycle_120_Steiner_pair_profile': cycle_profile(five_on_steiner),
}, indent=2))
