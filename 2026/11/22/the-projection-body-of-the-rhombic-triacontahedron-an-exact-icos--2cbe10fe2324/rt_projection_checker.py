"""Exact certificate for the geometric projection-body statement.
Run: python rt_projection_checker.py (requires SymPy). No network calls.
"""
from itertools import combinations
from collections import Counter
import sympy as s

R=s.sqrt(5); p=(1+R)/2
v=[s.Matrix(a) for a in [(0,1,p),(0,-1,p),(1,p,0),(-1,p,0),(p,0,1),(p,0,-1)]]
q=lambda e:s.simplify(s.expand(e))
D=lambda a,b,c:q(s.det(s.Matrix.hstack(a,b,c)))
minor=Counter(q(abs(D(*t))) for t in combinations(v,3))
assert minor==Counter({1+R:10, 3+R:10}),minor
V=sum(k*n for k,n in minor.items());assert q(V-(40+20*R))==0
c=[v[i].cross(v[j]) for i,j in combinations(range(6),2)]
assert len(c)==15
assert all(q(w.dot(w)-(1+R)**2)==0 for w in c)
spec=Counter(q(abs(D(*t))) for t in combinations(c,3))
expected=Counter({s.Integer(0):70,6+2*R:100,8+4*R:180,14+6*R:100,16+8*R:5})
assert spec==expected,(spec,expected)
S=sum(k*n for k,n in spec.items());VPi=8*S
assert q(VPi-(28160+12480*R))==0
assert q(VPi/V**2-(48-4*R)/5)==0
assert q(8-VPi/V**2-4*(R-2)/5)==0

# Exact unoriented-normal enumeration for every facet of the zonotope
# generated by the fifteen cross-product vectors. No reliance on hull rounding.
planes=[]
for i,j in combinations(range(15),2):
 normal=c[i].cross(c[j]);
 if all(q(x)==0 for x in normal): continue
 if not any(all(q(x)==0 for x in normal.cross(n)) for n in planes):
  planes.append(normal)
assert len(planes)==31
shape=Counter()
for n in planes:
 idx=[i for i,w in enumerate(c) if q(n.dot(w))==0]
 m=len(idx);shape[m]+=1
 assert m in (2,3,5)
 # A face is a planar zonotope of m distinct directions.
 pairs=[q(abs(c[i].dot(c[j]))/(1+R)**2) for i,j in combinations(idx,2)]
 if m==2: assert all(q(x)==0 for x in pairs)
 elif m==3: assert all(q(x-s.Rational(1,2))==0 for x in pairs)
 else:
  allowed=[p/2,(p-1)/2]
  assert all(any(q(x-y)==0 for y in allowed) for x in pairs)
assert shape==Counter({2:15,3:10,5:6}),shape
F={2*m:2*n for m,n in shape.items()}; assert F=={4:30,6:20,10:12}
E=sum(k*num for k,num in F.items())//2
assert E==180
vertices=2+E-sum(F.values());assert vertices==120
print('base_minors=',dict(minor))
print('projection_triple_minor_spectrum=',dict(spec))
print('base_volume=',V, 'projection_volume=',VPi)
print('normalized_ratio=',q(VPi/V**2))
print('facet_counts=',F,'vertices=',vertices,'edges=',E)
print('ALL_CHECKS_PASSED')
