"""Reproducible exact top-chain and product-torus lattice computation for the icosahedral graph.

Only the Python standard library is used. All arithmetic is exact over the integers
or the two-element field. There are no random samples or external data dependencies.
"""
import itertools, collections, time, math, json, pathlib
V=range(12)
E=[(0,1),(0,5),(0,7),(0,8),(0,11),(1,2),(1,5),(1,6),(1,8),
   (2,3),(2,6),(2,8),(2,9),(3,4),(3,6),(3,9),(3,10),
   (4,5),(4,6),(4,10),(4,11),(5,6),(5,11),(7,8),(7,9),
   (7,10),(7,11),(8,9),(9,10),(10,11)]
eidx={e:i for i,e in enumerate(E)}
adj={v:[] for v in V}
for u,v in E:adj[u].append(v);adj[v].append(u)
for v in V:adj[v].sort()
assert len(E)==30 and all(len(adj[v])==5 for v in V)
assert all(sum((a in adj[b]) for a,b in itertools.combinations(adj[v],2))==5 for v in V)
base={v:adj[v][0] for v in V};opts={v:adj[v][1:] for v in V}
C3=[tuple((v,j) for v,j in zip(vs,js)) for vs in itertools.combinations(V,3) for js in itertools.product(*[opts[v] for v in vs])]; C3index={c:i for i,c in enumerate(C3)}
C2=[(e,((u,ju),(v,jv))) for e in range(len(E)) for u,v in itertools.combinations(V,2) for ju,jv in itertools.product(opts[u],opts[v])]; C2index={c:i for i,c in enumerate(C2)}
def boundary(c):
 out=collections.defaultdict(int)
 for k,(v,j) in enumerate(c):
  rem=c[:k]+c[k+1:]
  for nb,s in ((j,1),(base[v],-1)):
   out[C2index[(eidx[tuple(sorted((v,nb)))],rem)]]+=s*((-1)**k)
 return {r:v for r,v in out.items() if v}
def allcycles():
 cset=set()
 for s in V:
  stack=[(s,(s,))]
  while stack:
   v,path=stack.pop()
   for w in adj[v]:
    if w==s:
     if len(path)>=3 and path[1]<path[-1]: cset.add(path)
    elif w>s and w not in path and len(path)<6:stack.append((w,path+(w,)))
 return sorted(cset,key=lambda x:(len(x),x))
cycs=allcycles();cycbm=[sum(1<<v for v in c) for c in cycs]
def cyclelocal(c):
 loc=[]
 for i,v in enumerate(c):
  a,b=c[i-1],c[(i+1)%len(c)]
  if b!=base[v]:loc.append(((v,b),1))
  if a!=base[v]:loc.append(((v,a),-1))
 return loc
cyclocs=[cyclelocal(c) for c in cycs]
def torus(chs):
 out=collections.defaultdict(int)
 for (a,ca),(b,cb),(c,cc) in itertools.product(*(cyclocs[z] for z in chs)):
  v=(a[0],b[0],c[0]); inv=(v[0]>v[1])+(v[0]>v[2])+(v[1]>v[2]);sgn=-1 if inv%2 else 1
  col=tuple(sorted((a,b,c)));out[C3index[col]]+=ca*cb*cc*sgn
 return {r:v for r,v in out.items() if v}
def add_scaled(x,y,c):
 for z,t in y.items():
  v=x.get(z,0)+c*t
  if v:x[z]=v
  elif z in x:del x[z]
start=time.monotonic()
print('C3 C2 cycles',len(C3),len(C2),len(cycs),collections.Counter(map(len,cycs)),flush=True)
# exact signed graph chains for all 700 pairs of disjoint cycles
terms=[];T=collections.Counter();
for i,ci in enumerate(cycs):
 b1=cycbm[i]
 for j in range(i+1,len(cycs)):
  b2=cycbm[j]
  if b1&b2:continue
  for k in range(j+1,len(cycs)):
   if (b1|b2)&cycbm[k]:continue
   ts=(i,j,k); t=torus(ts);typ=tuple(sorted(len(cycs[u]) for u in ts));T[typ]+=1;terms.append((typ,ts,t))
terms.sort(key=lambda it:(max(it[0]),it[0],it[1]))
print('toruscount',len(terms),T, 'sec',time.monotonic()-start,flush=True)
# independently verify boundary for all tori
for m,(_,ts,t) in enumerate(terms):
 bd=collections.defaultdict(int)
 for a,v in t.items():
  for row,b in boundary(C3[a]).items():bd[row]+=v*b
 if any(bd.values()): raise AssertionError(('NOT CYCLE',ts,[(r,v) for r,v in bd.items() if v][:3]))
print('all signed tori closed',time.monotonic()-start,flush=True)
# choose pivots unit from each new torus, no fractions
pivot_rows={}; chosen=[]; unred=[]; diag=[]; stats=[]
for m,(typ,ts,t) in enumerate(terms):
 x=t.copy()
 for p,y in pivot_rows.items():
  c=x.get(p,0)
  if c: add_scaled(x,y,-c)
 if not x:continue
 z=next((r for r,v in sorted(x.items()) if abs(v)==1),None)
 if z is None:
  print('NON-UNIT pivot',typ,ts,'count',len(x),'gcd',math.gcd(*x.values()),'max',max(map(abs,x.values())),flush=True)
  unred.append((m,typ,ts,x));continue
 c=x[z]
 if c==-1:x={r:-v for r,v in x.items()}
 pivot_rows[z]=x;chosen.append((m,typ,ts,z));stats.append((len(x),max(map(abs,x.values()))))
 if len(chosen)%10==0:print('integer pivots',len(chosen),'processed',m,'maxfill',max(s[0] for s in stats),'maxcoefficient',max(s[1] for s in stats),'sec',time.monotonic()-start,flush=True)
assert len(chosen)==110 and all(typ==(3,3,3) for _,typ,_,_ in chosen[:100])
assert all(typ==(3,3,6) for _,typ,_,_ in chosen[100:])
triangle_pivots=dict(list(pivot_rows.items())[:100])
for typ,ts,t in terms:
 if max(typ)>5:continue
 x=t.copy()
 for p,y in triangle_pivots.items():
  c=x.get(p,0)
  if c:add_scaled(x,y,-c)
 assert not x, ("short torus not generated by 100 triangle tori",ts)
print("ALL_SHORT_TORI_INTEGER_SPAN_100",flush=True)
certificate={
  "description":"Unit-pivot certificate of primitive geometric torus classes in a reduced top chain lattice",
  "graph_edges":E,
  "basis":[{"cycles":[list(cycs[t]) for t in ts],"type":list(typ),"pivot_coordinate":C3[z]} for m,typ,ts,z in chosen],
  "counts":{"chain3":len(C3),"chain2":len(C2),"short_cycle_count":len(cycs),"torus_count":len(terms),"triangle_tori":100,"primitive_short_rank":100,"full_rank":110,"max_length_required":6}
}
certificate_path=pathlib.Path(__file__).resolve().parent/"BASIS_CERTIFICATE.json"
assert certificate_path.exists(), "BASIS_CERTIFICATE.json is required alongside this verifier"
assert json.loads(certificate_path.read_text(encoding="utf-8"))==json.loads(json.dumps(certificate)), "basis certificate differs from independently recomputed basis"
print('integer pivot complete',len(chosen),'nonunit',len(unred),'long type',collections.Counter(typ for _,typ,_,_ in chosen),'stats',max(map(lambda y:y[0],stats)),max(map(lambda y:y[1],stats)), 'sec',time.monotonic()-start,flush=True)
# Ensure no zero remainder rational nonunit cases
assert not unred
assert len(chosen)==110
# Exact C3 boundary rank mod 2 (pivot lower bound)
bps={}
for col in C3:
 x=sum(1<<r for r,b in boundary(col).items() if b%2)
 while x:
  p=(x&-x).bit_length()-1
  if p in bps: x^=bps[p]
  else: bps[p]=x;break
print('d3 mod2 rank',len(bps),'nullity',len(C3)-len(bps),'sec',time.monotonic()-start,flush=True)
assert len(bps)==len(C3)-len(chosen)
print('EXACT_ICO_3PARTICLE_TORUS_THRESHOLD_OK',time.monotonic()-start)
