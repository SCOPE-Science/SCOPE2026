#!/usr/bin/env python3
"""Exact integer/rational checks supporting the octagonal-prism anticanonical theorem.

All infinite statements in the accompanying proof additionally use the rational
Ehrhart theorem and an explicit unimodular fan decomposition.
"""
from fractions import Fraction as F
from itertools import combinations
from math import comb

FAN = ((2,2),(1,2),(-1,1),(-2,-1),(-2,-2),(-1,-2),(1,-1),(2,1))

def cross(p,q):
    return p[0]*q[1]-p[1]*q[0]

def feasible(x,y):
    return all(a*x+b*y >= -1 for a,b in FAN)

def vertices():
    verts=set()
    for (a,b),(c,d) in combinations(FAN,2):
        det=a*d-b*c
        if det==0:
            continue
        x=F(b-d,det)
        y=F(c-a,det)
        if feasible(x,y):
            verts.add((x,y))
    return verts

EXPECTED_VERTS={
    (F(0),F(1,2)),(F(0),F(-1,2)),(F(1,2),F(0)),(F(-1,2),F(0)),
    (F(1,3),F(-2,3)),(F(-1,3),F(2,3)),
    (F(2,3),F(-1,3)),(F(-2,3),F(1,3))
}
assert vertices()==EXPECTED_VERTS
assert set(F(v).denominator for p in EXPECTED_VERTS for v in p)=={1,2,3}

# The ten rays give a lattice-unimodular star triangulation around (1,0,0).
# Entries are (degree, coordinate_a, coordinate_b), in cyclic angular order.
RAYS=((2,1,0),(2,0,1),(3,-1,2),(2,-1,1),(3,-2,1),
      (2,-1,0),(2,0,-1),(3,1,-2),(2,1,-1),(3,2,-1))
assert len(set(RAYS))==10
for i,(d,a,b) in enumerate(RAYS):
    assert all(F(f*a+g*b,d)>=-1 for f,g in FAN)
    assert any(f*a+g*b==-d for f,g in FAN)
    nd,c,e=RAYS[(i+1)%len(RAYS)]
    assert a*e-b*c==1, (i,a,b,c,e)
# By the cyclic boundary order, each cone generated by the central ray and
# two neighboring boundary rays has determinant 1. Every lattice point
# in the full pointed cone is a nonnegative integer sum of these rays.

def S(n):
    return {(a,b) for a in range(-n,n+1) for b in range(-n,n+1)
            if all(f*a+g*b>=-n for f,g in FAN)}
S1,S2,S3=S(1),S(2),S(3)
assert S1=={(0,0)}
assert S2-S1=={(1,0),(-1,0),(0,1),(0,-1),(1,-1),(-1,1)}
assert S3-S2=={(2,-1),(-2,1),(1,-2),(-1,2)}
# Projective anticanonical cone has |c|<=m and (a,b) in (m-|c|)Q.
# Lifting the 10 planar rays at c=0 and (1,0,0,c), c=-1,0,1,
# gives the irredundant 13-element Hilbert basis with weights 1^3,2^6,3^4.

E=[len(S(m)) for m in range(42)]
# Rational Ehrhart theorem: E is quadratic on each residue class modulo six.
# Exact coefficient triples are certified by three exact values per residue.
# E_r(m) = (11*m*m + b_r*m + c_r)/12.
coefs={0:(14,12),1:(8,-7),2:(14,12),3:(8,9),4:(14,-4),5:(8,9)}
for m,v in enumerate(E):
    b,c=coefs[m%6]
    assert 12*v==11*m*m+b*m+c, (m,v)

H=[E[m]+2*sum(E[:m]) for m in range(len(E))]
assert H[:13]==[1,3,11,29,59,105,173,263,381,531,715,937,1203]
# Generating-series identity to check:
# H(z) = B(z) / ((1-z)(1-z^2)(1-z^3)(1-z^6)).
B=[1,2,7,15,20,21,21,20,15,7,2,1]
D=[1]
for k in (1,2,3,6):
    new=[0]*(len(D)+k)
    for j,v in enumerate(D):
        new[j]+=v
        new[j+k]-=v
    D=new
for n in range(len(H)):
    c=sum(D[k]*H[n-k] for k in range(len(D)) if n>=k)
    assert c==(B[n] if n<len(B) else 0),(n,c)
assert B==B[::-1]
# Degree-one sections depend only on the third torus coordinate. At
# degree two the lattice points (a,b,c)=(0,0,0),(1,0,0),(0,1,0),(0,0,1)
# occur, proving the degree-two rational map is birational on the torus.
assert {(0,0),(1,0),(0,1)}.issubset(S2)
assert 0 in range(-2,3) and 1 in range(-2,3)
print('PASS: exact polar, unimodular sectors, 13 Hilbert basis degrees, index six, Ehrhart and section Hilbert series, birational threshold')
