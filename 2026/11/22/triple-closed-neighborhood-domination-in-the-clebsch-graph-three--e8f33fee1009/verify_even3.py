"""Independent even-five-word six-hole enumeration with S5 affine orbit partition."""
from collections import Counter, deque
from itertools import combinations, permutations
import json
W=tuple(i for i in range(32) if i.bit_count()%2==0)
assert len(W)==16
edges={a:{b for b in W if (a^b).bit_count()==4} for a in W}
assert all(len(edges[a])==5 for a in W)
closed={a:edges[a]|{a} for a in W}
all6=[]
for missing in combinations(W,6):
    M=set(missing)
    if all(len(closed[v]&M)<=3 for v in W):
        all6.append(frozenset(M))
assert len(all6)==312
# Larger missing sets violate monotone lower bound by exhaustive six-hole extension.
for missing in combinations(W,7):
    assert any(len(closed[v]&set(missing))>3 for v in W)
classes=Counter()
for missing in all6:
    degs=tuple(sorted(len(edges[v]&missing) for v in missing))
    classes[degs]+=1
assert classes=={(1,)*6:40,(0,2,2,2,2,2):192,(2,)*6:80}
# Full automorphism action generated by translations by even five-bit words and coordinate permutations.
permutations5=list(permutations(range(5)))
permuted=[]
for p in permutations5:
    tmap={v:sum(((v>>i)&1)<<p[i] for i in range(5)) for v in W}
    permuted.append(tmap)
remaining=set(all6); orbit_sizes=[]
while remaining:
    seed=next(iter(remaining))
    orbit={frozenset(tmap[x]^shift for x in seed) for tmap in permuted for shift in W}
    assert orbit<=remaining
    orbit_sizes.append(len(orbit));remaining-=orbit
assert Counter(orbit_sizes)=={40:1,80:1,192:1}
# Two-change exchange graph (six-hole overlaps of size at least four).
states=list(all6)
A=[[] for _ in states]
for i,j in combinations(range(len(states)),2):
    if len(states[i]&states[j])>=4:A[i].append(j);A[j].append(i)
assert sum(map(len,A))//2==5220
assert Counter(map(len,A))=={39:120,30:192}
seen=set();ecc=Counter()
for i in range(len(states)):
    dist={i:0};q=deque([i]);
    while q:
        a=q.popleft()
        for b in A[a]:
            if b not in dist:dist[b]=dist[a]+1;q.append(b)
    assert len(dist)==len(states)
    ecc[max(dist.values())]+=1
assert ecc=={3:312}
assert not any(len(x&y)==5 for x,y in combinations(states,2))
res={'optima':len(states),'minimum':10,'orbit_sizes':sorted(orbit_sizes),
     'six_hole_shapes':{str(k):v for k,v in classes.items()},
     'one_exchange_edges':0,'two_exchange_edges':5220,
     'two_exchange_degree_counts':dict(Counter(map(len,A))),
     'two_exchange_eccentricity_counts':dict(ecc)}
print(json.dumps(res,sort_keys=True))
