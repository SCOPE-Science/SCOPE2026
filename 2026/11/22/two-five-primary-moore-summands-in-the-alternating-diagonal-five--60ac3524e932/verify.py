#!/usr/bin/env python3
"""Exact integer certificate for the five-label alternating chessboard quotient.
Python 3 standard library only; no input files or external packages.
"""
from itertools import combinations, permutations
from collections import Counter
from functools import lru_cache

N=5

def even(p):
    return sum(p[i]>p[j] for i in range(N) for j in range(i+1,N))%2==0

GROUP=[p for p in permutations(range(N)) if even(p)]
assert len(GROUP)==60
PERM_EDGES=[tuple(N*p[i//N]+p[i%N] for i in range(N*N)) for p in GROUP]
FACES=[]
for k in range(1,N+1):
    for rows in combinations(range(N),k):
        for cols in permutations(range(N),k):
            FACES.append(sum(1<<(N*i+j) for i,j in zip(rows,cols)))
FACES=sorted(set(FACES))
assert Counter(f.bit_count() for f in FACES)=={1:25,2:200,3:600,4:600,5:120}

def permute_face(f,pe):
    q=0
    while f:
        low=f&-f
        q |= 1<<pe[low.bit_length()-1]
        f-=low
    return q

IMAGE={f:tuple(permute_face(f,p) for p in PERM_EDGES) for f in FACES}

@lru_cache(None)
def flags_ending(face):
    # Every nonempty strict chain whose maximum is 'face'.
    out=[(face,)]
    inds=[b for b in range(N*N) if face&(1<<b)]
    for k in range(1,len(inds)):
        for sub in combinations(inds,k):
            u=sum(1<<b for b in sub)
            for prefix in flags_ending(u):
                out.append(prefix+(face,))
    return tuple(out)

def orbit_key(chain):
    return min(tuple(IMAGE[f][g] for f in chain) for g in range(len(GROUP)))

ORBIT_CELLS=[set() for _ in range(N)]
for f in FACES:
    for chain in flags_ending(f):
        ORBIT_CELLS[len(chain)-1].add(orbit_key(chain))
ORBIT_CELLS=[sorted(x) for x in ORBIT_CELLS]
assert list(map(len,ORBIT_CELLS))==[45,308,744,720,240]
INDEX=[{chain:i for i,chain in enumerate(cells)} for cells in ORBIT_CELLS]
# The barycentric subdivision has no inversions; chain-orbits are genuine
# geometric quotient cells. Each cell has distinct ranks in its vertices.
BOUNDARIES=[None]
for d in range(1,N):
    columns=[]
    for chain in ORBIT_CELLS[d]:
        c={}
        for t in range(d+1):
            sub=orbit_key(chain[:t]+chain[t+1:])
            idx=INDEX[d-1][sub]
            c[idx]=c.get(idx,0)+(-1)**t
        columns.append({r:v for r,v in c.items() if v})
    BOUNDARIES.append(columns)

for d in range(2,N):
    for col in BOUNDARIES[d]:
        total={}
        for i,x in col.items():
            for j,y in BOUNDARIES[d-1][i].items():
                total[j]=total.get(j,0)+x*y
        assert all(z==0 for z in total.values()),'boundary-square failure'

ALIVE=[set(range(len(level))) for level in ORBIT_CELLS]
MOVES=[]
for d in range(N-1,2,-1):
    while True:
        cofaces={f:[] for f in ALIVE[d-1]}
        for c in sorted(ALIVE[d]):
            for f in BOUNDARIES[d][c]:
                if f in cofaces:cofaces[f].append(c)
        candidates=[(f,co[0]) for f,co in cofaces.items()
                    if len(co)==1 and abs(BOUNDARIES[d][co[0]][f])==1]
        if not candidates:break
        f,c=min(candidates)
        # All higher-dimensional cells are absent at each transition.
        assert not any(ALIVE[k] for k in range(d+1,N))
        ALIVE[d-1].remove(f)
        ALIVE[d].remove(c)
        MOVES.append((d,f,c))
assert Counter(d for d,_,_ in MOVES)=={4:240,3:404}
assert [len(s) for s in ALIVE]==[45,308,340,76,0]


def remaining_rows(d):
    rows=sorted(ALIVE[d-1]); cols=sorted(ALIVE[d])
    rev={j:k for k,j in enumerate(cols)}
    arr=[{} for _ in rows]
    for i,r in enumerate(rows):
        for j in cols:
            v=BOUNDARIES[d][j].get(r,0)
            if v:arr[i][rev[j]]=v
    return arr,len(cols)


def split_units(mat,ncols):
    """Integral unimodular row/column cancellations at entries ±1.
    Returns unit-pivot count and exact remaining matrix; all transforms
    are generated by integer row additions and row/column permutations.
    """
    rows=[dict(r) for r in mat]
    active_rows=list(range(len(rows)))
    active_cols=set(range(ncols))
    unit=0
    while True:
        cdeg=Counter(j for i in active_rows for j in rows[i])
        opts=[((len(rows[i])-1)*(cdeg[j]-1),len(rows[i]),cdeg[j],i,j)
              for i in active_rows for j,v in rows[i].items() if abs(v)==1]
        if not opts:break
        _,_,_,i,j=min(opts)
        v=rows[i][j]
        for r in active_rows:
            if r==i or j not in rows[r]:continue
            mult=rows[r][j]//v
            for k,w in rows[i].items():
                new=rows[r].get(k,0)-mult*w
                if new:rows[r][k]=new
                else:rows[r].pop(k,None)
        active_rows.remove(i)
        active_cols.remove(j)
        unit+=1
        assert all(j not in rows[r] for r in active_rows)
    remaining=[{j:v for j,v in rows[r].items() if j in active_cols}
               for r in active_rows]
    return unit,remaining,len(active_cols)

EVIDENCE=[]
for d,expect in [(1,44),(2,264),(3,74)]:
    A,ncol=remaining_rows(d)
    units,R,nc=split_units(A,ncol)
    assert units==expect,(d,units)
    if d<=2:
        assert all(not row for row in R),'no nonunit block expected'
    else:
        assert nc==2
        nonzero=[sorted(row.values()) for row in R if row]
        assert len(nonzero)==4 and sorted(nonzero)==[[-5],[-5],[5],[5]]
        # There are exactly two independent nonunit columns, each with
        # entries of gcd 5 and disjoint row supports: Smith(5,5).
        bycol={j:[row[j] for row in R if j in row] for j in sorted({j for row in R for j in row})}
        assert len(bycol)==2 and all(sorted(abs(x) for x in v)==[5,5] for v in bycol.values())
        EVIDENCE.append(bycol)

assert sum((-1)**k*len(ALIVE[k]) for k in range(N))==1
# The 3-dimensional residual CW complex has unit boundary ranks 44 and 264,
# while its top boundary has 74 units and the block diag(5,5).
# Thus H0=Z, H1=0, H2=(Z/5)^2, H3=0.
# The published chessboard connectivity bound makes Delta_5,5 simply
# connected. A5 is generated by 3-cycles, each fixing a diagonal rook
# vertex; Armstrong's theorem gives pi1 of the quotient = 0.
# The homological Whitehead theorem then upgrades the integral homology
# to the wedge of two M(Z/5,2) Moore spaces.
print('DIAGONAL_A5_CHESSBOARD_TWO_FIVE_MOORE_SPACES_OK')
print('quotient cell counts:',[len(x) for x in ORBIT_CELLS])
print('collapse pairs:',dict(sorted(Counter(d for d,_,_ in MOVES).items())))
print('residual cell counts:',[len(x) for x in ALIVE])
print('integer elementary divisors: B1 1^44, B2 1^264, B3 1^74 and 5^2')
