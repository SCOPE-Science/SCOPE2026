# u,v commute
assert mul(u,v)==mul(v,u)
# u,v involutory automorphisms commute: check u v = v u as maps already; check action matrices commute
print("action relations OK")
# Centre: elements commuting with all generators
gens=[r,s,tt,u,v]
Z=[n for n in range(N) if all(mul(n,g)==mul(g,n) for g in gens)]
print("|Z|=",len(Z))
# Frattini: Phi = S^2 [S,S]; compute squares and commutators subgroup
S2={mul(n,n) for n in range(N)}
