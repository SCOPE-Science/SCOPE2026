print("|Omega1(A)|=",len(Om))
# check Omega1(A) elementary abelian
for a in Om:
    for b in Om:
        assert mul(a,b) in Om and mul(a,b)==mul(b,a)
print("Omega1(A) elementary abelian OK; elts:",[tup(n) for n in Om])
# V centralizes Omega1(A)?
for w in Om:
    assert mul(u,w)==mul(w,u) and mul(v,w)==mul(w,v)
print("V centralizes Omega1(A) OK => C2^5 section Omega1(A)x<u,v>? check intersection")
