C={comm(a,b) for a in range(N) for b in gens}  # enough: commutators with gens generate [S,S] mod? use all pairs sample
# full commutator subgroup: use all pairs (1M) fine
Call={comm(a,b) for a in range(N) for b in range(N)}
print("num squares distinct:",len(S2),"num commutators distinct:",len(Call))
# subgroup generated by S2 union Call: BFS closure
gen=set(S2)|Call
# BFS
H={0}
stack=[0]
genlist=list(gen)
# closure under mul/inv
frontier=[0]
seen={0}
while frontier:
    nxt=[]
    for h in frontier:
        for g in genlist:
            for x in (mul(h,g),mul(g,h)):
                if x not in seen:
                    seen.add(x); nxt.append(x)
    frontier=nxt
Phi=seen
print("|Phi|=",len(Phi),"quotient rank =", end=" ")
import math
