# generators: r=(1,0,0,0,0), s=(0,1,0,0,0), t=(0,0,1,0,0), u=(0,0,0,1,0), v=(0,0,0,0,1)
idx = {tuple(e):n for n,e in enumerate(map(tuple,E.tolist()))}
r=idx[(1,0,0,0,0)]; s=idx[(0,1,0,0,0)]; tt=idx[(0,0,1,0,0)]; u=idx[(0,0,0,1,0)]; v=idx[(0,0,0,0,1)]
def pw(n,k):
    x=0
    for _ in range(k): x=mul(x,n)
    return x
def order(n):
    x=n; k=1
    while x!=0:
        x=mul(x,n); k+=1
        assert k<=2048
    return k
print("orders r,s,t,u,v:", order(r),order(s),order(tt),order(u),order(v))
assert order(r)==8 and order(s)==8 and order(tt)==4 and order(u)==2 and order(v)==2
# action checks: u r u = r^-1 etc. conjugation: u*r*u^{-1} since u order 2, u^-1=u
uru = mul(mul(u,r),u); rinv=INV[r]
assert uru==rinv, (tup(uru),tup(rinv))
usu = mul(mul(u,s),u); assert tup(usu)==(0,3,0,0,0), tup(usu)
utu = mul(mul(u,tt),u); assert tup(utu)==(0,0,3,0,0), tup(utu)
vrv = mul(mul(v,r),v); assert tup(vrv)==(5,0,0,0,0), tup(vrv)
vsv = mul(mul(v,s),v); assert tup(vsv)==(0,7,0,0,0), tup(vsv)
