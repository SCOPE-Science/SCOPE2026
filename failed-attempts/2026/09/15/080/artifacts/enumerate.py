# Normalizers/centralizers in S
def normalizer(H):
    H=set(H)
    return [g for g in S if all(mul(mul(g,h),inv(g)) in H for h in H)]
def centralizer(H):
    H=set(H)
    return [g for g in S if all(mul(g,h)==mul(h,g) for h in H)]

