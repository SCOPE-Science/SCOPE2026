# Enumerate D8, fusion system F_D8(A6) approx, Lambda_F, and normalizer/centralizer subbisets for P=Z.
from itertools import product

# D8 as dihedral group order 8: elements (i,j) with i in Z4 (rotation), j in Z2 (reflection)
# mult: (i1,j1)*(i2,j2) = (i1 + (-1)^j1 * i2, j1+j2 mod 2)
def mul(a,b):
    i1,j1=a; i2,j2=b
    if j1==0:
        return ((i1+i2)%4, (j1+j2)%2)
    else:
        return ((i1-i2)%4, (j1+j2)%2)
def inv(a):
    i,j=a
    if j==0:
        return ((-i)%4,0)
    else:
        return (i,1)
def conj(g,x):
    return mul(mul(g,x),inv(g))

elems=[(i,j) for i in range(4) for j in range(2)]
def ename(e):
    i,j=e
    if j==0:
        return ['1','r','r2','r3'][i]
    else:
        return ['s?','rs?','r2s?','r3s?'][i]  # (i,1)= r^i s
# fix names: (0,1)=s, (1,1)=rs, (2,1)=r2s, (3,1)=r3s
names={(0,0):'1',(1,0):'r',(2,0):'r2',(3,0):'r3',(0,1):'s',(1,1):'rs',(2,1):'r2s',(3,1):'r3s'}

S=elems
Z=[(0,0),(2,0)]
V=[(0,0),(2,0),(0,1),(2,1)]  # {1,r2,s,r2s}
Vp=[(0,0),(2,0),(1,1),(3,1)] # {1,r2,rs,r3s}
