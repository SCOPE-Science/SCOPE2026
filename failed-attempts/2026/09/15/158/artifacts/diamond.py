import sympy as sp

def sparse_sym(n, edges, diag_syms, edge_syms):
    M = sp.zeros(n)
    for i in range(n):
        M[i, i] = diag_syms[i]
    for (i, j), s in zip(edges, edge_syms):
        M[i, j] = s
        M[j, i] = s
    return M

def minors_n_1(M, n):
    gens = {}
    for di in range(n):
        for dj in range(di, n):
            rr = [x for x in range(n) if x != di]
            cc = [x for x in range(n) if x != dj]
            gens[(di, dj)] = sp.expand(M.extract(rr, cc).det())
    return gens

# Diamond: K4 minus edge 13 (1-indexed): vertices 0..3, edges all but (0,2).
