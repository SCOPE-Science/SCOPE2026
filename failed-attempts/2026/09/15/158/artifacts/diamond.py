# edges: 01:p, 03:s? let's: 01,02? no. Diamond: missing edge (0,2). edges: 01,03,12,23,13(i.e.1,3).
diag = [a,b,c,d]
edges = [(0,1),(0,3),(1,2),(2,3),(1,3)]
esyms = [p,s,q,r,t]
M = sparse_sym(4, edges, diag, esyms)
g = minors_n_1(M, 4)
print("=== Diamond n=4 ===")
nident = 0
for k, v in g.items():
    flag = "IDENTICALLY ZERO" if v == 0 else ""
    if v == 0: nident += 1
    print(f"M_{k}: {str(v)[:160]} {flag}")
