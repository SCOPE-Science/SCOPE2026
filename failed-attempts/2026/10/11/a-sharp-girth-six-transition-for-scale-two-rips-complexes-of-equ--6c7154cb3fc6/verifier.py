#!/usr/bin/env python3
"""Exact finite checks for the small-length equal-arm theta-graph Rips theorem.

All graph distances, cliques and mod-two boundary ranks are built afresh.
The argument for arbitrary parameters is in RESULT.md, not inferred from tests.
"""
from collections import defaultdict, deque
from itertools import combinations


def graph(m, length):
    assert m >= 3 and length >= 2
    verts = [('u', 0), ('v', 0)] + [(arm, t) for arm in range(m) for t in range(1, length)]
    ix = {v: i for i, v in enumerate(verts)}
    adj = [set() for _ in verts]
    for arm in range(m):
        path = [ix[('u', 0)]] + [ix[(arm, t)] for t in range(1, length)] + [ix[('v', 0)]]
        for a, b in zip(path, path[1:]):
            adj[a].add(b)
            adj[b].add(a)
    return verts, adj


def distances(adj):
    ans = []
    for a in range(len(adj)):
        dist = {a: 0}
        q = deque([a])
        while q:
            x = q.popleft()
            for y in adj[x]:
                if y not in dist:
                    dist[y] = dist[x] + 1
                    q.append(y)
        assert len(dist) == len(adj)
        ans.append(dist)
    return ans


def clique_levels(dist, r):
    n = len(dist)
    levels = {1: [(i,) for i in range(n)]}
    previous = levels[1]
    for k in range(2, n+1):
        nxt = [sigma + (j,) for sigma in previous
               for j in range(sigma[-1]+1,n)
               if all(dist[i][j] <= r for i in sigma)]
        if not nxt: break
        levels[k] = nxt
        previous = nxt
    return levels


def gf2_rank(vectors):
    piv = {}
    for x in vectors:
        while x:
            k = x.bit_length()-1
            if k not in piv:
                piv[k] = x
                break
            x ^= piv[k]
    return len(piv)


def reduced_betti(levels):
    ranks={}
    for k in sorted(levels):
        if k<2: continue
        imap={sigma:i for i,sigma in enumerate(levels[k-1])}
        columns=[]
        for sigma in levels[k]:
            mask=0
            for i in range(k):
                face=sigma[:i]+sigma[i+1:]
                mask ^= 1<<imap[face]
            columns.append(mask)
        ranks[k]=gf2_rank(columns)
    b={k-1: len(levels[k])-ranks.get(k,0)-ranks.get(k+1,0)
       for k in levels}
    b[0]-=1
    return {k:v for k,v in b.items() if v},ranks


def verify_girth_collapse(m, length, adj, levels):
    if length<4:return
    n=len(adj)
    centered_edges=set()
    faces=[sigma for k,level in levels.items() if k>=2 for sigma in level]
    for simplex in faces:
        if len(simplex)==2:
            a,b=simplex
            if b in adj[a]: continue
            centers=[x for x in range(n) if a in adj[x] and b in adj[x]]
        else:
            centers=[x for x in range(n) if all(i==x or i in adj[x] for i in simplex)]
        assert len(centers)==1,(m,length,simplex,centers)
    # Verify elementary face pairs: center cone pairs (sigma, sigma+center)
    leftover=set(faces)
    for v in range(n):
        neighbors=sorted(adj[v])
        for sz in range(len(neighbors),1,-1):
            for subset in combinations(neighbors,sz):
                upper=tuple(sorted((*subset,v)))
                assert subset in leftover and upper in leftover
                # each upper simplex has just one codimension-one coface sigma
                cofaces=[big for big in leftover if len(big)==len(subset)+1 and set(subset).issubset(big)]
                assert cofaces == [upper], (m,length,v,subset,cofaces)
                leftover.remove(subset)
                leftover.remove(upper)
    assert leftover=={tuple(sorted((u,v))) for u in range(n) for v in adj[u] if u<v}


def verify_suspension(m, verts, adj, dist, levels):
    ix={v:i for i,v in enumerate(verts)}
    u,v=ix[('u',0)],ix[('v',0)]
    A={ix[(arm,1)] for arm in range(m)}
    B={ix[(arm,2)] for arm in range(m)}
    assert dist[u][v]==3
    assert all(dist[u][x]<=2 and dist[v][x]<=2 for x in A|B)
    for a in A:
        for b in B:
            should = (verts[a][0]==verts[b][0])
            assert (dist[a][b]<=2)==should
    # entire scale-two simplicial complex equals S0 * K
    for k,level in levels.items():
        for s in level:
            assert not ({u,v} <= set(s))
    klevels=clique_levels(dist,2)
    internal_faces={s for lev in klevels.values() for s in lev if u not in s and v not in s}
    joined=internal_faces | {tuple(sorted((u,*s))) for s in internal_faces} | {tuple(sorted((v,*s))) for s in internal_faces}
    joined.add((u,)); joined.add((v,))
    assert joined == {s for level in levels.values() for s in level}


def verify_action(m):
    # H_1(K) generated by c_i-c_0 (i>0). Test graph-chain
    # reversal negates each cycle, while suspension-vertex swap negates again.
    def edge(a,b): return (tuple(sorted((a,b))), 1 if a<b else -1)
    def cycle(i,j):
        path=[('a',i),('b',i),('b',j),('a',j),('a',i)]
        res=defaultdict(int)
        for p,q in zip(path,path[1:]):
            e,s=edge(p,q); res[e]+=s
        return {e:k for e,k in res.items() if k}
    def transform(c,perm,reverse=False):
        def f(x):return ('b' if x[0]=='a' else 'a',perm[x[1]]) if reverse else (x[0],perm[x[1]])
        out=defaultdict(int)
        for (a,b),coef in c.items():
            e,s=edge(f(a),f(b));out[e]+=s*coef
        return {e:k for e,k in out.items() if k}
    for i in range(1,m):
        c=cycle(i,0)
        assert transform(c,tuple(range(m)),True)=={e:-k for e,k in c.items()}
        for shift in range(m):
            perm=tuple((j+shift)%m for j in range(m))
            assert transform(c,perm)==cycle(perm[i],perm[0])
    return True


def main():
    cases=0
    for m in range(3,7):
        for length in range(2,6):
            verts,adj=graph(m,length)
            d=distances(adj)
            for radius in (1,2):
                lev=clique_levels(d,radius)
                bet,rank=reduced_betti(lev)
                target=({1:m-1} if radius==1 else
                        {} if length==2 else
                        {2:m-1} if length==3 else {1:m-1})
                assert bet==target,(m,length,radius,bet,target)
                if radius==2:
                    if length==3:verify_suspension(m,verts,adj,d,lev)
                    if length>=4:verify_girth_collapse(m,length,adj,lev)
                cases+=1
            if length==3:
                assert max(max(row.values()) for row in d)==3
                assert reduced_betti(clique_levels(d,3))[0]=={}
        verify_action(m)
    print(f'VERIFY_OK cases={cases} exact_mod2_ranks=yes girth_collapse=yes suspension_identity=yes involution_signs=yes')

if __name__=='__main__':main()
